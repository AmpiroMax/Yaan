// ШКОЛА КУРГАНЛЫ — ОБЩИЕ РУКИ ПАКЕТА
//
// ЛОКАЛЬНЫЕ КООРДИНАТЫ ТЕ ЖЕ, ЧТО У ВСЕЙ ПОЛКИ: начало — северо-западный
// угол, дверь смотрит на +Z (юг). Для степного города это значит вот что:
// ГЛУХАЯ длинная стена приходится на СЕВЕР (z=0) — подветренную сторону, а
// вход и единственные окна на юг. Ставя дом дверью на красную линию, город
// получает подветренную глухую стену даром.
// ---------------------------------------------------------------------------

/// ПЕРЕХЛЁСТ ТЕЛ ПО ВЫСОТЕ. Допуск касания судьи связности — 0.02 м
/// (HOUSE_CONTACT_TOL_M), и венцы, поставленные ВСТЫК, расходятся островами на
/// первом же округлении. Тот же довод и то же число, что у Житнова.
inline constexpr float KUR_LAP = 0.06f;

/// ОТКОС СТЕНЫ — ГЛАВНЫЙ СИЛУЭТНЫЙ ПРИЗНАК ГОРОДА (§4.1: «глинобитная стена на
/// бутовом цоколе с наклонным откосом, стена сужается кверху»).
///
/// ЧИСЛО ВЫВЕДЕНО ИЗ РЕМЕСЛА, А НЕ ИЗ КРАСОТЫ. Глинобитную стену бьют в
/// опалубке ярусами по 0.8-1.0 м, и каждый следующий ярус ставят уже
/// предыдущего — иначе сырая глина расползается под собственным весом. Уклон
/// живой кладки 1:12..1:20; взято 1:16, то есть 3.6 градуса. На стене 3.6 м
/// это 0.225 м сужения на сторону — с двадцати метров видно, что стена не
/// вертикальна, а с двух метров видны сами уступы ярусов.
inline constexpr float KUR_BATTER = 1.0f / 16.0f;

/// ВЫСОТА ЯРУСА ОПАЛУБКИ, м. Ею же делится откос на уступы.
inline constexpr float KUR_LIFT = 0.90f;

/// ГЛИНОБИТНАЯ СТЕНА — ОДНА РУКА НА ВЕСЬ ПАКЕТ.
/// Вещество — САМАН (глина с соломой): mat=5 (Plaster), fill не ставится
/// (монолит, см. шапку). Порядок вершин задаёт лицо: a -> b по возрастанию X
/// даёт лицо на +Z, то есть наружу у южной стены.
inline ElementId kur_adobe(Forge& f, float y, float ax, float az, float bx, float bz,
                           float h, float th, const char* tone, const char* wear) {
    return f.wall(f.v(ax, y, az), f.v(bx, y, bz),
                  {{"height", f.num(h)},
                   {"thickness", f.num(th)},
                   {"mat", "5"},
                   {"tone", tone},
                   {"wear", wear}});
}

/// ГОРИЗОНТАЛЬНАЯ ПЛИТА. Обход против часовой сверху, лицо вверх.
/// ВЕРХ ПЛИТЫ — y + толщина/2, а не y + толщина: контур растёт в ОБЕ стороны
/// от своей плоскости (HousePlate.cpp, HOUSES.md §11.2). Три рецепта проекта
/// повисли ровно на этой половине толщины.
inline ElementId kur_slab(Forge& f, float x0, float z0, float x1, float z1, float y,
                          float th, const char* mat, const char* tone,
                          const char* wear) {
    return f.contour({f.v(x0, y, z0), f.v(x0, y, z1), f.v(x1, y, z1), f.v(x1, y, z0)},
                     {{"thickness", f.num(th)}, {"mat", mat}, {"tone", tone},
                      {"wear", wear}});
}

/// БУТОВЫЙ ЦОКОЛЬ (§4.1: «на бутовом цоколе»). Вещество — БУТ, дикий камень:
/// mat=3 (Stone), tone=3 (выветренный), fill=3 (блоки) — здесь ряды УМЕСТНЫ и
/// дёшевы: цоколь высотой 0.45 это один-два ряда, а не двадцать.
/// Зачем он вообще: глина, стоящая на земле, тянет капиллярную воду и садится.
/// Цоколь — единственное место степного дома, где есть камень.
inline ElementId kur_plinth(Forge& f, float ax, float az, float bx, float bz,
                            float h, float th) {
    const ElementId id = f.wall(f.v(ax, 0.0f, az), f.v(bx, 0.0f, bz),
                                {{"height", f.num(h)},
                                 {"thickness", f.num(th)},
                                 {"mat", "3"},
                                 {"tone", "3"},
                                 {"fill", "3"},
                                 {"wear", "0.7"}});
    return id;
}

/// ВЫНОС САМОГО НИЖНЕГО ПОЯСА ОТКОСА ЗА ЛИЦО СТЕНЫ, м. Он же — весь откос:
/// верхний пояс не выступает вовсе. При высоте тела 3.15 м это уклон 1:13.
inline constexpr float KUR_BAND_OUT = 0.24f;

/// ОТКОСНЫЙ КОРПУС: бутовый цоколь, четыре стены полной высоты и ПОЯСА
/// ОТКОСА снаружи.
///
/// ПОЧЕМУ ОТКОС СДЕЛАН ПОЯСАМИ СНАРУЖИ, А НЕ ВЕНЦАМИ САМОЙ СТЕНЫ, И ЭТО
/// ИЗМЕРЕННЫЙ ОТКАЗ, А НЕ ВКУС. Первый заход бил стену ярусами опалубки по
/// 0.90 м, каждый ярус уже предыдущего, — то есть ровно так, как её бьют в
/// жизни. Он не встал: РАСКЛАДКА ПРОЁМА ЖИВЁТ В ОДНОМ ЭЛЕМЕНТЕ СТЕНЫ, а
/// дверь высотой 2.05 м в стену высотой 0.85 м не помещается по построению.
/// Выбор был между «дверь на три яруса» — то есть три разрыва наземного
/// контура вместо одного, чего манифест полки не сводит в пятно стен, — и
/// откосом как ОТДЕЛЬНЫМ СЛОЕМ. Взят второй, и он же честнее по существу:
/// в настоящей глинобитной стене откос — это не сама стена, а ПРИСЫПКА
/// подошвы, которую подновляют каждую весну, потому что её съедает дождь.
///
/// ДВЕРЬ И ОКНА — ТОЛЬКО НА ЮГЕ. Север — глухая длинная стена на подветренную
/// сторону (§4.4), окон нет вовсе; у боковых по одному мелкому и высокому.
/// Южный фасад разрезан на три пролёта по той же причине, что у Житнова:
/// раскладка знает ОДИН вид проёма на стену, и дверь берёт верх над окнами.
///
/// Возвращает верх стен — отметку, на которую садится кровля.
inline float kur_batter_body(Forge& f, float x0, float z0, float x1, float z1,
                             float h, float th, const char* tone, const char* wear,
                             const char* win_south, const char* win_side) {
    constexpr float PL = 0.45f;                  // высота бутового цоколя
    const float pth = th + 0.10f;
    // ---------- цоколь: сплошная бутовая лента под всеми стенами -----------
    (void)kur_plinth(f, x1, z0, x0, z0, PL, pth);
    (void)kur_plinth(f, x1, z1, x1, z0, PL, pth);
    (void)kur_plinth(f, x0, z0, x0, z1, PL, pth);
    (void)kur_plinth(f, x0, z1, x1, z1, PL, pth);
    // ГЛИНЯНЫЙ ПОЛ, А НЕ ПАРКЕТ: дерева в степи нет, пол мажут глиной и
    // застилают кошмой. Верх плиты — PL + 0.12 (плита растёт в обе стороны).
    (void)kur_slab(f, x0, z0, x1, z1, PL + 0.06f, 0.12f, "5", "1", "0.55");
    // ---------- стены: саман полной высоты ---------------------------------
    const float y1 = PL - KUR_LAP;
    const float hh = h - PL + KUR_LAP;
    const auto side = [&](float ax, float az, float bx, float bz, const char* win) {
        const ElementId id = kur_adobe(f, y1, ax, az, bx, bz, hh, th, tone, wear);
        if (win[0] != 0) {
            (void)f.g.set_param(id, "windows", win);
        }
        return id;
    };
    (void)side(x1, z0, x0, z0, "");              // север — глухая (§4.4)
    (void)side(x1, z1, x1, z0, win_side);        // восток
    (void)side(x0, z0, x0, z1, win_side);        // запад
    const float d0 = x0 + (x1 - x0) * 0.5f - 0.9f;
    const float d1 = x0 + (x1 - x0) * 0.5f + 0.9f;
    (void)side(x0, z1, d0, z1, win_south);
    {
        const ElementId dr = side(d0, z1, d1, z1, "");
        (void)f.g.set_param(dr, "doors", "1");
    }
    (void)side(d1, z1, x1, z1, win_south);
    f.door_leaf((x0 + x1) * 0.5f, y1, z1);
    // ---------- пояса откоса: присыпка подошвы снаружи ---------------------
    // Три пояса: нижний выступает на KUR_BAND_OUT, верхний не выступает вовсе.
    // Ось пояса отодвинута наружу на полвыноса — иначе он рос бы и внутрь
    // комнаты, а откос у глинобитной стены только наружный.
    constexpr int BANDS = 3;
    const float bh = (h - PL) / static_cast<float>(BANDS);
    for (int k = 0; k < BANDS; ++k) {
        const float p = KUR_BAND_OUT * static_cast<float>(BANDS - k)
                        / static_cast<float>(BANDS);
        const float o = th * 0.5f + p * 0.5f;
        const float by = PL - KUR_LAP + bh * static_cast<float>(k);
        const float bhh = bh + KUR_LAP;
        // ЗАХОД В ТЕЛО СТЕНЫ 0.05, А НЕ 0.02: допуск касания судьи связности
        // РАВЕН 0.02, и пояс, поставленный ровно на него, расходится островом
        // на первом же округлении (тот же довод, что у KUR_LAP).
        const float t = p + 0.10f;
        // Пояса ЗАХОДЯТ ДРУГ НА ДРУГА В УГЛАХ (концы вынесены на тот же
        // отступ o): встык у них оставался бы вырез в четверть метра на
        // каждом углу — а откос обходит подошву кругом, углы в первую очередь.
        (void)kur_adobe(f, by, x1 + o, z0 - o, x0 - o, z0 - o, bhh, t, tone, wear);
        (void)kur_adobe(f, by, x1 + o, z1 + o, x1 + o, z0 - o, bhh, t, tone, wear);
        (void)kur_adobe(f, by, x0 - o, z0 - o, x0 - o, z1 + o, bhh, t, tone, wear);
        // Южный пояс разорван дверным пролётом: присыпка поперёк порога была
        // бы ступенькой, через которую надо перепрыгивать.
        (void)kur_adobe(f, by, x0 - o, z1 + o, d0, z1 + o, bhh, t, tone, wear);
        (void)kur_adobe(f, by, d1, z1 + o, x1 + o, z1 + o, bhh, t, tone, wear);
    }
    return h;
}

/// ПЛОСКАЯ ЗЕМЛЯНАЯ КРОВЛЯ С ПАРАПЕТОМ И ВОДОСЛИВНЫМИ НОСИКАМИ
/// (§4.2: «носики торчат из парапета, ритм по фасаду»).
///
/// ТРИ СЛОЯ, И КАЖДЫЙ ВИДЕН СО СВОЕЙ СТОРОНЫ, ПОЭТОМУ ИХ ТРИ, А НЕ ОДИН:
///   1. ТРОСТНИКОВЫЙ НАСТИЛ (mat=6, Thatch) — его видно СНИЗУ, из-под свеса,
///      и с земли у карниза; в жизни это то, по чему мажут глину.
///   2. ЗЕМЛЯНОЙ СЛОЙ (mat=7, Turf) — его видно СВЕРХУ, с кургана и с
///      кровли соседа. Дёрн, а не глина: кровлю в степи присыпают землёй, и
///      к третьему году она зарастает.
///   3. ПАРАПЕТ (саман, mat=5) — его видно ОТОВСЮДУ, и он единственный, что
///      читается с тракта.
/// Плоская кровля НЕ несёт признака roof=1 у настила: она ХОДИМАЯ (§4.3, «на
/// кровле живут и спят летом»), и мостить её как скат значило бы соврать
/// тому, кто по ней пойдёт. unsupported=1 нужен только свесу.
///
/// РАЗРЫВ ПАРАПЕТА на восточной стороне — там приходит наружный марш; парапет,
/// замкнутый кольцом, был бы стеной поперёк лестницы.
inline float kur_roof(Forge& f, float x0, float z0, float x1, float z1, float y_top,
                      float out, float par_h, float gap_z0, float gap_z1,
                      const char* tone, const char* wear) {
    const float ax = x0 - out;
    const float az = z0 - out;
    const float bx = x1 + out;
    const float bz = z1 + out;
    // 1. тростниковый настил: свес несёт его целиком, потому unsupported.
    {
        const ElementId id = kur_slab(f, ax, az, bx, bz, y_top + 0.09f, 0.18f,
                                      "6", "0", wear);
        (void)f.g.set_param(id, "unsupported", "1");
    }
    // 2. земляной слой поверх настила; верх кровли = y_top + 0.30.
    const float deck = y_top + 0.24f;
    {
        const ElementId id = kur_slab(f, ax, az, bx, bz, deck, 0.12f, "7", "1", wear);
        (void)f.g.set_param(id, "unsupported", "1");
    }
    const float walk = deck + 0.06f;             // верх плиты — то, по чему ходят
    // 3. парапет: четыре прогона по кромке, восточный разорван под марш.
    const float pt = 0.28f;
    const float py = walk - KUR_LAP;
    const float ph = par_h + KUR_LAP;
    (void)kur_adobe(f, py, bx, az, ax, az, ph, pt, tone, wear);
    (void)kur_adobe(f, py, ax, az, ax, bz, ph, pt, tone, wear);
    (void)kur_adobe(f, py, ax, bz, bx, bz, ph, pt, tone, wear);
    if (gap_z0 > gap_z1) {
        (void)kur_adobe(f, py, bx, bz, bx, az, ph, pt, tone, wear);
    } else {
        (void)kur_adobe(f, py, bx, bz, bx, gap_z1, ph, pt, tone, wear);
        (void)kur_adobe(f, py, bx, gap_z0, bx, az, ph, pt, tone, wear);
    }
    // ВОДОСЛИВНЫЕ НОСИКИ: брус привозного дерева, пробитый сквозь парапет и
    // вылетающий на 0.55 м за него. Шаг 2.2 м — ритм по фасаду, о котором
    // говорит §4.2; вода с плоской кровли уходит только ими, и потому они
    // стоят на ЮЖНОМ и СЕВЕРНОМ прогонах, вдоль длинной стороны.
    for (float x = ax + 1.1f; x < bx - 0.6f; x += 2.2f) {
        for (const float z : {az, bz}) {
            const float s = z < (az + bz) * 0.5f ? -1.0f : 1.0f;
            (void)f.beam(f.v(x, walk + 0.16f, z - s * 0.30f),
                         f.v(x, walk + 0.10f, z + s * 0.55f),
                         {{"radius", "0.06"}, {"form", "square"}, {"mat", "0"},
                          {"tone", "2"}, {"wear", "0.65"}});
        }
    }
    return walk;
}

/// НАРУЖНАЯ ЛЕСТНИЦА НА КРОВЛЮ (§4.3: «у каждого дома; на кровле живут и спят
/// летом»).
///
/// СОРОК ПЯТЬ ГРАДУСОВ, И ЭТО НЕ ВКУС, А ПОЛОСА СУДЬИ. Подступёнок движка
/// 0.28 (HOUSE_STAIR_RISE_STEEP_M), и при уклоне 45 гр. проступь РАВНА ему —
/// 0.28 при пороге 0.233 (рука 6 dfn_stairs_check). Нижняя граница уклона
/// (рука 7, 30.6 гр.) стоит ТОЛЬКО у тел со стенами — а у дома они есть,
/// значит марш обязан быть в полосе, и 45 гр. лежат в ней с запасом в обе
/// стороны. Ход равен подъёму, и это то, что делает марш коротким: степной
/// дом не может позволить себе шесть метров лестницы вдоль стены.
///
/// МАРШ ПРИЖАТ К ВОСТОЧНОЙ СТЕНЕ (касание, а не зазор — судья связности), а
/// НАВЕРХУ ЕГО ЖДЁТ ПЛОЩАДКА: свес кровли на востоке доведён до конца марша,
/// и по нему выходят на кровлю через разрыв в парапете.
/// ПЕРИЛ НЕТ (rail_side 0 дал бы две балюстрады): у глинобитной лестницы их и
/// не бывает — есть щека, и она здесь саманная, как весь дом.
inline void kur_roof_stair(Forge& f, float x_wall, float z_foot, float rise,
                           float half, const char* tone, const char* wear) {
    const float z_top = z_foot - rise;           // 45 гр.: ход равен подъёму
    const float cx = x_wall + half;
    // Марш: тело у самой стены, ступени открытые (open=1) — так их и
    // выкладывают из саманного кирпича, ставя на ребро.
    (void)f.contour({f.v(cx + half, 0.0f, z_foot), f.v(cx - half, 0.0f, z_foot),
                     f.v(cx - half, rise, z_top), f.v(cx + half, rise, z_top)},
                    {{"thickness", "0.16"}, {"fill", "6"}, {"open", "1"},
                     {"rise", f.num(HOUSE_FLIGHT_RISE)}, {"nosing", "1"},
                     {"riser", "1"}, {"mat", "5"}, {"tone", tone}, {"wear", wear}});
    // Щека марша — саманная стенка по НАРУЖНОЙ кромке, от земли до линии
    // носков. Она же то, чем открытый марш перестаёт читаться стопкой плит.
    (void)f.contour({f.v(cx + half, 0.0f, z_foot), f.v(cx + half, rise, z_top),
                     f.v(cx + half, rise + 0.42f, z_top),
                     f.v(cx + half, 0.42f, z_foot)},
                    {{"thickness", "0.22"}, {"mat", "5"}, {"tone", tone},
                     {"wear", wear}});
}

/// ПЛЕТЕНЬ — ЗАСЛОН И ЗАГОН ОДНОЙ РУКОЙ (§4.6 и §4.15).
///
/// ПЛЕТЕНИЕ — ЭТО РИТМ ДВУХ ТЕЛ, А НЕ ТЕКСТУРА: колья стоят шагом 0.8, прутья
/// идут поперёк ярусами, и каждый прут ОБХОДИТ кол то спереди, то сзади —
/// смещением на полтолщины кола. Ни одного нового умения движка это не просит:
/// прут это beam с form=round, а обход — знак смещения, чередующийся по номеру
/// яруса. С двух метров видно плетение, с двадцати — тёмная полоса, и ровно
/// это в степи и видно.
inline void kur_wattle(Forge& f, float x0, float z0, float x1, float z1, float h,
                       bool daubed, const char* wear) {
    const float dx = x1 - x0;
    const float dz = z1 - z0;
    const float len = std::sqrt(dx * dx + dz * dz);
    if (len < 0.2f) {
        return;
    }
    const float ux = dx / len;
    const float uz = dz / len;
    const float nx = -uz;
    const float nz = ux;
    const int posts = std::max(2, static_cast<int>(std::round(len / 0.8f)));
    // ЛЕЖЕНЬ ПО ЗЕМЛЕ — то, чем плетень остаётся ОДНИМ телом: без него колья
    // касаются только прутьев, а прут тоньше допуска касания на изгибе.
    (void)f.beam(f.v(x0, 0.06f, z0), f.v(x1, 0.06f, z1),
                 {{"radius", "0.07"}, {"form", "square"}, {"mat", "0"},
                  {"tone", "2"}, {"wear", wear}});
    for (int k = 0; k <= posts; ++k) {
        const float t = static_cast<float>(k) / static_cast<float>(posts);
        const float px = x0 + dx * t;
        const float pz = z0 + dz * t;
        (void)f.beam(f.v(px, 0.0f, pz), f.v(px, h, pz),
                     {{"radius", "0.055"}, {"mat", "0"}, {"tone", "2"},
                      {"wear", wear}});
    }
    const int rows = std::max(2, static_cast<int>(std::round(h / 0.26f)));
    for (int r = 0; r < rows; ++r) {
        const float y = 0.14f + (h - 0.24f) * static_cast<float>(r)
                                / static_cast<float>(rows - 1);
        const float s = (r % 2 == 0) ? 0.045f : -0.045f;
        (void)f.beam(f.v(x0 + nx * s, y, z0 + nz * s), f.v(x1 + nx * s, y, z1 + nz * s),
                     {{"radius", "0.038"}, {"mat", "0"}, {"tone", "1"},
                      {"wear", wear}});
    }
    if (daubed) {
        // ОБМАЗКА ГЛИНОЙ: заслон это ПЛЕТНЁВО-ГЛИНЯНАЯ стенка (§4.6), а не
        // голый плетень — иначе он не держит позёмку, ради которой поставлен.
        // Пластина ТОНЬШЕ прутьев не бывает: обмазка их прячет, и торчат
        // только колья.
        (void)f.wall(f.v(x0, 0.0f, z0), f.v(x1, 0.0f, z1),
                     {{"height", f.num(h - 0.18f)}, {"thickness", "0.16"},
                      {"mat", "5"}, {"tone", "1"}, {"wear", wear}});
    }
}

/// КУПОЛЬНАЯ ШКОЛА ВОЙЛОЧНОГО ЖИЛИЩА — ВЕЕР ПОВЕРХНОСТЕЙ.
///
/// ЛИМИТ ДОМИНАНТ ДЕРЖИТСЯ РАССТАНОВКОЙ, А НЕ КУЗНЕЙ, И У КУРГАНЛЫ ОН ДЕРЖИТСЯ
/// ИНАЧЕ, ЧЕМ У ЖИТНОВА. Граница конвейера (CITIES_12, «границы») разрешает
/// купол «только как ДОМИНАНТА 1-3 на город: бюджет постройки 200-600 трис».
/// У Житнова доминанта одна — гончарный горн у ворот. Здесь купол носит ОДИН
/// вид (войлочное жилище), но экземпляров его в поле стойбищ ДЕСЯТКИ, и это не
/// нарушение лимита, а его прочтение по существу: лимит стоит на БЮДЖЕТЕ
/// ПОСТРОЙКИ, и он соблюдён — 12 граней на 2 яруса плюс шапка это 36 контуров,
/// ~330 треугольников, то есть тот же порядок, что у горна. Юрта в степи —
/// не доминанта силуэта, а РЯДОВОЕ жильё: доминанты Курганлы это курганы и
/// три ветряка, и ни один из них не купол.
///
/// ДВЕНАДЦАТЬ ГРАНЕЙ, А НЕ ВОСЕМЬ. Восьмигранник радиуса 3.2 даёт хорду 2.45 и
/// стрелу сегмента 0.24 м — с трёх метров это гранёная башня, а не купол; при
/// двенадцати стрела 0.11, вдвое меньше собственной толщины войлочного полога.
/// Цена — линейна и уже сосчитана выше.
///
/// ФОРМА КУПОЛА ЮРТЫ — НЕ ПОЛУСФЕРА. Настоящий купол-обод пологий: жерди
/// выходят из решётки почти горизонтально и круто загибаются только у обода.
/// Отсюда показатель степени 1.7 у синуса — верх поднимается быстрее, чем
/// радиус убывает, и силуэт получается яйцевидно-приплюснутым, каким он и есть.
inline void kur_felt_dome(Forge& f, float cx, float cz, float y0, float r0, float h,
                          const char* mat, const char* tone, const char* wear,
                          float thick) {
    constexpr int SIDES = 12;
    constexpr int TIERS = 3;
    constexpr float PI = 3.14159265358979f;
    float rad[TIERS + 1];
    float lev[TIERS + 1];
    for (int i = 0; i <= TIERS; ++i) {
        const float a = (PI * 0.5f) * static_cast<float>(i) / static_cast<float>(TIERS);
        rad[i] = r0 * std::cos(a);
        lev[i] = y0 + h * std::pow(std::sin(a), 1.7f);
    }
    const auto pt = [&](int tier, int j) {
        const float t = 2.0f * PI * static_cast<float>(j) / static_cast<float>(SIDES);
        return glm::vec3{cx + rad[tier] * std::cos(t), lev[tier],
                         cz + rad[tier] * std::sin(t)};
    };
    for (int i = 0; i < TIERS; ++i) {
        for (int j = 0; j < SIDES; ++j) {
            const glm::vec3 a = pt(i, j);
            const glm::vec3 b = pt(i, j + 1);
            ElementId id = dfn::world::NO_ELEMENT;
            if (i + 1 == TIERS) {
                id = f.contour({f.v(a.x, a.y, a.z), f.v(b.x, b.y, b.z),
                                f.v(cx, lev[TIERS], cz)},
                               {{"thickness", f.num(thick)}, {"mat", mat},
                                {"tone", tone}, {"wear", wear}});
            } else {
                const glm::vec3 c = pt(i + 1, j + 1);
                const glm::vec3 d = pt(i + 1, j);
                id = f.contour({f.v(a.x, a.y, a.z), f.v(b.x, b.y, b.z),
                                f.v(c.x, c.y, c.z), f.v(d.x, d.y, d.z)},
                               {{"thickness", f.num(thick)}, {"mat", mat},
                                {"tone", tone}, {"wear", wear}});
            }
            (void)f.g.set_param(id, "roof", "1");
            (void)f.g.set_param(id, "unsupported", "1");
        }
    }
}

/// РЕШЁТКА СТЕНЫ ВОЙЛОЧНОГО ЖИЛИЩА (§4.8: «решётка, жерди, купол-обод»).
/// Двенадцатигранный барабан: по грани — два косых прута накрест, поверху —
/// пояс-обвязка. Дверной проём (грань j==door_face) остаётся без креста: там
/// стоит косяк.
inline void kur_yurt_lattice(Forge& f, float cx, float cz, float r0, float h,
                             int door_face, const char* wear) {
    constexpr int SIDES = 12;
    constexpr float PI = 3.14159265358979f;
    const auto pt = [&](int j, float y) {
        const float t = 2.0f * PI * static_cast<float>(j) / static_cast<float>(SIDES);
        return glm::vec3{cx + r0 * std::cos(t), y, cz + r0 * std::sin(t)};
    };
    for (int j = 0; j < SIDES; ++j) {
        const glm::vec3 a0 = pt(j, 0.0f);
        const glm::vec3 b0 = pt(j + 1, 0.0f);
        const glm::vec3 a1 = pt(j, h);
        const glm::vec3 b1 = pt(j + 1, h);
        // Стойка грани и пояс поверху — они и держат тело одним островом.
        (void)f.beam(f.v(a0.x, a0.y, a0.z), f.v(a1.x, a1.y, a1.z),
                     {{"radius", "0.05"}, {"mat", "0"}, {"tone", "1"}, {"wear", wear}});
        (void)f.beam(f.v(a1.x, a1.y, a1.z), f.v(b1.x, b1.y, b1.z),
                     {{"radius", "0.055"}, {"mat", "0"}, {"tone", "1"}, {"wear", wear}});
        if (j == door_face) {
            continue;
        }
        (void)f.beam(f.v(a0.x, a0.y, a0.z), f.v(b1.x, b1.y, b1.z),
                     {{"radius", "0.032"}, {"mat", "0"}, {"tone", "1"}, {"wear", wear}});
        (void)f.beam(f.v(b0.x, b0.y, b0.z), f.v(a1.x, a1.y, a1.z),
                     {{"radius", "0.032"}, {"mat", "0"}, {"tone", "1"}, {"wear", wear}});
    }
}

/// ЖЕРДИ КУПОЛА И ОБОД — КАРКАС БЕЗ ВОЙЛОКА. Обод (шанырак) собран
/// двенадцатью хордами: замкнутое кольцо, а не окружность, и его концы
/// совпадают с концами жердей — тело связно построением.
inline void kur_yurt_ribs(Forge& f, float cx, float cz, float r0, float y0, float h,
                          float hoop_r, const char* wear) {
    constexpr int SIDES = 12;
    constexpr float PI = 3.14159265358979f;
    const float y_hoop = y0 + h;
    const auto hoop = [&](int j) {
        const float t = 2.0f * PI * static_cast<float>(j) / static_cast<float>(SIDES);
        return glm::vec3{cx + hoop_r * std::cos(t), y_hoop, cz + hoop_r * std::sin(t)};
    };
    for (int j = 0; j < SIDES; ++j) {
        const float t = 2.0f * PI * static_cast<float>(j) / static_cast<float>(SIDES);
        const glm::vec3 foot{cx + r0 * std::cos(t), y0, cz + r0 * std::sin(t)};
        const glm::vec3 head = hoop(j);
        // Жердь гнутая: два звена с изломом на двух третях — прямая жердь
        // читается шатром, а не куполом.
        const glm::vec3 mid{cx + r0 * 0.62f * std::cos(t), y0 + h * 0.72f,
                            cz + r0 * 0.62f * std::sin(t)};
        (void)f.beam(f.v(foot.x, foot.y, foot.z), f.v(mid.x, mid.y, mid.z),
                     {{"radius", "0.042"}, {"mat", "0"}, {"tone", "1"}, {"wear", wear}});
        (void)f.beam(f.v(mid.x, mid.y, mid.z), f.v(head.x, head.y, head.z),
                     {{"radius", "0.042"}, {"mat", "0"}, {"tone", "1"}, {"wear", wear}});
        const glm::vec3 nxt = hoop(j + 1);
        (void)f.beam(f.v(head.x, head.y, head.z), f.v(nxt.x, nxt.y, nxt.z),
                     {{"radius", "0.06"}, {"mat", "0"}, {"tone", "2"}, {"wear", wear}});
    }
}

/// КРУГ ВЫТОПТАННОЙ ЗЕМЛИ — ОСНОВАНИЕ ВСЯКОГО СТОЙБИЩА. Двенадцатиугольная
/// плита в 2 см над землёй: она же то, чем всякое тело стойбища остаётся ОДНИМ
/// островом (котёл, тренога, камни очага касаются её, а не друг друга).
inline void kur_trodden_ring(Forge& f, float cx, float cz, float r0, float y,
                             const char* mat, const char* tone, const char* wear) {
    constexpr int SIDES = 12;
    constexpr float PI = 3.14159265358979f;
    std::vector<VertexId> ring;
    ring.reserve(SIDES);
    for (int j = 0; j < SIDES; ++j) {
        const float t = 2.0f * PI * static_cast<float>(j) / static_cast<float>(SIDES);
        ring.push_back(f.v(cx + r0 * std::cos(t), y, cz + r0 * std::sin(t)));
    }
    const ElementId id = f.contour(std::move(ring),
                                   {{"thickness", "0.04"}, {"mat", mat},
                                    {"tone", tone}, {"wear", wear}});
    (void)f.g.set_param(id, "unsupported", "1");
}

/// КОСТРИЩЕ: венец камней и тренога с котлом (§5: «котлы на треногах»).
/// Стоит НА круге вытоптанной земли, и потому связно с ним.
inline void kur_hearth(Forge& f, float cx, float cz, float y, float r0, bool tripod,
                       const char* wear) {
    constexpr int N = 9;
    constexpr float PI = 3.14159265358979f;
    for (int j = 0; j < N; ++j) {
        const float t = 2.0f * PI * static_cast<float>(j) / static_cast<float>(N);
        const float px = cx + r0 * std::cos(t);
        const float pz = cz + r0 * std::sin(t);
        (void)f.beam(f.v(px, y - 0.02f, pz), f.v(px, y + 0.20f, pz),
                     {{"radius", "0.13"}, {"sides", "5"}, {"mat", "3"},
                      {"tone", "3"}, {"wear", wear}});
    }
    if (!tripod) {
        return;
    }
    const float top = y + 1.55f;
    for (int j = 0; j < 3; ++j) {
        const float t = 2.0f * PI * static_cast<float>(j) / 3.0f + 0.5f;
        (void)f.beam(f.v(cx + (r0 + 0.25f) * std::cos(t), y, cz + (r0 + 0.25f) * std::sin(t)),
                     f.v(cx, top, cz),
                     {{"radius", "0.05"}, {"mat", "0"}, {"tone", "2"}, {"wear", wear}});
    }
    // Котёл — восьмигранное тулово на крюке; вещество ЧУГУН, которого в
    // реестре ещё нет: сегодня это тёмный камень, и это записано вслух.
    (void)f.beam(f.v(cx, top - 0.62f, cz), f.v(cx, top - 0.14f, cz),
                 {{"radius", "0.38"}, {"sides", "8"}, {"mat", "3"}, {"tone", "2"},
                  {"wear", "0.55"}});
}

