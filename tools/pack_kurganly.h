// САМАННЫЙ ДОМ-КУБ (§4.1-4.5: откосная глинобитная стена на бутовом цоколе,
// плоская земляная кровля с парапетом и носиками, наружная лестница на
// кровлю, глухая длинная стена на подветренную сторону).
//
// ЭТО ГЛАВНОЕ ТЕЛО ГОРОДА, И ОНО ОДНО В ДВУХ РАЗМЕРАХ, А НЕ ДВА РАЗНЫХ ДОМА.
// §3 паспорта: «этажность 1, редко 1.5; длинные низкие массы». Дом, у которого
// нет ни второго этажа, ни щипца, ни ската, отличается от соседа ровно двумя
// вещами — длиной глухой стены и высотой парапета, — и городу этого хватает:
// разнобой держат посадка (поворот ±10 гр.) и то, что между дворами 4-12 м.
//
// ДВУХЭТАЖНОСТИ ЗДЕСЬ НЕТ НАМЕРЕННО, И ЭТО ДЕШЕВЛЕ, ЧЕМ КАЖЕТСЯ. Второй ярус
// у Житнова стоил клетки, проёма, обвязки и балюстрады — а у степного дома
// «второй этаж» это КРОВЛЯ: на ней живут и спят летом (§4.3). Наружный марш
// ведёт именно туда, и ходимая плоская кровля даёт городу тот же вертикальный
// объём за одну лестницу вместо четырёх тел.
// ---------------------------------------------------------------------------
inline void forge_kurganly_house(const char* file, float W, float D, float H,
                                 float par, const char* win_south,
                                 const char* win_side, const char* wear) {
    Forge f;
    const float TH = 0.55f;
    const float top = kur_batter_body(f, 0.0f, 0.0f, W, D, H, TH, "1", wear,
                                      win_south, win_side);
    // НАРУЖНОГО МАРША НА КРОВЛЮ ЗДЕСЬ НЕТ, И ЭТО ОТЛОЖЕННЫЙ ХВОСТ, А НЕ
    // ЗАБЫТЫЙ ЭЛЕМЕНТ. §4.3 паспорта просит лестницу на кровлю у КАЖДОГО
    // дома, и рука для неё написана (kur_roof_stair ниже по файлу), но
    // dfn_stairs_check отверг её замером, которого я не успел разобрать до
    // остановки разработки:
    //     e45: ПРОСТУПЬ 0.139 МЕЛЬЧЕ 0.233 — «это стремянка, а не лестница»
    // при подъёме 3.90 м, ходе 3.90 м (ровно 45 гр.) и объявленном
    // подступёнке rise=0.28, который в .dfh стоит и который у Житнова на той
    // же руке даёт проступь 0.28. Судья при этом печатает ход 4.35 — на 0.45
    // БОЛЬШЕ заказанного, и та же добавка 0.45 выходит у малого дома
    // (3.90 против 3.45). Разойтись рецепт и судья могут только в одном
    // месте, и это место названо: откуда берётся +0.45 и почему число ступеней
    // выходит вдвое против round(подъём/0.28) = 14.
    // ПОКА ЭТО НЕ ИЗМЕРЕНО, ЛЕСТНИЦЫ НЕТ ВОВСЕ. Оставить непроходимый марш
    // «до выяснения» значило бы сдать боевую находку судьи как норму — а
    // порог рук 6 и 8 стоит на нуле (HOUSES.md §9.7). Кровля остаётся
    // ходимой по устройству и замкнутой парапетом; вход на неё — заказ
    // этапа 2 вместе с разбором этих 0.45 м.
    const float walk = kur_roof(f, 0.0f, 0.0f, W, D, top, 0.35f, par,
                                1.0f, 0.0f, "1", wear);
    // КОШМЫ И КОВРЫ НА ОГРАДЕ ПАРАПЕТА (§5, первая строка списка декора):
    // два полотнища, свешенные с южного парапета. Вещество — ВОЙЛОК, у
    // которого своей колонки листа нет; сегодня это mat=5/tone=0 (см. шапку).
    for (const float u : {0.28f, 0.66f}) {
        const float x = W * u;
        (void)f.contour({f.v(x - 0.55f, walk + par - 0.06f, D + 0.36f),
                         f.v(x + 0.55f, walk + par - 0.06f, D + 0.36f),
                         f.v(x + 0.55f, walk + par - 0.95f, D + 0.42f),
                         f.v(x - 0.55f, walk + par - 0.95f, D + 0.42f)},
                        {{"thickness", "0.03"}, {"mat", "5"}, {"tone", "0"},
                         {"paint", "3"}, {"wear", "0.5"}});
    }
    f.save(file);
}

// ---------------------------------------------------------------------------
// ВОЙЛОЧНОЕ ЖИЛИЩЕ — ОДИН РЕЦЕПТ В ТРЁХ СОСТОЯНИЯХ (§4.8: «ставится и
// снимается — сезонная застройка, один рецепт в двух состояниях: собран /
// только каркас / только круг на земле»).
//
// СОСТОЯНИЙ ТРИ, А НЕ ДВА, И ТРЕТЬЕ ПРИШЛО ИЗ ЛОР-РЕВЮ 28.08, А НЕ ИЗ ФОРМЫ.
// Сшивка (2): Тузлань рядом, Курганлы — тыл и ремонт армии, и поверх двух
// СЕЗОННЫХ состояний ложится третье — ВОЕННЫЙ ЛАГЕРЬ: «тот же круг-кострище
// плюс коновязи ремонтёров и армейские котлы, отдельных военных карт НЕ надо».
// Здесь, в кузнице, третье состояние — это ЧЕТВЁРТЫЙ рецепт (коновязь), а не
// четвёртая юрта: разница между сезоном и лагерем не в жилище, а в том, ЧТО
// СТОИТ РЯДОМ. Кто из трёх наборов выходит на карту, решает чертёж
// (tools/gen_kurganly_plan.py, ключ --state), и это правильное место: одна
// карта в трёх состояниях — вопрос посадки, а не выпечки.
//
// ДВЕРЬ У ЮРТЫ — НА ЮГ, КАК И У ВСЕЙ ПОЛКИ, и на этот раз совпадение не
// формальное: вход степного жилища ВСЕГДА обращён на юг (ветер с севера, свет
// с юга), и полка требует того же самого.
// ---------------------------------------------------------------------------
inline void forge_kurganly_yurt(const char* file) {
    Forge f;
    const float R = 3.15f;                 // радиус решётки
    const float WALL = 1.62f;              // высота решётки
    const float DOME = 1.55f;              // подъём купола над решёткой
    const float CX = R;
    const float CZ = R;
    // Круг вытоптанной земли под юртой — он же связывает подошву в одно тело.
    kur_trodden_ring(f, CX, CZ, R + 0.55f, 0.02f, "5", "1", "0.75");
    kur_yurt_lattice(f, CX, CZ, R, WALL, 3, "0.5");
    kur_yurt_ribs(f, CX, CZ, R, WALL, DOME, 0.62f, "0.5");
    // ВОЙЛОЧНЫЙ ПОЛОГ СТЕНЫ: двенадцать полотнищ по граням решётки, каждое
    // толщиной 8 см — кошма это не плёнка, у неё есть тело, и с двух метров
    // видно, что она провисает между жердями.
    {
        constexpr int SIDES = 12;
        constexpr float PI = 3.14159265358979f;
        for (int j = 0; j < SIDES; ++j) {
            const float t0 = 2.0f * PI * static_cast<float>(j) / SIDES;
            const float t1 = 2.0f * PI * static_cast<float>(j + 1) / SIDES;
            const float rr = R + 0.06f;
            const ElementId id =
                f.wall(f.v(CX + rr * std::cos(t0), 0.0f, CZ + rr * std::sin(t0)),
                       f.v(CX + rr * std::cos(t1), 0.0f, CZ + rr * std::sin(t1)),
                       {{"height", f.num(WALL)}, {"thickness", "0.08"},
                        {"mat", "5"}, {"tone", "0"}, {"wear", "0.55"}});
            if (j == 3) {
                (void)f.g.set_param(id, "doors", "1");
            }
        }
    }
    // Войлок купола — тот же веер, что несут жерди, на 6 см выше их.
    kur_felt_dome(f, CX, CZ, WALL + 0.06f, R + 0.06f, DOME, "5", "0", "0.55", 0.08f);
    // ОБОД-ШАНЫРАК ОСТАЁТСЯ ОТКРЫТЫМ: дым очага уходит в него, и это
    // единственное «окно» жилища. Веер купола идёт до макушки и накрыл бы
    // его, поэтому обод стоит ПОВЕРХ — кольцо привозного дерева на 12 хорд.
    {
        constexpr int SIDES = 12;
        constexpr float PI = 3.14159265358979f;
        const float y = WALL + DOME + 0.10f;
        for (int j = 0; j < SIDES; ++j) {
            const float t0 = 2.0f * PI * static_cast<float>(j) / SIDES;
            const float t1 = 2.0f * PI * static_cast<float>(j + 1) / SIDES;
            (void)f.beam(f.v(CX + 0.62f * std::cos(t0), y, CZ + 0.62f * std::sin(t0)),
                         f.v(CX + 0.62f * std::cos(t1), y, CZ + 0.62f * std::sin(t1)),
                         {{"radius", "0.07"}, {"mat", "0"}, {"tone", "2"},
                          {"wear", "0.55"}});
        }
    }
    // Дверь-створка в южной грани: косяк из привозного дерева и полотнище.
    f.door_leaf(CX, 0.0f, CZ + R + 0.10f);
    // АРКАН И ТЮК НА ЖЕРДИ У ВХОДА (§5): две строки декора, которые видно с
    // двух метров и по которым жилое стойбище отличается от пустого.
    // ШЕСТ СТОИТ НА КРУГЕ ВЫТОПТАННОЙ ЗЕМЛИ, А НЕ ЗА НИМ, и это не мелочь:
    // круг — единственное, чем подошва стойбища держится ОДНИМ телом, и
    // первый заход поставил шест в 4.10 м от середины при круге 3.70 —
    // судья связности намерил ровно этот зазор, 0.39 м.
    const float AX = CX + 1.85f;
    const float AZ = CZ + 2.95f;
    (void)f.beam(f.v(AX, 0.0f, AZ), f.v(AX, 1.85f, AZ),
                 {{"radius", "0.06"}, {"mat", "0"}, {"tone", "2"}, {"wear", "0.6"}});
    (void)f.beam(f.v(AX, 1.72f, AZ), f.v(AX + 1.10f, 1.72f, AZ),
                 {{"radius", "0.05"}, {"mat", "0"}, {"tone", "2"}, {"wear", "0.6"}});
    (void)f.beam(f.v(AX + 0.75f, 1.30f, AZ), f.v(AX + 0.75f, 1.68f, AZ),
                 {{"radius", "0.22"}, {"sides", "8"}, {"mat", "5"}, {"tone", "0"},
                  {"paint", "3"}, {"wear", "0.5"}});
    f.save(file);
}

