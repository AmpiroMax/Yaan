// ВЕТРОВОЙ ЗАСЛОН — ПЛЕТНЁВО-ГЛИНЯНАЯ СТЕНКА 2 м, СТОЯЩАЯ ОТДЕЛЬНО
// (§4.6: «перед каждыми воротами и вдоль прогонов»).
//
// ОТДЕЛЬНО СТОЯЩАЯ СТЕНКА — ЭТО ФОРМА, КОТОРОЙ У ПОЛКИ НЕ БЫЛО. Всё, что
// умеет полка, — это стена ДОМА и кольцо ГОРОДА; заслон не то и не другое:
// он ничего не огораживает и никуда не ведёт, он ЛОМАЕТ ВЕТЕР, и потому
// стоит поперёк него куском в шесть метров, а не кольцом.
//
// ОН ЖЕ — ЗАГОТОВКА ПОД ПАЛИСАД (лор-ревью, сшивка 3): «после поражения
// города ветровые заслоны становятся палисадами — оверлей декора, не карта».
// То есть тело у обоих одно, и разница придёт кольями поверх, а не вторым
// рецептом. Записано здесь, чтобы волна войны это нашла.
// ---------------------------------------------------------------------------
inline void forge_kurganly_windbreak(const char* file) {
    Forge f;
    const float L = 6.0f;
    const float H = 2.0f;
    kur_wattle(f, 0.0f, 0.0f, L, 0.0f, H, /*daubed=*/true, "0.7");
    // ПОДКОСЫ С ПОДВЕТРЕННОЙ СТОРОНЫ: стенка в два метра без опор ложится от
    // первой же позёмки, и в степи её всегда подпирают. Они же — то, чем
    // заслон читается заслоном, а не куском забора.
    for (const float x : {L * 0.2f, L * 0.5f, L * 0.8f}) {
        (void)f.beam(f.v(x, H - 0.35f, 0.0f), f.v(x, 0.0f, 1.15f),
                     {{"radius", "0.07"}, {"mat", "0"}, {"tone", "2"}, {"wear", "0.72"}});
    }
    // Присыпка подошвы глиной — та же присыпка, что у дома.
    (void)f.wall(f.v(-0.10f, 0.0f, 0.0f), f.v(L + 0.10f, 0.0f, 0.0f),
                 {{"height", "0.34"}, {"thickness", "0.52"}, {"mat", "5"},
                  {"tone", "1"}, {"wear", "0.75"}});
    f.save(file);
}

// ---------------------------------------------------------------------------
// СОЛЯНАЯ ВАРНИЦА (§4.13-4.14: «плоские выпарные карты с бортиками и
// мостками» на берегу солёного озера; район назван лор-ревю — «Белое поле»).
//
// ВАРНИЦА — ЭТО НЕ ДОМ, А НАВЕС НАД ЧЕТЫРЬМЯ КАРТАМИ. Стен у неё три четверти
// нет по делу: рассол выпаривают на воздухе, а кровля нужна только затем,
// чтобы дождь не разбавил садку. Отсюда форма: восемь столбов, плоская
// тростниковая кровля на них и МОСТКИ между картами — единственное, по чему
// здесь ходят.
//
// ВЕЩЕСТВО КАРТ — СОЛЬ (соляная корка), и своей записи в реестре у неё пока
// нет: сегодня это mat=5/tone=0, самый светлый ряд глины. Названо тут, чтобы
// волна веществ нашла место, где садка отличается от побелки.
// ---------------------------------------------------------------------------
inline void forge_kurganly_saltworks(const char* file) {
    Forge f;
    const float W = 9.2f;
    const float D = 7.0f;
    const float H = 2.65f;
    // ЧЕТЫРЕ ВЫПАРНЫЕ КАРТЫ: плоские чаши с бортиком в ладонь. Карта — это
    // геометрия, а не пятно на земле: бортик держит рассол, и он же
    // единственное, что видно с двадцати метров.
    for (int i = 0; i < 2; ++i) {
        for (int k = 0; k < 2; ++k) {
            const float x0 = 0.55f + static_cast<float>(i) * 4.4f;
            const float z0 = 0.55f + static_cast<float>(k) * 3.3f;
            const float x1 = x0 + 3.5f;
            const float z1 = z0 + 2.4f;
            (void)kur_slab(f, x0, z0, x1, z1, 0.08f, 0.16f, "5", "0", "0.5");
            const auto rim = [&](float ax, float az, float bx, float bz) {
                (void)f.wall(f.v(ax, 0.02f, az), f.v(bx, 0.02f, bz),
                             {{"height", "0.30"}, {"thickness", "0.18"},
                              {"mat", "5"}, {"tone", "0"}, {"wear", "0.55"}});
            };
            rim(x1, z0, x0, z0);
            rim(x1, z1, x1, z0);
            rim(x0, z0, x0, z1);
            rim(x0, z1, x1, z1);
        }
    }
    // МОСТКИ — крест из досок между картами: по ним ходит солевар с лопатой,
    // и они же связывают четыре карты в одно тело.
    (void)kur_slab(f, 0.0f, 3.05f, W, 3.45f, 0.24f, 0.10f, "0", "1", "0.7");
    (void)kur_slab(f, 4.35f, 0.0f, 4.85f, D, 0.24f, 0.10f, "0", "1", "0.7");
    // Восемь столбов навеса и обвязка поверху.
    const float px[4] = {0.30f, 4.60f, 4.60f, W - 0.30f};
    for (const float x : {0.30f, 4.60f, W - 0.30f}) {
        for (const float z : {0.30f, D - 0.30f}) {
            (void)f.beam(f.v(x, 0.10f, z), f.v(x, H, z),
                         {{"radius", "0.13"}, {"mat", "0"}, {"tone", "2"},
                          {"wear", "0.68"}});
        }
    }
    (void)px;
    for (const float z : {0.30f, D - 0.30f}) {
        (void)f.beam(f.v(0.18f, H - 0.10f, z), f.v(W - 0.18f, H - 0.10f, z),
                     {{"radius", "0.10"}, {"form", "square"}, {"mat", "0"},
                      {"tone", "2"}, {"wear", "0.68"}});
    }
    for (const float x : {0.30f, 4.60f, W - 0.30f}) {
        (void)f.beam(f.v(x, H - 0.10f, 0.18f), f.v(x, H - 0.10f, D - 0.18f),
                     {{"radius", "0.09"}, {"form", "square"}, {"mat", "0"},
                      {"tone", "2"}, {"wear", "0.68"}});
    }
    // ТРОСТНИКОВАЯ КРОВЛЯ ПЛОСКАЯ, КАК И ВСЯ КРОВЛЯ ГОРОДА: щипца нет ни у
    // одного тела пакета (§3).
    {
        const ElementId id = kur_slab(f, -0.45f, -0.45f, W + 0.45f, D + 0.45f,
                                      H + 0.06f, 0.26f, "6", "0", "0.62");
        (void)f.g.set_param(id, "roof", "1");
        (void)f.g.set_param(id, "unsupported", "1");
    }
    // СОЛЯНАЯ КУЧА ПОД НАВЕСОМ (§5: «соляные кучи под навесами») и лопата
    // солевара: две строки, по которым варница читается работающей.
    (void)f.beam(f.v(2.4f, 0.24f, 3.25f), f.v(2.4f, 1.05f, 3.25f),
                 {{"radius", "0.85"}, {"sides", "7"}, {"mat", "5"}, {"tone", "0"},
                  {"wear", "0.35"}});
    (void)f.beam(f.v(6.9f, 0.20f, 3.25f), f.v(7.35f, 1.75f, 3.05f),
                 {{"radius", "0.05"}, {"mat", "0"}, {"tone", "1"}, {"wear", "0.6"}});
    f.save(file);
}

// ---------------------------------------------------------------------------
// РАСКОЛ-ВОРОНКА С ВЕСАМИ (§4.15: «скотный баз — жердевые загоны с расколом-
// воронкой и весами, всё восточное поле»; район назван лор-ревю — «Раскол»).
//
// ВОРОНКА — ЭТО ЕДИНСТВЕННАЯ КРИВАЯ ЛИНИЯ ГОРОДА, И ОНА ФУНКЦИОНАЛЬНА.
// Гурт гонят широким фронтом, а через весы он обязан идти по одному; воронка
// сводит четырнадцать метров к девяноста сантиметрам на длине в двенадцать,
// и это ровно та форма, которую и в жизни строят из жердей. Она же — «сцена
// торга» (лор-ревью: Курганлы — каноническое место покупки коня).
//
// ЖЕРДИ, А НЕ ПЛЕТЕНЬ: загон должен ПРОСВЕЧИВАТЬ — гуртовщик видит скот
// сквозь него. Поэтому здесь kur_wattle зовётся БЕЗ обмазки, и это тот же
// рецепт в другом состоянии, а не второе тело.
// ---------------------------------------------------------------------------
inline void forge_kurganly_chute(const char* file) {
    Forge f;
    const float MOUTH = 7.0f;              // полуширина устья воронки
    const float NECK = 0.45f;              // полуширина горловины
    const float LEN = 12.0f;
    constexpr int SEG = 6;
    // Две сходящиеся стенки из жердей, ломаными по шесть звеньев.
    for (const float s : {-1.0f, 1.0f}) {
        for (int k = 0; k < SEG; ++k) {
            const float t0 = static_cast<float>(k) / SEG;
            const float t1 = static_cast<float>(k + 1) / SEG;
            const float w0 = MOUTH + (NECK - MOUTH) * t0 * t0;
            const float w1 = MOUTH + (NECK - MOUTH) * t1 * t1;
            kur_wattle(f, MOUTH + s * w0, LEN * t0, MOUTH + s * w1, LEN * t1,
                       1.45f, /*daubed=*/false, "0.72");
        }
    }
    // ВЕСЫ В ГОРЛОВИНЕ: помост на четырёх стойках, коромысло и гиря. Помост
    // ВРОВЕНЬ С ЗЕМЛЁЙ — скот на ступеньку не идёт, и в жизни его загоняют на
    // платформу, утопленную заподлицо.
    const float nx = MOUTH;
    const float nz = LEN + 1.35f;
    // ПОМОСТ ДОВЕДЁН ДО ГОРЛОВИНЫ: он единственное, что сводит ДВЕ стенки
    // воронки в одно тело — они сходятся, но не смыкаются (0.9 м в свету), и
    // первый заход развалился на шесть островов ровно по этой линии.
    (void)kur_slab(f, nx - 0.85f, LEN - 0.20f, nx + 0.85f, nz + 1.25f, 0.10f, 0.16f,
                   "0", "1", "0.7");
    for (const float sx : {-0.85f, 0.85f}) {
        (void)f.beam(f.v(nx + sx, 0.0f, nz - 1.25f), f.v(nx + sx, 2.55f, nz - 1.25f),
                     {{"radius", "0.10"}, {"mat", "0"}, {"tone", "2"}, {"wear", "0.7"}});
        (void)f.beam(f.v(nx + sx, 0.0f, nz + 1.25f), f.v(nx + sx, 2.55f, nz + 1.25f),
                     {{"radius", "0.10"}, {"mat", "0"}, {"tone", "2"}, {"wear", "0.7"}});
        (void)f.beam(f.v(nx + sx, 2.48f, nz - 1.25f), f.v(nx + sx, 2.48f, nz + 1.25f),
                     {{"radius", "0.08"}, {"form", "square"}, {"mat", "0"},
                      {"tone", "2"}, {"wear", "0.7"}});
    }
    // Поперечина поверху между стойками: без неё вся оснастка весов
    // (коромысло, серьга, цепь, гиря) висела отдельным островом.
    (void)f.beam(f.v(nx - 0.85f, 2.48f, nz), f.v(nx + 0.85f, 2.48f, nz),
                 {{"radius", "0.08"}, {"form", "square"}, {"mat", "0"},
                  {"tone", "2"}, {"wear", "0.7"}});
    // Коромысло поперёк и гиря на цепи — то, по чему весы узнаются издалека.
    (void)f.beam(f.v(nx - 1.35f, 2.72f, nz), f.v(nx + 1.35f, 2.72f, nz),
                 {{"radius", "0.07"}, {"form", "square"}, {"mat", "0"},
                  {"tone", "2"}, {"wear", "0.65"}});
    (void)f.beam(f.v(nx, 2.44f, nz), f.v(nx, 2.76f, nz),
                 {{"radius", "0.09"}, {"mat", "0"}, {"tone", "2"}, {"wear", "0.65"}});
    (void)f.beam(f.v(nx + 1.28f, 2.12f, nz), f.v(nx + 1.28f, 2.70f, nz),
                 {{"radius", "0.028"}, {"mat", "3"}, {"tone", "2"}, {"wear", "0.6"}});
    (void)f.beam(f.v(nx + 1.28f, 1.86f, nz), f.v(nx + 1.28f, 2.16f, nz),
                 {{"radius", "0.19"}, {"sides", "6"}, {"mat", "3"}, {"tone", "2"},
                  {"wear", "0.6"}});
    // ЧЕРЕПА СКОТА НА СТОЛБАХ УСТЬЯ (§5): две приметы база, видные с прогона.
    for (const float s : {-1.0f, 1.0f}) {
        // Столб стоит НА КРАЙНЕМ КОЛЕ устья, а не рядом с ним: вынесенный на
        // 0.35 м в сторону, он оставался островом (зазор 0.26-0.31 м).
        const float x = MOUTH + s * MOUTH;
        (void)f.beam(f.v(x, 0.0f, 0.0f), f.v(x, 2.05f, 0.0f),
                     {{"radius", "0.09"}, {"mat", "0"}, {"tone", "2"}, {"wear", "0.75"}});
        (void)f.beam(f.v(x, 1.86f, 0.0f), f.v(x, 2.14f, 0.0f),
                     {{"radius", "0.20"}, {"sides", "6"}, {"mat", "3"}, {"tone", "0"},
                      {"wear", "0.4"}});
    }
    f.save(file);
}

