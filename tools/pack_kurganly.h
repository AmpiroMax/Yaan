// КАМЕННАЯ БАБА НА ВЕРШИНЕ КУРГАНА (§4.10: «вокруг города, семь штук»;
// лор-ревью: курганов РОВНО СЕМЬ — лорная константа).
//
// ИЗВАЯНИЕ, А НЕ СТОЛБ, И РАЗЛИЧАЕТ ИХ ОДНА ЛИНИЯ — ПЛЕЧИ. Каменная баба
// узнаётся силуэтом: широкий плоский корпус, покатые плечи, шаровидная
// голова, руки сложены на животе. Всё это четыре тела, и больше не нужно:
// с двадцати метров, откуда её и видят, различима только линия плеч.
//
// «БЕЗЫМЯННЫЕ МЁРТВЫЕ» (лор-ревью): у Старшей Бабы стоит ещё варденский
// столб-часовенка, никем не опрокинутый, — но он ОБЩЕГОРОДСКОЕ тело, а не
// часть бабы, и ставит его чертёж.
// ---------------------------------------------------------------------------
inline void forge_kurganly_baba(const char* file) {
    Forge f;
    const float CX = 0.9f;
    const float CZ = 0.55f;
    // Подошва — вкопанная плита песчаника.
    (void)kur_slab(f, 0.0f, 0.0f, 1.8f, 1.1f, 0.06f, 0.18f, "3", "3", "0.8");
    // Корпус: плоский шестигранный столб, сужающийся книзу.
    (void)f.beam(f.v(CX, 0.10f, CZ), f.v(CX, 1.62f, CZ),
                 {{"radius", "0.36"}, {"sides", "6"}, {"mat", "3"}, {"tone", "0"},
                  {"wear", "0.8"}});
    // Плечи: короткая перемычка поперёк — та самая линия, по которой её узнают.
    (void)f.beam(f.v(CX - 0.44f, 1.58f, CZ), f.v(CX + 0.44f, 1.58f, CZ),
                 {{"radius", "0.20"}, {"sides", "6"}, {"mat", "3"}, {"tone", "0"},
                  {"wear", "0.8"}});
    // Голова.
    (void)f.beam(f.v(CX, 1.66f, CZ), f.v(CX, 2.06f, CZ),
                 {{"radius", "0.24"}, {"sides", "6"}, {"mat", "3"}, {"tone", "0"},
                  {"wear", "0.8"}});
    // Руки на животе: две коротких наклонных.
    for (const float s : {-1.0f, 1.0f}) {
        (void)f.beam(f.v(CX + s * 0.30f, 1.30f, CZ - 0.30f),
                     f.v(CX + s * 0.05f, 1.02f, CZ - 0.32f),
                     {{"radius", "0.075"}, {"mat", "3"}, {"tone", "0"}, {"wear", "0.8"}});
    }
    f.save(file);
}

