// 13. ОГОНЬ В ОЧАГЕ furn-fire, пятно 0.600 x 0.600 (замер меша). Ставится В
//     ЛОТОК очага: у furn-hearth под золы лежит на 0.20 и занимает 1.0 x 1.0
//     внутри бортика (0.20..1.20), то есть предмет садится в (0.40, 0.20, 0.40)
//     местных координат очага и оставляет по 0.20 зазора с каждой стороны.
//     Дрова — ЧЕТЫРЕ ПОЛЕНА КРЕСТ-НАКРЕСТ, а не аккуратный сруб: обугленное
//     дерево (краска-дёготь) под пламенем и есть то, что говорит «горит», а не
//     «светится». Износа у них НОЛЬ — см. разбор зелёной лужи выше.
// ---------------------------------------------------------------------------
void forge_fire() {
    Forge f;
    const float cx = 0.30f;
    const float cz = 0.30f;

    // Четыре полена крест-накрест, два нижних и два верхних.
    const float logs[4][3] = {{0.0f, 0.055f, 0.30f}, {1.5707963f, 0.055f, 0.30f},
                              {0.7853982f, 0.145f, 0.26f}, {2.3561945f, 0.145f, 0.26f}};
    for (const auto& L : logs) {
        const float a = L[0];
        const float y = L[1];
        const float half = L[2];
        f.bar({cx - half * std::cos(a), y, cz - half * std::sin(a)},
              {cx + half * std::cos(a), y, cz + half * std::sin(a)},
              0.055f, "0", "2", "round", {{"paint", "6"}});
    }
    ember_bed(f, cx, cz, 0.06f, 0.26f);
    flame_cluster(f, cx, cz, 0.16f, 0.62f, 0.19f);

    f.save("assets/houses/furn-fire.dfh");
}

