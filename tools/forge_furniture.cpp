// 3. КРОВАТЬ 1.15 (Х) x 2.08 (Z): рама на четырёх столбиках, дощатый настил,
//    изголовье-щит с навершиями (каталог §9: односпальная 1.9x0.85, рама
//    0.4, спинки со столбиками 0.9 и пирамидными навершиями).
//
//    ЧИСЛА ПЕРЕСЧИТАНЫ ПО РОСТУ ГЕРОЯ (крит владельца 28.08 «мебель не по
//    размеру с героем, она маленькая»), и здесь это была НЕ придирка к виду,
//    а замер: чистый настил между столбиками составлял 0.82 x 1.82 м при
//    PLAYER_CAPSULE_HEIGHT 1.80 — то есть герой на своей кровати НЕ ПОМЕЩАЛСЯ
//    (2 см в головах и ногах вместе), а верх настила стоял на 0.40 при
//    человеческой отметке лежака 0.50. Каталожная «односпальная 1.9x0.85»
//    описывает НАТУРУ, снятую глазом с картинки (§9 объявляет погрешность
//    ±15 %), и меркой герою она быть не может: мерка — сам герой.
//    Стало: чистый настил 0.97 x 1.90, верх настила 0.50, изголовье 1.10.
//    ДЛИНА ЗАЖАТА НЕ ВКУСОМ, А РАСКЛАДКОЙ: спальные ряды верхних ярусов
//    Корнхолла идут шагом 2.10 м по z (FURN_UPPER), и замер прибором
//    наложений даёт при габарите 2.05 те же 13 наложений, что и до правки,
//    а при 2.20 — 62 в 25 локациях. 2.08 в чертеже — это ровно 2.05 в
//    замере: ножной столбик кончается на L - in + radius.
// ---------------------------------------------------------------------------
void forge_bed(const char* file) {
    Forge f;
    const float W = 1.15f;  // ширина, восток-запад (плечи 0.45 + постель)
    const float L = 2.08f;  // длина, север-юг; изголовье на севере (z=0)
    // Отступ столбика от кромки — 0.09, а не 0.06: навершие-шайба 0.18 иначе
    // свешивается за габарит, и предмет, поставленный вплотную к стене,
    // въезжает в неё углом.
    const float in = 0.09f;
    const float DECK = 0.50f;          // ВЕРХ НАСТИЛА — человеческая отметка
    const float y_rail = DECK - 0.06f; // царга рамы держит настил снизу
    const float y_head = 1.10f;  // верх изголовья
    const float y_foot = 0.65f;  // верх ножного столбика

    const float xs[2] = {in, W - in};
    // Столбики: изголовные выше, ножные ниже — так кровать «смотрит» в комнату.
    for (const float x : xs) {
        f.bar({x, 0.0f, in}, {x, y_head, in}, 0.06f, "0", "2");
        f.bar({x, 0.0f, L - in}, {x, y_foot, L - in}, 0.06f, "0", "2");
    }
    // Рама: четыре царги по периметру на 0.34.
    f.bar({xs[0], y_rail, in}, {xs[1], y_rail, in}, 0.05f, "0", "2");
    f.bar({xs[0], y_rail, L - in}, {xs[1], y_rail, L - in}, 0.05f, "0", "2");
    f.bar({xs[0], y_rail, in}, {xs[0], y_rail, L - in}, 0.05f, "0", "2");
    f.bar({xs[1], y_rail, in}, {xs[1], y_rail, L - in}, 0.05f, "0", "2");
    // НАСТИЛ-ДОСКИ: плита с раскладкой досок (fill=5), лежит на царгах.
    f.slab(in, in, W - in, L - in, DECK, 0.06f, "1", "1",
           {{"fill", "5"}, {"wear", "0.3"}});
    // Изголовье — щит между высокими столбиками; изножье — низкая доска.
    f.panel({in, y_rail + 0.14f, in}, {W - in, y_rail + 0.14f, in}, y_head - 0.06f,
            0.05f, "1", "2");
    f.panel({in, y_rail + 0.14f, L - in}, {W - in, y_rail + 0.14f, L - in},
            y_foot - 0.06f, 0.05f, "1", "2");
    // Навершия столбиков изголовья — плоские шайбы 0.18 (каталог §7).
    for (const float x : xs) {
        f.slab(x - 0.09f, in - 0.09f, x + 0.09f, in + 0.09f, y_head + 0.04f, 0.05f,
               "0", "2");
    }

    f.save(file);
}

