//     красит загрузчик города; своего механизма цвета здесь не заводится.
//     Материал словами: мех, шкура.
// ---------------------------------------------------------------------------
void forge_hide(const char* file) {
    Forge f;
    // Обход ПО УБЫВАНИЮ угла (лицо вверх, правило disc8). Точки сняты как
    // «туловище + четыре лапы + голова + хвост» в пятне 1.70 x 1.25.
    const float y = 0.010f;
    const std::vector<std::pair<float, float>> outline = {
        {0.85f, 0.02f},  // голова
        {0.35f, 0.13f}, {0.06f, 0.05f}, {0.16f, 0.42f},  // левая передняя лапа
        {0.02f, 0.62f},
        {0.16f, 0.83f}, {0.05f, 1.20f}, {0.40f, 1.12f},  // левая задняя
        {0.85f, 1.23f},                                   // хвост
        {1.30f, 1.12f}, {1.65f, 1.20f}, {1.54f, 0.83f},  // правая задняя
        {1.68f, 0.62f},
        {1.54f, 0.42f}, {1.64f, 0.05f}, {1.35f, 0.13f},  // правая передняя
    };
    std::vector<VertexId> ring;
    ring.reserve(outline.size());
    for (auto it = outline.rbegin(); it != outline.rend(); ++it) {
        ring.push_back(f.v(it->first, y, it->second));
    }
    (void)f.contour(std::move(ring), {{"thickness", "0.020"}, {"mat", "6"},
                                      {"tone", "0"}, {"paint", "1"}});

    f.save(file);
}

