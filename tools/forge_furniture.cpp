// 25. КОТЁЛ НА ТРЕНОГЕ, пятно 1.10 x 1.10, верх треноги 1.20 (8 скринов из
//     19; на пяти из них он стоит РОВНО В ЦЕНТРЕ комнаты над очажной ямой —
//     это композиционный центр нордского дома, а не мелочь стола).
//     ТРЕНОГА ШИРЕ КОТЛА ПО ПОСТРОЕНИЮ, и это считано, а не подогнано на
//     глаз: ноги идут от радиуса 0.52 у пола к вершине, на высоте венца котла
//     (0.58) они стоят на радиусе 0.52*(1-0.58/1.20) = 0.269, а венец
//     кончается на 0.24 — просвет 0.03. Котёл, сквозь который проходят ноги
//     собственной треноги, — первое, что видно на кадре.
//     Материал словами: чугун (котёл), жердь (ноги), крюк — железо.
// ---------------------------------------------------------------------------
void forge_cauldron(const char* file) {
    Forge f;
    const float S = 1.10f;
    const float c = S * 0.5f;
    const float apex = 1.20f;
    const float spread = 0.52f;

    // Три жерди. Углы 90/210/330 — ноги не сходятся с осями пятна, и предмет
    // читается треногой с любой стороны.
    for (const float deg : {90.0f, 210.0f, 330.0f}) {
        const float t = deg * 0.01745329252f;
        f.bar({c + spread * std::cos(t), 0.0f, c + spread * std::sin(t)},
              {c, apex, c}, 0.024f, "0", "2");
    }
    // Крюк от вершины в котёл: без него котёл висит сам по себе, а судья
    // связности такой предмет не пропустит вовсе.
    f.bar({c, 0.52f, c}, {c, apex - 0.02f, c}, 0.011f, "3", "2", "square",
          {{"paint", "6"}});
    // Тулово стопкой барабанов: дно 0.13 -> пузо 0.24 -> венец 0.24, губа
    // 0.26 напуском. Разница соседних радиусов 2-3 см — завал читается
    // скруглением (довод у drum()).
    // КРАСКА 6 (ДЁГОТЬ) НА ЧУГУНЕ — И ЭТО ТОЖЕ ЗАМЕР. Первая выпечка шла голым
    // камнем тёмного ряда, и на кадре стенда котёл читался КАМЕННОЙ СТУПОЙ:
    // тёмный ряд атласа камня светлее закопчённого чугуна на целую ступень.
    // Краска — тот же слой отделки, что у бордюра и ковра; колонки металла у
    // набора нет, и она названа в отчёте отдельной строкой задания.
    const Params iron = {{"paint", "6"}};
    f.drum(c, c, 0.130f, 0.20f, 0.28f, 10, "3", "2", iron);
    f.drum(c, c, 0.195f, 0.28f, 0.38f, 10, "3", "2", iron);
    f.drum(c, c, 0.235f, 0.38f, 0.54f, 10, "3", "2", iron);
    f.drum(c, c, 0.215f, 0.54f, 0.58f, 10, "3", "2", iron);
    f.disc_n(c, c, 0.255f, 0.60f, 0.035f, 10, "3", "2", iron);
    // Три ножки котла: он стоит и без треноги, если поставить его на пол.
    for (const float deg : {30.0f, 150.0f, 270.0f}) {
        const float t = deg * 0.01745329252f;
        f.bar({c + 0.10f * std::cos(t), 0.0f, c + 0.10f * std::sin(t)},
              {c + 0.12f * std::cos(t), 0.24f, c + 0.12f * std::sin(t)},
              0.016f, "3", "2", "square", iron);
    }

    f.save(file);
}

