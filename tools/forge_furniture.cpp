// 34. КАНДЕЛЯБР НА ТРИ СВЕЧИ, пятно 0.26, верх пламени 0.51 (свеча видна на
//     15 скринах из 19 — вровень с посудой; в кадре она стоит на столе, на
//     полке и на каминной доске).
//     ПЛАМЯ — glow=1, тот же признак, каким светятся очаг и фонарь: кусок
//     уходит в эмиссивный поток и виден с любого удаления. Точку света
//     рецепт НЕ объявляет — светом интерьера занята своя волна, и второй
//     источник в комнате был бы спором двух рук об одной освещённости.
//     Материал словами: железо (стан), воск (свечи), пламя.
// ---------------------------------------------------------------------------
void forge_candlestick(const char* file) {
    Forge f;
    const float S = 0.26f;
    const float c = S * 0.5f;

    f.disc_n(c, c, 0.090f, 0.022f, 0.022f, 8, "3", "2");
    f.bar({c, 0.02f, c}, {c, 0.30f, c}, 0.016f, "3", "2", "square");
    // Средняя свеча на стане, две боковые на коромыслах.
    struct Arm { float dx; float dz; float y_cup; };
    const Arm arms[3] = {{0.0f, 0.0f, 0.30f}, {-0.095f, 0.0f, 0.235f},
                         {0.095f, 0.0f, 0.235f}};
    for (const Arm& a : arms) {
        if (a.dx != 0.0f) {
            f.bar({c, 0.255f, c}, {c + a.dx, a.y_cup, c + a.dz}, 0.012f, "3", "2", "square");
        }
        const float x = c + a.dx;
        const float z = c + a.dz;
        f.disc_n(x, z, 0.036f, a.y_cup + 0.018f, 0.018f, 8, "3", "2");  // розетка
        const float wick = a.y_cup + 0.018f;
        const float tall = a.dx == 0.0f ? 0.145f : 0.115f;
        f.drum(x, z, 0.019f, wick, wick + tall, 8, "5", "0");           // свеча
        f.drum(x, z, 0.011f, wick + tall, wick + tall + 0.045f, 6, "5", "0",
               {{"glow", "1"}});                                       // пламя
    }

    f.save(file);
}

