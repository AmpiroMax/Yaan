// ---------------------------------------------------------------------------
// 15. ГОРН furn-forge-hearth: каменная тумба с топкой, углями и пламенем,
//     над ней вытяжной колпак на двух стойках и дымовой стояк.
//     БЕЗ КОЛПАКА ГОРН — ЭТО ПРОСТО ОЧАГ НА НОЖКАХ. Кузнечный горн узнают по
//     вытяжке: она забирает половину силуэта и связывает тумбу с трубой,
//     которая у ветхой лавки уже стоит на крыше.
// ---------------------------------------------------------------------------
void forge_forge_hearth() {
    Forge f;
    const float W = 1.60f;      // вдоль стены
    const float D = 1.00f;      // от стены
    const float TOP = 0.85f;    // верх тумбы — рабочая высота горна
    const float th = 0.22f;     // толщина кладки
    const Params stone = {{"height", "0.85"}, {"thickness", "0.22"}, {"mat", "3"},
                          {"tone", "1"}, {"fill", "3"}, {"wear", "0"}};
    // ТУМБА: четыре цепочки по осевой линии кладки, обход СВ->СЗ->ЮЗ->ЮВ —
    // при нём лицо камня смотрит наружу (правило бортика очага).
    const float a = th * 0.5f;
    const float bx = W - a;
    const float bz = D - a;
    (void)f.wall(f.v(bx, 0.0f, a), f.v(a, 0.0f, a), stone);
    (void)f.wall(f.v(a, 0.0f, a), f.v(a, 0.0f, bz), stone);
    (void)f.wall(f.v(a, 0.0f, bz), f.v(bx, 0.0f, bz), stone);
    (void)f.wall(f.v(bx, 0.0f, bz), f.v(bx, 0.0f, a), stone);
    // Столешница горна и утопленная топка: под топки на 0.06 ниже верха.
    f.slab(0.0f, 0.0f, W, D, TOP, 0.10f, "3", "1");
    const float fx = W * 0.5f;
    const float fz = D * 0.55f;
    f.slab(fx - 0.30f, fz - 0.26f, fx + 0.30f, fz + 0.26f, TOP - 0.06f, 0.06f,
           "3", "2", {{"paint", "6"}});
    ember_bed(f, fx, fz, TOP - 0.03f, 0.20f);
    flame_cluster(f, fx, fz, TOP + 0.04f, 0.34f, 0.11f);
    // СОПЛО МЕХОВ из задней стенки: без притока воздуха горн не горн.
    f.bar({fx, TOP - 0.02f, D - th}, {fx, TOP - 0.02f, fz + 0.10f}, 0.05f, "0",
          "2", "square", {{"paint", "6"}});
    // КОЛПАК: четыре трапеции от широкой юбки к устью стояка.
    const float HOOD_LO = 1.35f;
    const float HOOD_HI = 1.95f;
    const float hw = 0.44f;   // полуширина устья
    const float lx0 = 0.10f, lx1 = W - 0.10f;
    const float lz0 = 0.06f, lz1 = D - 0.06f;
    const float ux0 = fx - hw, ux1 = fx + hw;
    const float uz0 = fz - hw * 0.55f, uz1 = fz + hw * 0.55f;
    const Params hood = {{"paint", "0"}};
    f.quad({lx0, HOOD_LO, lz0}, {lx1, HOOD_LO, lz0}, {ux1, HOOD_HI, uz0},
           {ux0, HOOD_HI, uz0}, 0.10f, "3", "1", hood);
    f.quad({lx1, HOOD_LO, lz1}, {lx0, HOOD_LO, lz1}, {ux0, HOOD_HI, uz1},
           {ux1, HOOD_HI, uz1}, 0.10f, "3", "1", hood);
    f.quad({lx0, HOOD_LO, lz1}, {lx0, HOOD_LO, lz0}, {ux0, HOOD_HI, uz0},
           {ux0, HOOD_HI, uz1}, 0.10f, "3", "1", hood);
    f.quad({lx1, HOOD_LO, lz0}, {lx1, HOOD_LO, lz1}, {ux1, HOOD_HI, uz1},
           {ux1, HOOD_HI, uz0}, 0.10f, "3", "1", hood);
    // Кант по юбке колпака: без него трапеции читаются картонными.
    f.bar({lx0, HOOD_LO, lz0}, {lx1, HOOD_LO, lz0}, 0.06f, "0", "2", "square",
          {{"paint", "6"}});
    f.bar({lx0, HOOD_LO, lz1}, {lx1, HOOD_LO, lz1}, 0.06f, "0", "2", "square",
          {{"paint", "6"}});
    // ДВЕ СТОЙКИ от передних углов тумбы к юбке: колпак висит на них, а не
    // в воздухе (правило опоры — то же, по которому у столба есть подкосы).
    for (const float px : {lx0, lx1}) {
        f.bar({px, TOP, lz0}, {px, HOOD_LO, lz0}, 0.05f, "0", "2", "square",
              {{"paint", "6"}});
    }
    // СТОЯК: квадратный брус от устья вверх. Верх 2.60 — под низ трубы,
    // которую раскладка уже ставит на кровле ветхой лавки.
    f.bar({fx, HOOD_HI - 0.04f, fz}, {fx, 2.60f, fz}, 0.30f, "3", "1", "square");

    f.save("assets/houses/furn-forge-hearth.dfh");
}

// ---------------------------------------------------------------------------
// 16. НАКОВАЛЬНЯ furn-anvil на дубовой колоде. Лицо на 0.78 — по обмеру
//     каталога от роста 1.8 м: наковальня стоит по костяшки опущенной руки.
//     КОЛОДА, А НЕ НОЖКИ: наковальня в жизни стоит на цельном чурбаке, и
//     четыре палки под ней читались бы табуретом.
// ---------------------------------------------------------------------------
void forge_anvil() {
    Forge f;
    // Ось смещена так, чтобы РОГ (он выходит за подошву на 0.30) уместился в
    // пятно без отрицательных координат: начало — угол пятна, как у всех.
    const float cx = 0.57f;
    const float cz = 0.19f;
    const float STUMP = 0.52f;   // верх колоды
    const float FACE = 0.78f;    // лицо наковальни
    const Params iron = {{"paint", "6"}};

    // Колода: круглый чурбак с торцом-годовыми кольцами (mat 2 — ТОРЕЦ).
    f.bar({cx, 0.0f, cz}, {cx, STUMP, cz}, 0.19f, "0", "2", "round");
    f.disc8(cx, cz, 0.19f, STUMP, 0.03f, "2", "1");
    // Подошва наковальни, талия и лицо — три яруса, как у настоящей.
    f.slab(cx - 0.19f, cz - 0.12f, cx + 0.19f, cz + 0.12f, STUMP + 0.10f, 0.10f,
           "0", "2", iron);
    f.bar({cx, STUMP + 0.10f, cz}, {cx, FACE - 0.09f, cz}, 0.075f, "0", "2",
          "square", iron);
    f.slab(cx - 0.26f, cz - 0.10f, cx + 0.26f, cz + 0.10f, FACE, 0.09f, "0", "2",
           iron);
    // РОГ: клин, сужающийся наружу по -X. Две грани сверху и снизу плюс бока —
    // собран quad-ами, потому что у bar() сечение одно на всю длину.
    const float hx = cx - 0.26f;
    const float hn = hx - 0.30f;   // остриё рога
    const float y0 = FACE - 0.09f;
    const glm::vec3 t0{hx, FACE, cz - 0.10f}, t1{hx, FACE, cz + 0.10f};
    const glm::vec3 b0{hx, y0, cz - 0.10f}, b1{hx, y0, cz + 0.10f};
    const glm::vec3 n0{hn, FACE - 0.035f, cz - 0.03f};
    const glm::vec3 n1{hn, FACE - 0.035f, cz + 0.03f};
    f.quad(t0, t1, n1, n0, 0.02f, "0", "2", iron);        // верх рога
    f.quad(b1, b0, n0, n1, 0.02f, "0", "2", iron);        // низ рога
    // Бока рога — ТРЕУГОЛЬНИКИ, а не четырёхугольники: у остриё одна точка на
    // сторону, и четвёртая вершина совпала бы с третьей (граф такое отвергает).
    (void)f.contour({f.v(t0), f.v(n0), f.v(b0)},
                    {{"thickness", "0.02"}, {"mat", "0"}, {"tone", "2"},
                     {"paint", "6"}});
    (void)f.contour({f.v(b1), f.v(n1), f.v(t1)},
                    {{"thickness", "0.02"}, {"mat", "0"}, {"tone", "2"},
                     {"paint", "6"}});
    // ХВОСТ с наковаленным отверстием — просто прямоугольная пятка по +X.
    f.slab(cx + 0.26f, cz - 0.08f, cx + 0.40f, cz + 0.08f, FACE, 0.07f, "0", "2",
           iron);
    // МОЛОТ, лежащий на лице: предмет, который говорит, что здесь работают.
    f.bar({cx - 0.06f, FACE + 0.05f, cz - 0.02f},
          {cx + 0.22f, FACE + 0.05f, cz + 0.03f}, 0.028f, "0", "2", "round");
    f.bar({cx - 0.14f, FACE + 0.05f, cz - 0.03f},
          {cx - 0.05f, FACE + 0.05f, cz - 0.02f}, 0.05f, "0", "2", "square", iron);

    f.save("assets/houses/furn-anvil.dfh");
}

// ---------------------------------------------------------------------------
// 17. БОЧКА ЗАКАЛКИ furn-quench: клёпаная кадь с двумя коваными обручами и
//     ЗЕРКАЛОМ ВОДЫ под кромкой. Без воды это просто бочка — а закалочная
//     кадь узнаётся именно тем, что в ней видно воду.
//     ОБРУЧИ ЕСТЬ, В ОТЛИЧИЕ ОТ furn-barrel, где их не стали делать («тонкое
//     кольцо прямой не собрать»): здесь обруч набран ВОСЕМЬЮ хордами по тем же
//     точкам, что и клёпки, — кольца по-прежнему нет, а восьмиугольник есть.
// ---------------------------------------------------------------------------
void forge_quench() {
    Forge f;
    const float cx = 0.331f;
    const float cz = 0.331f;
    const float r_lo = 0.25f;
    const float r_mid = 0.30f;
    const float r_hi = 0.28f;
    const float y_mid = 0.30f;
    const float H = 0.62f;
    const auto at = [&](float r, float y, int k) {
        const float t = 0.7853981634f * static_cast<float>(k);
        return glm::vec3{cx + r * std::cos(t), y, cz + r * std::sin(t)};
    };
    for (int k = 8; k > 0; --k) {
        f.quad(at(r_lo, 0.0f, k), at(r_lo, 0.0f, k - 1), at(r_mid, y_mid, k - 1),
               at(r_mid, y_mid, k), 0.04f, "1", "2");
        f.quad(at(r_mid, y_mid, k), at(r_mid, y_mid, k - 1), at(r_hi, H, k - 1),
               at(r_hi, H, k), 0.04f, "1", "2");
    }
    f.disc8(cx, cz, r_lo - 0.02f, 0.06f, 0.05f, "1", "1");
    // Два кованых обруча: восемь хорд по тем же вершинам, что и клёпки.
    for (const auto& hoop : {std::pair<float, float>{r_lo + 0.025f, 0.10f},
                             std::pair<float, float>{r_hi + 0.025f, H - 0.06f}}) {
        for (int k = 8; k > 0; --k) {
            f.bar(at(hoop.first, hoop.second, k), at(hoop.first, hoop.second, k - 1),
                  0.028f, "0", "2", "square", {{"paint", "6"}});
        }
    }
    // ЗЕРКАЛО ВОДЫ на 0.07 ниже кромки: краска — синяя из таблицы, другой у
    // рецепта нет; плитка самая бледная (Plaster/Light), чтобы синь не ушла
    // в грязь.
    f.disc8(cx, cz, r_hi - 0.03f, H - 0.07f, 0.03f, "5", "0", {{"paint", "5"}});
    // Клещи, перекинутые через кромку: тот же довод, что у молота.
    f.bar({cx - 0.10f, H + 0.03f, cz - 0.22f}, {cx + 0.02f, H + 0.03f, cz + 0.30f},
          0.022f, "0", "2", "round", {{"paint", "6"}});
    f.bar({cx - 0.04f, H + 0.03f, cz - 0.22f}, {cx + 0.02f, H + 0.03f, cz + 0.30f},
          0.022f, "0", "2", "round", {{"paint", "6"}});

    f.save("assets/houses/furn-quench.dfh");
}

