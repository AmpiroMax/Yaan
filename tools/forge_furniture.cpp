// ОГОНЬ КАК ВИДИМЫЙ ПРЕДМЕТ (претензии критика [N18] «очаг — зелёная лужа в
// ящике» и [N14] «жаровня — бочка без пламени»).
//
// ЗЕЛЁНАЯ ЛУЖА НАЙДЕНА ЗАМЕРОМ, И МЕХАНИЗМОВ ОКАЗАЛОСЬ ДВА, У РАЗНЫХ ДЕТАЛЕЙ.
// Прибор — разбор очага по КУСКАМ меша (габарит куска, его диагональ, износ
// элемента). Первая догадка «под очага зарос мхом» ПРОВАЛИЛАСЬ на числе, и это
// стоит записать: слой мха в AppHouse.cpp включается только у куска с
// part_organic, то есть length(phi-plo) < 1.4, а у пода 1.000 x 0.060 x 1.000
// даёт диагональ 1.4155 — он мимо порога на 1.6 см. Мха на поду нет.
//  (1) БОРТИК. Четыре цепочки, куски 0.56..1.24 по диагонали — органика ДА, —
//      и стоял износ 0.55. Слой мха красит вершину в (0.30, 0.52, 0.30) с силой
//      moss = min(1, wear * (spots - need) * 8), где need = 0.92 - 0.45 * low;
//      у бортика (y 0.14..0.38) low ≈ 0.8, need ≈ 0.56, то есть у ~44 % вершин
//      сила доходит до единицы, а на ГОРИЗОНТАЛЬНОЙ грани умножается ещё на
//      1.6. Это НАСЫЩЕННЫЙ зелёный, и он по всему бортику.
//  (2) ПОД. Износ 0.85 >= 0.7 уводит тон в ВЫВЕТРЕННЫЙ ряд атласа, а у камня
//      этот ряд несёт лишайник по построению: weather_of(Weathered) даёт
//      бюджет 0.62, и stone_texel подмешивает (0.62, 0.66, 0.46) с весом до
//      0.465. Серо-зелёная плёнка на всей плите 1.0 x 1.0 в коробе — это и есть
//      «лужа», только не мох, а лишайник.
// Оба механизма — наружное выветривание, приложенное к КОМНАТНОМУ очагу.
// Оба выключаются одним: износу здесь взяться неоткуда. Чернота золы — КРАСКА
// (дёготь), а не выветривание.
//
// ЭМИССИИ ПО РЕЦЕПТНОМУ ПУТИ НЕТ, и это проверено, а не предположено.
// Самосветный путь движка (RenderSystem::set_emissive_mesh, unlit-программа)
// питается ТОЛЬКО объектами .dfo с kind == "emissive" (AppWorld.cpp:654), и
// собирает их из полок объектов сцены. Постройки .dfh идут другим путём —
// плитками, через dfn_surface_light. Поэтому пламя здесь — ЯРКИЙ ВЕРШИННЫЙ
// ЦВЕТ на самой светлой плитке атласа: mat 5 (Plaster) + tone 0 (Light) —
// самая бледная клетка, какая есть, — умноженная краской. Краска берётся из
// HOUSE_PAINT_RGB, и других цветов у рецепта не бывает: охра (0.85,0.64,0.32)
// — тело пламени, белила (0.95,0.93,0.86) — сердцевина, красная фалу
// (0.66,0.28,0.22) — угли. Градиент собран СЛОЯМИ лепестков, а не переходом
// внутри детали: вершинный цвет у детали один.
// ===========================================================================

/// Лепесток пламени: плоский язык в вертикальной плоскости, проходящей через
/// ось (cx, cz) под углом ang. Полигон строго монотонен по высоте (левая
/// кромка идёт вверх, правая вниз), поэтому он прост по построению и уши
/// отсекаются без находок.
void flame_petal(Forge& f, float cx, float cz, float y0, float H, float W,
                 float ang, float lean, const char* paint) {
    const float ux = std::cos(ang);
    const float uz = std::sin(ang);
    const int M = 8;
    std::vector<VertexId> left, right;
    left.reserve(M + 1);
    right.reserve(M + 1);
    for (int k = 0; k <= M; ++k) {
        const float t = static_cast<float>(k) / static_cast<float>(M);
        // Профиль языка: широкий у основания, с одной перетяжкой и остриём.
        const float w = std::max(0.012f,
                                 W * std::pow(std::max(0.0f, 1.0f - t * t * 1.6f), 0.7f)
                                   * (0.75f + 0.25f * std::cos(6.2831853f * t * 1.5f)));
        const float c = lean * W * t * t;   // язык отклоняется набок
        const float y = y0 + H * t;
        left.push_back(f.v(cx + (c - w) * ux, y, cz + (c - w) * uz));
        right.push_back(f.v(cx + (c + w) * ux, y, cz + (c + w) * uz));
    }
    std::vector<VertexId> ring = left;
    for (int k = M; k >= 0; --k) {
        ring.push_back(right[static_cast<std::size_t>(k)]);
    }
    (void)f.contour(std::move(ring),
                    {{"thickness", "0.02"}, {"mat", "5"}, {"tone", "0"},
                     {"paint", paint}});
}

/// ПУЧОК ПЛАМЕНИ: три наружных языка охрой и три внутренних белилами вполовину
/// ниже. Три, а не один: одно полотно с любой стороны читается плоской
/// карточкой, а три пересекающихся дают объём с ЛЮБОГО направления. Углы
/// смещены на 30 гр. между слоями — иначе сердцевина прячется точно за телом.
void flame_cluster(Forge& f, float cx, float cz, float y0, float H, float W) {
    for (int k = 0; k < 3; ++k) {
        const float a = 3.14159265f * static_cast<float>(k) / 3.0f;
        const float lean = (k == 0) ? 0.18f : ((k == 1) ? -0.26f : 0.10f);
        flame_petal(f, cx, cz, y0, H * (0.88f + 0.12f * static_cast<float>(k % 2)),
                    W, a, lean, "2");  // охра — тело пламени
    }
    for (int k = 0; k < 3; ++k) {
        const float a = 3.14159265f * (static_cast<float>(k) / 3.0f + 1.0f / 6.0f);
        const float lean = (k == 1) ? 0.22f : -0.14f;
        flame_petal(f, cx, cz, y0 + H * 0.04f, H * 0.60f, W * 0.52f, a, lean,
                    "1");  // белила — сердцевина
    }
}

/// УГЛИ: восьмиугольная постель красной фалу и четыре ярких куска охрой.
/// Пустая тёмная плита читается ямой, а не жаром (та же находка, что у грядки:
/// «пустая коричневая плита читается лужей»).
void ember_bed(Forge& f, float cx, float cz, float y_top, float r) {
    f.disc8(cx, cz, r, y_top, 0.05f, "5", "0", {{"paint", "3"}});
    for (int k = 0; k < 4; ++k) {
        const float a = 1.5707963f * static_cast<float>(k) + 0.4f;
        const float rr = r * 0.45f;
        const float ex = cx + rr * std::cos(a);
        const float ez = cz + rr * std::sin(a);
        const float s = r * (0.16f + 0.05f * static_cast<float>(k % 3));
        f.slab(ex - s, ez - s, ex + s, ez + s, y_top + 0.03f, 0.05f, "5", "0",
               {{"paint", "2"}});
    }
}

