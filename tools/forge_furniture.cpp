// 21. СТУЛ СО СПИНКОЙ 0.50 x 0.50, сиденье на 0.44, спинка до 0.94 — САМЫЙ
//     ЧАСТЫЙ ПРЕДМЕТ ВСЕХ ДЕВЯТНАДЦАТИ СКРИНОВ (16 из 19; у лавки 8, у
//     табурета 5). До этой партии сидеть в комнате было НЕ НА ЧЁМ, кроме
//     лавки: у неё нет спинки, и она ставится вдоль стола, а не к очагу.
//     Задние ножки и стойки спинки — ОДНА деталь на всю высоту (так стул и
//     сколочен), поэтому спинка не «приделана», а вырастает из ножки.
//     Материал словами: дуб (тёсаный брус ножек, пилёная доска сиденья).
//     Мета сидения — НЕ ЗДЕСЬ: её механизм ведёт волна сидеть/лежать, а этот
//     рецепт печёт ровно тело.
// ---------------------------------------------------------------------------
void forge_chair(const char* file) {
    Forge f;
    const float S = 0.50f;
    const float seat = 0.44f;   // верх сиденья
    const float back = 0.94f;   // верх спинки
    const float ax = 0.055f;    // ось ножки от кромки
    const float bx = S - ax;

    // Задние стойки идут насквозь от пола до верха спинки; передние кончаются
    // под сиденьем. Спинка у стены — при z = 0.
    f.bar({ax, 0.0f, ax}, {ax, back, ax}, 0.026f, "0", "2");
    f.bar({bx, 0.0f, ax}, {bx, back, ax}, 0.026f, "0", "2");
    f.bar({ax, 0.0f, bx}, {ax, seat, bx}, 0.026f, "0", "2");
    f.bar({bx, 0.0f, bx}, {bx, seat, bx}, 0.026f, "0", "2");
    // Проножки на 0.14: без них четыре палки читаются «карточкой» — та же
    // находка, что у стола (деталь 1).
    f.bar({ax, 0.14f, ax}, {ax, 0.14f, bx}, 0.017f, "0", "2");
    f.bar({bx, 0.14f, ax}, {bx, 0.14f, bx}, 0.017f, "0", "2");
    f.bar({ax, 0.14f, bx}, {bx, 0.14f, bx}, 0.017f, "0", "2");
    // Сиденье и царга под ним.
    f.slab(0.02f, 0.02f, S - 0.02f, S - 0.02f, seat, 0.042f, "1", "1");
    f.bar({ax, seat - 0.08f, ax}, {bx, seat - 0.08f, ax}, 0.020f, "1", "2");
    f.bar({ax, seat - 0.08f, bx}, {bx, seat - 0.08f, bx}, 0.020f, "1", "2");
    // Две доски спинки и верхняя перекладина: три горизонтали читаются стулом
    // с любого угла, одна — калиткой.
    f.panel({ax, 0.60f, ax}, {bx, 0.60f, ax}, 0.71f, 0.028f, "1", "1");
    f.panel({ax, 0.76f, ax}, {bx, 0.76f, ax}, 0.87f, 0.028f, "1", "1");
    f.panel({ax, back - 0.07f, ax}, {bx, back - 0.07f, ax}, back, 0.034f, "1", "1");

    f.save(file);
}

