// 14. УЛИЧНАЯ ЖАРОВНЯ С ПЛАМЕНЕМ furn-brazier-fire, пятно 0.722 x 0.722 (замер).
//     Претензия [N14] дословно — «жаровня: бочка без пламени», и она точнее,
//     чем кажется: жаровни у города НЕТ ВОВСЕ. Раскладчик ставит на её место
//     furn-column.dfh — НЕСУЩУЮ КОЛОННУ с подкосами, ростом 2.60, и вешает
//     точку света над её макушкой. Столб с капителью и четырьмя подкосами — это
//     опора перекрытия, а не светильник, поэтому здесь предмет собран заново:
//     кованая корзина на столбе, угли и пламя.
//     ВЫСОТА ЧАШИ ВЫБРАНА ПОД УЖЕ СТОЯЩИЙ СВЕТ: у раскладчика точка света
//     висит на макушке столба (2.600) плюс BRAZIER_FLAME 0.15, то есть на 2.75.
//     Кромка корзины здесь на 2.28, пламя от 2.30 до 2.92 — свет 2.75 попадает
//     В ТЕЛО пламени, а не в пустоту над ним, и переставлять его не придётся.
// ---------------------------------------------------------------------------
void forge_brazier_fire(const char* file) {
    Forge f;
    const float cx = 0.36f;
    const float cz = 0.36f;
    const float POST = 2.05f;    // верх столба
    const float RIM = 2.28f;     // кромка корзины
    const Params iron = {{"paint", "6"}};

    // Каменный башмак: столб на земле без подошвы читается воткнутым.
    f.slab(cx - 0.26f, cz - 0.26f, cx + 0.26f, cz + 0.26f, 0.12f, 0.12f, "3", "1");
    // Три растопыренные ноги от башмака к стволу — без них столб «стоит на
    // точке» (та же находка, что у прилавка рынка).
    for (int k = 0; k < 3; ++k) {
        const float a = 2.0943951f * static_cast<float>(k) + 0.3f;
        f.bar({cx + 0.22f * std::cos(a), 0.06f, cz + 0.22f * std::sin(a)},
              {cx, 0.62f, cz}, 0.035f, "0", "2", "square", iron);
    }
    f.bar({cx, 0.0f, cz}, {cx, POST, cz}, 0.07f, "0", "2", "square", iron);
    // КОРЗИНА: восемь клёпок с развалом наружу плюс дно и обруч под кромкой.
    const auto at = [&](float r, float y, int k) {
        const float t = 0.7853981634f * static_cast<float>(k);
        return glm::vec3{cx + r * std::cos(t), y, cz + r * std::sin(t)};
    };
    for (int k = 8; k > 0; --k) {
        f.quad(at(0.16f, POST, k), at(0.16f, POST, k - 1),
               at(0.34f, RIM, k - 1), at(0.34f, RIM, k), 0.035f, "0", "2", iron);
    }
    f.disc8(cx, cz, 0.17f, POST + 0.05f, 0.04f, "0", "2", iron);
    for (int k = 8; k > 0; --k) {
        f.bar(at(0.335f, RIM - 0.05f, k), at(0.335f, RIM - 0.05f, k - 1), 0.028f,
              "0", "2", "square", iron);
    }
    ember_bed(f, cx, cz, POST + 0.12f, 0.22f);
    // ПЛАМЯ РАСТЁТ ИЗ УГЛЕЙ, А НЕ НАД НИМИ. Прежняя подошва RIM + 0.02 = 2.30
    // стояла на 0.075 выше верха углей (2.225): судья связности честно назвал
    // пламя отдельным островом — костёр, висящий над жаровней. Подошва
    // опущена на постель углей; верх пламени 2.82, и точка света раскладчика
    // (2.75) по-прежнему внутри тела пламени, а не над ним.
    flame_cluster(f, cx, cz, POST + 0.15f, 0.62f, 0.17f);

    f.save(file);
}


