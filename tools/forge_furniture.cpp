// 21. ЦВЕТНИК-КОРОБ 1.2 x 1.2 (заказ: «куда генератор насыплет цветы»).
//     Два исполнения — каменное и дощатое: ряд одинаковых коробов вокруг
//     дерева читается кладкой плитки, а не сквером.
//     ЗЕМЛЯ ВНУТРИ — mat 7 (Turf: трава по тёмной земле), а НЕ камень
//     выветренного ряда, которым набита грядка двора: у грядки этот ряд читался
//     серо-зелёной плёнкой (разбор «зелёной лужи»), а цветнику нужна тёмная
//     земля, на которой цветы генератора будут видны.
//     ЗЕМЛЯ УТОПЛЕНА на 0.06 ниже кромки: вровень с бортом она превращает
//     короб в тумбу, а не в ящик с землёй.
// ---------------------------------------------------------------------------
void forge_planter(const char* file, bool stone) {
    Forge f;
    const float S = 1.2f;
    const float H = 0.35f;
    const float th = stone ? 0.14f : 0.06f;
    const float a = th * 0.5f;
    const float b = S - a;

    if (stone) {
        // Обход СВ -> СЗ -> ЮЗ -> ЮВ: при нём лицо камня смотрит наружу
        // (правило бортика очага, деталь 6).
        const Params blocks = {{"height", "0.35"}, {"thickness", "0.14"},
                               {"mat", "3"}, {"tone", "1"}, {"fill", "3"}};
        (void)f.wall(f.v(b, 0.0f, a), f.v(a, 0.0f, a), blocks);
        (void)f.wall(f.v(a, 0.0f, a), f.v(a, 0.0f, b), blocks);
        (void)f.wall(f.v(a, 0.0f, b), f.v(b, 0.0f, b), blocks);
        (void)f.wall(f.v(b, 0.0f, b), f.v(b, 0.0f, a), blocks);
        // КОПИНГ — плита по периметру с напуском на ладонь: на неё садятся, и
        // по ней короб читается цветником, а не куском стены. Плит ЧЕТЫРЕ, по
        // числу бортов, а не одна на весь верх: сплошная запечатала бы ящик
        // крышкой, и земли внутри не стало бы видно.
        const float c = th + 0.03f;
        f.slab(-0.03f, -0.03f, S + 0.03f, c, H + 0.05f, 0.05f, "3", "1");
        f.slab(-0.03f, S - c, S + 0.03f, S + 0.03f, H + 0.05f, 0.05f, "3", "1");
        f.slab(-0.03f, c, c, S - c, H + 0.05f, 0.05f, "3", "1");
        f.slab(S - c, c, S + 0.03f, S - c, H + 0.05f, 0.05f, "3", "1");
    } else {
        // Дощатый: четыре борта и четыре угловых столбика.
        f.panel({a, 0.0f, 0.0f}, {a, 0.0f, S}, H, th, "1", "2");
        f.panel({S - a, 0.0f, 0.0f}, {S - a, 0.0f, S}, H, th, "1", "2");
        f.panel({0.0f, 0.0f, a}, {S, 0.0f, a}, H, th, "1", "2");
        f.panel({0.0f, 0.0f, S - a}, {S, 0.0f, S - a}, H, th, "1", "2");
        for (const float x : {0.06f, S - 0.06f}) {
            for (const float z : {0.06f, S - 0.06f}) {
                f.bar({x, 0.0f, z}, {x, H + 0.08f, z}, 0.06f, "0", "2", "square");
            }
        }
    }
    // ЗЕМЛЯ. Кромка земли заходит ПОД борт, а не встаёт к нему встык: шов двух
    // тел заподлицо на неровном свете показывает щель в пустоту короба.
    const float in = stone ? th - 0.02f : 0.04f;
    f.slab(in, in, S - in, S - in, H - 0.06f, 0.20f, "7", "1");

    f.save(file);
}

