// 4. СТЕЛЛАЖ У СТЕНЫ 1.2 x 0.35, высота 2.05: две стойки-щеки, три полки и
//    ВЕРХНЯЯ ПЛИТА-КРЫШКА (каталог §9: открытый стеллаж 1.0x0.35x1.5,
//    книжный шкаф 1.0x0.35x2.0, шаг полок ~0.45).
//    Ставится задней кромкой (z = D) к стене.
//
//    ВЫСОТА 1.80 -> 2.05 ПО КРИТУ ВЛАДЕЛЬЦА 28.08, и это самый несущий
//    сантиметр всей правки. Человеческая вилка стеллажа 1.8–2.2 м, и 1.80
//    стояло НА ЕЁ НИЖНЕЙ КРОМКЕ — ровно вровень с ростом героя 1.80. Замер
//    комнаты объясняет жалобу лучше, чем любой отдельный предмет: во всём
//    убранстве не было НИ ОДНОГО тела выше героя, стеллаж кончался ровно на
//    его макушке, а всё прочее (стол 0.80, лавка 0.45, бочка 0.84, кровать
//    0.99, поленница 1.20) — ниже его пояса и груди. Комната, у которой
//    потолок 2.7, а самая высокая вещь в рост вошедшего, читается кукольной
//    независимо от того, что каждая вещь по отдельности обмерена верно.
//    2.05 ВЫВЕДЕНО, А НЕ ВЫБРАНО: просвет над пятном СТЕЛЛАЖА замерен во всех
//    32 его местах обоих городов, худшее — мельница (пол 1.32, скат кровли
//    3.50, то есть 2.18); 2.05 проходит там с запасом 0.13, 2.20 не проходит.
// ---------------------------------------------------------------------------
void forge_shelf(const char* file) {
    Forge f;
    const float W = 1.2f;
    const float D = 0.35f;
    const float H = 2.05f;
    const float sx0 = 0.05f;      // ось левой стойки
    const float sx1 = W - 0.05f;  // ось правой

    for (const float x : {sx0, sx1}) {
        f.panel({x, 0.0f, 0.0f}, {x, 0.0f, D}, H, 0.06f, "1", "2");
    }
    // Три полки: 0.55 / 1.10 / 1.65 — шаг 0.55, под кувшин и котелок влезает.
    for (const float y : {0.55f, 1.10f, 1.65f}) {
        f.slab(sx0, 0.02f, sx1, D - 0.02f, y, 0.04f, "1", "1");
    }
    // КРЫШКА ПОВЕРХУ, а не четвёртая полка: над верхней полкой осталось 0.40,
    // и открытые щёки в этой полосе читались бы обрезанной мебелью. Плита
    // лежит ВНУТРИ пятна щёк (sx0..sx1), чтобы замеренный габарит предмета не
    // вырос ни на миллиметр — раскладка от этой правки не двигается вовсе.
    f.slab(sx0, 0.0f, sx1, D, H, 0.05f, "1", "1");
    // Обвязка сзади: верхняя и нижняя рейки — без них стеллаж складывается
    // ромбом, и это видно даже на статичной картинке (плоские щёки).
    f.bar({sx0, H - 0.13f, D - 0.04f}, {sx1, H - 0.13f, D - 0.04f}, 0.03f, "0", "2");
    f.bar({sx0, 0.12f, D - 0.04f}, {sx1, 0.12f, D - 0.04f}, 0.03f, "0", "2");

    f.save(file);
}

