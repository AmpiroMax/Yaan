// 24. КОМОД-БУФЕТ 1.00 x 0.48, столешница на 0.92 (13 скринов из 19 — второй
//     по частоте после стула: в кадре он стоит у стены и держит на себе всю
//     посуду). Каркас из двух щёк, цоколь, столешница с напуском, три
//     выдвижных ящика лицом и ручки-кольца.
//     Материал словами: дуб; ручки — железо.
// ---------------------------------------------------------------------------
void forge_cupboard(const char* file) {
    Forge f;
    const float W = 1.00f;
    const float D = 0.48f;
    const float H = 0.92f;
    const float plinth = 0.10f;

    // Щёки во всю высоту и задняя стенка: без задней короб просвечивает.
    f.panel({0.03f, 0.0f, 0.0f}, {0.03f, 0.0f, D}, H - 0.05f, 0.06f, "1", "2");
    f.panel({W - 0.03f, 0.0f, 0.0f}, {W - 0.03f, 0.0f, D}, H - 0.05f, 0.06f, "1", "2");
    f.panel({0.0f, plinth, D - 0.02f}, {W, plinth, D - 0.02f}, H - 0.05f, 0.03f, "1", "2");
    // Цоколь: короб, поднятый на 0.10, читается мебелью, стоящий на полу —
    // ящиком. Та же мысль, что у завалинки дома.
    f.slab(0.05f, 0.03f, W - 0.05f, D - 0.03f, plinth, 0.08f, "0", "2");
    f.slab(-0.025f, -0.025f, W + 0.025f, D + 0.02f, H, 0.05f, "1", "1");
    // ТРИ ЯЩИКА ЛИЦОМ, а не нарисованные линии: фасад выступает на 1.5 см и
    // даёт собственную тень — ровно то, чем комод отличается от тумбы-короба.
    const float y0 = plinth + 0.04f;
    const float step = (H - 0.09f - y0) / 3.0f;
    for (int i = 0; i < 3; ++i) {
        const float a = y0 + step * static_cast<float>(i);
        f.panel({0.08f, a + 0.015f, -0.012f}, {W - 0.08f, a + 0.015f, -0.012f},
                a + step - 0.015f, 0.026f, "1", "1");
        // Ручка-кольцо: короткий брусок поперёк — на 1 см от лица, тень своя.
        f.bar({W * 0.5f - 0.05f, a + step * 0.5f, -0.032f},
              {W * 0.5f + 0.05f, a + step * 0.5f, -0.032f}, 0.012f, "3", "2", "square");
    }

    f.save(file);
}

