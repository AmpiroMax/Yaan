// 6. КАМЕННЫЙ ОЧАГ 1.4 x 1.4 (каталог §10: приподнятый короб очага, бортик
//    обложен камнем, внутри — утопленный под с золой). Низкий короб:
//    плита-основание, бортик из блоков по периметру, под утоплен на 0.18
//    ниже кромки — в яму встаёт котёл на треноге.
// ---------------------------------------------------------------------------
/// ДВЕРЬ ДОЗЫ ПОД ЗЕЛЁНУЮ ЛУЖУ: DFN_FORGE_HEARTH_MOSS=1 печёт очаг с ПРЕЖНИМИ
/// износами (0.45 / 0.55 / 0.85) и без краски-дёгтя. Аддитивность правки
/// доказывается ею, а не обещанием: под этой дверью весь остальной набор
/// обязан сойтись бит-в-бит, а сам очаг — вернуться к принятому файлу.
bool hearth_moss() {
    static const bool on = std::getenv("DFN_FORGE_HEARTH_MOSS") != nullptr;
    return on;
}

void forge_hearth(const char* file) {
    Forge f;
    const float S = 1.4f;
    const float base_top = 0.14f;
    const float rim_h = 0.24f;   // бортик: верх на 0.38
    const float rim_th = 0.20f;
    // ИЗНОС У КОМНАТНОГО ОЧАГА — НОЛЬ, И ЭТО ВЫВОД, А НЕ ВКУС. Мох включается
    // ЛЮБЫМ износом выше нуля, и промежуточного значения нет: при wear = 0.1
    // сила пятна доходит до 0.38, при 0.55 — до единицы. Поджать нельзя,
    // можно только выключить.
    const char* w_base = hearth_moss() ? "0.45" : "0";
    const char* w_rim = hearth_moss() ? "0.55" : "0";
    const char* w_pan = hearth_moss() ? "0.85" : "0";

    f.slab(0.0f, 0.0f, S, S, base_top, 0.14f, "3", "1", {{"wear", w_base}});

    // БОРТИК: цепочки по осевой линии кладки (отступ в полтолщины), обход
    // СВ -> СЗ -> ЮЗ -> ЮВ -> СВ — при нём лицо камня смотрит НАРУЖУ.
    // РЕЛЬЕФ КЛАДКИ ОТ ИЗНОСА НЕ ЗАВИСИТ: глубина куска считается как
    // th * (0.7 + (0.3 + 0.5*wear) * дрожь), то есть при нуле блоки всё равно
    // гуляют на 30 % глубины. Пропадают только выпавшие куски и сколы.
    const float a = rim_th * 0.5f;
    const float b = S - a;
    const Params stone = {{"height", "0.24"}, {"thickness", "0.20"}, {"mat", "3"},
                          {"tone", "1"}, {"fill", "3"}, {"wear", w_rim}};
    (void)f.wall(f.v(b, base_top, a), f.v(a, base_top, a), stone);  // север
    (void)f.wall(f.v(a, base_top, a), f.v(a, base_top, b), stone);  // запад
    (void)f.wall(f.v(a, base_top, b), f.v(b, base_top, b), stone);  // юг
    (void)f.wall(f.v(b, base_top, b), f.v(b, base_top, a), stone);  // восток
    (void)rim_h;

    // ПОД: утопленная плита золы внутри бортика — верх на 0.20, то есть на
    // 0.18 ниже кромки. Чернота золы — КРАСКА (дёготь), а не выветривание:
    // прежний wear 0.85 не только звал мох, но и уводил тон в ВЫВЕТРЕННЫЙ ряд
    // атласа (серость с лишайником), то есть красил золу в цвет старого камня.
    f.slab(rim_th, rim_th, S - rim_th, S - rim_th, 0.20f, 0.06f, "3", "2",
           hearth_moss() ? Params{{"wear", w_pan}}
                         : Params{{"wear", w_pan}, {"paint", "6"}});

    f.save(file);
}


