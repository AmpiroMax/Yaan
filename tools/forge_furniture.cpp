//     Претензия владельца дословно: «нет объёма в них» и «между бордюром и
//     тропой зелени просвет — плохо». Сегодня кромка тропы — РИСУНОК на
//     текстуре земли; здесь она становится телом.
//
//     ПОЧЕМУ ЭТО НЕ city-kerb2 И НАЗВАНО ИНАЧЕ. city-kerb2-hNN — ПОДПОРНАЯ
//     КРОМКА террасы рынка: стенка 0.35 толщиной и до 1.2 м ростом, из которой
//     раскладчик собирает клин. Здесь предмет другого назначения и другого
//     порядка величины (0.22 x 0.31), и одно имя на двоих кончилось бы тем,
//     что раскладчик подобрал бы под тропу метровую стенку.
//
//     СЕЧЕНИЕ (заказ дословно): 0.22 ширина, 0.16 над землёй, ЗАГЛУБЛЕНИЕ 0.15
//     вниз. Заглубление — не украшение: земля города неровная, шаг сетки
//     рельефа 2 м, и камень, посаженный низом ровно на ноль, на первом же
//     бугре повисает в воздухе, а во впадине тонет целиком. 15 см — половина
//     размаха земли на длине сегмента.
//
//     ДВЕ ДЛИНЫ, 0.6 и 1.2. Тропа города — ломаная, и на повороте длинный
//     камень даёт веер со щелями; короткий добирает поворот, длинный держит
//     прямую дешевле (у 1.2 вдвое меньше кусков меша на метр кромки).
//
//     ФАСКА — ТЕЛОМ, А НЕ УСТУПОМ: две наклонные плитки от плеча 0.13 к
//     верхней площадке 0.15 шириной. Фаска вдвинута на 8 мм внутрь габарита,
//     потому что толщина плитки симметрична её плоскости — иначе полутолщина
//     наклонной грани вылезла бы за объявленные 0.22, и раскладчик считал бы
//     зазор по вранью.
//
//     КАК СТАВИТЬ (для городского генератора): origin — угол пятна, +X вдоль
//     кромки, камень занимает z 0..0.22, верх +0.16, низ -0.15. Чтобы не было
//     ТОЙ САМОЙ полоски зелени, грань z=0 сажается НЕ встык к полотну тропы, а
//     С НАХЛЁСТОМ НА НЕГО.
//     НАХЛЁСТ — 0.55, А НЕ 2-3 СМ, и число куплено расстановкой (замер
//     раскладчика 22.08, 268 сегментов): кромка полотна у нас НЕ ЖЁСТКАЯ —
//     износ тропы хранится по отсчётам решётки 1 м и интерполируется, поэтому
//     граница сплошного камня гуляет вокруг расчётной линии в пределах
//     ПОЛУКЛЕТКИ. При 3 см трава то подходила вплотную, то вылезала полосой с
//     внутренней стороны; полклетки нахлёста это снимает. Мои 2-3 см отвечали
//     на неровность ЗЕМЛИ и промахнулись мимо неровности КРОМКИ.
//
//     ТОН — ХОЛОДНЫЙ СЕРЫЙ, И ЭТО ЗАМЕР, А НЕ ВКУС (претензия раскладчика по
//     кадру: «бордюр читается красно-кирпичной лентой»). Прибор — средний тон
//     плитки набора против среднего тона клетки ПУТЕВОГО атласа, той самой,
//     что лежит рядом на земле:
//       COBBLE (мостовая)      0.411 0.385 0.336, теплота +0.075
//       CUT_SLAB (тёсаная)     0.356 0.363 0.363, теплота -0.007
//       Stone/Mid, голая       0.450 0.450 0.430, теплота +0.020
//       Stone/Light, голая     0.550 0.550 0.530, теплота +0.020
//     ПЕРВАЯ ДОГАДКА «плитка тёплая» ПРОВАЛИЛАСЬ НА ЧИСЛЕ, и это стоит
//     записать: камень набора почти нейтрален (+0.020), а ТЕПЛЕЕ ИЗ ДВОИХ —
//     САМА МОСТОВАЯ (+0.075). Красным читалась ЯРКОСТЬ: 0.55 у светлого
//     варианта против 0.41 у земли — на 34 % выше соседа, а самая яркая
//     поверхность кадра сильнее всех берёт цвет тёплого света, которым город и
//     освещён. Поэтому лечится не «сделать серее», а СНИЗИТЬ СВЕТЛОТУ в полосу
//     соседа и увести тон в холод.
//     ЛЕКАРСТВО — КРАСКА 7 (седая известь, 0.78/0.80/0.82), единственная
//     холодная в таблице: Mid x известь = 0.351 0.360 0.353 (теплота -0.002),
//     Light x известь = 0.429 0.440 0.435 (теплота -0.006). Первое — это
//     CUT_SLAB с точностью 0.012, второе — тот же тон на ступень светлее, для
//     чередования; контраст пары 0.078, видно чередование, но не шахматы.
//     МОСТОВАЯ В ТОН НЕ БЕРЁТСЯ НАМЕРЕННО, хотя просили «в тон COBBLE»: она
//     тёплая, и попадание в неё вернуло бы ровно ту претензию, с которой
//     пришли. Цель — тёсаный камень, а не мостовая.
//
//     ПРОВЕРЕНО НА КАДРЕ, А НЕ ТОЛЬКО НА АЛЬБЕДО (замер раскладчика, полдень,
//     dev-карта, коробки на однородных пятнах; sRGB как в буфере):
//       бордюр   0.640 0.630 0.597  теплота +0.043  яркость 0.622
//       CUT_SLAB 0.652 0.628 0.566  теплота +0.085  яркость 0.615
//       COBBLE   0.577 0.543 0.459  теплота +0.118  яркость 0.527
//     Порядок теплоты на кадре ТОТ ЖЕ, что предсказало альбедо: бордюр холоднее
//     ВСЕХ каменных соседей. Свет добавляет теплоту всем, и добавка идёт ПО
//     ЯРКОСТИ (у бордюра -0.002 -> +0.043, у тёсаной -0.007 -> +0.085): это
//     тёплое солнце, а не дефект отрисовки, и нести к рендеру нечего.
//
//     СВЕТЛЫЙ ВАРИАНТ (06b/12b) НЕ ЗАТЕМНЯТЬ — решение по кадру, а не вкус.
//     Его яркость 0.622 попадает в яркость ТЁСАНОЙ ПЛИТЫ (0.615, разница 1 %),
//     то есть из ленты он не выбивается. Выше мостовой он на 0.095, но мостовая
//     здесь — САМАЯ ТЁМНАЯ из трёх каменных поверхностей кадра, и подгонка под
//     неё стоила бы бордюру видимости как элемента. Предложение увести пару в
//     0.351/0.390 проверено и ОТКЛОНЕНО раскладчиком на кадре.
// ---------------------------------------------------------------------------
void forge_curb(const char* file, float L, const char* tone, const char* paint) {
    Forge f;
    const float W = 0.22f;      ///< ширина камня поперёк тропы
    const float TOP = 0.16f;    ///< верх над землёй
    const float DEEP = -0.15f;  ///< заглубление под землю
    const float SH = 0.13f;     ///< плечо: отсюда начинается фаска
    const float CW = 0.075f;    ///< полуширина верхней площадки
    const float IN = 0.008f;    ///< вдвижка фаски внутрь габарита
    const float cz = W * 0.5f;

    // КРАСКА НА КАЖДОЙ ДЕТАЛИ, а не на теле: вершинный цвет берётся с элемента,
    // и некрашеная фаска рядом с крашеным телом дала бы светлую кайму по всей
    // длине кромки — ровно ту «покрашенную линию», от которой уходим.
    const Params skin = {{"paint", paint}};

    // ТЕЛО: доска-щека, положенная на ребро вдоль кромки. panel(), а не bar():
    // сечение 0.22 x 0.28 не квадратное, а radius у bar() — одно число (тот же
    // довод, что у бордюров furn-walk2).
    f.panel({0.0f, DEEP, cz}, {L, DEEP, cz}, SH, W, "3", tone, skin);
    // Верхняя площадка.
    f.slab(0.0f, cz - CW, L, cz + CW, TOP, TOP - SH, "3", tone, skin);
    // Фаски: обход подобран так, чтобы лицо смотрело ВВЕРХ И НАРУЖУ.
    f.quad({L, SH, cz - CW - 0.027f + IN}, {0.0f, SH, cz - CW - 0.027f + IN},
           {0.0f, TOP, cz - CW}, {L, TOP, cz - CW}, 0.02f, "3", tone, skin);
    f.quad({0.0f, SH, cz + CW + 0.027f - IN}, {L, SH, cz + CW + 0.027f - IN},
           {L, TOP, cz + CW}, {0.0f, TOP, cz + CW}, 0.02f, "3", tone, skin);

    f.save(file);
}


