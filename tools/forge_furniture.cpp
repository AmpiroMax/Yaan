    f.panel({0.0f, 0.0f, L - b}, {W, 0.0f, L - b}, H, th, "1", "2",
            {{"wear", "0.5"}});
    // Земля — на 0.05 ниже кромки борта.
    f.slab(th, th, W - th, L - th, H - 0.05f, 0.16f, "3", "3", {{"wear", "0.9"}});
    // Четыре гребня поперёк грядки.
