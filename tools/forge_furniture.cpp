// 20. СКВЕР У ГИЛДЕРГРИНА: сегмент круговой скамьи и цветник.
//     Заказ владельца: «Гилдергрин должен стать точкой притяжения».
//
//     НАЧАЛО ДЕТАЛИ — ЦЕНТР КОЛЬЦА, А НЕ УГОЛ ПЯТНА, и это единственное место
//     в кузнице, где конвенция нарушена НАМЕРЕННО. Дуга, посаженная от угла
//     своего пятна, требует от раскладчика решить обратную задачу (где стоял
//     бы центр окружности, если её кусок повёрнут на yaw), и кольцо из восьми
//     таких кусков сходится только при точной арифметике в ЕГО коде. С центром
//     в начале детали постановка кольца — это восемь вызовов с ОДНОЙ И ТОЙ ЖЕ
//     точкой (ствол) и yaw = k * 45 гр., и разъехаться там нечему.
//     Кольцо Гилдергрина (city-treering) снаружи кончается на 2.775 (R 2.6 по
//     осевой плюс полтолщины 0.175), скамья начинается на 3.81 — метр чистого
//     прохода между бортиком и коленями сидящего.
//     ПРОПОРЦИИ ВЗЯТЫ У furn-bench, а не выдуманы: сиденье на 0.45, доска
//     0.055, опора — ДОСКА-ЩЕКА во всю глубину, проножка на 0.15. Отличий два,
//     и оба от формы: глубина 0.38 вместо 0.35 (у дуги внутренняя кромка
//     короче наружной, и по внутренней сиденье уже номинала) и ТРИ щеки вместо
//     двух — пролёт 3.1 м между двумя опорами провис бы доской.
// ---------------------------------------------------------------------------
void forge_bench_arc(const char* file, float R, float span_deg, int boards) {
    Forge f;
    const float SEAT = 0.45f;
    const float th_seat = 0.055f;
    const float D = 0.38f;
    const float ri = R - D * 0.5f;
    const float ro = R + D * 0.5f;
    const float rad = 3.14159265f / 180.0f;
    const float half = span_deg * 0.5f * rad;
    const float joint = 0.25f * rad;   ///< шов между досками, ~1.7 см при R 4
    const float w = (span_deg * rad - joint * static_cast<float>(boards - 1))
                    / static_cast<float>(boards);
    const auto at = [&](float r, float a, float y) {
        return glm::vec3{r * std::cos(a), y, r * std::sin(a)};
    };

    // СИДЕНЬЕ — трапеции-доски по дуге. Обход «внутренняя a0 -> внутренняя a1
    // -> наружная a1 -> наружная a0» при a1 > a0 даёт лицо ВВЕРХ (то же
    // правило обхода, что у slab: против часовой, если смотреть сверху).
    const float y = SEAT - th_seat * 0.5f;
    for (int k = 0; k < boards; ++k) {
        const float a0 = -half + (w + joint) * static_cast<float>(k);
        const float a1 = a0 + w;
        f.quad(at(ri, a0, y), at(ri, a1, y), at(ro, a1, y), at(ro, a0, y),
               th_seat, "1", "1");
    }
    // ТРИ ЩЕКИ: по концам (с отступом на полдоски внутрь) и посередине.
    const float a_leg = half - w * 0.5f;
    for (const float a : {-a_leg, 0.0f, a_leg}) {
        f.panel(at(ri + 0.02f, a, 0.0f), at(ro - 0.02f, a, 0.0f),
                SEAT - th_seat, 0.05f, "1", "2");
    }
    // Проножка двумя хордами по осевому радиусу — она и держит щёки от
    // расшатывания (furn-bench, деталь 2).
    for (const auto& seg : {std::pair<float, float>{-a_leg, 0.0f},
                            std::pair<float, float>{0.0f, a_leg}}) {
        f.bar(at(R, seg.first, 0.15f), at(R, seg.second, 0.15f), 0.035f, "0", "2");
    }

    f.save(file);
}

