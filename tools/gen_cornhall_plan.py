def ell(deg):
    """Точка овала. Знак у sin — МИНУС, и это не вкус: цепь гнутых прогонов
    кладёт бугор кладки наружу только при отрицательной знаковой площади
    контура (у Вайтрана -7680), то есть при обходе по часовой в чарте."""
    t = math.radians(deg)
    return (CX + A * math.cos(t), CZ - B * math.sin(t))

