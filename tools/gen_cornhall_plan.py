problems = []

def in_walls(x, z):
    inside = False
    n = len(WALL)
    j = n - 1
    for i in range(n):
        xi, zi = WALL[i]
        xj, zj = WALL[j]
        if (zi > z) != (zj > z) and x < (xj - xi) * (z - zi) / (zj - zi) + xi:
            inside = not inside
        j = i
    return inside

def body_rect(h):
    """Пятно тела: лицо на красной линии, тело растёт назад во двор."""
    fw, fd = FRONT[h["kind"]]
    r = math.radians(h["deg"])
    base = {"S": (0, 1), "N": (0, -1), "E": (1, 0), "W": (-1, 0)}[h["door"]]
    dx = base[0] * math.cos(r) - base[1] * math.sin(r)
    dz = base[0] * math.sin(r) + base[1] * math.cos(r)
    cx, cz = h["x"] - dx * fd / 2.0, h["z"] - dz * fd / 2.0
    return cx, cz, fw, fd

for i in range(len(HOUSES)):
    ax, az, aw, ad = body_rect(HOUSES[i])
    for j in range(i + 1, len(HOUSES)):
        bx, bz, bw, bd = body_rect(HOUSES[j])
        if math.hypot(ax - bx, az - bz) < (min(aw, ad) + min(bw, bd)) / 2 * 0.92:
            problems.append(
                f"ПЕРЕСЕЧЕНИЕ: {HOUSES[i]['kind']} ({ax:.0f},{az:.0f}) и "
                f"{HOUSES[j]['kind']} ({bx:.0f},{bz:.0f})")
for h in HOUSES:
    cx, cz, w, d = body_rect(h)
    for rd in ROADS:
        for (x0, z0), (x1, z1) in zip(rd["pts"], rd["pts"][1:]):
            vx, vz = x1 - x0, z1 - z0
            L2 = vx * vx + vz * vz
            t = max(0.0, min(1.0, ((cx - x0) * vx + (cz - z0) * vz) / L2))
            dd = math.hypot(cx - (x0 + vx * t), cz - (z0 + vz * t))
            if dd < rd["w"] / 2 + min(w, d) / 2 * 0.8:
                problems.append(f"НА ДОРОГЕ: {h['kind'] or 'дом'} "
                                f"({cx:.0f},{cz:.0f}) до оси {dd:.1f} м")
                break
inside = sum(1 for h in HOUSES if in_walls(h["x"], h["z"]))
