# ЩЕЛЬ РЫНОЧНОГО РЯДА В ЧЕРТЕЖЕ — НИЖНЯЯ КРОМКА НОРМЫ, А НЕ ЕЁ СЕРЕДИНА, и
# это условие того, чтобы спред щели (GAP_SPREAD паспорта) РАБОТАЛ. Норма
# пары гуляет 0.08..0.32 м, а расталкивание тел умеет только РАЗДВИНУТЬ пару,
# которой тесно, — значит шаг, положенный чертежом по середине нормы (0.2),
# спред мог бы увеличить, но не уменьшить, и половина ряда так и стояла бы
# через одинаковую ладонь. Положенный по нижней кромке, он даёт норме говорить
# целиком: где 0.08 — соседи почти смыкаются брандмауэрами (§4: «0.0-0.3 у
