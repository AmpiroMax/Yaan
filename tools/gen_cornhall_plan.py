def _shelf():
    """Манифест полки: строка на рецепт, разбор dict(zip(cols, split()))."""
    cols, rows = None, {}
    with open(os.path.join(ROOT, "assets/houses/INDEX.txt"),
              encoding="utf-8") as f:
        for line in f:
            if line.startswith("# columns:"):
                cols = line.split(":", 1)[1].split()
            elif cols and line.strip() and not line.startswith("#"):
                row = dict(zip(cols, line.split()))
                rows[row["file"]] = row
    return rows

def _num(v):
    return None if v == "-" else float(v)

SHELF = _shelf()
