HOUSES = []


def put(kind, x, z, deg, door, name=None, walk=None):
    """(x,z) — точка КРАСНОЙ ЛИНИИ, где стоит ЛИЦО дома. Дверная точка
    рецепта отодвигается от неё внутрь квартала на FACE_OFF: генератор сажает
    дом дверной гранью, а вынос лица за дверную точку у каждого рецепта свой.
    Схемное пятно передаётся нулевым — его единственное дело в house_frame
    это вынос двери от центра схемы, а он нам не нужен."""
    r = math.radians(deg)
    base = {"S": (0, 1), "N": (0, -1), "E": (1, 0), "W": (-1, 0)}[door]
    dx = base[0] * math.cos(r) - base[1] * math.sin(r)
    dz = base[0] * math.sin(r) + base[1] * math.cos(r)
    off = FACE_OFF.get(kind, 0.0)
    HOUSES.append({"x": round(x - dx * off, 2), "z": round(z - dz * off, 2),
                   "w": 0, "d": 0,
                   "deg": round(deg, 1), "door": door,
                   "walk": list(walk) if walk else None,
                   "name": name or "", "kind": kind})


def row(x_or_z, a, b, door, pattern, gap=0.2, axis="z", jitter=4.0, walk=None):
    """ФАСАДНЫЙ РЯД ПО КРАСНОЙ ЛИНИИ. Идёт от a до b, беря рецепты из
    pattern по кругу и подставляя следующий, пока хватает места; поворот
    каждого дома — ±jitter гр. вокруг линии ряда (норматив Корнхолла ±4).
    Щель gap — НОРМАТИВ РЯДА (0.0-0.3 у рынка, 1.0-2.0 в fringe belt); тот же
    норматив стоит в паспорте как GAP_M и держится расталкиванием тел."""
    t, i, out = a, 0, 0
    while True:
        kind = pattern[i % len(pattern)]
        front = FRONT[kind][0]
        if t + front > b:
            break
        deg = ((i * 37) % int(jitter * 2 + 1)) - jitter
        c = t + front / 2.0
        if axis == "z":
            put(kind, x_or_z, c, deg, door, walk=walk)
        else:
            put(kind, c, x_or_z, deg, door, walk=walk)
        t += front + gap
        i += 1
        out += 1
    return out


