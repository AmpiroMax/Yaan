    for rd in ROADS:
        for (x0, z0), (x1, z1) in zip(rd["pts"], rd["pts"][1:]):
            vx, vz = x1 - x0, z1 - z0
            L2 = vx * vx + vz * vz
            t = max(0.0, min(1.0, ((cx - x0) * vx + (cz - z0) * vz) / L2))
            dd = math.hypot(cx - (x0 + vx * t), cz - (z0 + vz * t))
