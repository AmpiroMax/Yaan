#!/bin/zsh
#
# File: tools/shoot_tiers_city.sh
#
# Responsibility:
# - РЕЦЕПТ ПРИЁМОЧНЫХ КАДРОВ ВТОРОЙ ВОЛНЫ ЯРУСОВ (закон посева — в города):
#   четыре камеры боевых городов, одна метка плеча, один прогон.
#
# Usage:
#     tools/shoot_tiers_city.sh <плечо> [<сборка>]
#   Плечо — только имя папки для кадров. САМО ПЛЕЧО ВЫБИРАЕТСЯ ГЕНЕРАТОРОМ, а
#   не этим файлом (правило 30, и та же дверь, что у стенда):
#     python3 tools/gen_city.py whiterun                 — ярусы (сдаётся)
#     DFN_CITY_TIERS=0 python3 tools/gen_city.py whiterun — «до»: город без
#         ярусов; его выпуск байт-в-байт совпадает с тем, что лежал в дереве
#         до этой волны, — то есть «до» здесь не память, а файл.
#
# ЗАЧЕМ ФАЙЛОМ, А НЕ СТРОКОЙ В ОТЧЁТЕ. Пара кадров «до/после» есть довод
# только если камера у обоих ОДНА. Камера, переписанная руками во второй раз,
# — это два разных кадра под одной подписью.
#
# КОНВЕНЦИЯ КАМЕРЫ (EditorCamera.h): yaw 0 смотрит на -Z, положительный yaw
# поворачивает по часовой стрелке сверху. Поза задаётся АБСОЛЮТНО
# (DFN_EDITOR_CAM), а не над землёй: у Житнова DFN_EDITOR_CAM_REL поднял
# камеру на восемьдесят метров — его земля ещё не стрималась к моменту, когда
# дверь спрашивала высоту, и «над землёй» оказалось над сырым склоном
# worldgen. Отметки взяты из поля высот города (.cache/city/<город>_heights).
#
# КАДР ИНОГДА ПРИХОДИТ ПЕРЕВЁРНУТЫМ ПО ВЕРТИКАЛИ — свойство захвата с
# бэкбуфера, а не сцены (та же камера в двух прогонах даёт оба варианта; в
# памяти зоны это записано с 15.08). Выпрямляется рукой:
#     sips -f vertical <кадр> --out <кадр>
# Автоматике это отдавать НЕЛЬЗЯ: единственный дешёвый признак «где небо» —
# яркость полосы, а кадр под сомкнутой кроной темнее сверху, чем снизу, и
# прибор переворачивал ВЕРНЫЙ кадр (замер: 51 против 36). Плечи «до» и
# «после» проходят одну и ту же обработку, поэтому пара остаётся доводом.
#
# AI Agents Notice:
# - Follow docs/ARCHITECTURE.md strictly.
set -e
ROOT=${0:a:h:h}
cd $ROOT
ARM=${1:?плечо: after | before}
# СБОРКА: вторым доводом, иначе — ПЕРВАЯ НАЙДЕННАЯ в дереве. Именованного
# умолчания здесь стоять не может: волна ярусов снималась из своего worktree
# (dfn-tiers-wt/build_tiers), а worktree сносится по её окончании — путь в
# умолчании протух бы ровно в тот день, когда отчёт сдан. Волна — данные и
# инструменты, ни одной строки C++: кадр снимает ЛЮБАЯ собранная сборка,
# и это само по себе довод (бинарь грузит сцену как есть).
BUILD=${2:-$(ls -td $ROOT/build*/engine/app/dfn_app 2>/dev/null | head -1 | xargs -I{} dirname {} | xargs -I{} dirname {} | xargs -I{} dirname {})}
if [[ ! -x $BUILD/engine/app/dfn_app ]]; then
  print -u2 "нет собранного dfn_app: укажи сборку вторым доводом"
  exit 2
fi
print "сборка: $BUILD/engine/app/dfn_app"

OUT=/tmp/citytiers-shots/$ARM
mkdir -p $OUT
shoot () {
  local nm=$1 map=$2 cam=$3
  DFN_EDITOR=1 DFN_OPEN_MAP=$map DFN_EDITOR_CAM="$cam" \
  DFN_HUD=0 DFN_INTERNAL_RES=1920x1080 DFN_TIME_OF_DAY=0.42 \
  DFN_CAPTURE_DIR=$OUT/$nm DFN_CAPTURE_AFTER_FRAMES=120 DFN_NULL_AUDIO=1 \
  $BUILD/engine/app/dfn_app >/tmp/citytiers-shots/$ARM-$nm.log 2>&1 || true
  # Обрезка редакторской рамки — та же для всех плеч, поэтому сравнение честное.
  sips -c 1286 1617 --cropOffset 154 143 $OUT/$nm/capture_000.png \
       --out /tmp/citytiers-shots/$ARM-$nm.png >/dev/null 2>&1 || true
}
# ВАЙТРАН, РОЩА ДУБА-ПОЛЯНЫ: ковёр и куртины под сомкнутыми кронами.
shoot wr-grove cities/whiterun "30,27.6,199,1.30,-0.12"
# ВАЙТРАН, ОПУШКА: стёжка на дуб-поляну, ковёр подходит к её бортику и ни
# одна плата не села на полотно.
shoot wr-edge  cities/whiterun "66,27.5,196,-1.107,-0.09"
# ВАЙТРАН, ДВОР: ковёр есть, подлеска нет — двор не лес.
shoot wr-yard  cities/whiterun "76,30.0,190,2.27,-0.35"
# ЖИТНОВ, РОЩА У ЗАПАДНОГО ТРАКТА: вся зелень этого города за кольцом стен.
shoot ch-grove cities/cornhall "24,25.4,380,1.19,-0.10"
ls /tmp/citytiers-shots/$ARM-*.png
