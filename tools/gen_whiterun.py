# «Композиция земли» ведёт игрока увереннее всего (гайд §10: мощение 55%
# против 40% у цвета), поэтому камнем идёт процессионная ось: южные ворота ->
# рынок -> замок, рынок -> восточные ворота, выход с моста. Плиты ЖЁСТКИЕ —
# рельеф они не повторяют, поэтому длина куска выбирается по РОВНОСТИ пятна:
# на плато ложится 24 м, на переломе 6. Кромка у city-cobble — наклонный
# поясок 0.30 м под 15 гр. (замер wr-forge: скачок 3 см против 22 см отвеса у
# прежних city-plaza), так что улицу можно переходить поперёк где угодно.
# ШТУЧНЫХ ПЛИТ НА УЛИЦАХ БОЛЬШЕ НЕТ (приказ владельца 22.08: «тропинки опять
# плитами кладутся, а не тропинкой каменной»). Каменный тракт стал СВОЙСТВОМ
# ЗЕМЛИ — класс полотна в строке path файла .relief, движок fde9a7b. Вместе с
# лентами ушла и вся машинерия их набора: выбор длины по ровности пятна,
# наклонные куски -sNN, цепь отметок, отступ на изломе. Она была верной для
# своей задачи и решила её (подъём к замку 23.4 -> 91.0%), но задачи этой
# больше нет: у полотна земли нет ни стыков, ни ступеней, ни «губы» над
# грунтом, и разрывов у него не бывает по построению. Держать её мёртвой
# значило бы врать о том, как построен город.
# ПЛИТАМИ ОСТАЛИСЬ ТРИ ВЕЩИ, и каждая — не тропа: мост (авторский настил),
# марш и подпорная кромка террасы (построенный перепад) и мостовая рынка
# (площадь — место, а не путь; по ней ходят во все стороны).
PAVE_TOP = 0.087    # верх мостовой city-cobble над её origin (у НИЖНЕЙ кромки)

PAVED = []
PAVE_OVERLAP = 1.0  # м2: больше — считается наложением плиты на плиту
PAVE_SLIVER = 0.05  # м2: меньше — численный волосок на изломе, не наложение
PAVE_FLICKER = 0.01 # м: ближе по высоте — соплоскостная пара, она мерцает
PAVE_MAX_DROP = 0.35  # круче — мостовую не кладём вовсе, это дело лестниц
PAVE_STEP = 0.20      # предельная ступень между СОСЕДНИМИ плитами одной улицы

def slab_top(p, px, pz, clamp=False):
    """Ходибельная отметка плиты в мировой точке: наклонный кусок ЕДЕТ.
    clamp=True прижимает точку к СВОЕМУ пятну: поверхность существует только
    над пятном, а за его краем честное значение — отметка ближней кромки.
    Без этого короткий крутой кусок, продлённый до середины между центрами,
    привирает на весь свой уклон: марш 2.1 м рядом с восьмиметровой плитой
    насчитывал ступень 0.85 м там, где кромки сходятся с точностью 3 см."""
    c = math.cos(math.radians(p[4]))
    sn = math.sin(math.radians(p[4]))
    lx = (px - p[0]) * c - (pz - p[1]) * sn
    if clamp:
        lx = max(-p[2]/2, min(p[2]/2, lx))
    return p[5] + p[6] * lx
def slab_covers(p, px, pz):
    c = math.cos(math.radians(p[4]))
    sn = math.sin(math.radians(p[4]))
    lx = (px - p[0]) * c - (pz - p[1]) * sn
    lz = (px - p[0]) * sn + (pz - p[1]) * c
    return abs(lx) <= p[2] / 2 and abs(lz) <= p[3] / 2

def rect_poly(cx, cz, w, d, yaw_deg):
    c = math.cos(math.radians(yaw_deg))
    sn = math.sin(math.radians(yaw_deg))
    return [(cx + lx*c + lz*sn, cz - lx*sn + lz*c)
            for lx, lz in ((-w/2, -d/2), (w/2, -d/2), (w/2, d/2), (-w/2, d/2))]

def poly_clip_area(subject, clip):
    """Площадь пересечения двух ВЫПУКЛЫХ многоугольников (Сазерленд-Ходжман).
    Нужна честная площадь, а не «касаются ли»: на изломе улицы соседние плиты
    задевают друг друга углом на десятки сантиметров — это нормальный шов, а
    вот 16 м2 в одной плоскости мерцают, и 15 м2 со ступенькой 0.40 м дают
    ровно ту кромку, ради которой у city-cobble делалась фаска (замер
    wr-forge: девять пар наложений в первой раскладке)."""
    out = subject
    n = len(clip)
    for i in range(n):
        ax, az = clip[i]
        bx, bz = clip[(i + 1) % n]
        ex, ez = bx-ax, bz-az
        def inside(p):
            return ex*(p[1]-az) - ez*(p[0]-ax) >= 0.0
        src, out = out, []
        if not src:
            return 0.0
        prev = src[-1]
        for cur in src:
            if inside(cur):
                if not inside(prev):
                    out.append(seg_cross(prev, cur, (ax, az), (ex, ez)))
                out.append(cur)
            elif inside(prev):
                out.append(seg_cross(prev, cur, (ax, az), (ex, ez)))
            prev = cur
    if len(out) < 3:
        return 0.0
    a = 0.0
    for i in range(len(out)):
        x0, z0 = out[i]
        x1, z1 = out[(i + 1) % len(out)]
        a += x0*z1 - x1*z0
    return abs(a) / 2.0

def seg_cross(p, q, a, e):
    dx, dz = q[0]-p[0], q[1]-p[1]
    den = e[0]*dz - e[1]*dx
    if abs(den) < 1e-12:
        return q
    t = (e[0]*(p[1]-a[1]) - e[1]*(p[0]-a[0])) / -den
    return (p[0] + dx*t, p[1] + dz*t)
def check_paving():
    """Раскладка обязана сама говорить, что положила плиту на плиту: пара
    в одной плоскости мерцает, пара со ступенькой даёт кромку посреди улицы."""
    import itertools
    bad = []
    joints = 0
    for a, b in itertools.combinations(PAVED, 2):
        ar = poly_clip_area(rect_poly(*a[:5]), rect_poly(*b[:5]))
        # СТУПЕНЬ МЕРЯЕТСЯ В ТОЧКЕ СТЫКА, А НЕ ПО ЦЕНТРАМ. У наклонных соседок
        # центры разнесены по высоте на весь уклон куска, а игрок переступает
        # там, где кромки сходятся: разность центров назвала бы дефектом
        # именно ту пару, которая сошлась по построению.
        mx, mz = (a[0] + b[0])/2, (a[1] + b[1])/2
        dy = abs(slab_top(a, mx, mz, clamp=True)
                 - slab_top(b, mx, mz, clamp=True))
        if ar > PAVE_SLIVER and dy < PAVE_FLICKER:
            bad.append(f"СОПЛОСКОСТНАЯ пара (мерцает): {ar:.2f} м2, "
                       f"разность верха {dy:.4f} м в ({a[0]:.0f},{a[1]:.0f})")
            continue
        if ar > PAVE_OVERLAP:
            bad.append(f"плита на плите: {ar:.1f} м2, ступень {dy:.2f} м "
                       f"в ({a[0]:.0f},{a[1]:.0f})")
            continue
        # СТЫК: кромки ближе 0.6 м. Дальше — землю между плитами мостит
        # рельеф, и разность отметок там ничего не значит (пара с ступенью
        # 3.5 м — это терраса, а не дефект).
        D = math.hypot(a[0]-b[0], a[1]-b[1]) or 1e-6
        ux, uz = (b[0]-a[0])/D, (b[1]-a[1])/D
        gap = D - half_proj(a[2], a[3], a[4], ux, uz) - half_proj(b[2], b[3], b[4], ux, uz)
        if gap < 0.6:
            joints += 1
            if dy > PAVE_STEP + 0.02:
                bad.append(f"стык с обрывом: зазор {gap:.2f} м, ступень {dy:.2f} м "
                           f"в ({a[0]:.0f},{a[1]:.0f})")
    print(f"мощение: {len(PAVED)} плит, {joints} стыков (кромки ближе 0.6 м)")
    if bad:
        print("ПРОВЕРКА МОЩЕНИЯ:")
        for b in sorted(set(bad)):
            print("  -", b)

