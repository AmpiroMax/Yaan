def _kit(pattern):
    """Ростовки читаются из assets/houses, а не выписываются: кузница печёт их
    волнами, и любое записанное сюда число — будущая ложь. Варианты ОДНОГО
    роста («r2» — тот же подъём другим вылетом) подхватываются наравне:
    иначе новый рецепт не просто не используется, он НЕВИДИМ, и отказ «нет
    замера поверхности» даже не печатается — а молчание тут неотличимо от
    исправности. Отдаём списком, а не словарём по росту: у h12 и h12r2 рост
    общий, и словарь молча оставил бы один из двух.
    Возвращает [(подъём, вылет, файл)]."""
    rx = re.compile(pattern.replace(".", r"\.").replace("%02d", r"\d\d[a-z]?\d?") + r"$")
    out = []
    for f in sorted(os.listdir(os.path.join(ROOT, "assets/houses"))):
        if not rx.match(f):
            continue
        xs, ys = [], []
        for line in open(os.path.join(ROOT, "assets/houses", f), encoding="utf-8"):
            t = line.split()
            if t and t[0] == "vertex":
                xs.append(float(t[3]))
                ys.append(float(t[4]))
        out.append((max(ys), max(xs) - min(xs), f))
    return out

def market_terrace(Hh, plate_top):
    """Строит перепад северной кромки рынка. Возвращает (маршей, отрезков)."""
    steps, kerbs = _kit(STEP_REC), dict((h, (f, ln)) for h, ln, f in _kit(KERB_REC))
    if not steps or not kerbs:
        print("терраса рынка: нет выпечки city-steps6/city-kerb2 — пропущено")
        return 0, 0
