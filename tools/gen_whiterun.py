    edge_z = float(mkz)
    # створ оси: где процессионная ломаная пересекает кромку
    ax = PLAN["roads"][2]["pts"]
    x_axis = None
    for (x0, z0), (x1, z1) in zip(ax, ax[1:]):
        if (z0 - edge_z) * (z1 - edge_z) <= 0 and z0 != z1:
            x_axis = x0 + (x1 - x0) * ((edge_z - z0) / (z1 - z0))
            break
    if x_axis is None:
        return 0, 0

    def street(x):
        """Ходибельная отметка улицы против точки x кромки. Улица — ПОЛОТНО
        ЗЕМЛИ, а не лента плит: по ней ходят по самому грунту, и никаких
        «вкоп 0.03 плюс верх камня» к отметке добавлять не надо. Пока эта
        добавка тут стояла, марш целился на 0.117 выше улицы, и с его верхней
        ступени игрок сходил на землю, лежащую на 0.175 ниже."""
        return hh_at(Hh, x, edge_z - 2.0)

    rise = street(x_axis) - plate_top
    # ВЫБОР РОСТОВКИ — ПО ХОДИБЕЛЬНОМУ ПОДЪЁМУ, а не по якорному: игрок идёт
    # по камню, и у марша h12 камень поднимается на 1.200+0.151-0.176 = 1.175.
    usable = []
