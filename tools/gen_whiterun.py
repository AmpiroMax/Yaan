        for along in (0.0, 2.5, -2.5, 5.0, -5.0):
            for step in (3.6, 4.4, 5.2, 6.0, 7.0):
                for sgn in (1.0, -1.0):
                    qx = px + tx2*along + nx*sgn*step
                    qz = pz + tz2*along + nz*sgn*step
                    if dist_to_roads(qx, qz) >= 0.9 and spot_free(qx, qz, 1.0):
                        found = (qx, qz)
                        break
                if found:
                    break
            if found:
                break
        if not found:
            print(f"  жаровня {note}: чистого места рядом нет — не ставлю")
            return 0
        px, pz = found
        d = dist_to_roads(px, pz)
        gy = sit(px, pz, 27.0, half=1.0)
        house("furn-column.dfh", px - 0.7, gy, pz - 0.7, (int(px*7) % 40) - 20,
              "жаровня: " + note)
        light(px, gy + 2.75, pz, HEARTH_COLOR, 7.0, "жаровня: " + note)
        return 1
