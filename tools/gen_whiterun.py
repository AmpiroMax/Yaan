    # (MAX_SHADOW_POINT_LIGHTS), и они по сюжету принадлежат очагам залов.
    # ОТСТУП ОТ ОСЕВОЙ обязателен: столб на проезжей части — это ровно тот
    # дефект, за который я в этой же волне убирал колодец с главной улицы.
    # Считается от полуширины дороги плюс полстолба плюс запас.
    def road_normal(px, pz):
        """Единичная нормаль к ближайшей дороге. Считается от КАСАТЕЛЬНОЙ в
        ближайшей точке, а не от вектора «точка минус ближайшая»: у точки,
        лежащей НА осевой, второй вектор вырождается в ноль, а именно такие
        точки я и отодвигаю."""
        best, tan = 1e9, (1.0, 0.0)
        for rd in PLAN["roads"]:
            for (x0, z0), (x1, z1) in zip(rd["pts"], rd["pts"][1:]):
                vx, vz = x1-x0, z1-z0
                L2 = vx*vx + vz*vz or 1e-9
                t = max(0.0, min(1.0, ((px-x0)*vx + (pz-z0)*vz) / L2))
                d = math.hypot(px - (x0+vx*t), pz - (z0+vz*t))
                if d < best:
                    nl = math.hypot(vx, vz) or 1.0
                    best, tan = d, (vx/nl, vz/nl)
        return (-tan[1], tan[0])

    def brazier(px, pz, note):
        # ОТОДВИГ ДО ЧИСТОГО МЕСТА. dist_to_roads меряет до КРОМКИ полосы
        # (минус полуширина), поэтому отрицательное значение — это «стоит на
        # проезжей части». Столб там — ровно тот дефект, за который в этой же
        # волне убирался колодец с главной улицы, так что не ставим вовсе,
        # пока не отойдём.
        # Жаровня жмётся к стене, как в жизни: радиус чистого места 1.0 —
        # это сам столб (1.4х1.4) с ладонью зазора, а не пустая площадка.
        # Ищем поперёк улицы в обе стороны и с небольшим сдвигом вдоль неё:
        # фасадные ряды стоят вплотную, и точный узел бывает занят крыльцом.
        nx, nz = road_normal(px, pz)
        tx2, tz2 = -nz, nx
