#pragma once

#include "engine/render/sources/PixelCanvas.h"

#include <string_view>

namespace dfn::app {

/// ГДЕ ЛЕЖИТ ПОЛОСА, в пикселях холста. Это ЖЁЛОБ ручки — отрезок, по
/// которому ездит её ЦЕНТР, — а не нарисованная линия: линия шире жёлоба на
/// пол-ручки с каждой стороны, и если считать значение по линии, то края
/// полосы недостижимы ровно на половину ручки.
struct SliderTrack {
    int x = 0;       ///< левый конец жёлоба
    int y = 0;       ///< середина полосы по высоте
    int w = 1;       ///< длина жёлоба
    int handle = 3;  ///< ПОЛНАЯ ширина ручки, px
    int height = 3;  ///< полная высота ручки, px
};

/// ХОД СТРЕЛКИ — ДВАДЦАТАЯ ПОЛОСЫ, мелкий (Shift) — двухсотая.
///
/// ДВАДЦАТЬ, потому что столько нажатий человек делает не думая, и потому что
/// у самой узкой из измеренных полос (`age` [0, 0.55]) двадцатая — это 0.0275
/// веса, то есть меньше миллиметра хода вершины: шаг, на котором ползунок
/// движется, а форма не прыгает.
inline constexpr int SLIDER_COARSE_STEPS = 20;
inline constexpr int SLIDER_FINE_STEPS = 200;

/// ТОЛЩИНА НАРИСОВАННОЙ ПОЛОСЫ И РАЗМЕР РУЧКИ — доли ВЫСОТЫ ПРОПИСНОЙ той
/// подписи, рядом с которой ползунок стоит. Не доли кадра: ползунок живёт в
/// строке текста, и связать его надо с буквой, а не с экраном, иначе на
/// 1920x1080 ручка окажется вдвое выше строки, которую подписывает.
inline constexpr float SLIDER_TRACK_THICK_FRAC = 0.18f;
inline constexpr float SLIDER_HANDLE_W_FRAC = 0.42f;
inline constexpr float SLIDER_HANDLE_H_FRAC = 1.05f;

/// ЦВЕТА ОТДАЁТ ВЫЗЫВАЮЩИЙ. Виджет — механика, а палитра принадлежит
/// странице: экран создания персонажа и страница настроек стоят на разных
/// грунтах, и цвет, вписанный сюда, был бы третьим, ничьим.
struct SliderInk {
    render::Color track{54, 56, 64};    ///< непройденная часть
    render::Color fill{120, 118, 112};  ///< пройденная
    render::Color handle{176, 172, 160};
    render::Color label{176, 172, 160};
    render::Color value{120, 118, 112};
    render::Color notch{120, 118, 112}; ///< ромбик зарубки
    render::Color band{120, 118, 112};  ///< народный отрезок дорожки
};

/// ЧТО НАРИСОВАНО НА ДОРОЖКЕ ПОМИМО РУЧКИ. Ноль полей — обычный ползунок;
/// договор виджета от этого не меняется, поэтому страница громкости, когда
/// доедет, просто не заполнит ничего.
///
/// ЗАЧЕМ ЭТО ВООБЩЕ (CHARGEN_UI.md, Р3). Ползунок телосложения ходит не от
/// нуля до единицы, а внутри УЗКОЙ ИЗМЕРЕННОЙ полосы, за которой судья
/// пропорций перестаёт держать фигуру. Игрок про это не знает и не должен
/// догадываться, почему ручка «упёрлась»: дорожка обязана СКАЗАТЬ, где стоит
/// нейтраль и где кончается свой народ.
struct SliderMarks {
    /// НАРОДНЫЙ ОТРЕЗОК: где сидит большинство своих. `hi <= lo` — нет такого.
    float band_lo = 0.0f;
    float band_hi = 0.0f;
    /// ЗАРУБКА — НЕЙТРАЛЬ ЭТОЙ РУЧКИ, то есть замер нашего же исходного тела,
    /// а не число из учебника: полоса, центрированная на учебнике, ставила бы
    /// ручку на старте уже сдвинутой (CHARGEN_UI.md, Р3).
    float notch = 0.0f;
    bool has_notch = false;
    /// СПЛОШНОЙ РОМБ ИЛИ ПОЛЫЙ. Сплошной — полосу МЕРИЛ судья, край есть
    /// предел канона. Полый — полосу выбрал человек, и судья тут слеп: так
    /// стоит РОСТ (масштабу судья безразличен по построению) и так будут
    /// стоять лицевые ручки-«черты». Без этой разницы правило «зарубка =
    /// измеренная нейтраль» на строке роста тихо врёт.
    bool measured = true;
};

/// ЗНАЧЕНИЕ ПОД ТОЧКОЙ, зажатое в [lo, hi]. `px` — координата холста.
/// Вырожденная полоса (hi <= lo) отдаёт lo: полоса нулевой ширины — это
/// законная цель без хода, а не повод делить на ноль.
[[nodiscard]] float slider_value_at(const SliderTrack& track, int px, float lo,
                                    float hi);

/// ГДЕ ЦЕНТР РУЧКИ ПРИ ЭТОМ ЗНАЧЕНИИ. Обратная к предыдущей и ЕДИНСТВЕННОЕ
/// место, где значение превращается в пиксель: и отрисовка, и проверка
/// «попал ли указатель в ручку» спрашивают её, а не считают сами.
[[nodiscard]] int slider_handle_x(const SliderTrack& track, float value, float lo,
                                  float hi);

/// ОДНО НАЖАТИЕ СТРЕЛКИ. `fine` — с зажатым Shift.
[[nodiscard]] float slider_key_step(float lo, float hi, bool fine);

/// ЯЩИК ЗАХВАТА: полоса плюс поля, чтобы указатель не проваливался между
/// строками и чтобы за ручку можно было взяться, не целясь в три пикселя.
/// Возвращает true, если точка внутри.
[[nodiscard]] bool slider_hit(const SliderTrack& track, int px, int py);

/// РИСУЕТ ОДИН ПОЛЗУНОК. `label` слева от полосы, `value_text` справа от неё;
/// обе строки уже локализованы вызывающим. `label_px` — кегль обеих.
///
/// `selected` подсвечивает ручку (клавиатурный фокус), `dragging` утолщает её
/// на пиксель: «мышь держит именно эту» — состояние, которое иначе видно
/// только по тому, что число меняется.
void draw_slider(render::PixelCanvas& canvas, const SliderTrack& track,
                 std::string_view label, int label_x, std::string_view value_text,
                 int value_right_x, float value, float lo, float hi,
                 const SliderInk& ink, int label_px, bool selected, bool dragging,
                 const SliderMarks* marks = nullptr);

/// РОМБИК. Отдельно от ползунка, потому что его же ставит вкладка
/// происхождения рядом с типажом, а не только дорожка.
void draw_diamond(render::PixelCanvas& canvas, int cx, int cy, int half,
                  render::Color colour, bool filled);

} // namespace dfn::app
