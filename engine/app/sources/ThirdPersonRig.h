/*
Module: engine/app
File: engine/app/sources/ThirdPersonRig.h

Responsibility:
- КТО КУДА СМОТРИТ И КТО КУДА ИДЁТ, когда камера летает вокруг тела. Мышь
  крутит СТРЕЛУ вокруг персонажа всегда; ввод движения задаёт направление
  ОТНОСИТЕЛЬНО КАМЕРЫ; тело доворачивается к этому направлению с ограниченной
  скоростью. Три предложения, три чистые функции, ни одного окна.

Key items:
- BODY_TURN_RATE_RAD_S: потолок угловой скорости разворота тела (NUMBERS.md).
- move_yaw_from_axes(): угол ввода в кадре камеры, atan2(страйф, вперёд).
- turn_body_toward(): шаг разворота с ограничением скорости, кратчайшей дугой.
- axes_in_body_frame(): те же оси, переписанные в систему ТЕЛА, чтобы мировое
  направление шага не зависело от того, докрутилось тело или ещё нет.
- ThirdPersonStep / third_person_step(): всё вместе — один вызов на кадр.

Dependencies:
- Uses: glm, generated constants. Ничего больше: ни ECS, ни ввода, ни физики.
- Used by: engine/app (App: путь камеры третьего лица), tests/app.

Notes:
- ПОЧЕМУ АЗИМУТ КАМЕРЫ — МИРОВОЙ УГОЛ, А НЕ ОТСТУП ОТ РЫСКА ТЕЛА. До этой
  волны камера считалась как `pose->yaw + orbit_yaw_`, то есть жила В СИСТЕМЕ
  ТЕЛА. Пока тело стояло, это было безразлично; как только тело начинает
  доворачиваться к камере, отступ обязан уменьшаться ровно на угол доворота, а
  два конца интерполяции кадра (prev и curr) читают ОДИН отступ и РАЗНЫЕ рыски
  — то есть азимут кадра дёргается назад на долю доворота каждый кадр. Мировой
  угол снимает вопрос: тело крутится, камера стоит, и ни один кадр не зависит
  от порядка, в котором это записали.
- ПОЧЕМУ ОСИ ПЕРЕПИСЫВАЮТСЯ, А НЕ «ИДЁМ КУДА СМОТРИМ». Симуляция считает шаг
  от рыска ТЕЛА (PlayerMovement: forward = f(state.yaw)), а заказ — «вперёд =
  от камеры». Пока тело доворачивается, эти два направления различаются на
  целых полкруга, и шаг вдоль тела нарисовал бы дугу вместо прямой. Разворот
  — это КАРТИНКА, направление — это НАМЕРЕНИЕ, и они разведены здесь.
- ДЛИНА ОСЕЙ СОХРАНЯЕТСЯ, а не нормируется: sim нормирует сам и только когда
  длина больше единицы (диагональ не быстрее прямой), поэтому нормировка здесь
  сделала бы полунажатый стик полным.

AI Agents Notice (must follow):
- Follow docs/ARCHITECTURE.md strictly.
- Чистые функции и простые данные (Rule 8, Rule 30): ни часов, ни ввода, ни
  мира. Время приходит параметром — иначе приёмка мерила бы стенную дельту.
*/

#pragma once

#include <glm/vec2.hpp>

namespace dfn::app {

/// Кратчайшая дуга из `from` в `to`, радианы в (-pi, pi].
[[nodiscard]] float shortest_arc(float from, float to);

/// Куда просится ввод В КАДРЕ КАМЕРЫ: 0 — прямо от камеры, +pi/2 — вправо.
/// Соглашение то же, что у рыска симуляции (docs/RIG.md): +X вправо, -Z вперёд,
/// поэтому угол — atan2(страйф, вперёд), а не наоборот.
[[nodiscard]] float move_yaw_from_axes(const glm::vec2& axes);

/// Шаг разворота тела к `target_yaw` со скоростью не выше `rate_rad_s`.
/// Возвращает новый рыск. `dt <= 0` — тождество.
[[nodiscard]] float turn_body_toward(float body_yaw, float target_yaw, float dt,
                                     float rate_rad_s);

/// Те же оси в системе тела: направление мирового шага сохраняется при любом
/// рассогласовании `body_yaw` и `want_yaw`.
[[nodiscard]] glm::vec2 axes_in_body_frame(const glm::vec2& axes, float body_yaw,
                                           float want_yaw);

/// НАСКОЛЬКО ДАЛЕКО ОТ НУЛЯ ВВОД СЧИТАЕТСЯ ВВОДОМ. Клавиатура даёт ровно 0
/// или ровно 1, поэтому порог здесь только ради стика и ради того, чтобы
/// atan2(0,0) не решал, куда развернуть стоящего.
inline constexpr float MOVE_AXES_DEADZONE = 0.05f;

/// Что этот кадр сделал с телом и с осями.
struct ThirdPersonStep {
    float body_yaw = 0.0f;       ///< новый рыск тела
    glm::vec2 move_axes{0.0f};   ///< оси, переписанные в систему тела
    float want_yaw = 0.0f;       ///< мировой азимут, к которому тело идёт
    bool turning = false;        ///< есть ли ввод движения вообще
};

/// ОДИН ВЫЗОВ НА КАДР. `cam_yaw` — мировой азимут камеры (мышь его уже
/// повернула), `axes` — сырой ввод, `body_yaw` — рыск тела на входе.
///
/// БЕЗ ВВОДА ТЕЛО НЕ ШЕВЕЛИТСЯ ВОВСЕ, и это половина заказа: «стоя персонаж НЕ
/// поворачивается за камерой». Поэтому при пустых осях возвращается тот же
/// рыск бит-в-бит, а не «рыск, доведённый до камеры с нулевой скоростью».
[[nodiscard]] ThirdPersonStep third_person_step(float body_yaw, float cam_yaw,
                                                const glm::vec2& axes, float dt,
                                                float rate_rad_s);

} // namespace dfn::app
