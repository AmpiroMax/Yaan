#pragma once

#include <glm/vec3.hpp>

namespace dfn::app {

/// РАДИУС РУКИ ОТ ПОЛОТНА, метры. Было 1.6 у городской створки и «сколько
/// придётся» у обратной (прицел растягивался под кривой спавн) — и обе величины
/// мерились от СЕРЕДИНЫ створки, то есть у высокой двери прибавляли к радиусу
/// ещё полвысоты. Здесь величина мерится до БЛИЖАЙШЕЙ ТОЧКИ ПОЛОТНА, и потому
/// значит ровно то, что говорит имя: с какого расстояния до двери её берут
/// рукой. 1.2 м — это шаг перед порогом плюс радиус капсулы игрока (0.35):
/// человек, стоящий у двери, дотягивается всегда, человек, идущий мимо в метре
/// от чужого крыльца, — нет.
///
/// ЗАПАС НАД ИЗМЕРЕННЫМ ХУДШИМ СЛУЧАЕМ, а не «на глаз»: живой прогон по 44
/// локациям обоих городов даёт от глаза вошедшего до полотна обратной двери
/// РОВНО 0.80 м во всех 44 (перепись всех 130 по файлам подтверждает ту же
/// геометрию: отход точки входа вбок не больше 0.55 м, по горизонтали не
/// больше 0.74 м). Порог стоит ВЫШЕ отвергнутого образца с запасом 0.40 м и
/// ниже прежних 1.6.
inline constexpr float DOOR_REACH_M = 1.2f;

/// НА СКОЛЬКО ПРЯМОУГОЛЬНИК ПРИЦЕЛА ШИРЕ ПОЛОТНА. Человек целится в дверь, а не
/// в её центр тяжести, и попадание в самую кромку створки обязано считаться
/// попаданием. 0.10 м — заметно меньше полуметра, на котором владелец требует
/// молчания («смотрю на стену рядом — подсказки нет»), и заметно больше
/// численного шума пересечения луча с плоскостью.
inline constexpr float DOOR_AIM_PAD_M = 0.10f;

/// ПОЛУТОЛЩИНА КОРОБКИ ПРИЦЕЛА. Коробка — это ПЛИТА ПО ПОЛОТНУ, а не куб вокруг
/// двери: куб 1.4x2.2x1.4 (как было) содержит внутри себя голову вошедшего, а
/// луч, начатый внутри выпуклого тела, Jolt засчитывает попаданием на нулевой
/// доле — отсюда и горящая с порога надпись «Выйти». Плита в 0.4 м толщиной
/// стоит В СТЕНЕ, и попасть внутрь неё головой нельзя.
inline constexpr float DOOR_AIM_SLAB_HALF_M = 0.20f;

/// КОНУС ВЗГЛЯДА ДЛЯ ПЕРЕХОДА БЕЗ ПОЛОТНА (cos 30°). [portal] композиции — это
/// точка в воздухе: у неё нет ни нормали, ни ширины, и прямоугольника из неё не
/// выйдет. Радиус и взгляд у неё всё равно проверяются — иначе тот же дефект
/// вернулся бы через заднюю дверь.
inline constexpr float DOOR_POINT_CONE_COS = 0.866f;

/// ПРЯМОУГОЛЬНИК СТВОРКИ В МИРЕ. Полотно — тонкая плита, и его геометрия
/// известна ровно там, где оно строится (upload_house_mesh): середина габарита,
/// наружная нормаль из тех же треугольников, полуширина и полувысота габарита.
struct DoorAim {
    glm::vec3 at{0.0f};                    ///< середина полотна, мировые
    glm::vec3 normal{0.0f, 0.0f, 1.0f};    ///< наружная нормаль, единичная, по XZ
    float half_w = 0.5f;                   ///< половина ширины поперёк нормали
    float half_h = 1.0f;                   ///< половина высоты
    float reach_m = DOOR_REACH_M;          ///< радиус руки от полотна
    /// ЕСТЬ ЛИ У ПЕРЕХОДА ПОЛОТНО. false — точка в воздухе ([portal] сцены):
    /// взгляд проверяется конусом, а не пересечением с прямоугольником.
    bool leaf = false;
};

/// ВЕРДИКТ ВМЕСТЕ С ВЕЛИЧИНАМИ, ПО КОТОРЫМ ОН ВЫНЕСЕН. Голый bool заставил бы
/// прибор считать те же числа второй раз — и разойтись с игрой при первой же
/// правке (правило 39).
struct DoorAimHit {
    bool ok = false;         ///< и в радиусе, и смотрим
    bool in_reach = false;   ///< радиус до ближайшей точки полотна
    bool looking = false;    ///< луч взгляда пересекает полотно
    float distance_m = 0.0f; ///< глаз -> ближайшая точка полотна
    float t_m = 0.0f;        ///< глаз -> точка прицеливания вдоль луча (0 — мимо)
    float u = 0.0f;          ///< точка прицеливания поперёк полотна, от середины
    float v = 0.0f;          ///< она же по высоте, от середины
};

/// КАСАТЕЛЬНАЯ ПОЛОТНА (единичная, по XZ, поперёк нормали). Ею же считается
/// поворот коробки прицела — см. door_leaf_yaw.
[[nodiscard]] glm::vec3 door_aim_tangent(const glm::vec3& normal);

/// ПОВОРОТ КОРОБКИ ПРИЦЕЛА ВОКРУГ ВЕРТИКАЛИ: местный +Z уходит в нормаль,
/// местный +X — в касательную. Одна формула на коробку и на вердикт.
[[nodiscard]] float door_leaf_yaw(const glm::vec3& normal);

/// ЦЕЛИТСЯ ЛИ ГЛАЗ В ЭТО ПОЛОТНО. `dir` — единичный вектор взгляда
/// (конвенция PlayerMovement: рыск 0 смотрит в -Z, положительный — по часовой
/// сверху, положительный тангаж — вверх).
[[nodiscard]] DoorAimHit door_aim(const DoorAim& aim, const glm::vec3& eye,
                                  const glm::vec3& dir);

} // namespace dfn::app
