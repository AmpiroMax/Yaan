#pragma once

#include <glm/vec3.hpp>

namespace dfn::app {

/// РАДИУС РУКИ ОТ ТЕЛА МЕБЕЛИ, метры. Та же величина и то же рассуждение, что
/// у DOOR_REACH_M: шаг перед предметом плюс радиус капсулы игрока (0.35).
/// Меряется до БЛИЖАЙШЕЙ ТОЧКИ ГАБАРИТА, а не до его середины, — иначе у
/// двухметровой кровати «рука» с торца оказалась бы длиннее, чем с бока, на
/// целый метр, и это была бы не рука, а форма предмета.
inline constexpr float SEAT_REACH_M = 1.2f;

/// НА СКОЛЬКО КОРОБКА ПРИЦЕЛА ШИРЕ ТЕЛА. Человек целится в лавку, а не в её
/// центр тяжести; попадание в кромку обязано считаться попаданием. То же
/// число, что у двери (DOOR_AIM_PAD_M), и по той же причине: заметно меньше
/// полуметра, на котором владелец требует молчания, и заметно больше шума
/// пересечения луча с плоскостью.
inline constexpr float SEAT_AIM_PAD_M = 0.10f;

/// РУКА МЕРЯЕТСЯ ОТ СТОЙКИ ЧЕЛОВЕКА, А НЕ ОТ ГЛАЗА, и это НЕ мелочь: у двери
/// створка два метра ростом и её ближайшая точка стоит вровень с глазом, а
/// лавка — 0.45, то есть глаз всегда выше неё на 1.25 м. Мерить от глаза
/// значило бы, что до лавки, у которой человек стоит вплотную, «1.40 м», и
/// сесть на неё нельзя ни с какой стороны (замерено этим рукавом до правки).
/// Поэтому радиус берётся от ВЕРТИКАЛЬНОГО ОТРЕЗКА глаз->подошва: до пола
/// человек дотягивается, не отходя.
///
/// `stand_m` ставит ВЫЗЫВАЮЩИЙ из config::PLAYER_EYE_HEIGHT — второй копии
/// этой строки здесь нет намеренно (файл не знает ни одной константы мира,
/// ровно как DoorAim.h). 0 — «мерить от точки», и это законный ответ для
/// прибора, у которого никакого человека нет.

/// ГАБАРИТ ПРЕДМЕТА В МИРЕ: коробка, повёрнутая вокруг вертикали.
struct SeatAim {
    glm::vec3 centre{0.0f};      ///< середина габарита, мировые
    glm::vec3 half{0.5f};        ///< полугабарит в МЕСТНЫХ осях предмета
    float yaw = 0.0f;            ///< поворот предмета вокруг вертикали, рад
    float reach_m = SEAT_REACH_M;///< радиус руки от ближайшей точки габарита
    /// РОСТ ГЛАЗА НАД ПОДОШВОЙ, м (см. блок выше). Радиус меряется от отрезка
    /// [глаз, глаз - stand_m] до габарита.
    float stand_m = 0.0f;
};

/// ВЕРДИКТ ВМЕСТЕ С ВЕЛИЧИНАМИ. Голый bool заставил бы прибор считать те же
/// числа второй раз — и разойтись с игрой при первой правке (правило 39).
struct SeatAimHit {
    bool ok = false;         ///< и в радиусе, и смотрим
    bool in_reach = false;   ///< радиус до ближайшей точки габарита
    bool looking = false;    ///< луч взгляда пересекает габарит
    float distance_m = 0.0f; ///< глаз -> ближайшая точка габарита
    float t_m = 0.0f;        ///< глаз -> точка входа луча в габарит (0 — мимо)
};

/// МЕСТНЫЕ КООРДИНАТЫ ТОЧКИ ОТНОСИТЕЛЬНО ПРЕДМЕТА. Вынесено отдельно, потому
/// что этой же формулой ставится коробка прицела в физике: коробка и вердикт
/// не могут разъехаться, пока они считаются одним выражением.
[[nodiscard]] glm::vec3 seat_aim_local(const SeatAim& aim, const glm::vec3& world);

/// ЦЕЛИТСЯ ЛИ ГЛАЗ В ЭТОТ ПРЕДМЕТ. `dir` — единичный вектор взгляда
/// (конвенция PlayerMovement: рыск 0 смотрит в -Z, положительный тангаж —
/// вверх).
///
/// ЛУЧ, НАЧАТЫЙ ВНУТРИ ГАБАРИТА, СЧИТАЕТСЯ ПОПАДАНИЕМ — и это НЕ та ошибка,
/// за которую поплатились двери. У двери голова попадала внутрь коробки
/// прицела оттого, что коробка была втрое шире полотна и висела в проёме, где
/// стоят; сюда же голова попадает, только если человек влез внутрь кровати, а
/// это не положение, из которого он смотрит на другую стену. Отдельная
/// проверка «стою в теле» была бы правилом без своего случая.
[[nodiscard]] SeatAimHit seat_aim(const SeatAim& aim, const glm::vec3& eye,
                                  const glm::vec3& dir);

} // namespace dfn::app
