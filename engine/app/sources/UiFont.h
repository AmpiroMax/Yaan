#pragma once

#include <cstdint>
#include <string_view>

#include "engine/render/sources/PixelCanvas.h"

namespace dfn::app {

/// Куда положен актив шрифта. Назван один раз: его читают и загрузчик, и
/// сообщение об отказе.
inline constexpr const char* UI_FONT_METRICS = "assets/fonts/ui_serif.fnt";

/// РОЛИ ТЕКСТА ИНТЕРФЕЙСА — вся лестница размеров, какая есть.
///
/// Пропорции сняты С ПРИНЯТЫХ КАДРОВ c6c0a68, а не выбраны заново: там пункт
/// меню занимал 14 строк из 360 (3.9 % высоты кадра по прописной). Высота
/// прописной у PT Serif — 0.70 кегля, отсюда и доли ниже. Иначе смена шрифта
/// незаметно переставила бы и размеры, и «стало не так, как на приёмке» никто
/// не смог бы назвать числом.
///
/// РОЛИ «ПУНКТ-АКЦЕНТ» БОЛЬШЕ НЕТ. Она была ровно одна на всю лестницу — 0.083
/// от высоты кадра, первый пункт корня и паузы, — и владелец отменил задумку
/// 27.08: «слово ПРОДОЛЖИТЬ бОльшим шрифтом написано, чем остальные —
/// поправить и сделать одинаково везде». Роль СНЯТА, а не оставлена
/// неиспользуемой: ступень, которую никто не просит, через неделю попросят
/// заново, не зная, почему её убрали.
enum class UiText : uint8_t {
    Title = 0, ///< заголовок страницы («Пауза», «Настройки», имя категории)
    Item,      ///< ЛЮБОЙ выбираемый пункт ЛЮБОЙ страницы. Их размер ОДИН.
    Caption,   ///< подпись под пунктом, значение настройки, строка статуса
    Small,     ///< знак студии, сноски — то, что читают, только если ищут
};

/// Кегль роли на холсте высоты `canvas_h`, снапнутый на ближайшую испечённую
/// ступень. Возвращает 0, когда актива нет.
[[nodiscard]] int ui_px(int canvas_h, UiText role);

/// Актив прочитан и хотя бы одна ступень есть.
[[nodiscard]] bool ui_font_ready();

/// Ширина строки в пикселях при кегле `px` (сумма перьевых шагов; последний
/// глиф не добавляет хвостового зазора, поэтому число годится для выравнивания
/// по правому краю).
[[nodiscard]] int ui_text_width(std::string_view utf8, int px);

/// Высота строки: расстояние между верхами двух соседних строк.
[[nodiscard]] int ui_line_height(int px);

/// Высота ПРОПИСНОЙ — то, что глаз считает «размером букв». Раскладка меряет
/// блоки текста именно ею: высота строки включает выносные элементы, которых
/// в «Продолжить» нет, и блок, сложенный по line_height, стоит выше, чем
/// выглядит.
[[nodiscard]] int ui_cap_height(int px);

/// Рисует `utf8` так, что ВЕРХ строки лежит на y (не базовая линия): страницы
/// меню складывались верхами строк ещё под блочным шрифтом, и смена шрифта не
/// должна была стать заодно сменой системы координат раскладки.
/// `shadow` кладёт чёрную копию со смещением — то, чем светлый текст держится
/// над затемнённым миром на странице паузы. Возвращает ширину.
int ui_draw_text(render::PixelCanvas& canvas, int x, int y, std::string_view utf8,
                 render::Color color, int px, bool shadow = false);

} // namespace dfn::app
