#pragma once

#include <cstdint>

#include <glm/vec3.hpp>

namespace dfn::app {

/// ВСЕ РУЧКИ ХВАТА В ОДНОМ МЕСТЕ.
struct GrabTuning {
    /// СКОЛЬКО ДЕРЖАТЬ, ЧТОБЫ ЭТО СЧИТАЛОСЬ «ВЗЯТЬ», с. 0.25 — заметно больше
    /// самого медленного человеческого щелчка (обычное нажатие 0.08-0.12 с) и
    /// заметно меньше времени, за которое рука устаёт ждать. Ниже 0.15
    /// открывание двери начинало бы иногда поднимать её ручку.
    float hold_s = 0.25f;
    /// РАДИУС РУКИ ДО ПРЕДМЕТА, м. Та же школа, что у двери (DOOR_REACH_M) и у
    /// мебели (SEAT_REACH_M): шаг перед предметом плюс радиус капсулы. Чуть
    /// больше их 1.2, потому что утварь мелкая и целятся в неё сверху вниз со
    /// стола, а не в упор.
    float reach_m = 1.6f;
    /// ГДЕ ПЕРЕД ГЛАЗОМ ВИСИТ ВЗЯТОЕ, м. 0.9 — вытянутая рука: ближе предмет
    /// закрывает пол-экрана, дальше он уже не «в руках».
    float carry_m = 0.90f;
    /// НА СКОЛЬКО ОПУСТИТЬ ТОЧКУ НОШЕНИЯ ОТ ЛУЧА ВЗГЛЯДА, м. Предмет, висящий
    /// ровно в перекрестье, закрывает то, куда идёшь.
    float carry_drop_m = 0.15f;
    /// ЗА СКОЛЬКО ПРУЖИНА ХОЧЕТ ВЫБРАТЬ РАССТОЯНИЕ, с. Это и есть жёсткость,
    /// но в единицах, которые можно проверить секундомером: 0.08 с — предмет
    /// догоняет руку за пять кадров.
    float reach_time_s = 0.08f;
    /// ПОТОЛОК СКОРОСТИ ВЕДЕНИЯ, м/с. Без него пружина, дотянувшись из-за
    /// угла, швыряет предмет сквозь стену за один тик — тело успевает пройти
    /// больше своей толщины между двумя проверками столкновений.
    float max_speed = 6.0f;
    /// ПОТОЛОК СИЛЫ ХВАТА, Н. 350 Н — это 35 кг, поднятые с ускорением 1g:
    /// кувшин и книга летят к руке мгновенно, мешок зерна (46 кг) ползёт,
    /// сундук не трогается вовсе. Именно эта величина делает вес ЗАМЕТНЫМ.
    float max_force_n = 350.0f;
    /// НА СКОЛЬКО ПРЕДМЕТ МОЖЕТ ОТСТАТЬ ОТ РУКИ, ПРЕЖДЕ ЧЕМ ВЫПАДЕТ, м.
    /// Заклиненный за косяком предмет обязан выпасть, а не тянуть игрока и не
    /// пройти сквозь дверь (записка №4, Б4.4). 0.8 — заметно больше, чем
    /// отставание на быстром развороте (замер: 0.25-0.35 м).
    float slip_m = 0.80f;
    /// СКОЛЬКО ВРЕМЕНИ ТЕРПЕТЬ ОТСТАВАНИЕ, с. Мгновенное выпадение отбирало бы
    /// предмет на каждом резком повороте; 0.35 с — это «он застрял», а не «я
    /// быстро обернулся».
    float slip_time_s = 0.35f;
    /// ИМПУЛЬС БРОСКА, Н*с. Скорость броска = импульс / масса, ограниченная
    /// потолком: кубок летит через комнату, мешок падает под ноги.
    float throw_impulse = 12.0f;
    float throw_max_speed = 8.0f;
    /// СКОРОСТЬ ВРАЩЕНИЯ ПРЕДМЕТА В РУКАХ, рад/с на щелчок колеса.
    float spin_rate = 2.2f;
};

/// ЧТО СЛУЧИЛОСЬ С КЛАВИШЕЙ. Считается по СЫРОМУ состоянию клавиши, а не по
/// защёлке: защёлку гасит выход из позы (волна «сидеть и лежать» гасит
/// interact_pressed в park_posture), и долгое нажатие сидящего было бы съедено.
enum class GrabPress : std::uint8_t {
    None = 0,     ///< ничего
    Holding = 1,  ///< клавиша нажата, но порога ещё не набрала
    Long = 2,     ///< порог набран — это «взять»
};

/// Состояние счётчика удержания между тиками.
struct GrabHold {
    float held_s = 0.0f;  ///< сколько клавиша уже нажата
    bool consumed = false; ///< долгое нажатие уже засчитано (не считать дважды)
};

/// Двигает счётчик на один тик и говорит, что это было.
/// `down` — сырое состояние клавиши СЕЙЧАС.
[[nodiscard]] GrabPress grab_press(GrabHold& hold, bool down, float dt,
                                   const GrabTuning& t);

/// СКОРОСТЬ, КОТОРУЮ НАДО НАПИСАТЬ ТЕЛУ ЭТОТ ТИК, чтобы оно шло к `target`.
/// Ускорение ограничено потолком силы, делённым на массу, — отсюда весь вес.
[[nodiscard]] glm::vec3 grab_velocity(const glm::vec3& position, const glm::vec3& velocity,
                                      const glm::vec3& target, float mass_kg, float dt,
                                      const GrabTuning& t);

/// ВЫПАЛ ЛИ ПРЕДМЕТ ИЗ РУК. `lag_s` — сколько уже длится отставание; функция
/// его же и двигает.
[[nodiscard]] bool grab_slipped(float distance_m, float dt, float& lag_s,
                                const GrabTuning& t);

/// Скорость броска для тела такой массы.
[[nodiscard]] float throw_speed(float mass_kg, const GrabTuning& t);

} // namespace dfn::app
