#pragma once

#include <cstdint>
#include <filesystem>
#include <glm/vec3.hpp>
#include <map>
#include <span>
#include <string>
#include <vector>

namespace dfn::app {

/// СТАТИЧНОЕ ИЛИ ПОДВИЖНОЕ. Не «тяжёлое/лёгкое»: кровать тяжела, но неподвижна
/// не поэтому, а потому что она ОБСТАНОВКА — на ней спят, у неё точка позы, и
/// уехавшая из-под спящего кровать была бы дефектом, а не физикой. Ровно эту
/// границу проводит Skyrim: мебель статична, утварь — клаттер.
enum class PropClass : std::uint8_t { Fixed = 0, Loose = 1 };

/// Плотность вещества, кг/м³, из таблицы ядра. -1 — имени нет в таблице
/// (вызывающий обязан проверить: молча взятый ноль дал бы невесомую утварь).
[[nodiscard]] float substance_density(std::string_view substance);

/// СТРОКА РЕЕСТРА ФИЗИКИ: что это за предмет.
struct PropRow {
    PropClass cls = PropClass::Fixed;
    std::string substance;  ///< имя из таблицы веществ ядра
    /// ТОЛЩИНА СТЕНКИ, м. 0 — предмет СПЛОШНОЙ (табурет, каравай, полено).
    /// Больше нуля — ОБОЛОЧКА, и тогда веществом занят не объём, а стенка.
    float wall_m = 0.0f;
    /// ЗАПОЛНЕНИЕ: какая доля НАРИСОВАННОГО объёма — вещество. 1 — вся.
    ///
    /// ЭТО НЕ ПОДГОНКА ПОД ЖЕЛАЕМОЕ ЧИСЛО, А ПРИЗНАНИЕ ИЗМЕРЕННОГО ФАКТА:
    /// кузница печёт БРУС ВДВОЕ ТОЛЩЕ настоящего. Замер по полке: у стула
    /// полки дерева 0.0223 м³, у настоящего стула той же формы (ножки 40 мм,
    /// сиденье 30 мм, три доски спинки) — 0.011; у стола 0.167 против 0.078.
    /// Отношение в обоих случаях около двух, и оно ОДНО И ТО ЖЕ, потому что
    /// причина одна — сечение бруска в рецепте.
    ///
    /// СТОЛБЕЦ УЙДЁТ К ЕДИНИЦЕ, КОГДА КУЗНИЦА СТАНЕТ ТОЧНЕЕ, и это проверяемо:
    /// заполнение меньше единицы у предмета — заявка на то, что его чертёж
    /// грубее вещи, а не на то, что он лёгкий.
    ///
    /// У ОБОЛОЧКИ заполнение не применяется: там долю вещества уже назвала
    /// толщина стенки, и умножать одно на другое значило бы сказать одно и то
    /// же дважды.
    float fill = 1.0f;
    std::string note;       ///< человеческий комментарий строки (не читается кодом)
};

/// Читает таблицу «имя класс вещество тело[solid|стенка в мм] [заполнение] # заметка».
/// Пустая карта на отсутствующем файле — и это ЗАКОННЫЙ ответ: мир без таблицы
/// ведёт себя ровно как вчера (всё неподвижно), а не падает.
[[nodiscard]] std::map<std::string, PropRow> load_prop_table(
    const std::filesystem::path& path);

/// СКОЛЬКО В ПРЕДМЕТЕ ВЕЩЕСТВА — посчитано по его собственным треугольникам.
struct MeshBulk {
    float volume_m3 = 0.0f;  ///< знаковый объём (дивергенция), всегда >= 0
    float area_m2 = 0.0f;    ///< площадь поверхности
    glm::vec3 lo{0.0f};      ///< габарит
    glm::vec3 hi{0.0f};
    float bbox_m3 = 0.0f;
    std::uint32_t triangles = 0;
};

/// Объём/площадь/габарит по треугольникам (indices — по три на треугольник).
[[nodiscard]] MeshBulk measure_bulk(std::span<const glm::vec3> positions,
                                    std::span<const std::uint32_t> indices);

/// МАССА ВМЕСТЕ С ПРИЧИНОЙ. Голое число заставило бы отчёт считать те же
/// величины второй раз и разойтись с игрой при первой правке (правило 39).
struct PropMass {
    float mass_kg = 0.0f;
    float used_volume_m3 = 0.0f; ///< объём, который пошёл в массу
    bool shell = false;          ///< масса посчитана по стенке, а не по объёму
    /// ОБОЛОЧКА НЕ СШИТА. Знаковый объём меша, у которого не сходятся края,
    /// не значит ничего: у корзины из трёх поясов плетения он может выйти
    /// хоть отрицательным. Тогда масса берётся по габариту с заполнением, и
    /// об этом ГОВОРИТСЯ — молчание здесь и есть мир двухсоткилограммовых
    /// сундуков, о котором предупреждала записка №4.
    bool fell_back = false;
    std::string finding; ///< пусто, когда всё сошлось
};

/// ДОЛЯ ГАБАРИТА, которую считаем занятой веществом, когда знаковый объём
/// негоден. Не «на глаз»: это НИЖНЯЯ разумная граница полосы ниже — то есть
/// самый лёгкий из правдоподобных ответов. Ошибиться в сторону лёгкого честнее:
/// слишком лёгкая корзина ездит по полу, слишком тяжёлая молча не поднимается,
/// и второе неотличимо от сломанного хвата.
inline constexpr float PROP_FALLBACK_FILL = 0.08f;

/// ПОЛОСА ПРАВДОПОДОБИЯ для отношения «знаковый объём / габарит». Ниже — меш
/// не замкнут или вывернут (плоский коврик, плетёная корзина); выше единицы
/// объём физически невозможен.
inline constexpr float PROP_VOLUME_RATIO_MIN = 0.02f;
inline constexpr float PROP_VOLUME_RATIO_MAX = 1.02f;

/// Границы массы: ниже нижней предмет не имеет веса вовсе (числовой шум даёт
/// летающую крошку), выше верхней — это уже не предмет.
inline constexpr float PROP_MASS_MIN_KG = 0.05f;
inline constexpr float PROP_MASS_MAX_KG = 400.0f;

/// Масса предмета из его геометрии и строки реестра.
[[nodiscard]] PropMass prop_mass(const MeshBulk& bulk, const PropRow& row,
                                 std::string_view name);

/// ТОЧКИ ВЫПУКЛОЙ ОБОЛОЧКИ ДЛЯ ТЕЛА. Прореживание — не оптимизация ради
/// оптимизации: построение оболочки у Jolt квадратично по точкам в худшем
/// случае, а комната поднимает тридцать тел за один вход в дом.
/// Прореживание идёт РАВНОМЕРНЫМ ШАГОМ по списку вершин, и это осознанно
/// хуже, чем выбор крайних: шаг не умеет потерять целую грань (он берёт
/// вершины отовсюду), а «выбрать крайние» — это и есть построение оболочки,
/// то есть та самая работа, которую мы пытаемся сократить.
[[nodiscard]] std::vector<glm::vec3> hull_points(std::span<const glm::vec3> positions,
                                                 std::size_t max_points);

/// СКОЛЬКО ТОЧЕК ХВАТИТ ОБОЛОЧКЕ. 192 — выше числа вершин любого подвижного
/// предмета сегодняшней полки (самый крупный, котёл, несёт 264 треугольника,
/// то есть заметно меньше вершин), поэтому сегодня прореживание НЕ СРАБАТЫВАЕТ
/// ни разу и оболочка точна. Порог заведён на завтра — на предмет, который
/// кузница испечёт вдесятеро подробнее.
inline constexpr std::size_t PROP_HULL_MAX_POINTS = 192;

} // namespace dfn::app
