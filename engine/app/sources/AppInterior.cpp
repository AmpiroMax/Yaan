/// ДОЗА СВЕТА ИНТЕРЬЕРА (DFN_INTERIOR_LIGHT), 0..1. 0 — прежний кадр
/// бит-в-бит: ambient локации как записан, огни как записаны. Живёт функцией,
/// а не значением, потому что читается в enter_interior, то есть уже после
/// разбора командной строки, и обязана быть ОДНОЙ на весь прогон (правило
/// таблицы дверей: доза — это Once, а не переключатель внутри прибора).
float App::interior_light_dose() {
    static const float dose = [] {
        const char* e = door_value("DFN_INTERIOR_LIGHT");
        if (e == nullptr || *e == '\0') {
            return 1.0f;
        }
        return std::clamp(std::strtof(e, nullptr), 0.0f, 1.0f);
    }();
    return dose;
}

/// ДОЗА ПРИЦЕЛА (DFN_DOOR_AIM). 1 (умолчание) — радиус ПЛЮС взгляд: плита по
/// полотну и вердикт door_aim(). 0 — прежний прицел бит-в-бит: куб вокруг
/// середины створки, радиус 1.6 м, никакой проверки взгляда. Отрицательное
/// плечо нужно не для красоты: «надпись горит с порога» и «надпись горит
/// только на дверь» обязаны предъявляться ОДНИМ бинарником (правило 47), иначе
/// «до» и «после» меряют неделю чужой работы.
bool App::door_aim_enabled() {
    static const bool on = [] {
        const char* e = door_value("DFN_DOOR_AIM");
        return e == nullptr || *e == '\0' || *e != '0';
    }();
    return on;
}

DoorAim App::doorway_aim(const HouseDoorway& d) {
    DoorAim a;
    a.at = d.at;
    a.normal = d.out_normal;
    a.half_w = std::max(d.half_w, 0.05f);
    a.half_h = std::max(d.half_h, 0.05f);
    a.reach_m = d.reach_m > 0.0f ? d.reach_m : DOOR_REACH_M;
    a.leaf = true;
    return a;
}

DoorAimHit App::door_aim_now(const PortalLink& link) const {
    DoorAimHit miss;
    const auto* cam = world_.get<components::CameraPose>(player_);
    if (cam == nullptr) {
        return miss;
    }
    // ВЗГЛЯД БЕРЁТСЯ ИЗ ТОЙ ЖЕ ПОЗЫ, ЧТО И ЛУЧ ПРИЦЕЛА (CameraPose, которую
    // пишет post_step), и по той же конвенции: рыск 0 смотрит в -Z,
    // положительный — по часовой сверху, положительный тангаж — вверх. Формула
    // повторяет InteractionSystem::view_direction и render::direction_from —
    // обе внутренние для своих файлов; расхождение здесь означало бы, что
    // подсказка загорается не там, куда указывает перекрестье.
    const float cp = std::cos(cam->pitch);
    const glm::vec3 dir{std::sin(cam->yaw) * cp, std::sin(cam->pitch),
                        -std::cos(cam->yaw) * cp};
    return door_aim(link.aim, cam->position, dir);
}

void App::filter_door_hover() {
    if (!door_aim_enabled() || !world_.has_resource<components::HoverTarget>()) {
        return;
    }
    auto& hover = world_.resource<components::HoverTarget>();
    if (hover.prompt_key == 0 || !world_.alive(hover.entity)) {
        return;
    }
    for (const PortalLink& link : portals_) {
        if (link.entity != hover.entity) {
            continue;
        }
        // ЛУЧ ПРИЦЕЛА УЖЕ ПОПАЛ В ТЕЛО ДВЕРИ — И ЭТОГО МАЛО. Jolt считает луч,
        // НАЧАТЫЙ ВНУТРИ выпуклого тела, попаданием на нулевой доле: голова,
        // оказавшаяся внутри коробки прицела, зажигала подсказку под любым
        // углом, включая взгляд в противоположную стену. Ровно это владелец и
        // прислал 28.08 («захожу в дом — сразу горит „выйти"»). Плита по
        // полотну делает такое положение головы невозможным у запечатанной
        // створки, но у ДЕКОРАТИВНОЙ проём сквозной и в нём стоят — значит
        // одной геометрии тела мало, и вердикт выносится здесь.
        if (!door_aim_now(link).ok) {
            hover = components::HoverTarget{};
        }
        return;
    }
}

void App::present_loading_frame(const char* shot_stem) {
    if (renderer_ == nullptr || window_ == nullptr) {
        return;
    }
    render::PixelCanvas& c = render_system_.hud();
    if (c.width() == 0 || c.height() == 0) {
        return;
    }
    loading_.draw(c);
    // БЕЗ ЭТОЙ СТРОКИ ЭКРАН НЕВИДИМ, и это не гипотеза: прогресс запекания
    // ассетов рисовался в тот же холст с 18.08 и никогда не показывался —
    // render гейтит блит на hud_visible_, а его выставляет только run().
    render_system_.set_hud_visible(true);
    window_->poll_events();
    render_system_.render(world_, *renderer_, camera_, 0.0f);
    // КАДР ЭКРАНА ЗАГРУЗКИ ИНАЧЕ НЕ ПОПАДАЕТ НИ НА ОДИН БЕСПИЛОТНЫЙ ПРОГОН.
    // Экран живёт между двумя кадрами штатной петли и потому невидим для
    // DFN_SHOT_AFTER, который считает ПОКАЗАННЫЕ ею кадры. Снимок пишется
    // ровно один раз НА СТВОЛ ИМЕНИ и только туда, куда прогон уже складывает
    // снимки, — новой двери для этого не нужно.
    if (shot_stem == nullptr || capture_dir_.empty() || !unattended_run()) {
        return;
    }
    const std::string stem(shot_stem);
    for (const std::string& done : loading_shots_) {
        if (done == stem) {
            return;
        }
    }
    loading_shots_.push_back(stem);
    (void)renderer_->save_screenshot(capture_dir_ + "/" + stem + "_000.png");
}

void App::load_step(const char* what) {
    if (!loading_.active()) {
        return;
    }
    loading_.stage(what);
    // ЯВНАЯ ДОЛЯ ГАСИТСЯ НА ГРАНИЦЕ ЭТАПА. Оставленная от предыдущего этапа,
    // она прибила бы полосу к его последнему проценту: экран показывал бы
    // движение внутри одного этапа и мёртвую полосу во всех остальных.
    loading_.set_progress(-1.0f);
    loading_frame_at_ = std::chrono::steady_clock::now();
    present_loading_frame(loading_shot_stem_);
}

void App::load_tick(float fraction) {
    if (!loading_.active()) {
        return;
    }
    const auto now = std::chrono::steady_clock::now();
    if (now - loading_frame_at_ < std::chrono::milliseconds(LOAD_FRAME_MIN_MS)) {
        return;
    }
    loading_frame_at_ = now;
    // ДОЛЯ ЭТАПА — ЭТО ДОЛЯ ЕГО КУСКА ПОЛОСЫ, а не всей полосы. Иначе на
    // границе каждого этапа полоса прыгала бы назад, к началу следующего
    // куска, — движение, которое человек читает как «загрузка сорвалась».
    const std::size_t done = loading_.stages().size();
    const std::size_t total = std::max(loading_.expected(), done + 1);
    loading_.set_progress((static_cast<float>(done)
                           + std::clamp(fraction, 0.0f, 1.0f))
                          / static_cast<float>(total));
    present_loading_frame(loading_shot_stem_);
}

void App::hold_loading_screen() {
    // ДЛИТЕЛЬНОСТЬ ЭКРАНА — ЭТО КАДРЫ, А НЕ ОДИН КАДР И ЗАСЫПАНИЕ. Спать
    // нельзя: окно перестаёт отвечать ОС, и рабочий стол помечает
    // приложение как зависшее посреди его же экрана загрузки (то же
    // рассуждение, что у полосы запекания ассетов).
    if (interior_fade_s_ <= 0.0f) {
        return;
    }
    const auto until = std::chrono::steady_clock::now()
                     + std::chrono::duration_cast<std::chrono::steady_clock::duration>(
                           std::chrono::duration<float>(interior_fade_s_));
    while (std::chrono::steady_clock::now() < until) {
        present_loading_frame(loading_shot_stem_);
    }
}

void App::upload_interior_body(const std::vector<std::uint32_t>& indices) {
    if (physics_ == nullptr) {
        return;
    }
    if (interior_body_.valid()) {
        physics_->destroy_body(interior_body_);
        interior_body_ = {};
    }
    if (interior_positions_.empty() || indices.empty()) {
        // Пустая локация — законное состояние (город без открытого дома).
        // Плита при этом тоже не нужна: падать некому.
        if (interior_plate_.valid()) {
            physics_->destroy_body(interior_plate_);
            interior_plate_ = {};
        }
        return;
    }
    platform::TerrainMeshDesc desc;
    desc.positions = interior_positions_;
    desc.indices = indices;
    desc.layer = physics::LAYER_STATIC;
    interior_body_ = physics_->create_terrain_mesh(desc);
    if (!interior_body_.valid()) {
        std::fprintf(stderr,
                     "[интерьер] коллайдер локации НЕ создан — сквозь стены "
                     "комнаты можно пройти\n");
    }
    if (interior_plate_.valid()) {
        physics_->destroy_body(interior_plate_);
        interior_plate_ = {};
    }
    platform::StaticBoxDesc plate;
    plate.center = {interior_pocket_.x, interior_pocket_.y - PLATE_DROP_M,
                    interior_pocket_.z};
    plate.half_extents = {PLATE_HALF_M, 0.5f, PLATE_HALF_M};
    plate.layer = physics::LAYER_STATIC;
    interior_plate_ = physics_->create_static_box(plate);
}

void App::clear_scene_portals(bool interior) {
    for (auto it = portals_.begin(); it != portals_.end();) {
        if (it->interior != interior) {
            ++it;
            continue;
        }
        if (world_.alive(it->entity)) {
            world_.destroy_deferred(it->entity);
        }
        it = portals_.erase(it);
    }
    world_.flush_destroyed();
    if (physics_ == nullptr
        || !world_.has_resource<gameplay::InteractableBodies>()) {
        return;
    }
    // Тела прицела снимает штатная уборка взаимодействий — она уже умеет
    // это делать по мёртвой сущности, и вторая уборка была бы вторым
    // владельцем одного ресурса.
    gameplay::reap_interactable_bodies(world_, *physics_);
}

void App::spawn_scene_portals(const world::SceneDoc& doc, bool interior,
                              const glm::vec3* entry) {
    if (physics_ == nullptr) {
        return;
    }
    clear_scene_portals(interior);
    // КООРДИНАТЫ ЛОКАЦИИ — СВОИ ОТ НУЛЯ, И ЭТО КАСАЕТСЯ ПЕРЕХОДОВ ТОЖЕ.
    // Композиция интерьера пишет позиции от собственного нуля (шапка любой
    // assets/scenes/int/**.scene: «Координаты СВОИ от нуля»), и enter_interior
    // сдвигает в карман ВСЁ, что из неё поднимает: постройки (H.position +
    // карман), светильники, точку входа. Прицел обратной двери сдвига не
    // получал — и вставал не в километре под городом, а посреди самого
    // города, на y ≈ 1.6 м. Изнутри его не было НИГДЕ: игрок входил в дом и
    // не мог выйти (жалоба владельца 27.08, живая игра). Беспилотный замер
    // выхода этого не поймал и не мог: DFN_INTERIOR_EXIT зовёт
    // leave_interior() напрямую, минуя прицел.
    const glm::vec3 origin = interior ? interior_pocket_ : glm::vec3{0.0f};
    for (std::size_t i = 0; i < doc.portals.size(); ++i) {
        const world::ScenePortal& P = doc.portals[i];
        const glm::vec3 at = P.at + origin;
        const ecs::EntityId id = world_.spawn();
        // ПЕРЕХОД НЕ РИСУЕТСЯ. Створка двери уже стоит в сцене как деталь
        // постройки; сущность здесь — только прицел и подсказка. Второй,
        // нарисованный «предмет-дверь» поверх настоящей двери — это два
        // описания одной вещи, и они разъедутся при первой правке дома.
        world_.add(id, components::Transform{.position = at,
                                             .rotation = {1.0f, 0.0f, 0.0f, 0.0f},
                                             .scale = glm::vec3{1.0f}});
        const std::uint64_t action =
            serialization::fnv1a64(P.to + "@" + std::to_string(i));
        // ПРИЦЕЛ ОБРАТНОЙ ДВЕРИ — ЭТО ЕЁ ПОЛОТНО, А НЕ ШАР ВОКРУГ ТОЧКИ.
        // РАСТЯЖКА СНЯТА (она стояла здесь с 27.08: радиус дотягивался до
        // точки входа, если та стояла вбок от створки). Растяжка была платой
        // за кривые спавны генератора, и платы этой больше нет: перепись 130
        // локаций обоих городов даёт худший отход точки входа 0.74 м по
        // горизонтали при радиусе руки 1.2 — промахов 0 из 130. А цена у неё
        // была ровно та, на которую владелец пожаловался 28.08: раздутая
        // коробка накрывала голову вошедшего, и подсказка «Выйти» горела с
        // порога под любым углом.
        //
        // ГДЕ ВЗЯТЬ ПОЛОТНО. У точки перехода нет ни нормали, ни ширины —
        // значит створка ищется среди СТВОРОК ЛОКАЦИИ, собранных заливкой из
        // той же геометрии, что и городские. Не нашлась (стенд, пилот,
        // композиция без оболочки) — прицел вырождается в конус вокруг точки,
        // и об этом печатается строка: молчаливое «беру любой угол» вернуло бы
        // жалобу.
        DoorAim aim;
        aim.at = at;
        aim.reach_m = DOOR_REACH_M;
        aim.leaf = false;
        if (interior) {
            float best = BACK_LEAF_SEARCH_M;
            for (const HouseDoorway& D : interior_doorways_) {
                const float dist = glm::length(D.at - at);
                if (dist < best) {
                    best = dist;
                    aim = doorway_aim(D);
                }
            }
        }
        float r = std::max(P.radius_m, 0.4f);
        float half_y = std::max(r, 1.0f);
        float reach = std::max(P.radius_m, 0.5f);
        if (door_aim_enabled()) {
            // РАДИУС ПРОВЕРЯЕТ ВЕРДИКТ, А НЕ ОБЩАЯ ДАЛЬНОСТЬ ВЗАИМОДЕЙСТВИЯ:
            // max_use_distance = 0 отдаёт штатное INTERACT_DISTANCE, и тогда
            // «в радиусе ли я» решается в ОДНОМ месте (door_aim), а не в двух.
            reach = 0.0f;
        }
        world_.add(id, gameplay::Highlightable{
                           .prompt_key = interior ? "prompt.leave" : "prompt.enter",
                           .max_use_distance = reach});
        world_.add(id, gameplay::Usable{.action = action,
                                        .repeatable = true,
                                        .used = false});
        platform::StaticBoxDesc box;
        box.center = at;
        box.half_extents = {r, half_y, r};
        if (door_aim_enabled()) {
            // ТЕЛО ПРИЦЕЛА СТАВИТСЯ ИЗ ТОГО ЖЕ ПРЯМОУГОЛЬНИКА, по которому
            // выносится вердикт: коробка и вердикт не могут разъехаться,
            // потому что это одни и те же четыре числа.
            box.center = aim.at;
            if (aim.leaf) {
                box.rotation = glm::angleAxis(door_leaf_yaw(aim.normal),
                                              glm::vec3{0.0f, 1.0f, 0.0f});
                box.half_extents = {aim.half_w + DOOR_AIM_PAD_M,
                                    aim.half_h + DOOR_AIM_PAD_M,
                                    DOOR_AIM_SLAB_HALF_M};
            } else {
                // ТОЧКА БЕЗ ПОЛОТНА: коробка остаётся прежней, написанной в
                // композиции. Она здесь не судья, а лишь то, во что обязан
                // попасть луч, чтобы вопрос вообще был задан: перехода-точки
                // не видно в кадре, и сузить его тело значило бы заставить
                // игрока угадывать невидимое. Решает конус вердикта.
                box.half_extents = {r, half_y, r};
            }
        }
        box.layer = physics::LAYER_INTERACTABLE;
        box.user_data = id.packed();
        const platform::PhysicsBodyHandle body = physics_->create_static_box(box);
        if (body.valid()) {
            if (!world_.has_resource<gameplay::InteractableBodies>()) {
                world_.add_resource(gameplay::InteractableBodies{});
            }
            world_.resource<gameplay::InteractableBodies>()
                .bodies[id.packed()] = body;
        }
        PortalLink link;
        link.action = action;
        link.index = i;
        link.interior = interior;
        link.entity = id;
        link.aim = aim;
        portals_.push_back(std::move(link));
        if (interior && world::portal_is_back(P)) {
            // ЧЕМ ИМЕННО ЦЕЛИТСЯ ОБРАТНАЯ ДВЕРЬ — В СТРОКЕ. «Полотно найдено»
            // и «взят конус вокруг точки» дают разное поведение под одной и
            // той же подсказкой, и без числа их не различить ни в логе, ни
            // глазами.
            std::fprintf(stderr,
                         "[интерьер] прицел обратной двери: %s, полотно "
                         "(%.2f %.2f %.2f) %.2fx%.2f м, нормаль (%.2f %.2f), "
                         "радиус %.2f м\n",
                         aim.leaf ? "ПОЛОТНО" : "точка (створки не нашлось)",
                         static_cast<double>(aim.at.x),
                         static_cast<double>(aim.at.y),
                         static_cast<double>(aim.at.z),
                         static_cast<double>(aim.half_w * 2.0f),
                         static_cast<double>(aim.half_h * 2.0f),
                         static_cast<double>(aim.normal.x),
                         static_cast<double>(aim.normal.z),
                         static_cast<double>(aim.reach_m));
            if (entry != nullptr) {
                // ДОСТАЁТ ЛИ ПРИЦЕЛ ДО ТОЧКИ ВХОДА — ТЕПЕРЬ ЗАМЕР, А НЕ
                // ПОПРАВКА. Раньше несовпадение молча растягивало коробку;
                // теперь оно называется числом и чинится в генераторе, у
                // которого одного есть на это право.
                const glm::vec3 eye{entry->x, entry->y + PLAYER_EYE_M, entry->z};
                const glm::vec3 to_door = glm::normalize(aim.at - eye);
                const DoorAimHit h = door_aim(aim, eye, to_door);
                std::fprintf(stderr,
                             "[интерьер] точка входа: до полотна %.2f м "
                             "(радиус %.2f) — %s\n",
                             static_cast<double>(h.distance_m),
                             static_cast<double>(aim.reach_m),
                             h.ok ? "дверь берётся рукой"
                                  : "ДВЕРИ ИЗ ТОЧКИ ВХОДА НЕ ДОСТАТЬ (дефект "
                                    "композиции локации)");
            }
        }
    }
    if (!doc.portals.empty()) {
        // МИРОВАЯ ОТМЕТКА ПЕРВОГО ПЕРЕХОДА — В СТРОКЕ, и это не украшение:
        // ровно её отсутствие скрывало дефект кармана. «Переходов на локации:
        // 1» печаталось верно и тогда, когда единственный прицел стоял на
        // километр выше игрока. Число, а не состояние (тот же довод, что у
        // LoadStage.ms).
        const glm::vec3 first = doc.portals.front().at + origin;
        std::fprintf(stderr,
                     "[интерьер] переходов на %s: %zu (первый в мире %.1f %.1f "
                     "%.1f)\n",
                     interior ? "локации" : "карте", doc.portals.size(),
                     static_cast<double>(first.x), static_cast<double>(first.y),
                     static_cast<double>(first.z));
    }
}

void App::spawn_house_portals() {
    if (physics_ == nullptr || house_doorways_.empty()) {
        return;
    }
    std::size_t open = 0;
    std::size_t decor = 0;
    for (std::size_t i = 0; i < house_doorways_.size(); ++i) {
        const HouseDoorway& D = house_doorways_[i];
        const ecs::EntityId id = world_.spawn();
        world_.add(id, components::Transform{.position = D.at,
                                             .rotation = {1.0f, 0.0f, 0.0f, 0.0f},
                                             .scale = glm::vec3{1.0f}});
        // ДЕЙСТВИЕ ИМЕНУЕТСЯ ТОЧКОЙ, А НЕ НОМЕРОМ ЗАПИСИ. Номер створки живёт
        // внутри прогона (порядок заливки), а координата — свойство города:
        // два перехода одного дома не сольются, а перевыпуск карты не
        // переназначит действия соседям.
        const std::uint64_t action = serialization::fnv1a64(
            "house-door@" + std::to_string(static_cast<int>(D.at.x * 100.0f))
            + "," + std::to_string(static_cast<int>(D.at.y * 100.0f))
            + "," + std::to_string(static_cast<int>(D.at.z * 100.0f)));
        // ТРИ ТИПА — ТРИ НАДПИСИ, И НИ ОДНОГО МОЛЧАНИЯ (владелец 26.08:
        // «остальные двери честно говорят заперто»; 27.08: «должны быть и
        // декоративные двери, что будут просто открываться»). Подсказка под
        // прицелом уже есть у каждого взаимодействия — новой системы не нужно,
        // нужен ключ строки по ТИПУ створки.
        const char* prompt = D.kind == DoorwayKind::Portal     ? "prompt.enter"
                             : D.kind == DoorwayKind::Locked   ? "prompt.locked"
                                                               : "prompt.open";
        const DoorAim aim = doorway_aim(D);
        world_.add(id, gameplay::Highlightable{
                           .prompt_key = prompt,
                           // Радиус решает вердикт прицела, и только он
                           // (см. spawn_scene_portals): 0 — штатная дальность.
                           .max_use_distance =
                               door_aim_enabled() ? 0.0f : 1.6f});
        world_.add(id, gameplay::Usable{.action = action,
                                        .repeatable = true,
                                        .used = false});
        platform::StaticBoxDesc box;
        box.center = D.at;
        if (door_aim_enabled()) {
            // ТЕЛО ПРИЦЕЛА — ПЛИТА ПО ПОЛОТНУ, повёрнутая вместе с ним.
            // Прежний куб 1.4x2.2x1.4 вокруг середины створки был вдвое шире
            // самой двери и, главное, ОБЪЁМОМ: в него входила голова стоящего
            // в проёме, а луч из нутра выпуклого тела Jolt засчитывает
            // попаданием на нулевой доле — подсказка загоралась без всякого
            // взгляда. Плита в 0.4 м толщиной живёт В СТЕНЕ.
            box.rotation = glm::angleAxis(door_leaf_yaw(aim.normal),
                                          glm::vec3{0.0f, 1.0f, 0.0f});
            box.half_extents = {aim.half_w + DOOR_AIM_PAD_M,
                                aim.half_h + DOOR_AIM_PAD_M,
                                DOOR_AIM_SLAB_HALF_M};
        } else {
            // ОТРИЦАТЕЛЬНОЕ ПЛЕЧО (DFN_DOOR_AIM=0): прежний куб бит-в-бит.
            box.half_extents = {0.7f, 1.1f, 0.7f};
        }
        box.layer = physics::LAYER_INTERACTABLE;
        box.user_data = id.packed();
        const platform::PhysicsBodyHandle body = physics_->create_static_box(box);
        if (body.valid()) {
            if (!world_.has_resource<gameplay::InteractableBodies>()) {
                world_.add_resource(gameplay::InteractableBodies{});
            }
            world_.resource<gameplay::InteractableBodies>()
                .bodies[id.packed()] = body;
        }
        PortalLink link;
        link.action = action;
        link.index = i;
        link.interior = false;
        link.house = true;
        link.to = D.interior;
        // ИМЯ ТОЧКИ ВХОДА ОДНО НА ВСЕ ДОМА: у локации волны Б одна дверь, и
        // называется она так же, как у пилота. Локация с двумя дверями
        // получит имена тогда, когда получит вторую дверь.
        link.to_spawn = D.interior.empty() ? std::string{} : std::string{"door"};
        link.entity = id;
        link.kind = D.kind;
        link.door_index = D.door_index;
        // ОБРАТНЫЙ АДРЕС — ЗДЕСЬ, А НЕ НА ВЫХОДЕ. Он выведен из полотна
        // (середина створки плюс шаг по наружной нормали), и потому один и тот
        // же, сколько бы раз игрок ни входил и с какой бы стороны ни подходил.
        // Высота остаётся высотой середины створки: на землю точку сажает
        // выход, лучом вниз, — там она уже пересчитывается по СЕГОДНЯШНЕЙ
        // геометрии крыльца, а не по той, что была на загрузке.
        link.back_at = D.at + D.out_normal * STEP_OUT_M;
        // ВЗГЛЯД ОТ ДОМА: игрок стоит СПИНОЙ К ДВЕРИ (владелец 27.08).
        // yaw 0 смотрит в -Z, положительный — по часовой сверху (конвенция
        // PlayerMovement и InteractionSystem::view_direction).
        link.back_yaw = std::atan2(D.out_normal.x, -D.out_normal.z);
        link.back_set = true;
        link.aim = aim;
        portals_.push_back(std::move(link));
        open += D.kind == DoorwayKind::Portal ? 1u : 0u;
        decor += D.kind == DoorwayKind::Decorative ? 1u : 0u;
    }
    std::fprintf(stderr,
                 "[интерьер] дверей построек: %zu — переходов %zu, заперто %zu, "
                 "декоративных %zu\n",
                 house_doorways_.size(), open,
                 house_doorways_.size() - open - decor, decor);
    // ТАБЛИЦА СТВОРОК ПОД ПРИБОРОМ ЗАГРУЗКИ. «Выход ставит игрока у СВОЕЙ
    // двери» — утверждение о координатах девяноста трёх дверей, и проверить
    // его по одному прогону, глядя в окно, нельзя. Печать только под
    // DFN_LOAD_LOG: 93 строки в каждом прогоне были бы шумом.
    if (const char* ll = door_value("DFN_LOAD_LOG");
        ll != nullptr && *ll != '\0' && *ll != '0') {
        for (const HouseDoorway& D : house_doorways_) {
            std::fprintf(stderr,
                         "[дверь] %s полотно (%.1f %.1f %.1f) нормаль "
                         "(%.2f %.2f) выход (%.1f %.1f %.1f) рыск %.2f%s%s\n",
                         D.kind == DoorwayKind::Portal       ? "переход"
                         : D.kind == DoorwayKind::Locked     ? "заперта"
                                                             : "декорат",
                         static_cast<double>(D.at.x), static_cast<double>(D.at.y),
                         static_cast<double>(D.at.z),
                         static_cast<double>(D.out_normal.x),
                         static_cast<double>(D.out_normal.z),
                         static_cast<double>(D.at.x + D.out_normal.x * STEP_OUT_M),
                         static_cast<double>(D.at.y),
                         static_cast<double>(D.at.z + D.out_normal.z * STEP_OUT_M),
                         static_cast<double>(
                             std::atan2(D.out_normal.x, -D.out_normal.z)),
                         D.interior.empty() ? "" : " -> ", D.interior.c_str());
        }
    }
    probe_door_aim();
}

void App::probe_door_aim() {
    // ПРИБОР ПРИЦЕЛА (DFN_DOOR_AIM_PROBE=1). Утверждение волны — «подсказка
    // горит, когда смотришь на створку, и молчит, когда смотришь на стену
    // рядом» — это утверждение о ДЕВЯНОСТА ТРЁХ дверях Вайтрана и трёхстах
    // Житнова, и предъявить его кадром из окна нельзя: кадр показывает одну
    // дверь под одним углом.
    //
    // ЧЕТЫРЕ РУКИ НА КАЖДУЮ СТВОРКУ, и три из них обязаны ПРОВАЛИТЬСЯ
    // (правило 30): прибор, у которого только положительное плечо, не
    // отличается от прибора сломанного.
    //   1. стою у двери, смотрю в полотно      -> подсказка ЕСТЬ
    //   2. стою там же, смотрю на стену в 0.5 м -> подсказки НЕТ
    //   3. стою там же, смотрю от дома          -> подсказки НЕТ
    //   4. стою в 3 м, смотрю в полотно         -> подсказки НЕТ (радиус)
    // Луч настоящий, по настоящим телам, и вердикт — та же door_aim(), что
    // работает в игре: прибор, пересчитывающий геометрию по-своему, мерил бы
    // себя (правило 39).
    static const bool on = [] {
        const char* e = door_value("DFN_DOOR_AIM_PROBE");
        return e != nullptr && *e != '\0' && *e != '0';
    }();
    if (!on || physics_ == nullptr || portals_.empty()) {
        return;
    }
    struct Arm {
        const char* name;
        std::size_t pass = 0;
    };
    Arm arms[4] = {{"смотрю в полотно"},
                   {"смотрю на стену в 0.5 м"},
                   {"смотрю от дома"},
                   {"стою в 3 м"}};
    std::size_t doors = 0;
    std::size_t no_body = 0;
    const float reach_probe = static_cast<float>(config::INTERACT_DISTANCE);
    for (const PortalLink& link : portals_) {
        if (!link.house || !link.aim.leaf) {
            continue;
        }
        ++doors;
        const DoorAim& A = link.aim;
        const glm::vec3 tangent = door_aim_tangent(A.normal);
        // ГЛАЗ ТАМ, ГДЕ ВСТАЁТ ВЫШЕДШИЙ, И НА ТОЙ ЖЕ ЗЕМЛЕ: точка выхода
        // сажается лучом вниз (leave_interior), и прибор обязан стоять там же,
        // иначе он меряет человека, парящего в воздухе перед дверью.
        glm::vec3 feet = link.back_at;
        const platform::RayHit ground = physics_->raycast(
            {feet.x, feet.y + EXIT_PROBE_UP_M, feet.z}, {0.0f, -1.0f, 0.0f},
            EXIT_PROBE_UP_M + EXIT_PROBE_DOWN_M, physics::LAYER_STATIC);
        if (ground.hit) {
            feet.y = ground.position.y + 0.02f;
        } else if (const auto h = chunks_.height_at({feet.x, feet.z})) {
            feet.y = *h + 0.02f;
        }
        const glm::vec3 eye{feet.x, feet.y + PLAYER_EYE_M, feet.z};
        const glm::vec3 far_eye = A.at + A.normal * 3.0f;
        const glm::vec3 side = A.at + tangent * (A.half_w + 0.5f);
        const glm::vec3 to_leaf = glm::normalize(A.at - eye);
        const glm::vec3 setups[4][2] = {
            {eye, to_leaf},
            {eye, glm::normalize(side - eye)},
            {eye, glm::normalize(glm::vec3{A.normal.x, 0.0f, A.normal.z})},
            {far_eye, glm::normalize(A.at - far_eye)},
        };
        const bool want[4] = {true, false, false, false};
        for (int a = 0; a < 4; ++a) {
            const glm::vec3 from = setups[a][0];
            const glm::vec3 dir = setups[a][1];
            // ПОЛНЫЙ ПУТЬ: тот же луч по тем же телам, что у update_hover, и
            // тот же вердикт, что у filter_door_hover.
            const platform::RayHit hit = physics_->raycast(
                from, dir, reach_probe, physics::LAYER_INTERACTABLE);
            bool lit = false;
            if (hit.hit) {
                const ecs::EntityId target{
                    static_cast<std::uint32_t>(hit.user_data >> 32),
                    static_cast<std::uint32_t>(hit.user_data & 0xFFFFFFFFull)};
                if (target == link.entity) {
                    // ПРИБОР ПОВТОРЯЕТ ПРАВИЛО СВОЕЙ ДОЗЫ, А НЕ СВОЁ МНЕНИЕ.
                    // При DFN_DOOR_AIM=0 подсказка загоралась ровно от того,
                    // что луч попал в тело двери ближе 1.6 м, — и контрольная
                    // рука обязана мерить ИМЕННО это, иначе «стало лучше»
                    // предъявляется прибором, который при нулевой дозе меряет
                    // другую систему (правило 48).
                    lit = door_aim_enabled() ? door_aim(A, from, dir).ok
                                             : hit.distance <= 1.6f;
                }
            } else if (a == 0) {
                ++no_body;
            }
            if (lit == want[a]) {
                ++arms[a].pass;
                continue;
            }
            // ПРОВАЛИВШАЯСЯ РУКА НАЗЫВАЕТ СЕБЯ ЧИСЛАМИ. Счёт «31 из 32» без
            // строки о промахнувшейся створке отправляет искать её глазами по
            // городу — а искать нужно не дверь, а причину: не достал луч, не
            // попал в своё тело или не дотянулся радиус.
            const DoorAimHit v = door_aim(A, from, dir);
            std::fprintf(stderr,
                         "[прицел] ПРОМАХ «%s» у полотна (%.1f %.1f %.1f), "
                         "глаз (%.1f %.1f %.1f)%s: "
                         "луч %s, радиус %.2f (%s), взгляд %s (u %.2f v %.2f, "
                         "полотно %.2fx%.2f)\n",
                         arms[a].name, static_cast<double>(A.at.x),
                         static_cast<double>(A.at.y), static_cast<double>(A.at.z),
                         static_cast<double>(from.x), static_cast<double>(from.y),
                         static_cast<double>(from.z),
                         ground.hit ? "" : " (опоры под точкой выхода НЕТ)",
                         hit.hit ? "во что-то попал" : "НЕ ПОПАЛ",
                         static_cast<double>(v.distance_m),
                         v.in_reach ? "в радиусе" : "ДАЛЕКО",
                         v.looking ? "в полотне" : "МИМО",
                         static_cast<double>(v.u), static_cast<double>(v.v),
                         static_cast<double>(A.half_w * 2.0f),
                         static_cast<double>(A.half_h * 2.0f));
        }
    }
    std::fprintf(stderr, "[прицел] створок под прибором: %zu\n", doors);
    for (const Arm& a : arms) {
        std::fprintf(stderr, "[прицел] %-24s %zu/%zu\n", a.name, a.pass, doors);
    }
    if (no_body > 0) {
        std::fprintf(stderr,
                     "[прицел] лучей, не нашедших СВОЁ тело в упор: %zu — тело "
                     "прицела стоит не на полотне\n",
                     no_body);
    }
}

void App::open_decorative_doors() {
    // ДВЕРЬ БЕСПИЛОТНОГО КАДРА ОТКРЫТОЙ СТВОРКИ (DFN_DOOR_OPEN=1). Повернуть
    // декоративную дверь умеет только рука на клавише E, стоящая перед ней, —
    // значит без этой двери «створка поворачивается на петле» есть
    // утверждение, которое не может предъявить ни один прогон. Открывает ВСЕ
    // декоративные разом: их на карте единицы, а искать нужную по номеру
    // означало бы знать номер до прогона, который его и печатает.
    static const bool on = [] {
        const char* e = door_value("DFN_DOOR_OPEN");
        return e != nullptr && *e != '\0' && *e != '0';
    }();
    if (!on) {
        return;
    }
    std::size_t n = 0;
    // КОПИЯ СПИСКА ДЕЙСТВИЙ, А НЕ ОБХОД ЖИВОГО: toggle_decorative_door ищет по
    // portals_ и правит запись в нём. Обходить контейнер, который правят
    // изнутри цикла, — та же ошибка, из-за которой переход исполняется ПОСЛЕ
    // раздачи событий, а не в обработчике.
    std::vector<std::uint64_t> actions;
    for (const PortalLink& l : portals_) {
        if (l.house && l.kind == DoorwayKind::Decorative) {
            actions.push_back(l.action);
        }
    }
    for (const std::uint64_t a : actions) {
        for (const PortalLink& l : portals_) {
            if (l.action == a) {
                toggle_decorative_door(l);
                ++n;
                break;
            }
        }
    }
    std::fprintf(stderr, "[интерьер] дверь DFN_DOOR_OPEN: открыто створок %zu\n", n);
}

void App::take_portal() {
    if (pending_portal_ == 0) {
        return;
    }
    const std::uint64_t action = pending_portal_;
    pending_portal_ = 0;
    for (const PortalLink& link : portals_) {
        if (link.action != action) {
            continue;
        }
        if (link.house) {
            // ТИП СТВОРКИ РЕШАЕТ, ЧТО ДЕЛАЕТ КЛАВИША, и это разные вещи, а не
            // оттенки одной: переход грузит локацию, запертая говорит вслух,
            // декоративная поворачивается на петле и никуда не ведёт.
            if (link.kind == DoorwayKind::Decorative) {
                toggle_decorative_door(link);
                return;
            }
            if (link.kind == DoorwayKind::Locked || link.to.empty()) {
                // ЗАПЕРТО. Надпись игрок уже прочитал под прицелом — здесь
                // остаётся строка для прогона: «нажал, и ничего не случилось»
                // и «нажал, и дверь ответила» неразличимы в логе иначе.
                std::fprintf(stderr, "[интерьер] дверь ЗАПЕРТА\n");
                return;
            }
            // КОПИЯ, А НЕ ССЫЛКА: вход правит portals_ (снимает переходы
            // локации, заводит новые), и ссылка в этот вектор умирает прямо
            // под ногами у enter_interior. Та же причина, по которой ниже
            // копируется запись портала композиции.
            const std::string to = link.to;
            const std::string spawn = link.to_spawn;
            const PortalReturn back{link.back_at, link.back_yaw, link.back_set};
            (void)enter_interior(to, spawn, back);
            return;
        }
        const world::SceneDoc& doc = link.interior ? interior_doc_ : scene_doc_;
        if (link.index >= doc.portals.size()) {
            return;
        }
        const world::ScenePortal P = doc.portals[link.index];
        if (world::portal_is_back(P)) {
            leave_interior();
        } else {
            // [portal] КОМПОЗИЦИИ ПОЛОТНА НЕ ИМЕЕТ, и обратного адреса у него
            // тоже нет: он — точка в воздухе, у которой нет ни нормали, ни
            // стороны «наружу». Точкой возврата остаётся поза игрока, и это
            // честно названо здесь, а не спрятано в умолчании аргумента.
            (void)enter_interior(P.to, P.to_spawn, PortalReturn{});
        }
        return;
    }
}

void App::toggle_decorative_door(const PortalLink& link) {
    // ДЕКОРАТИВНАЯ СТВОРКА ОТКРЫВАЕТСЯ ПОВОРОТОМ НА ПЕТЛЕ и ничего больше не
    // делает: ни загрузки, ни телепорта (владелец 27.08 — «просто
    // открываться, межкомнатные»). Состояние живёт у ССЫЛКИ ПЕРЕХОДА, а не у
    // меша: меш перезаливается на каждой правке дома, а «эта дверь открыта» —
    // свойство мира, которое обязано пережить перезаливку.
    //
    // ПОВОРОТ МГНОВЕННЫЙ, И ЭТО НАЗВАНО ВСЛУХ, а не выдано за анимацию:
    // плавный ход — время, а время двери требует своего тика и своей кривой.
    // Механика типа и поворота проверяема уже сегодня; плавность — следующий
    // шаг, и она НЕ будет вторым механизмом, только скоростью у этого.
    for (PortalLink& l : portals_) {
        if (l.action != link.action) {
            continue;
        }
        l.open = !l.open;
        constexpr float OPEN_ANGLE_RAD = 1.5707963f; // 90°
        render_system_.set_house_door_open(l.door_index,
                                           l.open ? OPEN_ANGLE_RAD : 0.0f);
        if (auto* h = world_.get<gameplay::Highlightable>(l.entity)) {
            h->prompt_key = l.open ? "prompt.close" : "prompt.open";
        }
        std::fprintf(stderr, "[интерьер] декоративная дверь %zu: %s\n",
                     l.door_index, l.open ? "ОТКРЫТА" : "ЗАКРЫТА");
        return;
    }
}

bool App::enter_interior(const std::string& scene_path,
                         const std::string& spawn_name,
                         const PortalReturn& back_addr) {
    if (renderer_ == nullptr || physics_ == nullptr || !world_.alive(player_)) {
        return false;
    }
    if (!world_.has_resource<gameplay::InteriorState>()) {
        world_.add_resource(gameplay::InteriorState{});
    }
    auto& state = world_.resource<gameplay::InteriorState>();
    if (state.depth() >= gameplay::INTERIOR_MAX_DEPTH) {
        // ПРЕДЕЛ — КОНСТАНТА, А НЕ УСТРОЙСТВО (владелец 24.08). Состояние
        // умеет стек любой глубины; сегодня разрешена одна ступень, и отказ
        // звучит вслух, а не проглатывается.
        std::fprintf(stderr,
                     "[интерьер] вложенность %zu уже на пределе (%zu) — вход в "
                     "%s ОТКАЗАН\n",
                     state.depth(), gameplay::INTERIOR_MAX_DEPTH,
                     scene_path.c_str());
        return false;
    }

    const auto t0 = std::chrono::steady_clock::now();
    static const bool load_log = [] {
        const char* e = door_value("DFN_LOAD_LOG");
        return e != nullptr && *e != '\0' && *e != '0';
    }();
    loading_.set_log(load_log);
    loading_.begin("Вход", scene_path);
    loading_.set_expected(5);
    // СНИМОК ЭКРАНА КОМНАТЫ ПОД СВОИМ СТВОЛОМ. enter_world перед этим ставила
    // «loading_world»: тот же прогон показывает два разных экрана, и рецепты
    // И15 знают комнату как loading_000.png.
    loading_shot_stem_ = "loading";
    loading_frame_at_ = std::chrono::steady_clock::now();
    if (interior_fade_s_ > 0.0f) {
        present_loading_frame();
    }

    // ---- ВСЁ, ЧТО МОЖЕТ НЕ ПОЛУЧИТЬСЯ, ДЕЛАЕТСЯ ДО ПРАВКИ МИРА ----
    world::SceneDoc doc;
    std::string serr;
    if (!world::read_scene(scene_path, doc, serr)) {
        std::fprintf(stderr, "[интерьер] %s: %s — вход ОТМЕНЁН\n",
                     scene_path.c_str(), serr.c_str());
        loading_.hide();
        return false;
    }
    loading_.stage("сцена локации прочитана");
    // ГДЕ КАРМАН. По центру города, чтобы дальность звука, тумана и всего
    // остального, что меряется от начала мира, осталась той же величины.
    const glm::vec4 wb = chunks_.world_bounds_xz();
    interior_pocket_ = {(wb.x + wb.z) * 0.5f, -POCKET_DEPTH_M,
                        (wb.y + wb.w) * 0.5f};

    const bool resident = (interior_resident_ == scene_path);
    if (!resident) {
        std::vector<PlacedHouse> houses;
        for (std::size_t hi = 0; hi < doc.houses.size(); ++hi) {
            const world::ScenePlacedHouse& H = doc.houses[hi];
            std::ifstream in(H.file);
            if (!in.good()) {
                std::fprintf(stderr,
                             "[интерьер] [house] %s: файл не открылся — вход "
                             "ОТМЕНЁН\n",
                             H.file.c_str());
                loading_.hide();
                return false;
            }
            std::stringstream ss;
            ss << in.rdbuf();
            PlacedHouse ph;
            const world::HouseIoResult io = world::read_house(ss.str(), ph.graph);
            if (!io.ok) {
                std::fprintf(stderr, "[интерьер] [house] %s:%d: %s — вход ОТМЕНЁН\n",
                             H.file.c_str(), io.line, io.why.c_str());
                loading_.hide();
                return false;
            }
            ph.pos = H.position + interior_pocket_;
            ph.yaw = H.yaw;
            ph.scene_index = hi;
            houses.push_back(std::move(ph));
        }
        interior_houses_ = std::move(houses);
        loading_.stage("постройки локации прочитаны");
        // КОМПОЗИЦИЯ ЛОКАЦИИ — ДО ЗАЛИВКИ, А НЕ ПОСЛЕ (волна Б). Заливка
        // читает у неё ключ sealed оболочки, а до этой строки interior_doc_
        // держал ПРЕДЫДУЩУЮ локацию: створка запечатывалась бы по чужой
        // записи. Присваивание стоит ПОСЛЕ всех чтений, которые могут не
        // получиться, — правило файла соблюдено.
        interior_doc_ = doc;
        upload_house_mesh(/*interior_only=*/true);
        loading_.stage("геометрия и коллайдер локации");
        interior_resident_ = scene_path;
    }

    // ---- С ЭТОГО МЕСТА МИР МЕНЯЕТСЯ ----
    if (!city_lights_saved_) {
        city_lights_ = render_system_.scene_lights();
        city_lights_saved_ = true;
    }
    // ДОЗА СВЕТА ИНТЕРЬЕРА — ОДНА НА ambient И НА ОГНИ. Две дозы дали бы
    // четыре руки, из которых две не соответствуют ни одной картинке: подъём
    // тьмы без очага — это плоская комната, очаг без подъёма — прежняя
    // жалоба. Правка одна, значит и дверь одна.
    const float ilight = interior_light_dose();
    std::vector<render::RenderSystem::ExtraLight> lamps;
    for (const world::SceneLight& L : doc.lights) {
        if (L.radius_m <= 0.0f) {
            continue;
        }
        render::RenderSystem::ExtraLight e;
        e.position = L.position + interior_pocket_;
        e.color = L.color;
        e.radius_m = L.radius_m;
        e.casts_shadow = L.casts_shadow;
        // ГЕЙТ ПО НЕБЕСНОЙ ВИДИМОСТИ ЗДЕСЬ ЛИШНИЙ: снаружи локации нечему
        // течь, а сам гейт погасил бы очаг в комнате без окон.
        e.interior = false;
        e.room_center_xz = L.room_center;
        e.room_half_xz = L.room_half;
        e.softness = L.softness;
        // ДОЗА МЕРЦАНИЯ ДОСТАЁТ И ДО КОМНАТЫ (28.08). DFN_LIGHT_FLICKER
        // обещает «ровный свет бит-в-бит», и до этой строки обещание
        // кончалось на пороге дома: город дозу применял (AppWorld), локация
        // — нет. Это не косметика, а ЕДИНСТВЕННЫЙ способ снять две побитово
        // сравнимые руки внутри: замерено на месте — две руки ОДНОГО
        // бинарника с одной дозой расходятся на 2.67 млн байт кадра при
        // максимуме 69, потому что фаза мерцания идёт от времени сцены.
        // Умолчание дозы 1.0 умножает на единицу, то есть прежний кадр
        // бит-в-бит по построению.
        static const float flicker_dose = [] {
            const char* e = door_value("DFN_LIGHT_FLICKER");
            return (e != nullptr && *e != '\0') ? std::strtof(e, nullptr)
                                                : 1.0f;
        }();
        e.flicker = L.flicker * flicker_dose;
        // ПОПРАВКА ОГНЯ ПО ЕГО РОЛИ (28.08). Множитель, а не число: цвет и
        // радиус несут экземплярную дрожь генератора («19 надверных фонарей
        // все бит-в-бит» — находка круга 6), и присвоение стёрло бы её,
        // вернув гирлянду одинаковых огней.
        if (ilight > 0.0f) {
            const bool hearth = flame_of(L) == Flame::Hearth;
            const float gain = hearth ? HEARTH_GAIN : CANDLE_GAIN;
            const float rgain = hearth ? HEARTH_RADIUS_GAIN : CANDLE_RADIUS_GAIN;
            e.color = L.color * (1.0f + (gain - 1.0f) * ilight);
            e.radius_m = L.radius_m * (1.0f + (rgain - 1.0f) * ilight);
            if (hearth) {
                e.softness = L.softness
                           + (HEARTH_SOFTNESS - L.softness) * ilight;
            }
        }
        lamps.push_back(e);
    }
    const std::size_t lamp_count = lamps.size();
    render_system_.set_scene_lights(std::move(lamps));
    render_system_.set_transient_lights({});

    if (!city_sky_saved_) {
        city_sun_color_ = render_system_.environment().sun_color;
        city_ambient_ = render_system_.environment().ambient_color;
        city_sky_saved_ = true;
    }
    // СОЛНЦЕ В НОЛЬ. У локации нет неба, и оставленное солнце светило бы
    // сквозь кладку из направления, которого внутри не существует.
    render_system_.environment().sun_color = glm::vec3{0.0f};
    const float amb = doc.air.set && doc.air.ambient >= 0.0f ? doc.air.ambient
                                                             : 0.10f;
    // ЧАС СУТОК СЧИТАЕТСЯ ИЗ ЧАСОВ, А НЕ ЧИТАЕТСЯ ИЗ ОКРУЖЕНИЯ, И ЭТО ЗАМЕР,
    // А НЕ ПРЕДПОЧТЕНИЕ. Первая версия брала env.sun_direction.y — и получала
    // 0.67 (полдень) при DFN_TIME_OF_DAY=0.0 (полночь). Причина названа в
    // самой петле кадра: apply_sky_time НЕ ЗОВЁТСЯ, пока мир подвешен
    // (у локации нет неба), а вход в локацию по двери DFN_INTERIOR случается
    // ДО ПЕРВОГО КАДРА — то есть окружение держит ещё умолчание структуры, и
    // ночная рука была неотличима от дневной. Здесь считается ровно то же,
    // что считает петля: доля суток из game_seconds_ и ТА ЖЕ функция
    // render::sun_direction_at (правило 35 — один хозяин у геометрии солнца).
    // Полоса 0..0.20 по высоте: солнце в 11.5° над горизонтом — уже день для
    // окна, ниже — сумерки.
    const double day_len = static_cast<double>(config::DAY_LENGTH_SECONDS);
    const double days = game_seconds_ / day_len;
    const float day_fraction = static_cast<float>(days - std::floor(days));
    const float sun_up = render::sun_direction_at(day_fraction).y;
    const float day = std::clamp(sun_up / 0.20f, 0.0f, 1.0f);
    const float lit_level = INTERIOR_AMBIENT_NIGHT
                          + (INTERIOR_AMBIENT_DAY - INTERIOR_AMBIENT_NIGHT) * day;
    const glm::vec3 lit_tint = INTERIOR_TINT_NIGHT
                             + (INTERIOR_TINT_DAY - INTERIOR_TINT_NIGHT) * day;
    const glm::vec3 amb_before{amb};
    const glm::vec3 amb_after = lit_tint * lit_level;
    render_system_.environment().ambient_color =
        amb_before + (amb_after - amb_before) * ilight;
    if (ilight > 0.0f) {
        std::fprintf(stderr,
                     "[интерьер] свет доза %.2f: ambient %.3f -> %.3f %.3f %.3f "
                     "(день %.2f, солнце %.2f), огней %zu\n",
                     static_cast<double>(ilight), static_cast<double>(amb),
                     static_cast<double>(render_system_.environment().ambient_color.r),
                     static_cast<double>(render_system_.environment().ambient_color.g),
                     static_cast<double>(render_system_.environment().ambient_color.b),
                     static_cast<double>(day), static_cast<double>(sun_up),
                     lamp_count);
    }
    if (doc.air.set && doc.air.fog_end_m > 0.0f) {
        render_system_.set_air_override(doc.air.fog_start_m, doc.air.fog_end_m,
                                        doc.air.cloud_cover);
    }

    loading_.stage("свет локации");
    // ТОЧКА ВОЗВРАТА — СВОЙСТВО ДВЕРИ, А НЕ ПОЗА ЧЕЛОВЕКА (владелец 27.08:
    // «выход из двери должен ставить игрока СПИНОЙ К ДВЕРИ, из которой он
    // вышел, рядом с тем домом, у которого был — не в какую-то рандомную
    // точку на карте»). Дверь знает, где её полотно и куда смотрит наружная
    // нормаль; поза же — это где человек СТОЯЛ в момент нажатия, и она
    // законно бывает какой угодно: подошёл боком, жал в прыжке, тянулся к
    // двери с крыльца соседа. Вернуть его туда — и есть та самая «рандомная
    // точка», в которой ни один игрок себя не узнает.
    //
    // ПОЗА ОСТАЁТСЯ ЗАПАСНОЙ РУКОЙ, и только для переходов БЕЗ полотна
    // ([portal] композиции — точка в воздухе, у которой нет ни нормали, ни
    // стороны «наружу»). Молчаливой она при этом не является: адрес двери
    // приходит явным аргументом, и его отсутствие — решение вызывающего.
    gameplay::InteriorReturn back;
    back.from_scene = state.inside() ? state.scene_path : gallery_scene_;
    if (back_addr.set) {
        back.position = back_addr.at;
        back.yaw = back_addr.yaw;
    } else {
        if (const auto* tr = world_.get<components::Transform>(player_)) {
            back.position = tr->position;
        }
        if (const auto* ps = world_.get<gameplay::PlayerState>(player_)) {
            back.yaw = ps->yaw;
        }
    }
    state.stack.push_back(back);
    state.scene_path = scene_path;
    state.door_open = true;

    glm::vec3 spawn = interior_pocket_;
    float spawn_yaw = 0.0f;
    bool found = false;
    for (const world::SceneSpawn& S : doc.spawns) {
        if (!spawn_name.empty() && S.name != spawn_name) {
            continue;
        }
        spawn = S.position + interior_pocket_;
        spawn_yaw = S.yaw;
        found = true;
        break;
    }
    if (!found && doc.has_spawn) {
        spawn = doc.spawn + interior_pocket_;
        spawn_yaw = doc.spawn_yaw;
        found = true;
    }
    if (!found) {
        // НЕТ ТОЧКИ ВХОДА — ЭТО ДЕФЕКТ ЛОКАЦИИ, а не повод молча высадить в
        // начало координат: пол комнаты может там не быть.
        std::fprintf(stderr,
                     "[интерьер] %s: ни [spawn] «%s», ни заголовочного spawn — "
                     "игрок встал в начало кармана\n",
                     scene_path.c_str(), spawn_name.c_str());
    }
    // ДОВОРОТ ПОСЛЕ ВХОДА (DFN_INTERIOR_TURN=<градусы>). Точка входа смотрит В
    // КОМНАТУ — так задумано, и дверь остаётся ЗА СПИНОЙ. Значит ни один
    // беспилотный прогон не может ни увидеть подсказку «Выйти», ни нажать на
    // неё, пока кто-то не развернёт игрока, а рука на клавише мыши в прогон не
    // приходит. Без этой двери сценарий владельца «вошёл, развернулся, вышел»
    // проверялся только человеком — и не проверялся.
    static const float turn_deg = [] {
        const char* e = door_value("DFN_INTERIOR_TURN");
        return (e != nullptr && *e != '\0') ? std::strtof(e, nullptr) : 0.0f;
    }();
    if (turn_deg != 0.0f) {
        spawn_yaw += turn_deg * 3.14159265358979f / 180.0f;
        std::fprintf(stderr, "[интерьер] дверь DFN_INTERIOR_TURN: доворот %.1f°\n",
                     static_cast<double>(turn_deg));
    }
    if (auto* ps = world_.get<gameplay::PlayerState>(player_)) {
        physics_->teleport_character(ps->character, spawn);
        ps->yaw = spawn_yaw;
        ps->vertical_velocity = 0.0f;
    }
    if (auto* tr = world_.get<components::Transform>(player_)) {
        tr->position = spawn;
    }
    if (auto* pt = world_.get<components::PreviousTransform>(player_)) {
        pt->position = spawn;
    }

    spawn_scene_portals(doc, /*interior=*/true, &spawn);
    interior_doc_ = std::move(doc);
    render_system_.set_world_suspended(true);
    state.visited = true;
    loading_.stage("переход и точка входа");

    loading_.finish();
    interior_enter_ms_ =
        std::chrono::duration<double, std::milli>(
            std::chrono::steady_clock::now() - t0).count();
    std::fprintf(stderr, "[интерьер] ВХОД %s за %.1f ms%s\n", scene_path.c_str(),
                 interior_enter_ms_, resident ? " (геометрия уже была залита)" : "");
    hold_loading_screen();
    loading_.hide();
    render_system_.set_hud_visible(false);
    return true;
}

void App::leave_interior() {
    if (!world_.has_resource<gameplay::InteriorState>()) {
        return;
    }
    auto& state = world_.resource<gameplay::InteriorState>();
    if (!state.inside() || !world_.alive(player_) || physics_ == nullptr) {
        return;
    }
    const auto t0 = std::chrono::steady_clock::now();
    const gameplay::InteriorReturn back = state.stack.back();
    state.stack.pop_back();
    state.scene_path = state.inside() ? state.stack.back().from_scene
                                      : std::string{};
    state.door_open = false;

    // ГЕОМЕТРИЯ ЛОКАЦИИ ОСТАЁТСЯ ЗАЛИТОЙ. Выход — это переключение флага и
    // телепорт; свод даёт на него 0.05 с, а перезаливка слота стоит на два
    // порядка больше. Повторный вход в тот же дом по той же причине почти
    // бесплатен.
    render_system_.set_world_suspended(false);
    clear_scene_portals(/*interior=*/true);

    if (city_lights_saved_) {
        render_system_.set_scene_lights(city_lights_);
    }
    if (city_sky_saved_) {
        render_system_.environment().sun_color = city_sun_color_;
        render_system_.environment().ambient_color = city_ambient_;
        city_sky_saved_ = false;
    }
    if (scene_doc_.air.set) {
        render_system_.set_air_override(scene_doc_.air.fog_start_m,
                                        scene_doc_.air.fog_end_m,
                                        scene_doc_.air.cloud_cover);
    } else {
        render_system_.clear_air_override();
    }

    // ПОСАДКА НА ТО, ЧТО ПОД НОГАМИ, А НЕ НА ОТМЕТКУ РЕЛЬЕФА. Адрес двери
    // несёт высоту СЕРЕДИНЫ СТВОРКИ — это метр с небольшим над порогом, и
    // высадить туда значило бы уронить человека с метра либо утопить его в
    // крыльце. Луч вниз находит настоящую опору: у Вайтрана дверь выходит на
    // каменную террасу, которой нет в поле высот, и посадка по земле провалила
    // бы вышедшего сквозь неё. Ни луч, ни поле высот не ответили — точка
    // остаётся как есть, и об этом печатается строка: падение с метра на
    // глазах игрока честнее, чем молчаливый телепорт в неизвестность.
    glm::vec3 out = back.position;
    const platform::RayHit ground = physics_->raycast(
        {out.x, out.y + EXIT_PROBE_UP_M, out.z}, {0.0f, -1.0f, 0.0f},
        EXIT_PROBE_UP_M + EXIT_PROBE_DOWN_M, physics::LAYER_STATIC);
    bool grounded = ground.hit;
    if (ground.hit) {
        out.y = ground.position.y + 0.02f;
    } else if (const auto h = chunks_.height_at({out.x, out.z})) {
        // ВТОРАЯ РУКА — ПОЛЕ ВЫСОТ. Луч меряет то, что ОТДАНО ФИЗИКЕ, а чанк
        // под дверью может быть ещё не резидентным: в живой игре человек
        // дошёл до двери ногами и чанк загружен, но беспилотный прогон
        // (DFN_INTERIOR) телепортируется внутрь с первого кадра, и у дальних
        // домов Житнова земли под точкой выхода физически нет. Поле высот
        // отвечает и там, где тела нет, — и это законный ответ, а не догадка:
        // земля в этой точке будет ровно на этой отметке, когда чанк придёт.
        out.y = *h + 0.02f;
        grounded = true;
    }
    if (auto* ps = world_.get<gameplay::PlayerState>(player_)) {
        physics_->teleport_character(ps->character, out);
        ps->yaw = back.yaw;
        ps->vertical_velocity = 0.0f;
    }
    if (auto* tr = world_.get<components::Transform>(player_)) {
        tr->position = out;
    }
    if (auto* pt = world_.get<components::PreviousTransform>(player_)) {
        pt->position = out;
    }

    interior_leave_ms_ =
        std::chrono::duration<double, std::milli>(
            std::chrono::steady_clock::now() - t0).count();
    // ТОЧКА ВЫХОДА — В СТРОКЕ, И ЭТО ПРИЁМКА, А НЕ ОТЛАДКА. «Игрока выкинуло в
    // рандомную точку» — жалоба о КООРДИНАТЕ, и без числа она проверяется
    // только глазами того, кто жаловался.
    std::fprintf(stderr,
                 "[интерьер] ВЫХОД за %.2f ms в (%.1f %.1f %.1f), рыск %.2f%s\n",
                 interior_leave_ms_, static_cast<double>(out.x),
                 static_cast<double>(out.y), static_cast<double>(out.z),
                 static_cast<double>(back.yaw),
                 grounded ? "" : " — ОПОРЫ ПОД ТОЧКОЙ ВЫХОДА НЕТ");
}

