constexpr glm::vec3 INTERIOR_TINT_DAY{0.90f, 0.94f, 1.00f};
constexpr glm::vec3 INTERIOR_TINT_NIGHT{1.00f, 0.82f, 0.62f};

/// ОЧАГ — ГЛАВНЫЙ ИСТОЧНИК, И ЕМУ НЕ ХВАТАЛО НЕ ДОСЯГАЕМОСТИ, А ГРАДИЕНТА.
/// РАДИУС УМЕНЬШАЕТСЯ, И ЭТО ЗАМЕР, А НЕ ОПЕЧАТКА. Генератор ставит очагу
/// радиус ПО ЗАЛУ (8.46 м в семиметровой комнате Житнова, 14.24 м в
/// постоялом дворе), а затухание у нас — smoothstep по ЛИНЕЙНОМУ окну: при
/// радиусе больше комнаты вся комната сидит в пологой верхушке кривой и
/// получает почти ОДНО И ТО ЖЕ число. Ровно это и читалось «огонь не греет»:
/// не тускло, а РОВНО. Первая проба с радиусом ×1.2 (как просил заказ) дала
/// медиану кадра 68 при плоской картинке — свет есть, источника нет. ×0.85
/// возвращает кривой рабочий участок внутри комнаты, а потерянную у стен
/// долю добирает общий свет, которого раньше не было вовсе.
///
/// ЯРКОСТЬ ×2.35 — ЭТО ПОДЪЁМ p95, а не «сделать теплее»: у владельца p95
/// кадра 0.13..0.85 при наших 0.07..0.10 до правки. Множитель, а не число:
/// цвет несёт экземплярную дрожь генератора.
///
/// МЯГКОСТЬ 0.40 против авторских 0.25 — большой открытый огонь огибает форму
/// (wrap-диффуз, у бочки нет резкого терминатора). Выше не поднята нарочно:
/// мягкость ЗАОДНО кладёт затухание положе (pow(fall, 1->0.6)), то есть
/// работает ПРОТИВ градиента, ради которого сжат радиус. 0.55 в пробе съело
/// половину выигранного контраста.
constexpr float HEARTH_RADIUS_GAIN = 0.85f;
constexpr float HEARTH_GAIN = 2.35f;
constexpr float HEARTH_SOFTNESS = 0.40f;

/// СВЕЧА И САЛО НА СТЕНЕ — ТОЧКА, А НЕ ВТОРОЙ ОЧАГ. Прибавка меньше
/// очаговой намеренно: подсвечник, спорящий яркостью с огнём зала, — это
/// ровно та ошибка, за которую ругают ванильный Skyrim («плоско, светит
/// отовсюду»). Радиус растёт чуть-чуть — комната яруса 6..12 м.
constexpr float CANDLE_RADIUS_GAIN = 1.15f;
constexpr float CANDLE_GAIN = 1.25f;

/// ЧТО ЭТО ЗА ОГОНЬ. Локация НАЗЫВАЕТ свои огни: gen_city пишет [light].note
/// («очаг: ...», «светец яруса: ...»), и разбор по имени — это чтение
/// авторского намерения, а не угадывание по числам.
enum class Flame { Hearth, Candle };

Flame flame_of(const world::SceneLight& L) {
    if (L.note.rfind("очаг", 0) == 0) {
        return Flame::Hearth;
    }
    if (L.note.rfind("светец", 0) == 0) {
        return Flame::Candle;
    }
    // ЗАПАСНАЯ РУКА ПО ЧИСЛАМ, И ОНА НЕ МОЛЧАЛИВАЯ ПО ЗАМЫСЛУ. Рукописная
    // локация (стенд, пилот, assets/scenes/int/broken.scene) заметок не
    // носит, а без разбора вовсе весь её свет получил бы поправку очага.
    // Мягкость — единственное поле, которого НЕ КАСАЕТСЯ экземплярная дрожь
    // генератора (дрожат яркость, радиус и мерцание), поэтому разделяет
    // надёжно: открытый огонь 0.15..0.25, стекло и фитиль 0.45..0.65.
    return L.softness <= 0.35f ? Flame::Hearth : Flame::Candle;
}

