// ГДЕ ОНА СТОИТ, и любое её усиление сначала выжигает пятно под собой и
// только потом доходит до угла. Угол — это ровно то место, куда ни одна
// лампа не достаёт, и его чинит только общий член. При этом форма комнаты не
// теряется: ambient умножается на ту же запечённую видимость и на fill, так
