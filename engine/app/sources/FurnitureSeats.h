/// НАЙДЕННАЯ ПЛОЩАДКА ПРЕДМЕТА, в МЕСТНЫХ координатах чертежа.
struct FurnSurface {
    bool found = false;
    float top_y = 0.0f;    ///< верх площадки (по ней и садятся)
    glm::vec2 lo{0.0f};    ///< пятно площадки, XZ
    glm::vec2 hi{0.0f};
    float area_m2 = 0.0f;  ///< площадь найденной площадки

    [[nodiscard]] float long_side() const;
    [[nodiscard]] float short_side() const;
    [[nodiscard]] glm::vec2 centre() const { return (lo + hi) * 0.5f; }
    /// Длинная ось площадки в местных координатах: (1,0) или (0,1).
    [[nodiscard]] glm::vec2 long_axis() const;
};

/// ЧТО ЭТО ЗА ПРЕДМЕТ ПО ЕГО ПЛОЩАДКЕ. `Table` — не поза, а ОБСТАНОВКА: у
/// стола садятся лицом к столу, и без этого различения лавка трактира
/// разворачивала бы человека спиной к столешнице (см. seat_facing).
enum class SpotKind : uint8_t { None = 0, Seat = 1, Lie = 2, Table = 3 };

/// --- ПОРОГИ КЛАССИФИКАТОРА, и каждый назван вместе с тем, кого он отсекает
/// на сегодняшней полке (правило 30: порог — это тоже измерение) ------------

/// Ниже этого площадка — не сиденье, а приступок очага (furn-hearth 0.14,
/// furn-planter 0.29, furn-walk2 0.08).
inline constexpr float SEAT_MIN_M = 0.35f;
/// Выше — уже не сиденье, и потолок здесь ВЫВЕДЕН, а не выбран: сесть так,
/// чтобы стопы стояли на полу, можно ровно до высоты СОБСТВЕННОГО КОЛЕНА
/// (BODY_KNEE_HEIGHT_FRAC x PLAYER_CAPSULE_HEIGHT = 0.513 м). Выше стопы
/// повисают — и поза это честно рисует (anim::sit_pose зажимает бедро и ноги
/// висят), но «сесть» такому предмету предлагать незачем. Отсекает сундук
/// (furn-chest, крышка 0.56), кадку (furn-quench 0.55), стол (0.765) и полку
/// (2.05); лавку 0.45 и дуговую лавку 0.45 пропускает.
///
/// ОДНО ЧИСЛО, ДВА ЧИТАТЕЛЯ, И ЭТО НАМЕРЕННО (правило 35): тот же рост колена
/// решает в anim::sit_pose, достанут ли стопы до пола. Разъехаться им нельзя —
/// иначе появится предмет, которому подсказка «Сесть» горит, а поза на нём
/// висит ногами в воздухе.
inline constexpr float SEAT_MAX_M =
    static_cast<float>(config::BODY_KNEE_HEIGHT_FRAC * config::PLAYER_CAPSULE_HEIGHT);
/// Короче — не лавка, а тумба (furn-quench 0.58x0.58).
inline constexpr float SEAT_MIN_LONG_M = 0.80f;
/// Шире — уже не сидят поперёк, а ложатся: разделитель между лавкой и лежаком.
inline constexpr float SEAT_MAX_SHORT_M = 0.70f;
/// Лежак: длиной не меньше человека (PLAYER_CAPSULE_HEIGHT 1.8 минус подушка
/// и подошва) и шириной не уже плеч.
inline constexpr float LIE_MIN_LONG_M = 1.60f;
inline constexpr float LIE_MIN_SHORT_M = 0.70f;
inline constexpr float LIE_MIN_M = 0.30f;
inline constexpr float LIE_MAX_M = 0.70f;
/// СТОЛ: выше сиденья и ниже полки. furn-table 0.765 при пятне 1.68x0.78 —
/// внутри; furn-quench 0.55 — ниже; furn-shelf 2.05 — выше; furn-anvil при
/// 0.78 отсекается шириной (0.38 против MIN_SHORT).
inline constexpr float TABLE_MIN_M = 0.60f;
inline constexpr float TABLE_MAX_M = 0.95f;
inline constexpr float TABLE_MIN_LONG_M = 0.60f;
inline constexpr float TABLE_MIN_SHORT_M = 0.50f;

/// САМАЯ ШИРОКАЯ ГОРИЗОНТАЛЬНАЯ ПЛОЩАДКА, СМОТРЯЩАЯ ВВЕРХ. Треугольники
/// местные, как в чертеже. Считает так: берёт треугольники с нормалью вверх,
/// раскладывает их по высоте с шагом SURFACE_BIN_M, копит площадь и габарит
/// каждой полки, возвращает самую большую по площади.
///
/// ПОЧЕМУ ПО ПЛОЩАДИ, А НЕ ПО ВЫСОТЕ: у кровати ВЫШЕ матраса стоят навершия
/// столбиков изголовья (0.18x0.18 каждое) — «самая высокая площадка» выбрала
/// бы их и уложила человека на столбик.
[[nodiscard]] FurnSurface furniture_surface(std::span<const glm::vec3> positions,
                                            std::span<const std::uint32_t> indices);

/// Шаг раскладки по высоте, м. Меньше толщины любого настила полки (0.05) —
/// иначе матрас и рама слились бы в одну полку; больше численного шума.
inline constexpr float SURFACE_BIN_M = 0.02f;

[[nodiscard]] SpotKind classify_surface(const FurnSurface& s);

/// ТОЧКА ПОЗЫ В МИРЕ.
struct FurnitureSpot {
    SpotKind kind = SpotKind::None;
    /// Место, куда встаёт ТАЗ: середина площадки по XZ, мировые; y — ПОЛ
    /// предмета (посадка чертежа), а не верх площадки. Разделение
    /// намеренное: поза считает свою высоту ОТ ПОЛА, потому что от пола же
    /// стоит корень тела.
    glm::vec3 floor_at{0.0f};
    /// Высота площадки над `floor_at` — единственное, что нужно позе.
    float surface_m = 0.0f;
    /// СИДЕНЬЕ: куда смотрит сидящий. ЛЕЖАК: куда уходит ГОЛОВА лежащего.
    /// Единичный, по XZ.
    glm::vec3 facing{0.0f, 0.0f, -1.0f};
    /// Габарит тела предмета для прицела (радиус + взгляд).
    SeatAim aim;
    /// Имя чертежа/объекта — для строки лога, не для решений.
    std::string source;
};

/// ПЛОЩАДКА + ПОСАДКА ПРЕДМЕТА -> ТОЧКА ПОЗЫ. `origin` — где стоит нулевой
/// угол чертежа в мире, `yaw` — его поворот (местный +X уходит в
/// (cos, 0, -sin), местный +Z — в (sin, 0, cos): конвенция сцен).
/// `body_lo/body_hi` — местный габарит ВСЕГО предмета: им очерчивается
/// коробка прицела, чтобы «смотрю на лавку» значило смотреть на лавку, а не
/// на её сиденье.
[[nodiscard]] FurnitureSpot furniture_spot(const FurnSurface& s, SpotKind kind,
                                           const glm::vec3& origin, float yaw,
                                           const glm::vec3& body_lo,
                                           const glm::vec3& body_hi);

/// КУДА СМОТРИТ СИДЯЩИЙ. Лавка — вещь двусторонняя, и стороны у неё НЕ
/// равноправны: у стола садятся ЛИЦОМ К СТОЛУ, у стены — лицом от стены.
/// Поэтому направление не выводится из самой лавки, а ВЫБИРАЕТСЯ между двумя
/// её сторонами по обстановке комнаты:
///   1. есть стол ближе TABLE_NEAR_M к одной из сторон — лицом к нему;
///   2. иначе — лицом в сторону середины комнаты.
/// `cross` — поперечная ось лавки в мире (единичная, XZ); `tables` — центры
/// столов (мировые); `room_centre` — середина комнаты.
[[nodiscard]] glm::vec3 seat_facing(const glm::vec3& seat_xz, const glm::vec3& cross,
                                    std::span<const glm::vec3> tables,
                                    const glm::vec3& room_centre);

