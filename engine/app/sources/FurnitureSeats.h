// ТОЧКА СТАРТА ПОЗЫ: ГДЕ ЧЕЛОВЕК СТОИТ, ЧТОБЫ СЕСТЬ (ЛЕЧЬ) БЕЗ ПЕРЕКОСА
// ---------------------------------------------------------------------------
//
// ЗАЧЕМ ОНА ВООБЩЕ. Переход в позу ведёт КОРЕНЬ ТЕЛА от места, где человек
// стоит, к `posture_ground` (anim::body_root_for смешивает эти две точки
// долей `plan`). Значит расстояние между ними — это в точности та дистанция,
// НА КОТОРУЮ ТЕЛО ПРОЕДЕТ за 0.6 с перехода, и никакая анимация её не
// спрячет. Точка старта — единственный способ сделать этот проезд коротким и
// ОДИНАКОВЫМ на каждом прогоне: не «где случилось нажать E», а «где стоит
// человек, который садится на этот предмет».

/// ГДЕ ЧЕЛОВЕК ОБЯЗАН СТОЯТЬ ПЕРЕД ПОЗОЙ. Чистый вывод из меты предмета.
struct PostureStart {
    bool valid = false;
    /// Подошвы, мировые. Высота — пол предмета (`FurnitureSpot::floor_at.y`):
    /// на этом полу стоит и предмет, и человек.
    glm::vec3 at{0.0f};
    /// Рыск СТОЯЩЕГО, конвенция симуляции (0 смотрит в -Z).
    float yaw = 0.0f;
    /// Куда он смотрит: единичный, XZ. Наружу от предмета — человек стоит
    /// СПИНОЙ к тому, на что садится, и это не стиль, а геометрия: садятся,
    /// опускаясь назад, а не падая вперёд.
    glm::vec3 facing{0.0f, 0.0f, -1.0f};
};

/// ТОЧКА СТАРТА ИЗ МЕТЫ. `from` — где человек стоит СЕЙЧАС, и он нужен ровно
/// для одного решения: у лежака СТОРОН ДВЕ (у сиденья сторона уже выбрана
/// комнатой в seat_facing), а какая из них свободна, знает только тот, кто на
/// одной из них стоит. Функция от этого не перестаёт быть чистой — она
/// по-прежнему не спрашивает ни мира, ни физики.
///
/// КАК ВЫВЕДЕНО РАССТОЯНИЕ ДО ПРЕДМЕТА (и почему оно не выбрано на глаз):
/// человек стоит вплотную к предмету, но не в нём, значит его капсула КАСАЕТСЯ
/// габарита — расстояние от середины габарита равно полугабариту В СТОРОНУ
/// ПОДХОДА (seat_aim_support), плюс отступ коробки прицела SEAT_AIM_PAD_M (в
/// физике мебель стоит ИМЕННО ЭТОЙ коробкой, и упирается капсула в неё), плюс
/// PLAYER_CAPSULE_RADIUS. Ближе — точка НЕДОСТИЖИМА, человек упрётся раньше
/// неё и подход кончится таймаутом (замерено на лавке x112z271: подошвы
/// встали на 0.10 м раньше точки, посчитанной без отступа); дальше — тело
/// поедет к сиденью на этот излишек. Оба плеча названы, среднего значения
/// между ними нет.
[[nodiscard]] PostureStart posture_start(const FurnitureSpot& spot,
                                         const glm::vec3& from);

/// --- ПОРОГИ ПОДХОДА, И НИ ОДИН ИЗ НИХ НЕ ВЫБРАН ---------------------------
/// Общая мерка у всех одна — ШАГ СИМУЛЯЦИИ: порог короче того, что интегратор
/// проходит за один тик, недостижим по построению (человек перешагивает точку
/// и ходит вокруг неё вечно), а порог длиннее ощутимой доли шага виден глазом.
/// Единственный порог, названный не отсюда, — потолок автопилота: его назвал
/// владелец, и он проверен полкой (см. ниже).

/// ДОШЁЛ, м. За тик ходьбы человек проходит WALK_SPEED x SIM_DT = 0.030 м;
/// втрое больше — 0.090 — это порог, до которого шаг не может «не дотянуть»
/// ни на одной машине, и втрое меньше радиуса капсулы (0.35), то есть
/// незаметный на глаз.
inline constexpr float SEAT_ARRIVE_M =
    3.0f * static_cast<float>(config::WALK_SPEED * config::SIM_DT);

/// ДОВЕРНУЛСЯ, рад. Ровно ОДИН тик разворота (BODY_TURN_RATE x SIM_DT =
/// 0.128 рад = 7.4°): остаток, который доводится защёлкой позы, не больше
/// того, что штатный доворот прошёл бы за следующий кадр, — то есть
/// неотличим от продолжения доворота, а не от рывка.
inline constexpr float SEAT_ALIGN_RAD =
    static_cast<float>(config::BODY_TURN_RATE * config::SIM_DT);

/// ДОКУДА АВТОПИЛОТ ВЕДЁТ ЧЕЛОВЕКА САМ, м. Названа владельцем (заказ 28.08,
/// пункт 4: «короткий автопилот <= 3 м»), и НЕ строка docs/NUMBERS.md — по той
/// же причине, по которой там нет ни DOOR_REACH_M, ни SEAT_REACH_M: это
/// величина ВЗАИМОДЕЙСТВИЯ, у неё ровно один читатель (механика поз), и в
/// таблице мира она стояла бы рядом с ростом человека, ничего общего с ним не
/// имея.
///
/// НАЗВАННОЕ ЧИСЛО ПРОВЕРЕНО ПОЛКОЙ, а не принято на веру. Самый долгий
/// законный подход на сегодняшней полке — дуговая лавка (пятно 3.21x0.66):
/// человек стоит у её конца, целится (SEAT_REACH_M 1.2 м до ближайшей точки
/// габарита), а точка старта — у середины пятна, то есть 3.21/2 = 1.61 м
/// вдоль лавки плюс 1.2 м, откуда целился, — 2.8 м. Кровать (0.97x1.90) с
/// дальнего бока даёт 0.97 + 2 x 0.35 = 1.67 м. Потолок 3.0 накрывает худший
/// образец полки с запасом 0.2 м и отсекает соседнюю комнату.
inline constexpr float SEAT_APPROACH_MAX_M = 3.0f;

/// НАСКОЛЬКО ДОЛЖНО СОКРАТИТЬСЯ РАССТОЯНИЕ, ЧТОБЫ СЧЕСТЬ «ОН ИДЁТ», м. Треть
/// того, что интегратор проходит за тик (0.030): меньше — шум решателя,
/// больше — идущий человек считался бы стоящим.
inline constexpr float SEAT_STALL_EPS_M =
    static_cast<float>(config::WALK_SPEED * config::SIM_DT) / 3.0f;

/// СКОЛЬКО НЕПОДВИЖНОСТИ ЗНАЧИТ «УПЁРСЯ», с. Вчетверо дольше, чем нужно,
/// чтобы пройти порог прибытия (SEAT_ARRIVE_M / WALK_SPEED = 0.050 с): за
/// один тик человека может задержать ступенька или угол, за четыре порога —
/// уже стена. Ветка не косметическая, у неё есть свой замер: у лавки,
/// приставленной к столу, точка старта лежит В СТОЛЕ (между их телами 0.10 м
/// при радиусе капсулы 0.35), и без этой ветки посадка за таким столом не
/// случалась ВООБЩЕ.
inline constexpr float SEAT_STALL_S =
    4.0f * SEAT_ARRIVE_M / static_cast<float>(config::WALK_SPEED);

/// СКОЛЬКО ЖДАТЬ, ПОКА ОН ДОЙДЁТ, с. ВДВОЕ дольше самого долгого законного
/// подхода: SEAT_APPROACH_MAX_M / WALK_SPEED = 1.67 с ходьбы плюс полкруга
/// доворота pi / BODY_TURN_RATE = 0.41 с — итого 2.08 с, и запас той же
/// величины на обход стула, оказавшегося на дороге. Всё, что дольше, — это
/// застрявший человек, а не идущий, и он обязан быть отпущен вслух, а не
/// толкаться в угол до конца сессии.
inline constexpr float SEAT_APPROACH_TIMEOUT_S =
    2.0f * (SEAT_APPROACH_MAX_M / static_cast<float>(config::WALK_SPEED)
            + 3.14159265358979f / static_cast<float>(config::BODY_TURN_RATE));

/// НАСКОЛЬКО БЛИЗКО СТОЛ, ЧТОБЫ СЧИТАТЬСЯ «ЭТИМ» СТОЛОМ, м. Замер полки: в
/// раскладке трактира лавка стоит на 0.50-0.80 м от края стола (стол 1.8x0.9
/// на z=1.00, лавки на z=0.50 и z=2.10 — от середины лавки до середины стола
/// 0.95 и 1.15 м), а СЛЕДУЮЩИЙ стол зала отстоит на 4.9 м. Порог 1.60 стоит
/// выше худшего принятого образца (1.15) и втрое ниже отвергнутого (4.9).
inline constexpr float TABLE_NEAR_M = 1.60f;

// ---------------------------------------------------------------------------
// СБОР ТОЧЕК ПО КОМПОЗИЦИИ: ОДНО ПРАВИЛО НА ДВА НЕБА
// ---------------------------------------------------------------------------
//
// ЗАЧЕМ ВЫНЕСЕНО. Мебель приходит в игру из ДВУХ композиций: карман локации
// (то, что залил вход в дом) и карта под открытым небом (то, что залил вход в
// мир). Правило же у них одно — «замерь площадку, назови её, разверни
// сидящего», — и второй его копии быть не может: она разошлась бы с первой в
// тот день, когда порог сиденья подвинут (правило 32). Поэтому здесь стоит
// правило, а у вызывающего остаётся ровно то, чем две композиции и
// отличаются: ГДЕ он берёт вещи и ОТКУДА берёт их геометрию.
//
// ЧИСТА ПО-ПРЕЖНЕМУ: ни мира, ни ECS, ни физики. Геометрию приносит
// вызывающий по требованию — тем и куплено то, что сбор меряется в тесте без
// окна, на тех же чертежах, что стоят на карте.

/// ОДНА ПОСТАВЛЕННАЯ ВЕЩЬ КОМПОЗИЦИИ.
struct SeatPiece {
    /// Имя чертежа/объекта. Оно же КЛЮЧ ЗАМЕРА: геометрию спрашивают ОДИН РАЗ
    /// на имя, потому что шесть одинаковых лавок комнаты — это шесть раз один
    /// и тот же ответ, а сборка меша стоит дороже всего остального вместе.
    std::string key;
    /// Где стоит нулевой угол чертежа В МИРЕ (карман локации вызывающий уже
    /// прибавил: сборщик не знает, что такое карман).
    glm::vec3 origin{0.0f};
    float yaw = 0.0f;
};

/// КТО ДАЁТ ГЕОМЕТРИЮ. Возвращает false — вещь молча пропускается (её меш не
/// собрался, объекта нет на полке); о таком кричит заливка, и второй крик той
/// же беды читался бы как вторая беда.
using SeatGeometryFn = std::function<bool(const SeatPiece& piece,
                                          std::vector<glm::vec3>& positions,
                                          std::vector<std::uint32_t>& indices)>;

/// ЧТО НАШЛОСЬ НА КОМПОЗИЦИИ.
struct SeatCollection {
    /// Только сиденья и лежаки, уже развёрнутые (seat_facing) и с ростом
    /// человека в прицеле. Столы сюда не попадают: стол — обстановка.
    std::vector<FurnitureSpot> spots;
    std::size_t seats = 0;
    std::size_t lies = 0;
    std::size_t tables = 0;
    /// Сколько РАЗНЫХ имён спрошено у геометрии — цена сбора в сборках меша.
    std::size_t measured = 0;
    /// ЗАМЕРЕНО И ОТКЛОНЕНО, по одной записи на ИМЯ. Отказ — такой же ответ,
    /// как посадка, и без него «на стул не садятся» неотличимо от «стула не
    /// заметили»: у первого есть числа (площадка 0.46 x 0.46 при пороге
    /// длины 0.80), у второго их нет вовсе. Стол сюда не попадает — он не
    /// отказ, а обстановка.
    struct Refused {
        std::string key;
        FurnSurface surface;
    };
    std::vector<Refused> refused;
};

/// ПРАВИЛО ЦЕЛИКОМ: замер -> вид -> точка -> разворот. `centre` — та середина,
/// по которой разворачивается лавка, у которой нет своего стола (см.
/// seat_facing): под крышей это середина комнаты, под открытым небом —
/// середина расстановки, и другого ответа у открытой площадки нет, потому что
/// стены, от которой отворачиваются, там тоже нет.
[[nodiscard]] SeatCollection collect_furniture_spots(std::span<const SeatPiece> pieces,
                                                     const SeatGeometryFn& geometry,
                                                     const glm::vec3& centre);

