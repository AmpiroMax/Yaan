#pragma once

#include "engine/render/sources/PixelCanvas.h"

#include <chrono>
#include <cstddef>
#include <cstdint>
#include <string>
#include <vector>

namespace dfn::render {

/// ОДИН ЭТАП ЗАГРУЗКИ. Несёт ЧИСЛО, а не только слово: «постройки залиты» —
/// это состояние, «постройки залиты 214.6 мс» — это замер, по которому кто-то
/// может действовать. Тот же довод, что у SceneFinding::amount_m.
struct LoadStage {
    std::string what;    ///< «постройки залиты (меши+AO+коллайдер)»
    double ms = 0.0;     ///< сколько занял ЭТОТ этап; 0 — ещё идёт
    bool done = false;
};

/// ЭКРАН ЗАГРУЗКИ. Модель (какая локация, какие этапы, сколько времени) плюс
/// оформление (draw). Живёт столько же, сколько приложение: у него нет
/// ресурсов, а очистка между загрузками — это begin().
class LoadingScreen {
public:
    /// Начинает загрузку: очищает этапы, запускает часы, ставит заголовок.
    /// `title` — имя локации («Дом у рынка»), `subtitle` — строка мельче
    /// (путь сцены, «Вайтран», подсказка).
    void begin(std::string title, std::string subtitle);

    /// НАЗЫВАЕТ РАБОТУ, КОТОРАЯ ТОЛЬКО ЧТО СДЕЛАНА, и закрывает её отрезок.
    /// Зовётся ПОСЛЕ работы, а не до, и это не вкус: прибор DFN_LOAD_LOG
    /// печатает пару «что сделано / сколько заняло», и он старше экрана.
    /// Открывающая семантика («сейчас делаю X») сдвинула бы каждую строку
    /// прибора на одну — рецепты, разбирающие его вывод, стали бы читать
    /// время соседнего этапа под именем этого.
    void stage(std::string what);

    /// СКОЛЬКО ЭТАПОВ У ЭТОЙ ЗАГРУЗКИ — для полосы. Число знает вызывающий:
    /// сам экран не может его вывести, а полоса, ползущая по выдуманному
    /// прогнозу времени, врёт дважды в секунду.
    void set_expected(std::size_t stages) { expected_ = stages; }

    /// Закрывает последний этап и останавливает часы. Экран остаётся
    /// active() до hide(): последний кадр обязан показать итог.
    void finish();

    /// Гасит экран. Разделено с finish() намеренно: «загрузка кончилась» и
    /// «экран убран» — разные события, и между ними стоит кадр, ради
    /// которого экран существует.
    void hide();

    [[nodiscard]] bool active() const { return active_; }
    [[nodiscard]] const std::vector<LoadStage>& stages() const { return stages_; }
    [[nodiscard]] const std::string& title() const { return title_; }

    /// Сколько миллисекунд прошло с begin(). После finish() — итог загрузки.
    [[nodiscard]] double elapsed_ms() const;

    /// ЯВНАЯ ДОЛЯ 0..1. Отрицательное значение (умолчание) — «доля
    /// неизвестна», и тогда полоса считается ПО ЭТАПАМ. Отдельный вход нужен
    /// тем загрузкам, у которых есть счёт (N домов из M), а не только список.
    void set_progress(float fraction) { progress_ = fraction; }
    [[nodiscard]] float progress() const;

    /// ПЛЕЧО DFN_LOAD_LOG. Значение двери читает зона app (таблица дверей
    /// живёт там), а печатает — экран, потому что список этапов у него.
    void set_log(bool on) { log_ = on; }

    /// Рисует штатное оформление в холст. Холст очищается НЕПРОЗРАЧНО: экран
    /// загрузки закрывает мир, а не подсвечивает его.
    void draw(PixelCanvas& canvas) const;

    /// Строка отчёта одной загрузки для приёмки и для чата карты:
    /// «вход 431.2 мс: снос 3.1 | сцена 12.0 | ...».
    [[nodiscard]] std::string report() const;

private:
    using Clock = std::chrono::steady_clock;

    std::string title_;
    std::string subtitle_;
    std::vector<LoadStage> stages_;
    Clock::time_point begun_{};
    Clock::time_point marked_{};
    double total_ms_ = 0.0;
    std::size_t expected_ = 0;
    float progress_ = -1.0f;
    bool active_ = false;
    bool running_ = false;
    bool log_ = false;
};

} // namespace dfn::render
