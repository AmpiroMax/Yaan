#pragma once

#include "engine/core/materials/sources/MaterialRegistry.h"
#include "engine/render/sources/PartsAtlas.h"

#include <string>
#include <string_view>

namespace dfn::render {

/// ИМЯ ЛИСТА НАБОРА В РЕЕСТРЕ. Одно определение (правило 39): его пишут
/// данные, его читает мост, его же назовёт кузница, когда веществу
/// понадобится СВОЙ маленький лист вместо колонки в общей простыне (§2.6).
inline constexpr std::string_view PARTS_SHEET = "parts";

/// Имя колонки по ординалу. Пустая строка — ординал вне листа.
[[nodiscard]] std::string_view part_surface_name(PartSurface surface);
/// Имя ряда по ординалу.
[[nodiscard]] std::string_view part_tone_name(PartTone tone);
/// Ординал по имени. false — такого имени в раскладке нет, и это находка,
/// а не повод подставить нулевую колонку.
[[nodiscard]] bool part_surface_by_name(std::string_view name, PartSurface& out);
[[nodiscard]] bool part_tone_by_name(std::string_view name, PartTone& out);

/// ИМЕНОВАННОЕ ВЕЩЕСТВО ЭТОЙ ПАРЫ, если оно есть; иначе MATERIAL_NONE.
[[nodiscard]] core::MaterialId named_material_of(PartSurface surface, PartTone tone);

/// ПОЛНОЕ ОТОБРАЖЕНИЕ СТАРОЙ ПАРЫ В ЗАПИСЬ — обратная совместимость целиком в
/// одной функции. Секция HOUS формата v3 несёт (surface, tone); каждая из 36
/// пар обязана получить вещество, иначе полка мебели и построек перестанет
/// рисоваться в тот день, когда рисовальщик начнёт спрашивать материал.
///
/// Пары с именем отдают именованную запись; остальные получают ВЫВЕДЕННУЮ: та
/// же клетка, тот же ряд, умолчания по блику, ИЗНОС ПО РЯДУ (ряд Weathered —
/// это и есть «выветренное»; запись, которая об этом промолчит, потеряла бы
/// единственное, что пара про износ сообщала). Умолчания — это в точности
/// сегодняшний ламберт, и потому кадр не меняется ни на бит.
[[nodiscard]] core::MaterialRecord material_of(PartSurface surface, PartTone tone);

/// СВЕРКА РАСКЛАДКИ ДАННЫХ С ПЕРЕЧИСЛЕНИЯМИ АТЛАСА. false — разошлись, и
/// `why` (если дан) говорит, где именно. Это ворота, за которыми стоит вся
/// полка: имя, толкуемое против другой раскладки, перекрашивает молча.
[[nodiscard]] bool parts_sheet_matches_atlas(const core::MaterialTable& table,
                                             std::string* why = nullptr);

/// КАКОЙ ПРОГРАММОЙ РИСУЕТСЯ ЭТО ВЕЩЕСТВО — ОДНО МЕСТО, ГДЕ ЭТО РЕШАЕТСЯ
/// (MATERIALS.md §2.4). До этой волны программу выбирал ПОТОК файла: WOOD →
/// prop, CARD и BARK → foliage, HOUS → prop с вырезанной плиткой, — и потому
/// «чтобы брус стал кирпичом, надо было перепечь меш в другой поток», а
/// текстурированная стена, поехавшая по пути листвы, обязана была отдельно
/// гасить ветер, фейд по ракурсу и просвет листа.
///
/// Теперь спрашивают ВЕЩЕСТВО: качается ли оно (motion) и вырезается ли
/// (opacity). Программ по-прежнему две, но ни одна из них больше не значит
/// «это лист» или «это стена» — они значат «сплошная» и «вырезаемая».
///
/// ЧТО ЭТО НЕ ДЕЛАЕТ И ПОЧЕМУ (честно). Сами шейдеры не слиты: fs_foliage и
/// fs_prop остались двумя файлами. Слить их — это сменить кадр листвы, а
/// ряды атласа деревьев v1/v2 заморожены (сторож trees_v1_frozen), и волна с
/// требованием «доза 0 — бит в бит» не вправе их трогать. Слито РЕШЕНИЕ:
/// его больше нельзя принять в новом месте по-своему.
[[nodiscard]] std::string_view material_program(const core::MaterialRecord& rec);

} // namespace dfn::render
