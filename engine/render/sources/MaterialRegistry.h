#pragma once

#include "engine/render/sources/PartsAtlas.h"

#include <glm/vec3.hpp>

#include <cstdint>
#include <span>
#include <string_view>

namespace dfn::render {

/// КАК МАТЕРИАЛ ДВИЖЕТСЯ. Ветер листвы перестаёт быть отдельной вселенной и
/// становится СВОЙСТВОМ ВЕЩЕСТВА: лист качается, брус нет, и это единственная
/// разница между ними по этой оси. Сегодня разницу несёт выбор программы
/// (foliage против prop), из-за чего текстурированная стена, поехавшая по
/// пути листвы, обязана была отдельно гасить ветер, фейд по ракурсу и
/// просвет листа — три чужих поведения, которые она носит по недоразумению.
enum class MaterialMotion : std::uint8_t {
    Static = 0, ///< стоит: камень, брус, металл, ткань на стене
    Foliage = 1, ///< качается на общем ветре: листва, трава, позже — флаги
};

/// КАК МАТЕРИАЛ ЗАКРЫВАЕТ ПИКСЕЛЬ.
enum class MaterialOpacity : std::uint8_t {
    Opaque = 0, ///< сплошной: стена — замкнутый объём (правило 52)
    Cutout = 1, ///< маска с покрытием: карточка листа, решётка, ставня
};

/// ОДНА ЗАПИСЬ РЕЕСТРА.
///
/// Поля разложены по вопросам, а не по удобству упаковки: «чем покрыто»,
/// «какого оттенка», «как отражает», «светится ли», «как повторяется», «как
/// потрёпано», «как движется». Читающий рецепт должен видеть вещество, а не
/// набор координат в чужих атласах.
struct Material {
    /// ИМЯ — то, чем материал называют рецепт, инструмент и владелец:
    /// "oak-log", "brick-red", "gold-leaf". Не идентичность (идентичность —
    /// это порядковый, см. заметку про порядок в шапке), а рукоятка.
    std::string_view name{};

    // --- ЧЕМ ПОКРЫТО --------------------------------------------------------
    /// Есть ли у материала ПЛИТКА вообще. false — альбедо берётся плоским
    /// (сегодняшний путь prop бит-в-бит), и это не «недоделанный материал»:
    /// у полированного золота нет зерна на нашем масштабе, ему плитка не
    /// нужна, ему нужен блик.
    bool tiled = false;
    /// Колонка листа набора: ЧТО ЭТО ЗА ПОВЕРХНОСТЬ (волокно, зерно, стебли).
    PartSurface surface = PartSurface::HewnTimber;
    /// Ряд листа набора: тон И износ одной осью (см. PartsAtlas.h).
    PartTone tone = PartTone::Mid;
    /// МЕТРОВ ПОВЕРХНОСТИ НА ОДИН ПОВТОР ПЛИТКИ. Здесь, а не в PartSkin,
    /// потому что до .dfo это число сегодня не доезжает вовсе, и черепица
    /// 0.3 м не может отличаться от стены 1 м, покуда оно живёт у кузницы.
    float tile_span_m = PARTS_TILE_SPAN_M;

    // --- КАКОГО ОТТЕНКА -----------------------------------------------------
    /// МНОЖИТЕЛЬ на альбедо (на плитку либо на плоский цвет). Линейный,
    /// 1,1,1 — не трогать. Это то, чем «кирпич красный» отличается от
    /// «кирпича палевого», не заводя второй колонки атласа.
    glm::vec3 tint{1.0f, 1.0f, 1.0f};

    // --- КАК ОТРАЖАЕТ -------------------------------------------------------
    /// ШЕРОХОВАТОСТЬ 0..1. 1 — чистый ламберт, то есть В ТОЧНОСТИ сегодняшний
    /// кадр; ниже — собранный блик. Умолчание 1 выбрано ради этого: материал,
    /// который про блик молчит, не двигает ни пикселя.
    float roughness = 1.0f;
    /// МЕТАЛЛИЧНОСТЬ 0..1. У металла блик окрашен САМИМ материалом (золото
    /// бликует золотым), у диэлектрика — белый. Ради этого поля волна и
    /// существует в глазах владельца: «для золота/металла уже есть нужда —
    /// герб». Сегодня золотой герб — это ламберт цвета горчицы.
    float metalness = 0.0f;

    // --- СВЕТИТСЯ ЛИ --------------------------------------------------------
    /// СОБСТВЕННОЕ СВЕЧЕНИЕ, линейное. Сегодня самосветность — БУЛЕВ ФЛАГ
    /// куска (HouseSubmesh::emissive) и отрицательный z в u_params: пламя
    /// либо горит целиком без освещения, либо не горит. Поверхность, которая
    /// СЛЕГКА тлеет (угли, окно с огнём внутри, руна), сегодня невыразима.
    glm::vec3 emission{0.0f, 0.0f, 0.0f};

    // --- КАК ПОТРЁПАНО ------------------------------------------------------
    /// ШТАТНЫЙ ИЗНОС 0..1 материала. Рецепт может его перебить, но у вещества
    /// есть своя норма: соломенная кровля новой не бывает, золото герба —
    /// бывает только новым.
    float wear = 0.5f;

    // --- КАК ЖИВЁТ ----------------------------------------------------------
    MaterialMotion motion = MaterialMotion::Static;
    MaterialOpacity opacity = MaterialOpacity::Opaque;
};

/// МЕСТО МАТЕРИАЛА В РЕЕСТРЕ. Стабильный порядковый — это то, что поедет в
/// .dfo v4 вместо пары (поверхность, тон). uint16 с запасом: 36 пар листа
/// набора и десяток именованных — это первая сотня, а мир из двенадцати
/// городов легко просит тысячу.
using MaterialId = std::uint16_t;

/// «МАТЕРИАЛА НЕ НАЗВАНО». Не ошибка и не заглушка: это ровно тот случай, в
/// котором геометрия красится так, как красилась до материалов, — плоским
/// цветом вершины. Ноль выбран сознательно, чтобы обнулённое поле нового
/// формата означало «как раньше», а не «неизвестный материал».
inline constexpr MaterialId MATERIAL_NONE = 0;

/// ВСЯ ТАБЛИЦА. Индекс == MaterialId; запись 0 — MATERIAL_NONE.
[[nodiscard]] std::span<const Material> materials();

/// Одна запись по идентификатору. Идентификатор за пределами таблицы отдаёт
/// запись 0 (плоский цвет вершины) — файл из будущего должен рисоваться
/// бледно, а не падать.
[[nodiscard]] const Material& material(MaterialId id);

/// Поиск по имени. MATERIAL_NONE, если такого имени нет.
[[nodiscard]] MaterialId material_by_name(std::string_view name);

/// ПОЛНОЕ ОТОБРАЖЕНИЕ СТАРОЙ ПАРЫ В МАТЕРИАЛ — обратная совместимость целиком
/// в одной функции. Секция HOUS формата v3 несёт (surface, tone); каждая из
/// 36 пар обязана получить материал, иначе полка мебели и построек перестанет
/// рисоваться в тот день, когда рисовальщик начнёт спрашивать материал.
///
/// ПОЧЕМУ ЭТО НЕ ТАБЛИЦА ИЗ 36 ИМЁН. Именованных материалов у нас восемь, а
/// пар тридцать шесть; выдумать 28 имён, которых никто не заказывал, значило
/// бы засорить реестр записями без клиентов (правило 5 наоборот). Пары,
/// у которых нет имени, получают ВЫВЕДЕННЫЙ материал: те же плитка и тон,
/// умолчания по блику и износу. Он неотличим от сегодняшнего кадра — и это
/// проверяется, а не обещается (MaterialRegistryTests).
[[nodiscard]] Material material_of(PartSurface surface, PartTone tone);

/// ИМЕНОВАННЫЙ материал этой пары, если он есть; иначе MATERIAL_NONE.
/// Отдельно от material_of, потому что это РАЗНЫЕ вопросы: «чем это красить»
/// (всегда есть ответ) и «как это вещество зовут» (имя есть не у всего).
[[nodiscard]] MaterialId named_material_of(PartSurface surface, PartTone tone);

} // namespace dfn::render
