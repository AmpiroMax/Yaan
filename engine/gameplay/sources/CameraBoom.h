#pragma once

#include "engine/platform/physics/interfaces/IPhysics.h"

#include <glm/vec3.hpp>

namespace dfn::gameplay {

/// Оснастка стрелы. Значения по умолчанию — те самые, с которыми третье лицо
/// жило до коллизии (3.2 назад, 0.55 вверх): вид кадрируется под фигуру с
/// запасом сверху и ни из чего не выводится, это отладочный вид.
struct CameraBoomDesc {
    float back = 3.2f;          ///< отвод назад по взгляду, м
    float lift = 0.55f;         ///< подъём над головой (мировой верх), м
    float probe_radius = 0.25f; ///< радиус сферы-щупа, м
    float margin = 0.05f;       ///< отступ от точки касания, м
    float return_rate = 10.0f;  ///< 1/с, темп ВЫПУСКА стрелы обратно
};

/// Куда и как далеко стрела хочет уехать при данном взгляде. ДВА ЧИСЛА В ОДНОМ
/// ОТВЕТЕ на всякий случай не для краткости: длина стрелы ЗАВИСИТ ОТ ТАНГАЖА
/// (взгляд и мировой верх не ортогональны нигде, кроме горизонта), и функция,
/// возвращающая только направление, немедленно обзавелась бы второй, считающей
/// длину по своей формуле — тем самым расхождением, которое Rule 39 называет
/// теневой копией. При тангаже 0 длина равна hypot(back, lift) = 3.247 м, при
/// взгляде отвесно вниз — back + lift = 3.75 м.
struct CameraBoomAim {
    glm::vec3 direction{0.0f, 0.0f, 1.0f}; ///< единичное, от головы к камере
    float reach = 0.0f;                    ///< желаемая длина стрелы, м
};

[[nodiscard]] CameraBoomAim camera_boom_aim(float yaw, float pitch, const CameraBoomDesc& d);

/// Что вернул щуп, тем и ограничена стрела. Чистая функция от ответа физики:
/// промах — полная длина `reach`; касание — расстояние до центра сферы минус
/// отступ, не ниже нуля (ноль = камера прижата к голове, законный исход).
[[nodiscard]] float camera_boom_free_length(const platform::RayHit& sweep, float reach,
                                            const CameraBoomDesc& d);

/// Единственное место, где стрела трогает физику.
[[nodiscard]] platform::RayHit camera_boom_sweep(const platform::IPhysics& physics,
                                                 const glm::vec3& head,
                                                 const CameraBoomAim& aim,
                                                 const CameraBoomDesc& d,
                                                 platform::CollisionMask mask);

/// ПОТОЛОК ТАНГАЖА СТРЕЛЫ У ЛЕЖАЩЕГО, рад (25.8° вниз). Не «красивый ракурс»,
/// а СЛЕДСТВИЕ УСТРОЙСТВА СТРЕЛЫ: она уходит НАЗАД ПО ВЗГЛЯДУ, а лежащий
/// смотрит в потолок — значит «назад» у него ВНИЗ, в матрас. Потолок тангажа
/// держит стрелу над телом при любом взгляде, и он именно потолок, а не
/// фиксированный угол: смотреть ниже (то есть подниматься выше над телом)
/// игроку никто не запрещает — так камера и обводит тело сверху-сбоку, как в
/// Skyrim при сне.
///
/// ВЕЛИЧИНА ВЫБРАНА КАДРОМ, И ОБА КАДРА СНЯТЫ (docs/acceptance/seat-poses.md):
/// при 11.5° стрела упирается в стену на 2.43 м и кадр занимает стена, тело
/// внизу; при 25.8° потолок комнаты обрезает стрелу до 1.52 м, и камера
/// смотрит на лежащего сверху-сбоку — тело в кадре целиком.
///
/// СИДЯЩЕМУ ЭТОТ ПОТОЛОК НЕ НУЖЕН, и app его сидящему не выдаёт: у сидящего
/// взгляд по умолчанию ГОРИЗОНТАЛЕН, стрела ведёт себя ровно как у стоящего
/// (кадр приёмки №2 это и показывает), а навязанный взгляд под ноги отнял бы
/// у сидящего в трактире всю комнату.
inline constexpr float POSTURE_BOOM_PITCH_MAX = -0.45f;

/// Откуда пускать стрелу и с каким тангажом, когда тело лежит или сидит.
struct CameraBoomPerch {
    glm::vec3 origin{0.0f}; ///< начало стрелы (и центр обвода)
    float pitch = 0.0f;     ///< тангаж, которым считается стрела и кадр
};

/// НАЧАЛО СТРЕЛЫ НАД ТЕЛОМ. `perch` — точка над предметом, на котором тело
/// лежит: её считает тот, кто знает габарит предмета (app по точке позы), а
/// не эта функция — здесь нет ни мира, ни мебели. `weight` — доля позы
/// (0 — стоит, 1 — в позе), по ней всё и смешивается, поэтому вход в позу не
/// дёргает камеру.
///
/// ВЫСОТА БЕРЁТСЯ НЕ МЕНЬШЕ ГЛАЗА: у сидящего глаз (1.26 м над полом) и так
/// выше верха лавки, и поднимать его незачем — доза для сидящей руки приёмки
/// остаётся нулевой. У лежащего глаз в 0.25 м над матрасом, и вот его-то
/// поднять и надо: сфера щупа радиусом 0.25 начинала ВНУТРИ кровати.
///
/// ПОЧЕМУ НЕ ФИЛЬТР ПО ТЕЛУ МЕБЕЛИ (первое, что приходит в голову, — «пусть
/// щуп не видит кровать, как не видит утварь»): у кровати НЕТ СВОЕГО ТЕЛА.
/// Вся локация — оболочка, пол и вся мебель разом — это ОДНА сетка на
/// LAYER_STATIC (App::upload_interior_body), и «не видеть кровать» означало бы
/// не видеть и стену за ней, то есть вернуть ровно ту жалобу, ради которой
/// щуп заводился. Поэтому лечение геометрическое: щуп начинает там, где он
/// заведомо свободен.
/// `pitch_cap` — потолок тангажа ЭТОЙ позы (лежащему POSTURE_BOOM_PITCH_MAX,
/// сидящему предел камеры, то есть ничего). Число, а не признак позы: зона
/// камеры не знает и не должна знать, чем сидение отличается от лежания.
[[nodiscard]] CameraBoomPerch camera_boom_perch(const glm::vec3& eye, float pitch,
                                                const glm::vec3& perch, float pitch_cap,
                                                float weight);

/// Состояние стрелы между кадрами. Отрицательная длина — «ещё не заводилась»:
/// первый кадр после включения вида встаёт на свободную длину без взлёта.
struct CameraBoomState {
    float length = -1.0f;
};

/// Шаг сглаживания. Возвращает длину, с которой рисуется ЭТОТ кадр.
[[nodiscard]] float camera_boom_step(CameraBoomState& state, float free_length, float dt,
                                     const CameraBoomDesc& d);

} // namespace dfn::gameplay
