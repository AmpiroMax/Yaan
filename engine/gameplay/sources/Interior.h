#pragma once

#include <cstddef>
#include <cstdint>
#include <glm/vec3.hpp>
#include <string>
#include <vector>

namespace dfn::gameplay {

/// ОДНА СТУПЕНЬ СТЕКА ЛОКАЦИЙ: откуда вошли и куда высадить на выходе.
struct InteriorReturn {
    /// Сцена, В КОТОРОЙ стоял игрок до входа. Пусто — это была карта мира.
    std::string from_scene;
    /// Точка возврата в координатах ТОЙ сцены и взгляд.
    glm::vec3 position{0.0f};
    float yaw = 0.0f;
};

/// СОСТОЯНИЕ ПЕРЕХОДА. Ресурс мира; отсутствие ресурса и пустой стек значат
/// одно и то же — игрок снаружи.
struct InteriorState {
    /// Путь к .scene открытой локации. Пусто — игрок снаружи.
    std::string scene_path;
    /// Стек возвратов. Размер = ГЛУБИНА вложенности (0 — улица).
    std::vector<InteriorReturn> stack;
    /// Был ли игрок здесь раньше — для «уже разграблено» и для звука двери.
    bool visited = false;
    /// Открыта ли створка перехода, которым вошли.
    bool door_open = false;
    /// ПУСТОЙ КОНТЕЙНЕР НА БУДУЩЕЕ, и он здесь намеренно: «что отсюда уже
    /// унесли» — свойство ЛОКАЦИИ, а не мира, и день, когда это понадобится,
    /// не должен быть днём смены версии секции сохранения.
    std::vector<std::uint64_t> taken_items;

    [[nodiscard]] bool inside() const { return !stack.empty(); }
    [[nodiscard]] std::size_t depth() const { return stack.size(); }
};

/// СЕГОДНЯШНИЙ ПРЕДЕЛ ВЛОЖЕННОСТИ. Волна А зоны И15 разрешает одну ступень.
/// Это КОНСТАНТА, а не устройство: подъём предела до трёх — правка одной
/// строки, а не переписывание состояния (владелец 24.08).
inline constexpr std::size_t INTERIOR_MAX_DEPTH = 1;

} // namespace dfn::gameplay
