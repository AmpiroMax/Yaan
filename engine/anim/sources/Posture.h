#pragma once

#include "engine/anim/sources/Pose.h"
#include "engine/anim/sources/Rig.h"

#include <cstdint>

namespace dfn::anim {

/// ЧТО СЕЙЧАС ДЕЛАЕТ ТЕЛО. Значения — контракт с `BodyDrive::posture`
/// (простые данные, правило 8), дополнять в КОНЕЦ.
enum class Posture : uint8_t {
    None = 0, ///< живое тело: локомоция, воздух, присяд
    Sit = 1,  ///< сидит на сиденье высотой posture_height_m
    Lie = 2,  ///< лежит на спине на лежаке высотой posture_height_m
};

/// НАКЛОН ГОЛЕНИ СИДЯЩЕГО ОТ ОТВЕСА, рад. Не «на глаз»: у сидящего человека
/// голень стоит почти отвесно, чуть вынося стопу вперёд от колена, и эти 7°
/// — та самая малость. Величина ВЫБРАНА, а бедро из неё ВЫВОДИТСЯ (см.
/// sit_pose): наоборот было бы хуже — угол бедра обязан подстраиваться под
/// высоту сиденья, иначе стопы у высокой лавки уходят в пол.
inline constexpr float SIT_SHIN_TILT_RAD = 0.12f;

/// НАКЛОН КОРПУСА СИДЯЩЕГО ВПЕРЁД, рад (~8°). «Лёгкий наклон» из заказа.
/// Отсчёт как у бегового наклона в Clips.cpp: вперёд — ОТРИЦАТЕЛЬНЫЙ тангаж
/// корпуса, голова контр-поворачивается, чтобы взгляд остался горизонтальным.
inline constexpr float SIT_TRUNK_LEAN_RAD = 0.14f;

/// ПОЗА СИДЯ. `seat_above_ground_m` — высота ПОВЕРХНОСТИ сиденья над той
/// землёй, к которой привязан корень тела (у лавки это 0.45 — замер верха
/// настила с самого чертежа).
///
/// ЧТО ЗДЕСЬ РЕШАЕТСЯ ГЕОМЕТРИЕЙ, А НЕ ВКУСОМ: тазобедренная ось стоит выше
/// сиденья на ПОЛОВИНУ ТОЛЩИНЫ НОГИ (бедро лежит на настиле), а угол бедра
/// подбирается так, чтобы ЛОДЫЖКА села ровно на свою стоячую высоту, то есть
/// стопа встала на пол. Оттого поза одинаково верна и у лавки 0.45, и у
/// низкой скамьи: при недосягаемом полу acos зажимается и ноги честно висят.
[[nodiscard]] LocalPose sit_pose(const Rig& rig, float seat_above_ground_m);

/// ПОЗА ЛЁЖА НА СПИНЕ. `deck_above_ground_m` — высота НАСТИЛА (у кровати
/// реестра 0.50 — верх матраса, замер с чертежа).
///
/// Тело кладётся поворотом таза на +90° вокруг X: местное «вверх» уходит в
/// местное +Z (назад), лицо — в мировой верх. Руки при этом сами ложатся
/// вдоль тела, стопы сами встают носками вверх — это не подгонка, а прямое
/// следствие того, что все они висят по -Y от своих суставов.
[[nodiscard]] LocalPose lie_pose(const Rig& rig, float deck_above_ground_m);

/// СКОЛЬКО ДЛИТСЯ ДВИЖЕНИЕ, с. Не одно число на обе позы: лечь — путь длиннее
/// (таз опускается ниже И тело откидывается на 90°), и та же длительность
/// читалась бы падением. Величины из заказа зоны: сесть 0.5–0.7, лечь 0.8–1.0.
inline constexpr float SIT_TRANSIT_S = 0.60f;
inline constexpr float LIE_TRANSIT_S = 0.90f;
[[nodiscard]] float posture_transit_s(Posture p);

/// ДОЛИ ОДНОГО ПЕРЕХОДА. Пять чисел вместо одного веса — ровно затем, что
/// переход НЕ кроссфейд: части тела приходят к позе не одновременно, и
/// именно их сдвиг делает движение дугой, а не прямой.
///
/// Все пять — доли ОДНОГО времени `t` (0 — стоит, 1 — в позе), каждая
/// монотонна, каждая точна на концах (0 в 0 и 1 в 1) и каждая выходит из
/// концов с НУЛЕВОЙ производной: рывок на входе и на выходе — это и есть то,
/// от чего заказ уходит.
struct PostureTransit {
    /// Живой слой уходит, тело переходит на процедурное движение. Доезжает
    /// РАНО: дальше поза ведётся траекторией, а не весом кроссфейда.
    float take = 1.0f;
    /// Таз по дуге вниз — главная координата перехода.
    float drop = 1.0f;
    /// Корень (место и рыск) переносится к мебели. ОПЕРЕЖАЕТ `drop` у
    /// сиденья: сначала человек оказывается над лавкой, потом опускается, —
    /// это и есть дуга. Одинаков с `drop` у лежака: туда переносятся, уже
    /// опускаясь.
    float plan = 1.0f;
    /// Корпус, голова и руки — доезжают последними.
    float settle = 1.0f;
    /// ОТКИДЫВАНИЕ: таз разворачивается на 90°, ноги идут за ним. Только у
    /// Lie; у Sit тождественный 0.
    float recline = 0.0f;
};

/// Доли по времени `t` (зажимается в [0,1]).
[[nodiscard]] PostureTransit posture_transit(Posture p, float t);

/// ПОЗА НА ПОЛПУТИ — И ОНА ЖЕ ОБА КОНЦА. При долях, равных единице, отдаёт
/// ровно sit_pose/lie_pose (это проверено тестом, а не обещано): концы и
/// середина обязаны быть ОДНОЙ функцией, иначе переход — третье описание
/// позы. Колени и бёдра здесь ВЕДОМЫЕ: двузвенник решается на ТЕКУЩЕЙ высоте
/// таза, а не интерполируется между двумя решёнными углами, — оттого стопа
/// стоит на полу на каждом кадре спуска, а не только на концах.
[[nodiscard]] LocalPose posture_pose(const Rig& rig, Posture p, float height_m,
                                     const PostureTransit& w);

/// ГДЕ У ЭТОЙ ПОЗЫ ГЛАЗ, мировые. Считается ПО СКЕЛЕТУ: сустав шеи плюс
/// (PLAYER_EYE_HEIGHT − высота шеи) вдоль собственной оси головы плюс
/// PLAYER_EYE_FORWARD вдоль её взгляда. На стоячей позе это ровно та точка,
/// куда камеру ставит sim, — значит формула не заводит второй камеры, а
/// продолжает первую в позы, у которых голова уехала (крит: у лежащего
/// «глаз на оси капсулы» оказался бы в потолке над кроватью).
[[nodiscard]] glm::vec3 posture_eye(const Rig& rig, const LocalPose& pose,
                                    const BodyRoot& root);

/// РЫСК ТЕЛА, ЛЕЖАЩЕГО ГОЛОВОЙ В `head_dir` (единичный, XZ). Обратная
/// сторона того, что голова уходит в местное +Z: обычный «рыск взгляда»
/// уложил бы человека головой в ноги.
[[nodiscard]] float lie_yaw_for_head_dir(float head_dir_x, float head_dir_z);

} // namespace dfn::anim
