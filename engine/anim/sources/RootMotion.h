#pragma once

#include "engine/anim/sources/FootIk.h"

#include <array>
#include <cstdint>
#include <glm/vec3.hpp>

namespace dfn::anim {

/// ЗАЯВКА ЛОКОМОЦИИ ЗА ТИК — что зона просит у мира.
struct LocomotionOut {
    /// Смещение корня за тик в системе тела (y = 0), метры.
    glm::vec3 root_delta_model{0.0f};
    /// Фаза шага [0,1) — часы этой зоны, для боба камеры и событий.
    float phase = 0.0f;
    /// Постановка стопы на этом тике: [0] левая, [1] правая.
    std::array<bool, 2> footfall{};
    /// Ложь — заявки нет (нет клипов, нет опоры, прежний шов): сим двигает
    /// капсулу как прежде.
    bool valid = false;
};

/// ПАМЯТЬ КОРНЕВОГО ДВИЖЕНИЯ между тиками, плоские данные.
struct RootMotionState {
    /// Оценка скорости тела, м/с: спадающий пик модуля смещения за тик.
    /// По ней стопа, отстающая от тела (садится или отрывается), теряет вес
    /// опоры — её Δp уже не ход тела.
    float speed_est_mps = 0.0f;
    /// Среднее смещение последней сплошной опоры — инерция на тики без опоры
    /// (полёт бега, прыжок): тело летит с той скоростью, с какой оттолкнулось,
    /// а не с той, с какой стопа отклеивалась.
    glm::vec3 coast{0.0f};
    /// Средний ход текущей опоры — скользящее среднее длиной в шаг
    /// (STEP_MEMORY_S), не накопительное: на ходьбе полёта нет, окно не
    /// сбрасывается, и накопленное с ходьбы среднее тянуло трусцу после
    /// ходьбы к 2,5 м/с против 2,9 с места.
    glm::vec3 window_mean{0.0f};
    bool window_has = false;
    /// Сколько тиков подряд опора слабая (Σw < 1): на окне смены опоры тело
    /// едет по инерции текущей опоры, дальше — как скажут стопы.
    uint32_t weak_n = 0;
    /// Смещение прошлого тика — для предела ускорения (ROOT_ACCEL_MAX_MPS2).
    glm::vec3 last_delta{0.0f};
    bool has_last = false;
};

/// ОДИН ТИК: уточняет `curr.support` движением стоп (правит на месте) и
/// возвращает смещение корня в системе тела, при котором опорная стопа
/// осталась бы на месте. `dt` — шаг тика, секунды.
/// `travel` — ось, по которой стопы уходят под телом (единичная, в системе
/// тела): (0,0,+1) для хода вперёд, −move_dir_model вообще (§9.3) —
/// мах/опора/отставание меряются проекцией Δp на неё.
[[nodiscard]] glm::vec3 root_motion_step(const ContactState& prev, ContactState& curr,
                                         float dt, RootMotionState& state,
                                         const glm::vec3& travel = glm::vec3{0.0f, 0.0f, 1.0f});

/// Постановки: вес опоры пересёк `on_weight` снизу вверх.
[[nodiscard]] std::array<bool, 2> detect_footfalls(const ContactState& prev,
                                                   const ContactState& curr,
                                                   float on_weight);

} // namespace dfn::anim
