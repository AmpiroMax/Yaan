#pragma once

#include "engine/anim/sources/SkinnedBody.h"
#include "engine/core/skeleton/sources/Skeleton.h"

#include <cstdint>
#include <span>
#include <vector>

namespace dfn::anim {

/// КАКОЙ СУСТАВ КАКОМУ ЗЕРКАЛЬНАЯ ПАРА. `partner[j] == j` — сустав на оси тела
/// (таз, позвоночник, голова): его зеркало он сам. -1 — пары не нашлось, и
/// такой сустав слой НЕ ТРОГАЕТ вовсе, что и есть верный ответ для косточки
/// плаща, которой не с чем меняться.
struct MirrorMap {
    std::vector<int32_t> partner;
    uint32_t pairs = 0;   ///< сколько нашлось настоящих пар (левая+правая = одна)
    uint32_t centres = 0; ///< сколько суставов сами себе зеркало
    uint32_t lone = 0;    ///< сколько осталось без пары
    [[nodiscard]] bool valid() const { return !partner.empty() && pairs > 0; }
};

/// ДОПУСК ПОИСКА ПАРЫ, доли РОСТА скелета (габарит бинда по вертикали).
///
/// ДОЛЯ, А НЕ МЕТРЫ: карлик и великан на одном рецепте обязаны получать одну и
/// ту же разметку, а метровый допуск на первом склеил бы всё тело в одну пару.
/// 0.01 роста — это около 1.8 см на нашем каноне, то есть заведомо больше
/// кривизны бинда (замерено на HumanBase: худшая пара расходится на 0.4 мм) и
/// заведомо меньше расстояния между соседними суставами одной руки (5 см).
inline constexpr float MIRROR_TOLERANCE_FRAC = 0.01f;

[[nodiscard]] MirrorMap build_mirror_map(const skel::Skeleton& skeleton);

/// ЗЕРКАЛО ПОЗЫ: `out[j]` = отражение того, что делает `partner[j]`. Размеры
/// обоих пролётов не меньше skeleton.size(); `out` может совпадать с `sample`
/// только если вызывающий не против — здесь он не может, и функция это
/// проверяет копией.
void mirror_pose(const skel::Skeleton& skeleton, const MirrorMap& map,
                 std::span<const JointLocal> sample, std::span<JointLocal> out);

/// СМЕСЬ ПОЗЫ С ЗЕРКАЛОМ ПОЗЫ ПОЛУЦИКЛОМ ПОЗЖЕ, на месте.
///
/// `half` — та же анимация, взятая через половину своей длительности.
/// `dose` в [0, 0.5]: 0 — побитовое тождество (на нём стоит контрольная рука
/// приёмки), 0.5 — точная антисимметрия. Больше 0.5 не имеет смысла и
/// срезается: это уже «стать зеркалом самого себя через полцикла», то есть
/// сдвиг фазы, а не симметрия.
void mirror_blend(const skel::Skeleton& skeleton, const MirrorMap& map,
                  std::span<const JointLocal> half, float dose,
                  std::span<JointLocal> sample);

/// ПРИБОР: на сколько метров расходятся две половины тела за цикл — худшее по
/// суставам расстояние между суставом и отражением его пары полуциклом позже.
/// Ноль у идеально антисимметричной походки.
[[nodiscard]] float mirror_asymmetry(const skel::Skeleton& skeleton,
                                     const MirrorMap& map,
                                     std::span<const JointLocal> sample,
                                     std::span<const JointLocal> half);

} // namespace dfn::anim
