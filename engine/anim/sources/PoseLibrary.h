namespace dfn::anim {

/// ОПОРНЫЕ СТОЙКИ-ПОСРЕДНИКИ. Значения — ИНДЕКС В ЦЕПИ, и это контракт:
/// маршрут между двумя опорами есть отрезок этой цепи, а длительность колена
/// берётся по паре соседних индексов. Вставить опору в середину — значит
/// пересмотреть обе таблицы, и такая вставка обязана быть решением.
enum class Support : uint8_t {
    Stand = 0,    ///< на двух ногах
    Crouch = 1,   ///< на корточках / на сиденье: таз опущен, стопы под тазом
    SitFloor = 2, ///< таз на полу
    LieProne = 3, ///< тело на полу лицом вниз
};
inline constexpr uint32_t SUPPORT_COUNT = 4;

/// ПОЗЫ РЕЕСТРА. Первые четыре — сами опоры (см. Notes: посредник это
/// обычная запись). Порядок дальше — порядок ленты приёмки и порядок,
/// в котором доза перебирает позы клавишами.
enum class PoseId : uint8_t {
    // --- опоры ---------------------------------------------------------
    Stand = 0,          ///< обычная стойка покоя
    Crouch,             ///< присяд
    SitFloor,           ///< сидя на полу, ноги вперёд
    LieProne,           ///< лёжа на животе, руки по швам
    // --- гражданские стоячие -------------------------------------------
    HandsOnHips,        ///< руки в бока (референс владельца)
    HandsBehindBack,    ///< руки за спиной
    HandsBehindHead,    ///< руки за головой, лёгкий наклон («задержанный»)
    Attention,          ///< «солдатик»
    ArmUpLeft,          ///< левая рука вверх
    ArmUpRight,         ///< правая рука вверх
    ArmsUp,             ///< обе руки вверх
    // --- низкие ---------------------------------------------------------
    SquatTouchFloor,    ///< присед с касанием руками пола
    PushUp,             ///< упор лёжа
    Plank,              ///< планка на предплечьях
    SitCross,           ///< сидя скрестно
    SitLegsApart,       ///< сидя, ноги врозь
    SplitFront,         ///< шпагат продольный
    SplitSide,          ///< шпагат поперечный
    // --- стул -----------------------------------------------------------
    SitChairHandsTable, ///< сидя на стуле, руки на столе
    SitChairHandsKnees, ///< сидя на стуле, руки на коленях
    // --- оружие (верх тела; ноги ведёт локомоция) ------------------------
    Guard1H,            ///< одноручный клинок
    Guard2H,            ///< двуручный
    GuardBow,           ///< лук на изготовку
};
inline constexpr uint32_t POSE_COUNT = 23;

[[nodiscard]] constexpr uint32_t pose_index(PoseId p) { return static_cast<uint32_t>(p); }

/// ЦЕЛЬ КИСТИ. Точка задана В СИСТЕМЕ ТАЗА (начало — тазобедренная ось, +X
/// вправо от фигуры, +Y вверх, +Z назад — docs/RIG.md) и В ДОЛЯХ ВЫСОТЫ
/// БЕДРА, а не в метрах: доля переносится на фигуру другого роста, метр — нет.
/// Таз выбран началом отсчёта, а не плечо, потому что половина целей реестра
/// — это точки НА ТАЗЕ или на полу, и мерить их от плеча значило бы
/// пересчитывать их при всяком наклоне корпуса.
struct ArmTarget {
    bool used = false;
    glm::vec3 at{0.0f};    ///< доли hip_height, система ТАЗА
    /// ЗАКРУТКА ЛОКТЯ вокруг оси плечо->кисть, град. Двузвенник, приведённый
    /// к цели, оставляет ровно одну свободу — куда смотрит локоть, — и она
    /// решает, руки в бока это или руки перед собой. Знак — АБСОЛЮТНЫЙ, как
    /// у всех прочих величин реестра (+ = к +X, то есть к правой стороне
    /// фигуры); зеркальная строка меняет его вместе с X цели.
    float swivel_deg = 0.0f;
};

/// НОГА УГЛАМИ. Порядок применения — рыск, крен, тангаж (q = Ry * Rz * Rx), и
/// он выбран не наугад: у ноги, уже поднятой тангажом почти в горизонт, крен
/// вокруг собственной оси Z её уже никуда не разводит, а рыск вокруг ОТВЕСА
/// — разводит, и именно это нужно скрестному сидению. Крен остаётся ради
/// поперечного шпагата, где тангаж нулевой.
struct LegAngles {
    float thigh_pitch_deg = 0.0f; ///< сгибание в тазобедренном, + = вперёд
    float thigh_yaw_deg = 0.0f;   ///< разведение вокруг отвеса, + = к +X
    float thigh_roll_deg = 0.0f;  ///< отведение вбок в плоскости фронта, + = к +X
    float knee_deg = 0.0f;        ///< сгибание колена, + = сгиб (внутри
                                  ///< переводится в отрицательный тангаж —
                                  ///< см. предел BODY_KNEE_FLEX_MAX)
    float ankle_deg = 0.0f;       ///< тангаж стопы, + = носок на себя
};

/// ОДНА СТРОКА РЕЕСТРА.
struct PoseRecord {
    std::string_view name;   ///< машинное имя (доза, лента, отчёт)
    std::string_view label;  ///< как поза называется по-русски на экране
    Support support = Support::Stand;
    /// КЛИП ОТКРЫТОЙ БИБЛИОТЕКИ, если он есть в дереве; пусто — поза
    /// авторская. Строка ничего не решает внутри зоны (см. Notes), она
    /// НАЗЫВАЕТ ИСТОЧНИК: заказ требует сначала брать готовое.
    std::string_view source_clip;
    /// Высота таза в долях СТОЯЧЕЙ высоты бедра. 1 — стоит.
    float hip_frac = 1.0f;
    /// Наклон таза, град: -90 кладёт тело ничком, +90 — на спину (тот же
    /// поворот, которым Posture.h укладывает на лежак).
    float pelvis_pitch_deg = 0.0f;
    float torso_pitch_deg = 0.0f; ///< + = наклон корпуса вперёд
    float torso_roll_deg = 0.0f;
    float head_pitch_deg = 0.0f;  ///< + = взгляд вниз
    /// РЕШАТЬ ЛИ ДВУЗВЕННИК НОГИ ПОД ОПУЩЕННЫЙ ТАЗ. Истина у приседа и у
    /// сидения на стуле: там углы ног не авторские, а СЛЕДСТВИЕ высоты таза,
    /// и записать их числом значило бы, что на фигуре с другой ногой стопы
    /// уедут в пол (тот же довод, что у anim::sit_pose).
    bool fold_legs = false;
    /// ПОЗА НА СИДЕНЬЕ. Таз и ноги приходят от anim::sit_pose — той же
    /// функции, которой игрок садится на лавку, — а высота сиденья является
    /// параметром pose_of(). Свой набор углов для стула был бы вторым
    /// описанием сидения и разошёлся бы с игровым молча (правило 35).
    bool on_seat = false;
    /// Истина — правая сторона есть зеркало левой (крен, рыск и X цели
    /// меняют знак). Ложь — обе стороны заданы явно.
    bool symmetric = true;
    /// ВЕРХ ТЕЛА ТОЛЬКО. Оружейные стойки: ноги при них ходят обычной
    /// ходьбой, и маска ветвей (PoseLayers.h) это уже умеет.
    bool upper_only = false;
    std::array<LegAngles, 2> leg{};   ///< [0] левая
    std::array<ArmTarget, 2> arm{};   ///< [0] левая
};

[[nodiscard]] const PoseRecord& pose_record(PoseId p);
[[nodiscard]] std::string_view pose_name(PoseId p);
/// Поза по машинному имени; POSE_COUNT-значный промах отдаётся как `Stand`
/// вместе с ложью во втором возврате.
[[nodiscard]] PoseId pose_by_name(std::string_view name, bool* found = nullptr);
[[nodiscard]] Support pose_support(PoseId p);

/// СТРОКА РЕЕСТРА + ПРОПОРЦИИ -> ПОЗА. Чистая функция: ни файла, ни клипа.
[[nodiscard]] LocalPose pose_of(const Rig& rig, PoseId p);
/// То же, но для поз на сиденье (`on_seat`) высота сиденья приходит ИЗВНЕ:
/// на стенде это образцовые 0.45 лавки, в мире — замер того предмета, на
/// который человек сел. У прочих поз параметр не читается.
[[nodiscard]] LocalPose pose_of(const Rig& rig, PoseId p, float seat_height_m);

// --- ГРАФ ПЕРЕХОДОВ -------------------------------------------------------

/// СКОЛЬКО ДЛИТСЯ КОЛЕНО МАРШРУТА, с. Паспорт у каждой величины, потому что
/// длительность здесь — это утверждение о том, ЧТО ИМЕННО ЕДЕТ.
///
/// ПОЗА <-> ЕЁ СОБСТВЕННЫЙ ПОСРЕДНИК: 0.45 с. Вес тела при этом НЕ ПЕРЕНОСИТСЯ
/// — опора та же, меняются только конечности (руки в бока -> руки вниз). Это
/// быстрее любого переноса веса и медленнее хвата: у человека такое движение
/// занимает 0.3–0.6 с.
inline constexpr float POSE_TO_SUPPORT_S = 0.45f;
/// СТОЯ <-> ПРИСЕД: 0.55 с. Приседание на корточки — одно сгибание коленей,
/// без переноса рук; у нас же оно обязано быть не быстрее собственного
/// присяда локомоции, чтобы два одинаковых на вид движения не шли с разной
/// скоростью.
inline constexpr float SUPPORT_STAND_CROUCH_S = 0.55f;
/// ПРИСЕД <-> СИДЯ НА ПОЛУ: 0.80 с. Здесь вес ПЕРЕНОСИТСЯ со стоп на таз, и
/// именно поэтому дольше присяда: у человека это движение с опорой на руку.
inline constexpr float SUPPORT_CROUCH_SITFLOOR_S = 0.80f;
/// СИДЯ НА ПОЛУ <-> ЛЁЖА НИЧКОМ: 0.90 с. Ровно длительность укладки на лежак
/// (anim::LIE_TRANSIT_S) и по той же причине: путь длиннее на целое
/// откидывание корпуса, и та же длительность, что у присяда, читалась бы
/// падением.
inline constexpr float SUPPORT_SITFLOOR_LIEPRONE_S = 0.90f;

/// ПОТОЛОК УГЛОВОЙ СКОРОСТИ СУСТАВА В ПЕРЕХОДЕ, рад/с. Приёмка заказа
/// («переход не рвёт суставы») написана в нём.
///
/// ЧИСЛО ВЗЯТО НЕ С ПОТОЛКА, А У КОНТРОЛЬНОЙ РУКИ (правило 47: мерить
/// РАЗНОСТЬ против принятого, а не величину на проверяемом). Быстрее всего в
/// движке уже сейчас двигается СТОПА В ПОХОДКЕ: замер gait_pose на шаге и на
/// беге даёт 15.96 рад/с (915 °/с) в обоих случаях — и эта походка принята и
/// снята в кадрах. Переход, который держится НИЖЕ уже принятого движения, по
/// определению не рвёт больше, чем рвёт бег. Худший переход реестра при этом
/// стоит на 9.89 рад/с (566 °/с, бедро на пути «лёжа ничком -> продольный
/// шпагат»), так что 12 — это запас в четверть над худшим и четверть под
/// принятым.
inline constexpr float POSE_MAX_JOINT_RATE = 12.0f;

/// Длительность колена между двумя СОСЕДНИМИ опорами.
[[nodiscard]] float support_step_s(Support a, Support b);

/// САМОЕ ДЛИННОЕ ЧИСЛО КОЛЕН: поза -> своя опора -> три ребра цепи -> чужая
/// опора -> поза = пять колен, шесть узлов.
inline constexpr uint32_t POSE_ROUTE_MAX = 6;

/// МАРШРУТ. Узлы — позы реестра (посредники в их числе), у каждого колена
/// своя длительность.
struct PoseRoute {
    std::array<PoseId, POSE_ROUTE_MAX> step{};
    std::array<float, POSE_ROUTE_MAX - 1> leg_s{};
    uint32_t count = 0; ///< число УЗЛОВ; колен на единицу меньше
    [[nodiscard]] uint32_t legs() const { return count > 0 ? count - 1 : 0; }
    [[nodiscard]] float total_s() const;
};

/// ИЗ ЛЮБОЙ ПОЗЫ В ЛЮБУЮ. Узлы: сама поза, её опора, отрезок цепи опор,
/// опора цели, цель. Повторы схлопываются — переход из опоры в её же позу не
/// заводит колена нулевой длины.
[[nodiscard]] PoseRoute pose_route(PoseId from, PoseId to);

/// СОСТОЯНИЕ ПРОИГРЫВАНИЯ, простые данные (правило 8): своих часов не имеет,
/// время приходит в pose_transit_advance.
struct PoseTransit {
    PoseRoute route{};
    uint32_t leg = 0;      ///< какое колено едет
    float t_s = 0.0f;      ///< сколько его уже проехали
    bool moving = false;
    [[nodiscard]] PoseId from() const;
    [[nodiscard]] PoseId to() const;
    /// Куда маршрут ведёт целиком (последний узел).
    [[nodiscard]] PoseId target() const;
};

/// Ставит тело в позу без всякого движения — начальное состояние.
[[nodiscard]] PoseTransit pose_transit_at(PoseId p);
/// Заводит маршрут ОТ ТОГО, ЧТО СЕЙЧАС РИСУЕТСЯ. Прерывание на полпути
/// законно: маршрут строится от ближайшего узла, а не от изначальной позы, —
/// иначе смена цели посреди вставания уводила бы тело обратно на пол.
void pose_transit_begin(PoseTransit& tr, PoseId to);
/// Один шаг времени. Переваливает колена, пока не кончится dt.
void pose_transit_advance(PoseTransit& tr, float dt);

/// ПОЗА НА МГНОВЕНИИ МАРШРУТА. Между узлами — сглаженная доля (нулевая
/// производная на обоих концах), чтобы стык колен не давал излома угловой
/// скорости: именно этот излом приёмка меряет как «переход рвёт суставы».
[[nodiscard]] LocalPose pose_transit_pose(const Rig& rig, const PoseTransit& tr);

/// ДОЛЯ ОДНОГО КОЛЕНА, сглаженная. Вынесена, потому что её же читает прибор
/// приёмки: судья и движение обязаны считать долю ОДНИМ выражением.
[[nodiscard]] float pose_ease(float u);

} // namespace dfn::anim
