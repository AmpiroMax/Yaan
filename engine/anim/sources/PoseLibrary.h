/*
Module: engine/anim
File: engine/anim/sources/PoseLibrary.h

Responsibility:
- РЕЕСТР ИМЕНОВАННЫХ ПОЗ И ГРАФ ПЕРЕХОДОВ МЕЖДУ НИМИ. Двадцать три позы —
  гражданские стойки, пол, лёжа, стул и три оружейные — заданы ДАННЫМИ (одна
  строка реестра на позу), а из позы в позу тело идёт МАРШРУТОМ через опорные
  стойки-посредники, а не кроссфейдом напрямую.

Key items:
- PoseId / POSE_COUNT: перечень поз. Порядок — контракт с лентой и дозой,
  дополнять В КОНЕЦ.
- Support / SUPPORT_COUNT: четыре опорных стойки (стоя, присед, сидя на полу,
  лёжа на животе). Это ЦЕПЬ: соседние по индексу связаны переходом, дальние —
  только через промежуточные.
- PoseRecord / pose_record(): сама строка реестра. Ноги — углами, руки —
  ЦЕЛЬЮ КИСТИ (двузвенник решается), таз — высотой и наклоном.
- pose_of(): строка реестра + пропорции рига -> LocalPose.
- PoseRoute / pose_route(): маршрут из позы в позу через посредников, вместе
  с длительностью каждого колена.
- PoseTransit / pose_transit_*(): состояние проигрывания маршрута (простые
  данные) и поза на любом его мгновении.

Dependencies:
- Uses: Rig.h, Pose.h, glm. Ни мира, ни ECS, ни часов.
- Used by: Body.cpp (живой привод), engine/app (стенд, доза), tests/character.

Notes:
- ПОЧЕМУ РУКИ ЗАДАНЫ ЦЕЛЬЮ, А НОГИ УГЛАМИ. Это не вкус, а два разных вопроса.
  «Руки в бока» — утверждение о ТОЧКЕ: кисть лежит на гребне подвздошной
  кости, и на модели с другими руками эта точка та же, а углы другие. Шпагат
  же — утверждение об УГЛЕ: бедро разведено на девяносто градусов, и никакая
  точка этого не скажет. Записать одно языком другого значило бы, что поза
  разъезжается при первой правке пропорций (правило 35 в его исходном виде:
  величина описывается там, где она измеряется).
- ЧЕТЫРЕ ПОСРЕДНИКА — ЭТО ЦЕПЬ, А НЕ ЗВЕЗДА, и это прямое следствие заказа
  («встать из сидя скрестно = ноги распрямить -> присед -> стоя»). Между
  «лёжа на животе» и «стоя» нет прямого ребра: человек проходит через сидя на
  полу и через присед, и маршрут это ПОКАЗЫВАЕТ, а не сокращает. Звезда с
  центром «стоя» дала бы телепорт из лежачей позы в стоячую за одно колено.
- ПОЗА-ПОСРЕДНИК ЕСТЬ ОБЫЧНАЯ ЗАПИСЬ РЕЕСТРА. Отдельного «служебного» набора
  углов для перехода не заводится: иначе присед, который видно на стенде, и
  присед, через который проходит маршрут, стали бы двумя описаниями одного
  положения тела и разошлись бы молча.
- ИСТОЧНИК КАЖДОЙ ПОЗЫ НАЗВАН СТРОКОЙ. У части поз в дереве уже лежит клип
  открытой библиотеки (KayKit Adventurers, CC0, assets/objects/characters —
  Sit_Chair_Pose, Sit_Floor_Pose, Lie_Pose, 2H_Melee_Idle, 2H_Ranged_Aiming);
  поле `source_clip` называет его. Сам реестр от ассета НЕ ЗАВИСИТ — он обязан
  считаться в тесте без единого файла, — но приложение, у которого модель с
  этим клипом загружена, вправе взять готовую позу вместо авторской.
- ПОЗЫ ВОЗВРАЩАЮТСЯ БЕЗ apply_joint_limits, ровно как у Posture.h: пределы
  накладывает единственный выход evaluate_body_pose. Тест зоны при этом
  проверяет, что НАЛОЖЕНИЕ ПРЕДЕЛОВ НИЧЕГО НЕ МЕНЯЕТ — то есть что реестр
  законен сам по себе, а не спасается зажимом на выходе.

AI Agents Notice (must follow):
- Follow docs/ARCHITECTURE.md strictly.
- Pure functions and plain data (Rule 8, Rule 30): no ECS, no IO, no clock.
  Время перехода приходит параметром.
- Углы в таблице — В ГРАДУСАХ и это НАМЕРЕННО: реестр читает человек, который
  правит позу, а не машина. Радианы живут внутри pose_of().
*/

