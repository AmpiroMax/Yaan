#pragma once

#include <glm/vec3.hpp>

#include <cstdint>
#include <filesystem>
#include <optional>
#include <span>
#include <string>
#include <string_view>
#include <vector>

namespace dfn::core {

/// КАК МАТЕРИАЛ ДВИЖЕТСЯ. Ветер листвы — СВОЙСТВО ВЕЩЕСТВА, а не отдельная
/// вселенная: лист качается, брус нет, и это единственная разница между ними
/// по этой оси. Сегодня разницу несёт ВЫБОР ПРОГРАММЫ, из-за чего
/// текстурированная стена, поехавшая по пути листвы, обязана отдельно гасить
/// ветер, фейд по ракурсу и просвет листа — три чужих поведения.
enum class MaterialMotion : std::uint8_t {
    Static = 0,  ///< стоит: камень, брус, металл, ткань на стене
    Foliage = 1, ///< качается на общем ветре: листва, трава, позже — флаги
};

/// КАК МАТЕРИАЛ ЗАКРЫВАЕТ ПИКСЕЛЬ.
enum class MaterialOpacity : std::uint8_t {
    Opaque = 0, ///< сплошной: стена — замкнутый объём (правило 52)
    Cutout = 1, ///< маска с покрытием: карточка листа, решётка, ставня
};

/// МЕСТО ЗАПИСИ В ЗАГРУЖЕННОЙ ТАБЛИЦЕ. Внутрипроцессная рукоятка: на диск
/// едет имя (см. заметку в шапке).
using MaterialId = std::uint16_t;

/// «МАТЕРИАЛА НЕ НАЗВАНО» — запись 0, всегда присутствует, всегда безымянна.
inline constexpr MaterialId MATERIAL_NONE = 0;

/// РАСКЛАДКА ЛИСТА, ОБЪЯВЛЕННАЯ В ДАННЫХ. Ядро не знает ни одного атласа; оно
/// знает, что файл реестра назвал колонки и ряды такими-то именами в таком-то
/// порядке. Кто рисует — сверяет этот порядок со своим перечислением ОДНИМ
/// тестом, и расхождение ловится там, а не перекраской полки.
struct MaterialSheet {
    std::string name;                 ///< "parts"
    std::vector<std::string> columns; ///< колонка — РИТМ поверхности
    std::vector<std::string> rows;    ///< ряд — тон и износ одной осью
};

/// ОДНА ЗАПИСЬ РЕЕСТРА. Поля разложены по вопросам, а не по удобству упаковки.
struct MaterialRecord {
    /// ИМЯ — рукоятка рецепта, инструмента, файла и владельца: "oak-log",
    /// "brick-red", "gold-leaf". Пустое имя есть только у записи 0.
    std::string name;

    // --- ЧЕМ ПОКРЫТО --------------------------------------------------------
    /// Есть ли у вещества ЗЕРНО вообще. false — альбедо берётся плоским, и это
    /// не «недоделанный материал»: у полированного золота нет зерна на нашем
    /// масштабе, ему нужен блик, а не плитка.
    bool tiled = false;
    std::string sheet;       ///< ИМЯ ЛИСТА, где живёт зерно ("parts")
    std::string cell_column; ///< координата в листе ПО ИМЕНИ ("hewn-timber")
    std::string cell_row;    ///< координата в листе ПО ИМЕНИ ("mid")
    /// МЕТРОВ ПОВЕРХНОСТИ НА ОДИН ПОВТОР. Здесь, а не у кузницы: сегодня шаг
    /// повтора запечён в uv (PartSkin::span_m потребляется НА ВЫПЕЧКЕ), и
    /// потому соломенная кровля повторяется с шагом дощатой стены.
    float tile_span_m = 1.0f;

    // --- КАКОГО ОТТЕНКА -----------------------------------------------------
    /// МНОЖИТЕЛЬ на альбедо (на плитку либо на плоский цвет вершины).
    glm::vec3 tint{1.0f, 1.0f, 1.0f};

    // --- КАК ОТРАЖАЕТ -------------------------------------------------------
    /// 1 — чистый ламберт, то есть В ТОЧНОСТИ кадр до материалов; ниже —
    /// собранный блик. Умолчание 1 выбрано ради этого.
    float roughness = 1.0f;
    /// У металла блик окрашен САМИМ веществом (золото бликует золотым), у
    /// диэлектрика — белый. Ради этого поля владелец назвал герб.
    float metalness = 0.0f;

    // --- СВЕТИТСЯ ЛИ --------------------------------------------------------
    /// Линейное собственное свечение: цвет и сила разом.
    glm::vec3 emission{0.0f, 0.0f, 0.0f};

    // --- КАК ПОТРЁПАНО И НАСКОЛЬКО РАЗНОЕ -----------------------------------
    /// ШТАТНАЯ НОРМА ИЗНОСА вещества: соломенная кровля новой не бывает,
    /// золото герба бывает только новым.
    float wear = 0.5f;
    /// АМПЛИТУДА ИЗНОСА — насколько сильно погода вправе двигать этот износ по
    /// месту (небо, высота, мировой шум — §2.8). Ноль — однородный кусок, то
    /// есть сегодняшний кадр.
    float wear_amp = 0.0f;
    /// АМПЛИТУДА РАЗБРОСА ЭКЗЕМПЛЯРА (критерий К6) — насколько ЭТОМУ веществу
    /// вообще позволено отличаться от себя: у гранита мало, у выветренной
    /// доски много.
    ///
    /// ПОЧЕМУ ЗДЕСЬ ТОЛЬКО АМПЛИТУДА, А ЗНАЧЕНИЕ — НЕТ. Кузница
    /// детерминирована, а личность объекта — хэш содержимого: держи реестр
    /// само ЗНАЧЕНИЕ, все четыре стула прочли бы одно число и остались
    /// побитово одинаковыми, то есть К6 не выполнился бы ни при каком значении
    /// поля. Значение берётся из СЕМЕНИ РАССТАНОВКИ и принадлежит сцене — тот
    /// же приём, которым живёт флора.
    float scatter_amp = 0.0f;

    // --- КАК ЖИВЁТ ----------------------------------------------------------
    MaterialMotion motion = MaterialMotion::Static;
    MaterialOpacity opacity = MaterialOpacity::Opaque;

    // --- ОСЬ 6: ФИЗИКА ВЕЩЕСТВА ---------------------------------------------
    /// Плотность, кг/м³ — единственное поле оси 6, честно принадлежащее
    /// веществу и ничему больше. Масса предмета = плотность × объём × заполнение.
    float density_kg_m3 = 1000.0f;
    /// Трение и упругость — свойства ПАРЫ веществ; здесь лежит вклад ОДНОГО.
    /// Правило сложения пары названо один раз и не здесь, а у того, кто сводит
    /// пару (PhysicsSubstance.h: трение sqrt(f1·f2), упругость max(r1,r2)).
    float friction = 0.2f;
    float restitution = 0.0f;
    /// ИМЯ ПОВЕРХНОСТИ ДЛЯ ЗВУКА УДАРА. Тег, а не звук: материал не знает про
    /// звук, звук знает про материал.
    std::string surface_tag = "generic";
    /// Порог энергии на площадь, кДж/м², выше которого вещество трескается;
    /// 0 — не бьётся. Объявлен и не открыт: «глиняная миска бьётся, глиняная
    /// стена нет» решает вещество × масштаб × роль, а роли ещё нет.
    float brittle_kj_m2 = 0.0f;

    // --- ЛИЧНОСТЬ -----------------------------------------------------------
    /// fnv1a64 по СОДЕРЖИМОМУ записи (см. material_record_hash). Считается при
    /// загрузке; в файл реестра не пишется — он бы разошёлся с полями.
    std::uint64_t content_hash = 0;
};

/// ЛИЧНОСТЬ ЗАПИСИ — ЕЁ СОДЕРЖИМОЕ. Порядок полей ниже — часть контракта:
/// перестановка полей внутри этой функции сменила бы все личности разом.
[[nodiscard]] std::uint64_t material_record_hash(const MaterialRecord& rec);

/// ЗАГРУЖЕННЫЙ РЕЕСТР: записи, листы и указатель имён.
class MaterialTable {
public:
    /// Пустая таблица — это НЕ пустой список: запись 0 («материала не
    /// названо») есть всегда, потому что отсутствие материала — тоже ответ.
    MaterialTable();

    [[nodiscard]] std::span<const MaterialRecord> records() const {
        return {records_.data(), records_.size()};
    }
    [[nodiscard]] std::size_t size() const { return records_.size(); }

    /// Запись по номеру. Номер за пределами таблицы отдаёт запись 0: файл из
    /// будущего рисуется бледно, а не роняет игру.
    [[nodiscard]] const MaterialRecord& record(MaterialId id) const {
        return records_[id < records_.size() ? id : MATERIAL_NONE];
    }

    /// Номер по имени; MATERIAL_NONE, если имени нет. Пустое имя не находит
    /// ничего — иначе опечатка в рецепте молча стала бы «как раньше».
    [[nodiscard]] MaterialId find(std::string_view name) const;

    /// Лист по имени; nullptr, если такого листа реестр не объявлял.
    [[nodiscard]] const MaterialSheet* sheet(std::string_view name) const;

    /// КООРДИНАТА ЗАПИСИ В ЕЁ ЛИСТЕ, вычисленная ПО ДАННЫМ. false — у записи
    /// нет плитки либо её лист/клетка не объявлены: это находка данных, а не
    /// повод подставить нулевую клетку.
    [[nodiscard]] bool cell_of(const MaterialRecord& rec, std::uint32_t& column,
                               std::uint32_t& row) const;

    /// ИМЕНОВАННОЕ ВЕЩЕСТВО ЭТОЙ КЛЕТКИ, если оно есть; иначе MATERIAL_NONE.
    /// Это обратная совместимость целиком: пара (поверхность, тон) старого
    /// файла ищет себе имя и, не найдя, остаётся собой.
    [[nodiscard]] MaterialId of_cell(std::string_view sheet_name,
                                     std::uint32_t column, std::uint32_t row) const;

    /// ЛИЧНОСТЬ ВСЕЙ ТАБЛИЦЫ — свёртка личностей записей в порядке файла.
    /// Нужна тому, кто кэширует по реестру (лист плиток, запечённая полка).
    [[nodiscard]] std::uint64_t table_hash() const { return table_hash_; }

    /// Откуда прочитана (для сообщений). Пусто у таблицы по умолчанию.
    [[nodiscard]] const std::string& source() const { return source_; }

    friend bool parse_material_table(std::string_view text, std::string_view source,
                                     MaterialTable& out,
                                     std::vector<std::string>* errors);

private:
    void reindex();

    std::vector<MaterialRecord> records_;
    std::vector<MaterialSheet> sheets_;
    std::string source_;
    std::uint64_t table_hash_ = 0;
};

/// ЧТЕНИЕ ТЕКСТА РЕЕСТРА. Возвращает false, если файл СОДЕРЖАЛ ОШИБКИ — и при
/// этом заполняет `out` тем, что удалось прочесть: рукав, а не приговор
/// (Rule 29). Всякая находка попадает в `errors` строкой с номером строки.
///
/// ГРАММАТИКА (строчная, `#` — комментарий до конца строки):
///
///     sheet parts
///         columns = hewn-timber sawn-board ... pane
///         rows    = light mid dark weathered
///
///     material oak-log
///         cell      = parts:hewn-timber/dark
///         span_m    = 1.0
///         roughness = 1.0
///         wear      = 0.55
///         substance = oak          # физику взять у записи "oak"
///
/// Ключ `substance` — НАСЛЕДОВАНИЕ ФИЗИКИ по имени: плотность, трение,
/// упругость, тег и хрупкость берутся у названной записи, если сама запись их
/// не назвала. Так вещество письма и вещество облика говорят об одном дубе
/// одними числами, и второй таблицы плотностей не заводится.
[[nodiscard]] bool parse_material_table(std::string_view text, std::string_view source,
                                        MaterialTable& out,
                                        std::vector<std::string>* errors);

/// Чтение файла. nullopt — файла нет или он не открылся; ОШИБКИ РАЗБОРА
/// таблицу не отменяют (см. выше), они приходят в `errors`.
[[nodiscard]] std::optional<MaterialTable>
load_material_table(const std::filesystem::path& path,
                    std::vector<std::string>* errors = nullptr);

/// ТАБЛИЦА ПРОЦЕССА. Читается ОДИН РАЗ при первом обращении: из пути в
/// переменной среды DFN_MATERIALS, иначе из assets/materials/yaan.dfmat.
///
/// ЧТО БУДЕТ, ЕСЛИ ФАЙЛА НЕТ. Таблица останется с одной записью 0, то есть
/// «материала не названо» на всё, — и это ровно докатериальный кадр, а не
/// чёрный экран. Отказ печатается вслух один раз: молчаливое падение в
/// умолчания — это способ не заметить, что реестр не приехал.
[[nodiscard]] const MaterialTable& material_registry();

/// ПЕРЕЗАГРУЗКА ТАБЛИЦЫ ПРОЦЕССА — для инструментов и тестов, которым нужен
/// свой файл. Возвращает false, если файл не открылся (прежняя таблица цела).
bool reload_material_registry(const std::filesystem::path& path,
                              std::vector<std::string>* errors = nullptr);

/// ПУТЬ РЕЕСТРА ПО УМОЛЧАНИЮ — одно определение на движок, инструменты и
/// тесты (правило 39).
[[nodiscard]] const char* default_material_registry_path();

} // namespace dfn::core
