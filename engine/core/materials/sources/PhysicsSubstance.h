/// Вся таблица — для отчёта, рукава и будущего слияния с реестром материалов.
[[nodiscard]] constexpr const std::array<PhysicsSubstance, 27>& substances() {
    return SUBSTANCES;
}

/// Запись по номеру. Неизвестный номер даёт нулевую запись, а не выход за
/// границы: физика с испорченным номером обязана работать как «не сказано».
[[nodiscard]] constexpr const PhysicsSubstance& substance(SubstanceId id) {
    return SUBSTANCES[id < SUBSTANCES.size() ? id : SUBSTANCE_DEFAULT];
}

/// Номер по имени; SUBSTANCE_NONE, если имени нет.
[[nodiscard]] constexpr SubstanceId find_substance(std::string_view name) {
    for (std::size_t i = 0; i < SUBSTANCES.size(); ++i) {
        if (SUBSTANCES[i].name == name) {
            return static_cast<SubstanceId>(i);
        }
    }
    return SUBSTANCE_NONE;
}

