/// ЧТЕНИЕ БИБЛИОТЕКИ СТИЛЕЙ (.dfstyle). Формат — ТОТ ЖЕ ЛЕКСЕР, ЧТО У .dfh:
/// строки, первый токен — слово, остальные — пары key=value без пробелов,
/// '#' до конца строки — примечание. Одна грамматика на два файла, потому что
/// дизайнер учит её один раз, а вторая грамматика в соседнем файле — это второй
/// повод ошибиться.
///
///     # dfstyle 1
///     style frame_oak
///       board_step=0.23 edge_margin=0.00
///       brace_deg=60
///       opening=window opening_w=1.00 opening_h=1.00 opening_sill=1.10
///
/// Строка "style <имя>" открывает запись; любая следующая строка из пар
/// key=value ложится в открытую запись. Отступы значения не имеют — они для
/// глаза. Повтор ключа перекрывает прежнее значение: файл читается сверху вниз,
/// как его и правит человек.
///
/// ЧИТАТЕЛЬ ОТВЕРГАЕТ, А НЕ ЧИНИТ, и это не выбор строгости, а правило семьи
/// (см. HouseFile.h). Неизвестный ключ, голое слово вместо пары, повтор имени
/// стиля, не-число в числовом поле — всё это ОТКАЗ с номером строки. Молча
/// пропущенная опечатка — это свойство, которое дизайнер задал, а движок не
/// применил, и искать он его будет глазами по картинке.
///
/// РАСШИРЕНИЕ .dfstyle, А НЕ .dfs: .dfs в этом дереве уже занято дельтами
/// сохранения (SaveDelta.cpp), и два формата под одним расширением — это
/// вопрос «чем это открывать», заданный каждому инструменту.
[[nodiscard]] StyleIoResult parse_wall_styles(const std::string& text,
                                              std::vector<WallStyle>& out);

