/// Вид проёма. Дверь отличается от окна не только размером: у неё подоконник
/// равен нулю по определению, иначе через неё нельзя войти.
enum class OpeningKind : std::uint8_t { None = 0, Window, Door };

/// СТИЛЬ — ОПИСАНИЕ, А НЕ МЕШ (§2.4 замысла). Здесь нет ни одной вершины: есть
/// шаг, угол и размер, из которых укладчик порождает раскладку под любую длину.
///
/// ПОЧЕМУ ЭТО НЕ КОД. Правила 5 и 6 контракта: содержимое живёт в данных, и
/// смена содержимого не требует пересборки. Дизайнер, которому нужно подвинуть
/// подоконник на 5 см, не обязан звать компилятор — и это не удобство, а
/// условие того, что стилей будет много.
struct WallStyle {
    /// Имя, которым элемент .dfh ссылается на стиль: style=frame_oak.
    std::string name;

    // -- обшивка --------------------------------------------------------------
    /// Шаг доски ВДОЛЬ СТЕНЫ, метры. Он же ШИРИНА доски: щели между досками у
    /// нас нет и быть не может (HOUSES.md §2 — «ни щели между досками»), а
    /// отдельное поле ширины было бы способом её задать.
    float board_step = HOUSE_BOARD_STEP_DEFAULT;
    /// Полоса у каждого торца, которую обшивка не занимает, метры.
    float edge_margin = HOUSE_BOARD_EDGE_MARGIN_DEFAULT;

    // -- раскосы --------------------------------------------------------------
    /// ЦЕЛЕВОЙ угол к горизонту, радианы. Ноль — раскосов нет.
    float brace_rad = HOUSE_BRACE_RAD_DEFAULT;

    // -- проёмы ---------------------------------------------------------------
    OpeningKind opening = OpeningKind::None;
    /// РАЗМЕР ФИКСИРОВАН И НЕ ЗАВИСИТ НИ ОТ ЧЕГО. Тянуть его вместе со стеной —
    /// ровно тот дефект, ради которого стиль перестал быть мешем.
    float opening_w = HOUSE_WINDOW_W_DEFAULT;
    float opening_h = HOUSE_WINDOW_H_DEFAULT;
    /// Высота низа проёма над подошвой стены. У двери принудительно ноль.
    float opening_sill = HOUSE_WINDOW_SILL_DEFAULT;

    /// ПРОСТЕНОК: наименьшая сплошная стена между двумя проёмами и между
    /// проёмом и торцом, метры. Пусто — ВЫВЕСТИ: один шаг доски. Простенок уже
    /// одной доски не стена, а перемычка: обшивке его нечем описать.
    std::optional<float> opening_pier;
    /// ШАГ РЯДА проёмов (между центрами), метры. Пусто — ВЫВЕСТИ: ширина
    /// проёма плюс простенок, то есть самый плотный законный ряд.
    ///
    /// ПОЧЕМУ ШАГ, А НЕ РАВНОМЕРНОЕ РАСПРЕДЕЛЕНИЕ ПО ДЛИНЕ. Равномерное
    /// (центры в L*(2i+1)/2n) разводит окна тем дальше, чем длиннее стена, —
    /// то есть масштабирует РИСУНОК проёмов вместе со стеной. Это тот же
    /// растянутый меш, только не в размере окна, а в расстоянии между ними, и
    /// пользователь отверг именно масштабирование. При фиксированном шаге
    /// растяжение стены добавляет ОБШИВКИ, а не разгоняет окна.
    std::optional<float> opening_pitch;
};

