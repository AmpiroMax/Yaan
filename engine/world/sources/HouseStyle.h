/// ШАГ ОБШИВКИ ПО УМОЛЧАНИЮ, МЕТРЫ. Решение пользователя дословно: «ну и пусть
/// не влезает, текстуру покручу» — то есть шаг задан В МЕТРАХ и НЕ ПОДГОНЯЕТСЯ
/// под длину стены. Доля от длины вела бы себя ровно как растянутый меш: на
/// шестиметровой стене доска была бы вдвое шире, чем на трёхметровой.
///
/// 0.23 — не выбрано, а ВЗЯТО У УЖЕ ИСПЕЧЁННОГО НАБОРА: PartForgeWalls.cpp
/// несёт LOG_COURSE_M = 0.23 («the log wall rhythm», согласовано с перевязкой
/// углов сруба corner-log-*), выставленный по референсным кадрам
/// images_examples/houses_outdoors. Число, у которого появилась вторая зона,
/// перестаёт принадлежать первой (правило 35) — поэтому оно в реестре.
inline constexpr float HOUSE_BOARD_STEP_DEFAULT = 0.23f;

/// ПОТОЛОК ШАГА ОБШИВКИ, МЕТРЫ, И ОН ВЫВЕДЕН, А НЕ НАЗНАЧЕН. Остаток
/// (одеваемая длина минус колонны * шаг) делится поровну между торцами, поэтому
/// неодетая полоса у каждого торца не больше step/2. Торец стены сидит НА ОСИ
/// угловой стойки (решение 18.08, §7.0 замысла), значит стойка прикрывает ровно
/// свой радиус. Условие «неодетая полоса внутри тела стойки» — step/2 <= radius,
/// то есть step <= 2 * HOUSE_LINE_RADIUS_DEFAULT = 0.24.
///
/// ЗАЧЕМ ЭТО ВООБЩЕ: HOUSES.md §2 запрещает сквозной просвет прямо и по
/// жалобе пользователя («у него стены несплошные»). Шаг 0.30, который просится
/// на язык как «обычная доска», даёт 0.15 неодетой полосы против 0.12 радиуса
/// и открывает 3 см дневного света у каждого угла — молча.
///
/// Умолчание 0.23 проходит потолок с запасом 4 %, и это ТОНКО; поэтому правило
/// работает НЕ УМОЛЧАНИЕМ, а проверкой на каждой стене: стиль с большим шагом
/// получает LayoutIssue::CladdingLeaksAtEnd с числом, а не тишину.
inline constexpr float HOUSE_BOARD_STEP_MAX = 0.24f;

/// ЗАЗОР У ТОРЦА ПО УМОЛЧАНИЮ, МЕТРЫ: полоса у каждого конца стены, которую
/// обшивка не занимает. НОЛЬ, и это вывод, а не лень: любая ненулевая полоса
/// складывается с половиной остатка и вылезает из-под угловой стойки (см.
/// HOUSE_BOARD_STEP_MAX). Поле оставлено дизайнеру для наличника или четверти,
/// но умолчание обязано быть тем, что не течёт.
inline constexpr float HOUSE_BOARD_EDGE_MARGIN_DEFAULT = 0.0f;

/// ЦЕЛЕВОЙ УГОЛ РАСКОСА, РАДИАНЫ (60°). Целевой, а не заданный: раскос
/// натянут между низом и верхом своего пролёта, поэтому его ФАКТИЧЕСКИЙ угол
/// считается из геометрии — «доски, что под углами, будут менять угол и
/// растягиваться» (пользователь). Цель нужна только для одного: сколько
/// пролётов нарезать в свободном участке, чтобы фактический угол не уходил
/// далеко. Ноль — раскосов у стиля нет.
///
/// ПОЛОСА ФАКТИЧЕСКОГО УГЛА ВЫВОДИТСЯ, А НЕ ЗАМЕРЯЕТСЯ НАУГАД. Пусть номинальный
/// пролёт nominal = H/tan(t), а x = len/nominal. Пролётов берётся n = round(x),
/// значит фактический угол = atan(tan(t) * n/x), а n/x ∈ (n/(n+0.5), n/(n-0.5)]
/// — шире всего при n = 1, где это (2/3, 2]. При цели 60° полоса выходит
/// (atan(1.1547), atan(3.4641)] = (49.11°, 73.90°], и она СУЖАЕТСЯ с ростом n
/// (при n = 2 это уже (54.20°, 66.59°]).
///
/// ПОЛОСА ДЕЙСТВУЕТ НА КАЖДЫЙ ВЫДАННЫЙ РАСКОС, а не на большинство, и держится
/// это тем же выводом: участок короче nominal/2 (x < 0.5) раскоса НЕ ПОЛУЧАЕТ
/// вовсе. Иначе округление дало бы ноль пролётов, зажим вернул бы единицу, и
/// простенок в 23 см между двумя окнами получил бы «раскос» под 86° — то есть
/// стойку, названную раскосом. Рукав сметает полосу с обоих концов: 49.2° на
/// длинном участке и 73.7° на самом коротком, который ещё получает раскос.
inline constexpr float HOUSE_BRACE_RAD_DEFAULT = 1.0471976f;

/// РАЗМЕРЫ ПРОЁМОВ ПО УМОЛЧАНИЮ, МЕТРЫ. Взяты у испечённого набора
/// (PartForgeWalls.cpp: WIN_W_M/WIN_H_M/WIN_SILL_M/DOOR_W_M/DOOR_H_M), у
/// которого они выставлены по референсным кадрам и по мерке героя: дверь шире
/// PLAYER_CAPSULE_RADIUS*2 = 0.70 с косяками и выше PLAYER_CAPSULE_HEIGHT 1.8
/// (HOUSES.md §6: «проём выше 1.8 и шире 0.7» — СЛЕДУЕТ, а не выбирается).
/// Подоконник 1.10 при PLAYER_EYE_HEIGHT 1.70 держит стекло на уровне глаза.
inline constexpr float HOUSE_WINDOW_W_DEFAULT = 1.00f;
inline constexpr float HOUSE_WINDOW_H_DEFAULT = 1.00f;
inline constexpr float HOUSE_WINDOW_SILL_DEFAULT = 1.10f;
inline constexpr float HOUSE_DOOR_W_DEFAULT = 1.00f;
inline constexpr float HOUSE_DOOR_H_DEFAULT = 2.05f;

/// ДОПУСК ВМЕЩЕНИЯ, МЕТРЫ. Ровно та точность, с которой числа переживают файл:
/// HouseFile печатает координаты через "%.4f", то есть 0.1 мм — всё, что тоньше,
/// не отличимо от шума записи. Без допуска floor() на числах с плавающей точкой
/// выбрасывает третье окно из стены, в которую оно вмещается ТОЧНО.
inline constexpr float HOUSE_FIT_EPS = 1e-4f;

