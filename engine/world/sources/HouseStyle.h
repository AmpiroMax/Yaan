/// ЧТО ИЗВЕСТНО ПРО САМУ СТЕНУ. Длина и высота приходят из графа (вершины), а
/// число проёмов — СВОЙСТВО ЭЛЕМЕНТА, не стиля (§2.4): в .dfh это токен
/// openings=3 рядом с style=frame_oak. Правки HouseGraph для этого не нужно —
/// Element::params уже несёт пары «имя=значение».
struct WallSpec {
    float length = 0.0f;
    float height = 0.0f;
    /// Сколько проёмов ЗАПРОШЕНО. Сколько встанет — ответ раскладки.
    int openings = 0;
    /// Радиус угловой стойки, в тело которой уходит торец стены (§7.0
    /// замысла: крепление к ОСИ, нахлёст — норма). Нужен ровно для одного —
    /// сказать, прикрыт ли неодетый остаток обшивки. Умолчание совпадает с
    /// HOUSE_LINE_RADIUS_DEFAULT; равенство держит static_assert в .cpp.
    float post_radius = 0.12f;
};

/// ДОСКА: прямоугольник в координатах стены. Одна колонна обшивки даёт ОДНУ
/// доску на глухой стене и две (над проёмом и под ним) там, где её пересёк
/// проём.
struct BoardRun {
    /// Номер колонны вдоль стены, с нуля. Куски одной колонны носят один номер:
    /// «сколько досок влезло по длине» — это счёт КОЛОНН, а не кусков.
    int column = 0;
    float u0 = 0.0f;
    float u1 = 0.0f;
    float v0 = 0.0f;
    float v1 = 0.0f;
};

/// РАСКОС: отрезок от низкого конца к высокому. Низкий конец всегда СНАРУЖИ,
/// то есть дальше от середины стены — так раскосы зеркальны относительно
/// середины, и это проверяется числом, а не разглядыванием.
struct BracePlacement {
    float u_low = 0.0f;
    float v_low = 0.0f;
    float u_high = 0.0f;
    float v_high = 0.0f;
    /// ФАКТИЧЕСКИЙ угол к горизонту, радианы. Он и есть «раскос меняет угол».
    float angle_rad = 0.0f;
    /// Длина отрезка, метры. Она и есть «раскос растягивается».
    float length = 0.0f;
};

/// ПРОЁМ. Размер взят у стиля и не зависит ни от длины стены, ни от числа
/// соседей.
struct OpeningPlacement {
    OpeningKind kind = OpeningKind::Window;
    float u0 = 0.0f;
    float u1 = 0.0f;
    float v0 = 0.0f;
    float v1 = 0.0f;
    [[nodiscard]] float center_u() const { return (u0 + u1) * 0.5f; }
};

enum class LayoutIssue : std::uint8_t {
    /// Просили N, влезло M < N. САМАЯ ВАЖНАЯ ЗДЕСЬ: требование пользователя —
    /// «если не умещаются, то максимум сколько влезло», и молчаливое
    /// исполнение этого требования неотличимо от опечатки в числе проёмов.
    OpeningsDropped,
    /// Проём не помещается по ВЫСОТЕ: подоконник плюс высота выше стены.
    OpeningTooTall,
    /// Не влезло ни одной доски: стена короче собственного шага обшивки.
    NoBoardsFit,
    /// Неодетый остаток у торца шире, чем радиус угловой стойки, — сквозной
    /// просвет, запрещённый HOUSES.md §2.
    CladdingLeaksAtEnd,
    /// Стена вырождена: нулевая или отрицательная длина либо высота.
    WallDegenerate,
};

struct LayoutFinding {
    LayoutIssue issue = LayoutIssue::WallDegenerate;
    /// Число, если оно у находки есть: сколько метров попросил проём, какова
    /// неодетая полоса. Ноль — числа нет.
    float value = 0.0f;
    int requested = 0;
    int placed = 0;
    std::string what;
};

/// СПИСОК ТОГО, ЧТО ГДЕ СТОИТ. Не геометрия: ни одной вершины, ни одной
/// нормали. Порядок ДЕТЕРМИНИРОВАН (доски слева направо, куски колонны снизу
/// вверх, проёмы слева направо, раскосы слева направо), иначе две сборки одного
/// дома дадут разный меш и «до и после» перестанет что-либо значить.
struct WallLayout {
    std::vector<BoardRun> boards;
    std::vector<BracePlacement> braces;
    std::vector<OpeningPlacement> openings;
    std::vector<LayoutFinding> findings;

    /// Сколько проёмов запросили и сколько встало. Разница ГОВОРИТСЯ ВСЛУХ —
    /// и полем, и находкой: поле читает код, находку читает человек.
    int openings_requested = 0;
    int openings_placed = 0;
    /// Число КОЛОНН обшивки: floor((length - 2*edge_margin) / board_step).
    int board_columns = 0;
    /// Неодетая полоса у КАЖДОГО торца, метры: edge_margin + остаток/2.
    /// Симметрична по построению — остаток делится поровну.
    float end_bare = 0.0f;

    [[nodiscard]] bool has(LayoutIssue i) const;
    [[nodiscard]] const LayoutFinding* find(LayoutIssue i) const;
};

/// УКЛАДЧИК. Дано: длина, высота, число запрошенных проёмов, стиль. Разложить:
/// доски, раскосы, проёмы. Порядок решений и есть правило:
///
///  1. ПРОЁМЫ ПЕРВЫМИ, потому что они не двигаются ни на миллиметр ради
///     обшивки: их размер фиксирован, а положение — по центру и симметрично.
///     Сколько влезло, столько и встало; сколько не влезло — сказано.
///  2. ОБШИВКА кладётся по всей одеваемой длине шагом В МЕТРАХ, остаток делится
///     поровну между торцами (иначе стена перестала бы быть симметричной ради
///     остатка), после чего КАЖДАЯ КОЛОННА РЕЖЕТСЯ ПРОЁМАМИ. Доска не проходит
///     сквозь проём — она кончается у него и начинается за ним.
///  3. РАСКОСЫ живут в свободных участках между проёмами и торцами, во всю
///     высоту. Раскос сквозь окно — не плотницкое дело, а ошибка с диагональю.
///     Участок короче половины номинального пролёта раскоса не получает.
[[nodiscard]] WallLayout lay_out_wall(const WallSpec& spec, const WallStyle& style);

/// СКОЛЬКО ПРОЁМОВ ВЛЕЗЕТ на такой длине при таком стиле. Отдельной функцией,
/// потому что редактору это нужно ДО раскладки — показать дизайнеру потолок
/// прямо в поле ввода, а не после того, как он запросил пять.
[[nodiscard]] int wall_opening_capacity(float length, const WallStyle& style);

