/// Радиус прямой по умолчанию: расстояние от оси до ГРАНИ, то есть половина
/// толщины бруса. 0.12 — бревно в 24 см, ходовая стойка сруба.
inline constexpr float HOUSE_LINE_RADIUS_DEFAULT = 0.12f;
/// Сколько граней у «круглой» прямой. Восемь: при 24 см толщины девятая грань
/// уже уже пикселя на дистанции, с которой бревно вообще видно.
inline constexpr int HOUSE_ROUND_SIDES = 8;
/// Толщина поверхности по умолчанию — пол/стена в 20 см.
inline constexpr float HOUSE_SURFACE_THICKNESS_DEFAULT = 0.20f;

/// МЕРА НЕПЛОСКОСТИ: наибольшее отклонение вершины контура от наилучшей по МНК
/// плоскости, ДЕЛЁННОЕ на собственный размах контура. Безразмерная — и это
/// главное решение всей меры.
///
/// ПОЧЕМУ ДЕЛИМ. Абсолютный допуск в сантиметрах отвечает на другой вопрос: он
/// объявляет 10 см перекоса ошибкой и на террасе 12 м, и на ступеньке 60 см,
/// хотя в первом случае это доля процента, а во втором сложенная пополам доска.
/// Вред от кривого контура — ИЗЛОМ на диагонали, а угол излома задан отношением
/// прогиба к пролёту, а не прогибом.
///
/// ЧТО ИМЕННО РАЗДЕЛЯЕТСЯ, словами, до всяких чисел: слева «все якоря те, что
/// дизайнер хотел, а кривизна пришла от земли, на которой дом стоит»; справа
/// «один якорь взят не тот» — вместо углового схвачен подоконный или
/// потолочный. Это разные беды: первую пользователь разрешил прямо («пусть
/// выкопанный овраг под землёй будет нормой, провисшие дома тоже норм», §5.8
/// замысла), вторая чинится одним перевыбором.
///
/// ГДЕ СТОИТ ЧИСЛО — ИЗМЕРЕНО, а не назначено. Оба крайних образца
/// воспроизводит рукав test_house_mesh, случай «мера неплоскости различает
/// наклонный пол и промах по якорю»:
///
///   ПРИНЯТЫЕ    пандус 4x3 под 30 град, строго в плоскости      0.0000
///               скат 6x4, конёк кривой на 5 см                  0.0017
///               пол 8x6 по земле, углы +-10 см                  0.0100
///               пол 6x5 по земле, углы +-8 см                   0.0102
///               терраса 12x8 по земле, углы +-25 см             0.0173  <- наибольший
///   ОТВЕРГНУТЫЕ промах на якорь подоконника 0.9 м, комната 6x5  0.0288  <- наименьший
///               промах на якорь подоконника 0.5 м, комната 3x3  0.0295
///               промах на потолочный якорь 2.6 м, комната 8x6   0.0648
///               промах на потолочный якорь 2.6 м, комната 4x3   0.1228
///               контур, сложенный пополам                       0.2009
///
/// Порог — ГЕОМЕТРИЧЕСКАЯ СЕРЕДИНА между наибольшим принятым и наименьшим
/// отвергнутым: sqrt(0.0173 * 0.0288) = 0.0223. Запас 1.29x вниз и 1.29x вверх.
/// Полоса узкая, и это говорится вслух, а не прячется: правило 45 требует
/// НАЗВАННЫЙ отвергнутый образец, и он назван — 0.0288, промах на подоконник.
/// Физическое чтение порога: на пролёте 6 м разрешено 13 см перекоса, на 12 м —
/// 26 см.
///
/// ЧЕГО МЕРА НЕ УМЕЕТ, названо прямо: промах на 0.3 м в комнате 6x5 даёт 0.0096
/// и ПРОХОДИТ. Он неотличим от неровной земли по построению, а не по недосмотру
/// — 30 см на пролёте 8 м это ровно то, что пользователь разрешил называть
/// провисшим домом. Ловить такое пришлось бы другим прибором: не кривизной
/// контура, а тем, что якорь занят соседней постройкой по высоте.
inline constexpr float HOUSE_CONTOUR_FLATNESS_MAX = 0.0223f;

/// Ниже этого всё считается вырождением: нулевая длина, нулевая площадь,
/// совпавшие точки. В метрах и в метрах квадратных соответственно.
inline constexpr float HOUSE_GEOM_EPS = 1e-5f;

