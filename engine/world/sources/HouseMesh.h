struct FittedPlane {
    /// Центр тяжести вершин — точка на плоскости.
    glm::vec3 origin{0.0f};
    /// Единичная нормаль. ЗНАК ВЗЯТ ИЗ ПОРЯДКА ОБХОДА по правилу правой руки
    /// (§2.3 замысла): МНК даёт направление с точностью до знака, а порядок
    /// вершин снимает эту неоднозначность.
    glm::vec3 normal{0.0f, 1.0f, 0.0f};
    /// Наибольшее отклонение вершины от плоскости, метры.
    float max_deviation = 0.0f;
    /// Наибольшее расстояние между двумя вершинами контура, метры.
    float span = 0.0f;
    /// max_deviation / span. Сравнивать с HOUSE_CONTOUR_FLATNESS_MAX.
    float flatness = 0.0f;
    /// Площадь контура, спроецированного на плоскость. Ноль — вершины на одной
    /// прямой, плоскости у них нет.
    float area = 0.0f;
    bool degenerate = true;
};

/// Наилучшая по методу наименьших квадратов плоскость: нормаль — собственный
/// вектор ковариации при НАИМЕНЬШЕМ собственном значении (полные наименьшие
/// квадраты, то есть минимум суммы квадратов расстояний ДО ПЛОСКОСТИ, а не по
/// вертикали — вертикальная подгонка врёт тем сильнее, чем круче скат, и на
/// стене врёт бесконечно).
[[nodiscard]] FittedPlane fit_contour_plane(std::span<const glm::vec3> pts);

/// Проекция контура на плоскость. u_out/v_out — ортонормированный базис с
/// u x v == plane.normal; u направлен вдоль ПЕРВОГО ребра контура, чтобы
/// результат не зависел от мировых осей и был воспроизводим.
[[nodiscard]] std::vector<glm::vec2> project_contour(std::span<const glm::vec3> pts,
                                                     const FittedPlane& plane,
                                                     glm::vec3& u_out, glm::vec3& v_out);

/// Отсечение ушей. Возвращает тройки индексов ИСХОДНОГО контура, обходимые
/// против часовой стрелки в базисе (u,v), то есть с нормалью по plane.normal.
/// Пустой ответ — уши кончились раньше треугольников: контур самопересекается
/// или вырожден.
[[nodiscard]] std::vector<std::uint32_t> triangulate_contour(std::span<const glm::vec2> poly);

/// Самопересечение контура (§6.2). Проверяет несмежные рёбра попарно.
[[nodiscard]] bool contour_self_intersects(std::span<const glm::vec2> poly);

/// Система координат текстуры на грани: начало, ось u, ось v. Повёрнута на
/// tex_deg ВОКРУГ НОРМАЛИ. u x v == normal при любом угле, поэтому масштаб
/// текстуры не меняется — поворот остаётся поворотом, а не сдвигом.
struct UvFrame {
    glm::vec3 origin{0.0f};
    glm::vec3 u{1.0f, 0.0f, 0.0f};
    glm::vec3 v{0.0f, 0.0f, 1.0f};
    [[nodiscard]] glm::vec2 at(glm::vec3 p) const;
};

[[nodiscard]] UvFrame make_uv_frame(glm::vec3 origin, glm::vec3 normal, glm::vec3 u_hint,
                                    float tex_deg);

// ---------------------------------------------------------------------------
// Меш и коллайдер
// ---------------------------------------------------------------------------

struct HouseVertex {
    glm::vec3 pos{0.0f};
    glm::vec3 normal{0.0f};
    /// В МЕТРАХ, а не в долях грани. Текстура тогда не тянется при удлинении
    /// балки: стало длиннее — стало больше повторов, а не растянутый узор.
    glm::vec2 uv{0.0f};
};

/// Какие индексы принадлежат какому элементу. Нужно редактору: «выбрал стену —
/// подсветилась стена», без второго прохода по графу.
struct MeshPart {
    ElementId element = NO_ELEMENT;
    std::uint32_t index_begin = 0;
    std::uint32_t index_count = 0;
    /// МАТЕРИАЛ КУСКА, если он не материал элемента (-1 — элементный).
    /// Появился вместе с кладкой (20.08): стена собирается ИЗ КУСКОВ — доски
    /// фахверка это брус, кирпичи это глина, блоки это камень, — а элемент
    /// по-прежнему один. У элемента может быть НЕСКОЛЬКО частей.
    int mat_override = -1;
    int tone_override = -1;
    /// ЧИСТО ФИЗИЧЕСКАЯ ЧАСТЬ (21.08): в коллайдер, но не в картинку.
    /// Единственный законный жилец — пандус под открытыми ступенями: капсула
    /// зажимается в V-канаве «кромка проступи + фаска следующего блока»
    /// (char-трасса бота Вайтрана), и никакая честная форма ступени этого не
    /// снимает; гладкий невидимый пандус — стандартное решение. Флаг
    /// симметричен MeshBuilder.collider=false (картинка без физики).
    bool collider_only = false;
};

/// ВЫПУКЛЫЙ КУСОК КОЛЛАЙДЕРА. Физике нужны выпуклые тела, а Г-образная комната
/// выпуклой не является — поэтому пластина разбирается на призмы ПО ТЕМ ЖЕ
/// треугольникам, что и меш. Разбирать отдельным алгоритмом было бы второй
/// копией правды (правило 39): та разъехалась бы с мешем в первый же день,
/// когда кто-нибудь поправит триангуляцию.
struct ConvexPart {
    ElementId element = NO_ELEMENT;
    std::vector<glm::vec3> points;
};

enum class MeshIssue : std::uint8_t {
    /// Опечатка в свойствах: ключ, которого нет.
    UnknownParam,
    /// Нулевая длина, нулевая площадь, совпавшие вершины.
    Degenerate,
    /// Мера неплоскости выше порога. Геометрия ВСЁ РАВНО СТРОИТСЯ: дизайнер
    /// посреди правки обязан видеть то, что сделал. Находка — сигнализация, а
    /// не запрет.
    ContourNonPlanar,
    ContourSelfIntersects,
    /// Уши кончились раньше треугольников.
    TriangulationFailed,
    /// Цепочка без высоты — стены нет.
    ChainNeedsHeight,
    /// Отрезок цепочки вертикален: выдавливание вверх даёт нулевую площадь.
    ChainSegmentVertical,
    /// Вершина кровельного элемента без стены/опоры рядом (правило опоры
    /// крыш 20.08); unsupported=1 выводит элемент из-под правила.
    RoofUnsupported,
    /// Прямая с одной вершиной и без длины.
    LineNeedsLength,
    /// У прямой больше двух вершин: взяты первые две.
    LineExtraRefs,
    /// Сказанное раскладкой обшивки (HouseStyle): «просил 3 окна, влезло 2»,
    /// щель у торца и прочее. Текст приходит из раскладки дословно.
    CladdingSaid,
};

struct MeshFinding {
    ElementId element = NO_ELEMENT;
    MeshIssue issue = MeshIssue::Degenerate;
    /// Число, если у находки оно есть (мера неплоскости — есть).
    float value = 0.0f;
    std::string what;
};

/// ПРАВИЛО ОПОРЫ КРЫШ (заказ 20.08, эвристика гиперграфа дословно: «у
/// гиперребра типа „крыша" не должно быть вершин без смежных гиперрёбер
/// стен»). Смежность здесь двойная: общая вершина ИЛИ геометрическая
/// близость к любому не-кровельному элементу (свесы висят на СВОИХ вершинах
/// в полуметре от стены — это норма, а не дыра). Правило ПРОВЕРОЧНОЕ, не
/// запретительное: элемент с unsupported=1 из него выходит (руины).
[[nodiscard]] std::vector<MeshFinding> check_roof_support(const HouseGraph& g);

struct HouseMesh {
    std::vector<HouseVertex> vertices;
    std::vector<std::uint32_t> indices;
    std::vector<MeshPart> parts;
    std::vector<ConvexPart> convex;
    std::vector<MeshFinding> findings;

    [[nodiscard]] std::size_t triangle_count() const { return indices.size() / 3; }
    /// Диапазон индексов элемента; nullptr — элемент ничего не породил.
    [[nodiscard]] const MeshPart* part_of(ElementId id) const;
};

/// Весь дом разом, в КООРДИНАТАХ ПОСТРОЙКИ. Мировые получаются переносом
/// world = origin + rotate_y(yaw, local) при постановке (§2.6): здесь их нет
/// намеренно, иначе типовой дом приколотился бы к одному месту.
///
/// ПОРЯДОК ДЕТЕРМИНИРОВАН: элементы обходятся по возрастанию имени, поэтому две
/// сборки одного графа дают побайтово один меш. Без этого «до и после» ничего
/// не значит, потому что «до» каждый раз разное.
[[nodiscard]] HouseMesh build_house_mesh(const HouseGraph& g);

/// Нормаль поверхности с уже учтённым facing_flipped. Нужна редактору ДО
/// подтверждения: §4.3 требует показать, куда смотрит лицо, пока контур ещё
/// набирается, иначе дизайнер узнает об этом по текстуре.
[[nodiscard]] bool surface_normal(const HouseGraph& g, ElementId id, glm::vec3& out);

/// ЗАПЕЧЁННАЯ НЕБЕСНАЯ ВИДИМОСТЬ ПО ВЕРШИНАМ (22.08, «постройки плоские и
/// приклеены»: контраст фасада 1.58x против 5.80x эталона, откос ворот той же
/// яркости, что фасад). По байту на вершину built-меша: 16 лучей в верхнюю
/// полусферу против СОБСТВЕННЫХ частей постройки (равномерная сетка ускорения,
/// части collider_only не заслоняют — невидимый пандус не должен темнить
/// видимую лестницу). Канал уже ждёт: v_color0.a у построек прибит к 255, а
/// dfn_surface_light читает его как sky_vis и умножает на него ambient — сюда
/// ложится без единой правки шейдера. Пол 0.30: запечатанный интерьер тёмен,
/// но не чёрен — прямой свет очага и солнца канал не трогает.
/// Детерминирован: тот же меш — те же байты.
[[nodiscard]] std::vector<std::uint8_t> bake_house_sky_visibility(const HouseMesh& mesh);

/// ВИДНОЕ МЕСТО ПОВЕРХНОСТИ — точка, от которой рисуют её стрелку нормали.
///
/// СРЕДНЕЕ ПО ВСЕМ ВЕРШИНАМ. Решение пользователя 18.08, уточнённое им же после
/// первого захода: «стрелка всегда должна стоять между mean от всех координат
/// точек, не важно 2, 3 или 100 их».
///
/// Первый заход считал точку, РАВНОУДАЛЁННУЮ от углов (центр описанной
/// окружности по МНК). Она отвечает на другой вопрос — «откуда все углы
/// одинаково далеко» — и на вытянутом или невыпуклом контуре уезжает далеко от
/// самого полотна: у прямоугольного треугольника садится на середину
/// гипотенузы, у Г-образной комнаты может оказаться вне неё вовсе. Среднее
/// такого не умеет по построению: оно всегда внутри выпуклой оболочки вершин.
///
/// У ЦЕПОЧКИ середина её ломаной ПОДНИМАЕТСЯ на половину высоты полотна: оба
/// якоря стены лежат внизу, и стрелка из их середины росла бы из-под пола.
[[nodiscard]] bool surface_centre(const HouseGraph& g, ElementId id, glm::vec3& out);

/// Все имена элементов графа по возрастанию. Отдельной функцией, потому что у
/// HouseGraph сегодня нет перебора элементов, а порядок обязан быть один и тот
/// же у меша, у коллайдера и у находок.
[[nodiscard]] std::vector<ElementId> ordered_elements(const HouseGraph& g);

