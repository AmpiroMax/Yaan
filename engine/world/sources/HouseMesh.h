struct HouseVertex {
    glm::vec3 pos{0.0f};
    glm::vec3 normal{0.0f};
    /// В МЕТРАХ, а не в долях грани. Текстура тогда не тянется при удлинении
    /// балки: стало длиннее — стало больше повторов, а не растянутый узор.
    glm::vec2 uv{0.0f};
};

/// Какие индексы принадлежат какому элементу. Нужно редактору: «выбрал стену —
/// подсветилась стена», без второго прохода по графу.
struct MeshPart {
    ElementId element = NO_ELEMENT;
    std::uint32_t index_begin = 0;
    std::uint32_t index_count = 0;
};

/// ВЫПУКЛЫЙ КУСОК КОЛЛАЙДЕРА. Физике нужны выпуклые тела, а Г-образная комната
/// выпуклой не является — поэтому пластина разбирается на призмы ПО ТЕМ ЖЕ
/// треугольникам, что и меш. Разбирать отдельным алгоритмом было бы второй
/// копией правды (правило 39): та разъехалась бы с мешем в первый же день,
/// когда кто-нибудь поправит триангуляцию.
struct ConvexPart {
    ElementId element = NO_ELEMENT;
    std::vector<glm::vec3> points;
};

enum class MeshIssue : std::uint8_t {
    /// Опечатка в свойствах: ключ, которого нет.
    UnknownParam,
    /// Нулевая длина, нулевая площадь, совпавшие вершины.
    Degenerate,
    /// Мера неплоскости выше порога. Геометрия ВСЁ РАВНО СТРОИТСЯ: дизайнер
    /// посреди правки обязан видеть то, что сделал. Находка — сигнализация, а
    /// не запрет.
    ContourNonPlanar,
    ContourSelfIntersects,
    /// Уши кончились раньше треугольников.
    TriangulationFailed,
    /// Цепочка без высоты — стены нет.
    ChainNeedsHeight,
    /// Отрезок цепочки вертикален: выдавливание вверх даёт нулевую площадь.
    ChainSegmentVertical,
    /// Прямая с одной вершиной и без длины.
    LineNeedsLength,
    /// У прямой больше двух вершин: взяты первые две.
    LineExtraRefs,
};

struct MeshFinding {
    ElementId element = NO_ELEMENT;
    MeshIssue issue = MeshIssue::Degenerate;
    /// Число, если у находки оно есть (мера неплоскости — есть).
    float value = 0.0f;
    std::string what;
};

struct HouseMesh {
    std::vector<HouseVertex> vertices;
    std::vector<std::uint32_t> indices;
    std::vector<MeshPart> parts;
    std::vector<ConvexPart> convex;
    std::vector<MeshFinding> findings;

    [[nodiscard]] std::size_t triangle_count() const { return indices.size() / 3; }
    /// Диапазон индексов элемента; nullptr — элемент ничего не породил.
    [[nodiscard]] const MeshPart* part_of(ElementId id) const;
};

/// Весь дом разом, в КООРДИНАТАХ ПОСТРОЙКИ. Мировые получаются переносом
/// world = origin + rotate_y(yaw, local) при постановке (§2.6): здесь их нет
/// намеренно, иначе типовой дом приколотился бы к одному месту.
///
/// ПОРЯДОК ДЕТЕРМИНИРОВАН: элементы обходятся по возрастанию имени, поэтому две
/// сборки одного графа дают побайтово один меш. Без этого «до и после» ничего
/// не значит, потому что «до» каждый раз разное.
[[nodiscard]] HouseMesh build_house_mesh(const HouseGraph& g);

/// Нормаль поверхности с уже учтённым facing_flipped. Нужна редактору ДО
/// подтверждения: §4.3 требует показать, куда смотрит лицо, пока контур ещё
/// набирается, иначе дизайнер узнает об этом по текстуре.
[[nodiscard]] bool surface_normal(const HouseGraph& g, ElementId id, glm::vec3& out);

/// ВИДНОЕ МЕСТО ПОВЕРХНОСТИ — точка, от которой рисуют её стрелку нормали.
///
/// Заказ пользователя 18.08 дословно: «вектор нормали стены рисуется от какой-
/// то грани, а не в видном месте. Видное место — точка равноудалённая от всех
/// вершин». Он прав и в диагнозе: у стены-цепочки середина её ЯКОРЕЙ лежит на
/// НИЖНЕЙ кромке (якорей всего два, оба внизу), а само полотно уходит вверх —
/// стрелка и росла из-под пола.
///
/// ЧТО СЧИТАЕТСЯ. Для замкнутого контура — точка, РАВНОУДАЛЁННАЯ от вершин,
/// в наилучшей плоскости контура: центр окружности по методу наименьших
/// квадратов (система 3x3 по x, z и свободному члену). У правильного
/// многоугольника это его центр, у вытянутого — точка, от которой все углы
/// видны «одинаково далеко», а не смещённая к скоплению вершин середина.
/// Вырожденный случай назван: если система неразрешима (вершины на одной
/// прямой), берётся середина — она всегда существует.
///
/// Для цепочки — середина её ломаной, поднятая на ПОЛОВИНУ высоты полотна:
