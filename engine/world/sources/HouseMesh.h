/// ПРЕДЕЛЬНЫЙ ИЗЛОМ РЕБРА, ГРАДУСЫ: круче — ребро считается острым, то есть
/// БЕЗ фаски. 50 выведено, а не выбрано: прямой угол, срезанный фаской,
/// распадается ровно на два излома по 45°, и порог обязан лежать между 45 и
/// 90 с запасом на обе стороны. Пятьдесят даёт 5° сверху на кривизну контура
/// (пол по земле, скат с кривым коньком) и 40° снизу до неcрезанного угла —
/// то есть промахнуться в обе стороны одинаково трудно.
///
/// ВОСЬМИГРАННОЕ БРЕВНО ПРОХОДИТ ЭТУ МЕРУ И ДО ВСЯКОЙ ФАСКИ, и это верно, а
/// не дыра: у него излом 45° по построению, и блик оно ловит той же гранью,
/// какую фаска и добавляет. Мера спрашивает «есть ли на ребре грань, ловящая
/// свет», а не «звали ли здесь фаску».
inline constexpr float HOUSE_BEVEL_TURN_DEG = 50.0f;

/// ПЕРЕПИСЬ РЁБЕР МЕША. Ребро — пара треугольников, делящих отрезок (вершины
/// сводятся ПО МЕСТУ: затенение плоское, у каждой грани вершины свои).
///
/// СЧИТАЮТСЯ ТОЛЬКО ВЫПУКЛЫЕ рёбра, и только те, где грани вообще расходятся.
/// Невыпуклое ребро — внутренний угол комнаты: фаска там забирала бы материал
/// СНАРУЖИ тела, и требовать её значит требовать другой предмет. Плоский стык
/// (диагональ триангуляции крышки) ребром не является вовсе.
///
/// РЕБРО, У КОТОРОГО ТРЕУГОЛЬНИКОВ НЕ ДВА, В ПЕРЕПИСЬ НЕ ИДЁТ. Это шов двух
/// разных тел, вставленных друг в друга (стена входит В тело столба — решение
/// пользователя 18.08, нахлёст здесь норма): «ребра» там нет, есть
/// пересечение поверхностей, и его фаска не лечит.
struct HouseEdgeCensus {
    int convex = 0;          ///< выпуклых рёбер всего
    int bevelled = 0;        ///< из них с изломом НЕ круче порога
    int sharp = 0;           ///< convex - bevelled
    float convex_len_m = 0.0f;   ///< их суммарная длина
    float sharp_len_m = 0.0f;    ///< длина острых
    float worst_deg = 0.0f;  ///< наибольший излом среди выпуклых
    /// Доля рёбер с фаской — само число К4. Единица у меша без выпуклых
    /// рёбер (пустой меш, одна плоскость): нечему быть острым.
    [[nodiscard]] float share() const {
        return convex == 0 ? 1.0f : static_cast<float>(bevelled) / static_cast<float>(convex);
    }
};

[[nodiscard]] HouseEdgeCensus house_edge_census(const HouseMesh& mesh,
                                                float max_turn_deg = HOUSE_BEVEL_TURN_DEG);

/// Нормаль поверхности с уже учтённым facing_flipped. Нужна редактору ДО
/// подтверждения: §4.3 требует показать, куда смотрит лицо, пока контур ещё
/// набирается, иначе дизайнер узнает об этом по текстуре.
[[nodiscard]] bool surface_normal(const HouseGraph& g, ElementId id, glm::vec3& out);

/// ЗАПЕЧЁННАЯ НЕБЕСНАЯ ВИДИМОСТЬ ПО ВЕРШИНАМ (22.08, «постройки плоские и
/// приклеены»: контраст фасада 1.58x против 5.80x эталона, откос ворот той же
/// яркости, что фасад). По байту на вершину built-меша: 16 лучей в верхнюю
/// полусферу против СОБСТВЕННЫХ частей постройки (равномерная сетка ускорения,
/// части collider_only не заслоняют — невидимый пандус не должен темнить
/// видимую лестницу). Канал уже ждёт: v_color0.a у построек прибит к 255, а
/// dfn_surface_light читает его как sky_vis и умножает на него ambient — сюда
/// ложится без единой правки шейдера. Пол 0.30: запечатанный интерьер тёмен,
/// но не чёрен — прямой свет очага и солнца канал не трогает.
/// Детерминирован: тот же меш — те же байты.
///
/// `window_light` — ДОЗА СВЕТА ИЗ ОКОН (0 — прежние байты бит-в-бит, правило
/// 47). Пол 0.30 запечатанной комнаты стоит по построению: все шестнадцать
/// лучей идут в верхнюю полусферу и упираются в собственную кровлю, поэтому
/// у стены рядом с окном и у стены в дальнем углу видимость РОВНО одна и та
/// же — «свет из окна» в этой мере не существовал как величина. Доза выше
/// нуля добавляет к видимости вершины долю неба, ВОШЕДШУЮ ЧЕРЕЗ ПРОЁМ
/// (mesh.windows), с проверкой заслонения тем же лучом: перегородка между
/// комнатами обязана эту долю отрезать, иначе окно верхнего яруса засветит
/// нижний сквозь перекрытие.
[[nodiscard]] std::vector<std::uint8_t> bake_house_sky_visibility(
    const HouseMesh& mesh, float window_light = 0.0f);

/// ВИДНОЕ МЕСТО ПОВЕРХНОСТИ — точка, от которой рисуют её стрелку нормали.
///
/// СРЕДНЕЕ ПО ВСЕМ ВЕРШИНАМ. Решение пользователя 18.08, уточнённое им же после
/// первого захода: «стрелка всегда должна стоять между mean от всех координат
/// точек, не важно 2, 3 или 100 их».
///
/// Первый заход считал точку, РАВНОУДАЛЁННУЮ от углов (центр описанной
/// окружности по МНК). Она отвечает на другой вопрос — «откуда все углы
/// одинаково далеко» — и на вытянутом или невыпуклом контуре уезжает далеко от
/// самого полотна: у прямоугольного треугольника садится на середину
/// гипотенузы, у Г-образной комнаты может оказаться вне неё вовсе. Среднее
/// такого не умеет по построению: оно всегда внутри выпуклой оболочки вершин.
///
/// У ЦЕПОЧКИ середина её ломаной ПОДНИМАЕТСЯ на половину высоты полотна: оба
/// якоря стены лежат внизу, и стрелка из их середины росла бы из-под пола.
[[nodiscard]] bool surface_centre(const HouseGraph& g, ElementId id, glm::vec3& out);

