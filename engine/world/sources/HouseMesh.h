enum class LineForm : std::uint8_t { Round = 0, Square, Ngon, Plank };

/// ЗАПОЛНЕНИЕ/ПОКРЫТИЕ — ИМЕНАМИ, а не голым float (аудит #3, находка 17:
/// «ни компилятор, ни панель не знают, что fill=9 не бывает»). Поле в
/// ElementParams остаётся числом — у лексера ОДНА таблица числовых полей, —
/// но ЧИТАЕТСЯ только через fill_kind(): неизвестное число падает в Plain.
enum class WallFill : std::uint8_t {
    Plain = 0,
    Brick = 2,
    Block = 3,
    Logs = 4,
    Parquet = 5,
    Stairs = 6,
    Shingle = 7,
    Tile = 8,
};

/// Числа элемента.
///
/// ВРЕМЕННОЕ МЕСТО ХРАНЕНИЯ. Element сегодня несёт только std::string style, и
/// правка HouseGraph — не моя зона. Поэтому свойства едут ВНУТРИ этой строки,
/// точкой с запятой: "oak;form=square;radius=0.15;tex_deg=45". Формат выбран не
/// от лени, а под ограничение записи: HouseFile пишет style= ОДНИМ токеном без
/// пробелов, значит любой разделитель, кроме пробела, переживает круговой
/// прогон файла — и на это стоит рукав, а не надежда.
///
/// Что предлагается внести в HouseGraph вместо этого — в отчёте зоны.
struct ElementParams {
    /// Имя стиля: то, что стояло в строке до первой точки с запятой.
    std::string name;

    // -- прямая --------------------------------------------------------------
    LineForm form = LineForm::Round;
    /// Число граней для Ngon; 0 — брать по форме.
    int sides = 0;
    /// Расстояние от оси до ГРАНИ (не до угла). Одно и то же значение даёт
    /// одинаковую на глаз толщину круглому бревну и квадратному брусу.
    float radius = HOUSE_LINE_RADIUS_DEFAULT;
    /// Только для прямой с ОДНОЙ вершиной. 0 — не задана, элемент не строится.
    float length = 0.0f;
    /// Градусы, и у каждого своя работа: x — отклонение от вертикали, y —
    /// куда это отклонение направлено, z — ПОВОРОТ ПРОФИЛЯ вокруг собственной
    /// оси. Направление задаётся двумя числами, третье вращает сечение — для
    /// квадратного бруса это разные вещи, и потому углов три, а не два.
    float angle_x = 0.0f;
    float angle_y = 0.0f;
    float angle_z = 0.0f;

    // -- поверхность ---------------------------------------------------------
    float thickness = HOUSE_SURFACE_THICKNESS_DEFAULT;
    /// Только для цепочки. 0 — не задана, стена не строится.
    float height = 0.0f;
    /// Поворот текстуры ВОКРУГ НОРМАЛИ поверхности, градусы, по правилу правой
    /// руки. Вокруг нормали, а не вокруг мировой вертикали: на наклонном полу
    /// второе растягивает текстуру в 1/cos(наклон) раз, и рукав это меряет.
    float tex_deg = 0.0f;
    /// ОБШИВКА ПО РАСКЛАДКЕ (HouseStyle): 1 — стена-цепочка одевается досками,
    /// раскосами и проёмами ПОВЕРХ несущей пластины. Геометрия, а не картинка:
    /// «у стен объём как у собранных деталей» (заказ 19.08).
    float clad = 0.0f;
    /// ВИД КЛАДКИ (заказ 20.08: «не просто текстуру — стену собрать из
    /// нескольких элементов: из дощечек, из кирпичиков, из каменных блоков»).
    /// 0 — гладкая/фахверк по clad; 2 — кирпичная кладка; 3 — каменные блоки;
    /// 4 — венцы сруба (горизонтальный брус рядами);
    /// 5 — паркет досками по замкнутому контуру; 6 — лестничный марш на
    /// четырёх точках (две нижние — ширина, две верхние — куда пришёл);
    /// 7 — кровля дранкой рядами; 8 — кровля черепицей рядами.
    float fill = 0.0f;
    /// Дверные проёмы в стене (штук). Раскладка умеет один вид проёма на
    /// стену: дверь и окна разом — находка вслух, двери берут верх.
    float doors = 0.0f;
    /// МЕЛКИЕ ДЕТАЛИ СТЕНЫ (заказ 20.08: «больше мелких деталей»). Каждая —
    /// число-флаг, геометрию строит сама стена: perерубы углов сруба
    /// (logends — торчащие торцы брёвен на обоих концах пролёта), ставни у
    /// окон (shutters), каменная ступень-крыльцо перед дверью (porch),
    /// каменная завалинка вдоль низа (plinth).
    float logends = 0.0f;
    float shutters = 0.0f;
    float porch = 0.0f;
    float plinth = 0.0f;
    /// КРЫША ЯВНЫМ ПРИЗНАКОМ (20.08, правило опоры): fill 7/8 — кровля и без
    /// него; гладкому скату (солома) признак ставит кузница/панель. unsupported=1
    /// выключает проверку опоры У ЭТОГО элемента — руины строятся законно.
    float roof = 0.0f;
    float unsupported = 0.0f;
    /// ОТКРЫТЫЙ МАРШ (20.08: «для улицы, ветхих и деревенских домов нужны
    /// ступеньки с зазорами»): 1 — доски на тетивах, под ними воздух; 2 —
    /// ступени из ОТДЕЛЬНЫХ каменных блоков с зазорами 2-4 см и джиттером
    /// (EXTERIOR_CATALOG.md, эталон image copy 12). 0 — сплошные коробы.
    float open = 0.0f;
    /// ПОТОЛОЧНЫЕ БАЛКИ (INTERIOR_CATALOG.md, топ-1): под пластиной контура —
    /// брусья 0.2x0.25 шагом ~1.4 м вдоль короткой оси, режутся контуром.
    float beams = 0.0f;
    /// ИЗНОС 0..1 (заказ 20.08: «эффект износа, старения»). Геометрический
    /// слой: сильнее дрожь глубины кусков, выпадающие куски кладки и кровли
    /// (по хэшу — две сборки дают один меш). Тон и мох по низу — слой
    /// отделки, его читает загрузка меша, как mat/tone/paint.
    float wear = 0.0f;
    /// Прямая-«лестница» (наследие 20.08, из панели убрана — марш теперь
    /// fill=6 на контуре): ступени между двумя якорями, radius — половина
    /// ширины. Старые .dfh с stairs=1 строятся по-прежнему.
    float stairs = 0.0f;
    /// Сколько окон ПРОСИТ дизайнер. Раскладка ставит «сколько влезло» и
    /// говорит это вслух числом (LayoutIssue::OpeningsDropped -> находка).
    float windows = 0.0f;
};

