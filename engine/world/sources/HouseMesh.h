struct FittedPlane {
    /// Центр тяжести вершин — точка на плоскости.
    glm::vec3 origin{0.0f};
    /// Единичная нормаль. ЗНАК ВЗЯТ ИЗ ПОРЯДКА ОБХОДА по правилу правой руки
    /// (§2.3 замысла): МНК даёт направление с точностью до знака, а порядок
    /// вершин снимает эту неоднозначность.
    glm::vec3 normal{0.0f, 1.0f, 0.0f};
    /// Наибольшее отклонение вершины от плоскости, метры.
    float max_deviation = 0.0f;
    /// Наибольшее расстояние между двумя вершинами контура, метры.
    float span = 0.0f;
    /// max_deviation / span. Сравнивать с HOUSE_CONTOUR_FLATNESS_MAX.
    float flatness = 0.0f;
    /// Площадь контура, спроецированного на плоскость. Ноль — вершины на одной
    /// прямой, плоскости у них нет.
    float area = 0.0f;
    bool degenerate = true;
};

/// Наилучшая по методу наименьших квадратов плоскость: нормаль — собственный
/// вектор ковариации при НАИМЕНЬШЕМ собственном значении (полные наименьшие
/// квадраты, то есть минимум суммы квадратов расстояний ДО ПЛОСКОСТИ, а не по
/// вертикали — вертикальная подгонка врёт тем сильнее, чем круче скат, и на
/// стене врёт бесконечно).
[[nodiscard]] FittedPlane fit_contour_plane(std::span<const glm::vec3> pts);

/// Проекция контура на плоскость. u_out/v_out — ортонормированный базис с
/// u x v == plane.normal; u направлен вдоль ПЕРВОГО ребра контура, чтобы
/// результат не зависел от мировых осей и был воспроизводим.
[[nodiscard]] std::vector<glm::vec2> project_contour(std::span<const glm::vec3> pts,
                                                     const FittedPlane& plane,
                                                     glm::vec3& u_out, glm::vec3& v_out);

/// Отсечение ушей. Возвращает тройки индексов ИСХОДНОГО контура, обходимые
/// против часовой стрелки в базисе (u,v), то есть с нормалью по plane.normal.
/// Пустой ответ — уши кончились раньше треугольников: контур самопересекается
/// или вырожден.
[[nodiscard]] std::vector<std::uint32_t> triangulate_contour(std::span<const glm::vec2> poly);

/// Самопересечение контура (§6.2). Проверяет несмежные рёбра попарно.
[[nodiscard]] bool contour_self_intersects(std::span<const glm::vec2> poly);

/// Система координат текстуры на грани: начало, ось u, ось v. Повёрнута на
/// tex_deg ВОКРУГ НОРМАЛИ. u x v == normal при любом угле, поэтому масштаб
/// текстуры не меняется — поворот остаётся поворотом, а не сдвигом.
struct UvFrame {
    glm::vec3 origin{0.0f};
    glm::vec3 u{1.0f, 0.0f, 0.0f};
    glm::vec3 v{0.0f, 0.0f, 1.0f};
    [[nodiscard]] glm::vec2 at(glm::vec3 p) const;
};

[[nodiscard]] UvFrame make_uv_frame(glm::vec3 origin, glm::vec3 normal, glm::vec3 u_hint,
                                    float tex_deg);

