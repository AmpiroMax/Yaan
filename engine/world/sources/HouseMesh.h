/// ДОПУСК КОНТАКТА. Два тела считаются соединёнными, если зазор между ними
/// МЕНЬШЕ этого числа (пересечение — зазор отрицательный, тоже контакт).
///
/// 0.02 ВЫВЕДЕНО СНИЗУ, А НЕ ВЗЯТО КРУГЛЫМ. Нижняя граница — зазор досок
/// обшивки HOUSE_BOARD_GAP_M = 0.012 (HOUSES.md §2): доски соседнего ряда
/// стоят в 12 мм друг от друга НАМЕРЕННО, и допуск ниже 12 мм рассыпал бы
/// каждый фасад на сотню островов, то есть правило кричало бы там, где всё
/// правильно. Верхняя граница — самая мелкая настоящая нашивка набора: кант
/// карниза отстоит от кромки ската на 0.06 (Forge::eaves_trim), и допуск выше
/// 6 см начал бы СШИВАТЬ то, что на самом деле висит. 0.02 лежит между ними с
/// запасом втрое в обе стороны.
inline constexpr float HOUSE_CONTACT_TOL_M = 0.02f;

/// ОСТРОВ — компонента связности графа контактов тел постройки.
struct HouseIsland {
    /// Элементы, чьи тела попали в остров; по возрастанию, без повторов.
    std::vector<ElementId> elements;
    /// Сколько выпуклых тел в острове.
    std::size_t bodies = 0;
    float y_lo = 0.0f;
    float y_hi = 0.0f;
    /// Держит САМОЕ НИЖНЕЕ тело постройки — это и есть «земля» (нижний ярус).
    bool grounded = false;
    /// Зазор до ближайшего тела ЧУЖОГО острова, метры. Отрицательного не
    /// бывает по построению (иначе был бы контакт). Бесконечность — ничего
    /// ближе метра не нашлось.
    float nearest_gap = 0.0f;
    /// Чьё это ближайшее тело. NO_ELEMENT — не нашлось.
    ElementId nearest_element = NO_ELEMENT;
};

/// ГРАФ КОНТАКТОВ ТЕЛ ПОСТРОЙКИ, разобранный на компоненты связности.
///
/// Правило: остров обязан быть ОДИН. Дом собран из тел, которые друг друга
/// держат; вторая компонента — это кусок, который висит в воздухе, и никакая
/// проверка по вершинам его не видит, потому что вершины у него свои
/// собственные и все на месте. Именно так башня Вайтрана получила парапет с
/// шатром, стоящие на 0.125 м выше площадки: check_roof_support смотрит на
/// ВЕРШИНЫ и близость к любому не-кровельному элементу, а не на тела.
struct HouseConnectivity {
    /// Первым — заземлённый остров, дальше по убыванию числа тел.
    std::vector<HouseIsland> islands;
    std::size_t bodies = 0;
    float tolerance_m = HOUSE_CONTACT_TOL_M;
    [[nodiscard]] bool ok() const { return islands.size() <= 1; }
};

/// Тела берутся ИЗ КОЛЛАЙДЕРА (HouseMesh::convex), а не из картинки: держит
/// дом то, что имеет тело. Косметика (подтёки и трещины износа,
/// MeshBuilder::collider = false) в граф не входит и не может «приклеить»
