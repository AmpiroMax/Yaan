#pragma once

#include <string>
#include <vector>

#include "engine/world/sources/HouseGraph.h"

namespace dfn::world {

/// Что мешает зарегистрировать. Пусто — можно.
struct RegisterFinding {
    std::string why;
    ElementId element = NO_ELEMENT;
    VertexId vertex = NO_VERTEX;
};

/// Вырезать компоненту, в которой лежит вершина, в отдельный граф.
///
/// Имена в новом графе СВОИ: он самостоятельная постройка, и тащить в него
/// сквозные имена карты значило бы сделать тип, зависящий от карты, из которой
/// его вырезали.
[[nodiscard]] bool extract_component(const HouseGraph& src, VertexId seed,
                                     HouseGraph& out);

/// Проверки, которые обязаны пройти ПЕРЕД тем, как тип попадёт в библиотеку.
///
/// Решение пользователя 18.08 про «щели»: «нельзя при регистрации дом
/// фиксировать, у которого есть рёбра, где есть стена, но нет просто ребра».
/// То есть КАЖДАЯ ПОВЕРХНОСТЬ ОБЯЗАНА ОПИРАТЬСЯ НА КАРКАС: стена, натянутая
/// между вершинами, между которыми нет прямой, висит на пустоте.
[[nodiscard]] std::vector<RegisterFinding> check_registrable(const HouseGraph& g);

} // namespace dfn::world
