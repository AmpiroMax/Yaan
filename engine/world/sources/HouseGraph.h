#pragma once

#include <cstddef>
#include <cstdint>
#include <string>
#include <vector>

#include <glm/vec3.hpp>

namespace dfn::world {

/// Устойчивые имена. Устойчивость — требование записи: v1 обязан значить ту же
/// вершину после чтения, иначе ссылки «вершина на оси» рассыплются.
using VertexId = std::uint32_t;
using ElementId = std::uint32_t;
inline constexpr VertexId NO_VERTEX = 0;
inline constexpr ElementId NO_ELEMENT = 0;

/// Чем задано положение вершины. Три способа, и все три из разговора 18.08.
enum class Anchoring : std::uint8_t {
    /// Свободная точка в координатах постройки — в том числе В ВОЗДУХЕ.
    /// Пользователь просил уметь ставить вершины где угодно; отвес до земли
    /// рисует редактор, модели он не нужен.
    Free = 0,
    /// Высота берётся у рельефа. ТАКАЯ ВЕРШИНА СЧИТАЕТСЯ ЗАЗЕМЛЁННОЙ, и это
    /// единственный источник заземления во всей модели.
    OnGround,
    /// Точка НА ОСИ элемента-прямой, параметр вдоль неё. Двинулась прямая —
    /// вершина поехала за ней, и это не стоит ничего.
    OnEdge,
};

/// Вершина — ЧИСТАЯ ТОЧКА. Ни радиуса, ни материала, ни цвета: всё это свойства
/// элементов, которые к ней крепятся. Соблазн повесить сюда «свойства якоря»
/// надо гасить: якорь не рисуется как предмет, он место.
struct Vertex {
    VertexId id = NO_VERTEX;
    Anchoring anchoring = Anchoring::Free;
    /// Координаты ПОСТРОЙКИ, не мира. Мировые вычисляются при постановке:
    /// world = origin + rotate_y(yaw, local). Хранить мировые значило бы
    /// приколотить дом к одному месту и потерять переносимость.
    glm::vec3 local{0.0f};
    /// Только для Anchoring::OnEdge: на какой оси сидит и где вдоль неё.
    ElementId host = NO_ELEMENT;
    float host_t = 0.0f;
};

/// Видов ДВА. Лестница была третьим и перестала им быть решением пользователя
/// 18.08: она натягивается между вершинами на разной высоте, то есть это
/// наклонная поверхность, а проём над ней размечает дизайнер якорями.
enum class ElementKind : std::uint8_t {
    /// Колонна, балка, стойка, перекладина — ОДНО И ТО ЖЕ. Одна или две вершины.
    Line = 0,
    /// Пол, потолок, стена, скат — ОДНО И ТО ЖЕ. Контур (>=3) или цепочка (>=2)
    /// с высотой. Различаются ориентацией и стилем, и это не повод плодить виды.
    Surface,
};

/// Элемент — гиперребро. Порядок вершин ЗНАЧИМ: из него выводится нормаль.
struct Element {
    ElementId id = NO_ELEMENT;
    ElementKind kind = ElementKind::Line;
    std::vector<VertexId> refs;
    /// Имя стиля: «сруб», «фахверк», «камень». Стиль — ОПИСАНИЕ, а не меш:
    /// доски тянутся и меняют угол, окна размер не меняют.
    std::string style;
    /// Разворот нормали. Порядок обхода даёт верный ответ почти всегда,
    /// переключатель спасает случай, когда обошли не в ту сторону.
    bool facing_flipped = false;
};

/// Почему операция не выполнена. ok == true — выполнена.
struct GraphResult {
    bool ok = true;
    std::string why;
    /// Кто держит вершину, которую просили удалить. Голый отказ на пятом этаже
    /// превращается в поиск виноватого руками — поэтому список, а не флаг.
    std::vector<ElementId> blockers;
};

class HouseGraph {
public:
    // -- создание ------------------------------------------------------------
    VertexId add_vertex(Anchoring anchoring, glm::vec3 local);
    /// Вершина на оси элемента. Отказ, если хозяин не прямая или его нет.
    GraphResult add_vertex_on_edge(ElementId host, float t, VertexId& out);
    /// Отказ, если ссылок мало для вида или упомянута несуществующая вершина.
    GraphResult add_element(ElementKind kind, std::vector<VertexId> refs,
                            std::string style, ElementId& out);

    // -- удаление ------------------------------------------------------------
    /// ОТКАЗЫВАЕТ, пока на вершине висит хоть один элемент, и возвращает их
    /// список. Решение пользователя: «удалять бревно нельзя давать, пока к нему
    /// что-то привязано».
    GraphResult remove_vertex(VertexId id);
    GraphResult remove_element(ElementId id);

    // -- запросы -------------------------------------------------------------
    [[nodiscard]] const Vertex* vertex(VertexId id) const;
    [[nodiscard]] const Element* element(ElementId id) const;
    [[nodiscard]] std::size_t vertex_count() const { return vertices_.size(); }
    [[nodiscard]] std::size_t element_count() const { return elements_.size(); }
    /// Элементы, которые упоминают эту вершину. Ровно то, что просил
    /// пользователь: выбрал узел — подсветились все смежные стройматериалы.
    [[nodiscard]] std::vector<ElementId> incident(VertexId id) const;

    // -- правка ---------------------------------------------------------------
    /// ЦЕНТРАЛЬНАЯ ОПЕРАЦИЯ ВСЕЙ ЗАТЕИ. Пользователь: «я хочу уметь якоря
    /// двигать, и за ними соответственно должны тянуться все элементы, что
    /// привязаны, так я могу раздвигать стены очень быстро без необходимости
    /// всё перестраивать».
    ///
    /// Двигается ТОЛЬКО вершина. Геометрия элементов нигде не хранится — она
    /// выводится из вершин, поэтому «за ней потянулось» получается само, а не
    /// обходом списка. Обход нужен для ДРУГОГО: вершины, сидящие на осях
    /// сдвинутых прямых, обязаны пересчитать своё положение, и вершины на ИХ
    /// осях тоже — это и есть каскад.
    ///
    /// Вершину с Anchoring::OnEdge двигать напрямую НЕЛЬЗЯ: её положение
    /// принадлежит хозяину. Отказ, а не тихое игнорирование.
    GraphResult move_vertex(VertexId id, glm::vec3 new_local);
    /// Разворот нормали поверхности. Отдельным методом, а не полем наружу:
    /// правка через модель — единственный способ не разъехаться с индексами.
    GraphResult set_facing(ElementId id, bool flipped);

    /// Положение вершины В КООРДИНАТАХ ПОСТРОЙКИ, с уже разрешёнными осями.
    /// Для Free и OnGround это её собственное поле; для OnEdge — точка на оси
    /// хозяина, посчитанная рекурсивно.
    ///
    /// ЗАЩИТА ОТ ЦИКЛА живёт здесь: вершина на прямой, чей конец сидит на другой
    /// прямой, которая опирается на первую, — ошибка ввода, а не повод уйти в
    /// бесконечность. Спуск ограничен числом вершин и возвращает последнее
    /// осмысленное положение.
    ///
    /// ЧЕСТНАЯ ОГОВОРКА: сегодня эту защиту ПРОВЕРИТЬ НЕЧЕМ, и я не делаю вид,
    /// что она проверена. Через нынешний API цикл не построить — ссылки
    /// элемента задаются при создании и потом не меняются, так что замкнуть
    /// круг некуда. Защита написана под ЧТЕНИЕ ФАЙЛА, где ссылки приходят
    /// текстом и могут быть какими угодно; там у неё и появится рукав. Пока
    /// его нет — это код, работающий по построению, а не по измерению, и
    /// разница названа.
    [[nodiscard]] glm::vec3 resolved_local(VertexId id) const;

    // -- компоненты связности ------------------------------------------------
    /// ПОСТРОЙКА = КОМПОНЕНТА СВЯЗНОСТИ. Это определение, а не следствие:
    /// «каждый компонент связности должен считаться отдельной постройкой; если
    /// две компоненты связали, это теперь единая постройка» (пользователь,
    /// 18.08). Возвращает вершины, сгруппированные по компонентам; порядок
    /// групп и порядок внутри групп ДЕТЕРМИНИРОВАН, иначе две загрузки одного
    /// файла назовут постройки по-разному.
    [[nodiscard]] std::vector<std::vector<VertexId>> components() const;

    /// Компонента, в которой лежит вершина: индекс в результате components().
    /// npos — вершины нет. Нужно инструменту регистрации: «выбрал ЛЮБУЮ
    /// вершину — подсветилась вся постройка».
    [[nodiscard]] std::size_t component_of(VertexId id) const;

    /// МОСТЫ: элементы, удаление которых РАЗОРВЁТ постройку надвое.
    ///
    /// Считается ЗАРАНЕЕ, а не после удаления, и в этом весь смысл. Пользователь
    /// хочет знать про распад до того, как он случился: «если у постройки
    /// удалили мост или узел, то стало две компоненты связности». Узнать об этом
    /// постфактум — значит узнать, когда чинить уже нечего.
    ///
    /// «МОСТ» ЗДЕСЬ ЗНАЧИТ «РАЗОРВЁТ», А НЕ «РАЗОРВЁТ РОВНО НАДВОЕ», и это
    /// исправление моего собственного рассуждения, пойманное рукавом. Я записал
    /// в комментарии, что гиперребро мостом быть не может — «убрав его, рвём
    /// сразу все N связей, и надвое из этого не следует». Проверка показала, что
    /// это неверно ПО СУЩЕСТВУ: единственный пол на трёх якорях, будучи убран,
    /// рассыпает их на три постройки. Это распад, и предупреждать о нём надо
    /// ровно так же, как о распаде надвое. Код был прав, проза — нет.
    ///
    /// Отсюда определение: элемент — мост, если без него компонент СТАНОВИТСЯ
    /// БОЛЬШЕ. Считается перебором: копия без элемента, пересчёт компонент,
    /// сравнение. Дороже классического обхода в глубину, но тот знает только
    /// рёбра с двумя концами и на гиперрёбрах отвечает неверно.
    [[nodiscard]] std::vector<ElementId> bridges() const;

private:
    [[nodiscard]] glm::vec3 resolved_local_step(VertexId id, std::size_t depth) const;
    [[nodiscard]] Vertex* find_vertex(VertexId id);
    [[nodiscard]] Element* find_element(ElementId id);

    std::vector<Vertex> vertices_;
    std::vector<Element> elements_;
    VertexId next_vertex_ = 1;
    ElementId next_element_ = 1;
};

/// Сколько вершин НУЖНО этому виду как минимум. Выражением, а не проверкой в
/// теле add_element: у правила должен быть прибор, а у прибора — одно место.
[[nodiscard]] constexpr std::size_t min_refs_for(ElementKind kind) {
    return kind == ElementKind::Line ? 1u : 2u;
}

} // namespace dfn::world
