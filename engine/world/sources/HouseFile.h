#pragma once

#include <string>

#include "engine/world/sources/HouseGraph.h"

namespace dfn::world {

struct HouseIoResult {
    bool ok = true;
    std::string why;
    /// Номер строки, с 1. Ноль — беда не про строку (файл не открылся).
    int line = 0;
};

/// Постройка в текст. Порядок строк детерминирован: вершины по возрастанию
/// имени, затем элементы. Две записи одного графа обязаны совпасть побайтово,
/// иначе diff перестанет что-либо значить.
[[nodiscard]] std::string write_house(const HouseGraph& g);

/// Текст в постройку. Граф очищается ДО чтения: дочитывание в непустой граф
/// давало бы разный результат в зависимости от того, что там лежало.
[[nodiscard]] HouseIoResult read_house(const std::string& text, HouseGraph& out);

} // namespace dfn::world
