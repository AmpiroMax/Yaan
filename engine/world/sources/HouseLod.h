#pragma once

#include <cstdint>

namespace dfn::world {

/// СТУПЕНЬ ДЕТАЛИЗАЦИИ ПОСТРОЙКИ. Порядок — по возрастанию грубости, и на это
/// опирается сравнение уровней в house_lod_for_distance.
enum class HouseLod : std::uint8_t {
    /// Всё, что есть в рецепте: фаска, кладка, обшивка, ряды кровли, мелочь.
    Full = 0,
    /// Без фаски, без косметики износа, без КИРПИЧНОЙ кладки — её шаг первым
    /// уходит под предел разрешения (см. таблицу).
    Mid = 1,
    /// Оболочка: стены плитами, скаты плоскостями, ни одного рядного слоя и
    /// ни одной накладной мелочи. Проёмы ОСТАЮТСЯ (довод у
    /// HOUSE_LOD_FAR_KEEPS_OPENINGS).
    Far = 2,
};
inline constexpr int HOUSE_LOD_COUNT = 3;

/// ПИКСЕЛЕЙ НА МЕТР ПОПЕРЁК ВЗГЛЯДА НА РАССТОЯНИИ ОДНОГО МЕТРА, кадр FullHD.
///
/// ВЫВОД: проекция линейна по тангенсу, поэтому высота кадра H пикселей
/// покрывает 2*tg(fov_y/2) метров на метр дистанции. При CAMERA_FOV_Y = 1.309
/// рад (75°, docs/NUMBERS.md) и H = 1080 это 1080 / (2*tg 37.5°) =
/// 1080 / 1.53466 = 703.7. Число FullHD, а не DESIGN_RES_H=360 (там вышло бы
/// 234.6): владелец перевёл проект на FullHD 15.08, и лестница, выведенная в
/// 360 строках, срезала бы на треть ближе, чем видит его монитор.
inline constexpr float HOUSE_LOD_PPM_FULLHD = 703.7f;

/// ПРЕДЕЛ РАЗРЕШЕНИЯ ПОВТОРЯЮЩЕГОСЯ СЛОЯ, ПИКСЕЛЕЙ НА ШАГ. Два — не запас
/// вкуса, а Найквист: узор с шагом меньше двух пикселей не может быть
/// разрешён кадром и превращается в своё среднее, то есть в ровный тон. Это и
/// есть разрешение «срезать слой»: срезанный слой отдаёт ровно то, во что он
/// всё равно превратился бы.
inline constexpr float HOUSE_LOD_MIN_PX = 2.0f;

/// Расстояние, за которым слой с шагом \p feature_m перестаёт разрешаться.
[[nodiscard]] constexpr float house_lod_cut_distance_m(float feature_m) {
    return feature_m * HOUSE_LOD_PPM_FULLHD / HOUSE_LOD_MIN_PX;
}

// ---------------------------------------------------------------------------
// ТАБЛИЦА ВЫВОДА. Слой -> его шаг (метры, из кода печи) -> расстояние, за
// которым он неразличим (house_lod_cut_distance_m). Пороги ступеней стоят
// РОВНО на разрывах этого ряда — там, где следующий слой ещё далеко.
//
//   фаска ребра            HOUSE_BEVEL_W_DEFAULT 0.010     3.5 м
//   трещина износа         HouseWalls, ширина    0.018     6.3 м
//   ряд кирпича            HouseWalls 0.065+0.010 = 0.075  26.4 м   <- MID 28
//   -------------------------------------------------------------
//   ставня/крыльцо/торец   HouseWalls, ~0.15               52.8 м
//   доска обшивки          HOUSE_BOARD_STEP_DEFAULT 0.22   77.4 м
//   ряд каменных блоков    HouseWalls 0.22+0.015 = 0.235   82.7 м
//   дранка (выпуск)        HouseRoof 0.28                  98.5 м
//   венец сруба            HouseWalls 0.26+0.035 = 0.295  103.8 м
//   черепица (выпуск)      HouseRoof 0.30                 105.6 м   <- FAR 110
//   -------------------------------------------------------------
//   оконный проём          HOUSE_WINDOW_W_DEFAULT 1.00    351.8 м
//
// Разрыв между 26.4 и 52.8 и разрыв между 105.6 и 351.8 — это и есть две
// ступени. Третьей ступени нет не из лени: между 106 и 352 м резать нечего.
// ---------------------------------------------------------------------------

/// ВХОД В СРЕДНЮЮ СТУПЕНЬ, метры. 28 — округление вверх от 26.4 (ряд кирпича).
inline constexpr float HOUSE_LOD_MID_IN_M = 28.0f;

/// ВХОД В ДАЛЬНЮЮ СТУПЕНЬ, метры. 110 — округление вверх от 105.6 (черепица),
/// то есть от САМОГО КРУПНОГО из рядных слоёв: за этим порогом ни один из них
/// уже не разрешается, и оболочка отдаёт их усреднённым тоном.
inline constexpr float HOUSE_LOD_FAR_IN_M = 110.0f;

/// ПЕРЕХЛЁСТ ПОЛОС, метры. У построек смена ступени БЕСПЛАТНА (все три формы
/// уже лежат в видеопамяти), поэтому перехлёст здесь не про цену перепечки, а
/// про дрожь картинки: без него игрок, стоящий на самом краю полосы, получал
/// бы мигание фасада с частотой собственного покачивания. Шесть метров — это
/// 1.2 с хода бегом (5 м/с), то есть верхняя граница частоты переключения.
inline constexpr float HOUSE_LOD_HYSTERESIS_M = 6.0f;

/// ДАЛЬНЯЯ ФОРМА СОХРАНЯЕТ ПРОЁМЫ, и это НАМЕРЕННОЕ отступление от первой
/// формулировки заказа («коробка+крыша, без проёмов»). Довод — та же таблица:
/// проём метровой ширины неразличим только с 352 м, то есть на входе в
/// дальнюю ступень он занимает 6.4 пикселя и читается ритмом фасада. Цена
/// его сохранения — пластина с прорезями вместо цельной, десятки
/// треугольников против дюжины, при том что рядные слои, которые ступень и
/// срезает, стоят тысячи. Убрать проёмы значило бы отдать видимое ради
/// полупроцента.
inline constexpr bool HOUSE_LOD_FAR_KEEPS_OPENINGS = true;

/// Ступень по расстоянию до постройки, с перехлёстом полос. \p current — та,
/// на которой предмет стоит сейчас: без неё гистерезиса не существует.
[[nodiscard]] HouseLod house_lod_for_distance(float distance_m, HouseLod current);

/// Ширина фаски для ступени: у средней и дальней её нет (3.5 м, таблица).
[[nodiscard]] float house_lod_bevel(HouseLod lod, float bevel_m);

/// Имя ступени для журналов и приборов.
[[nodiscard]] const char* house_lod_name(HouseLod lod);

} // namespace dfn::world
