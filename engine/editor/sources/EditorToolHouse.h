/// Что нашлось на оси прямой под прицелом.
struct HouseEdgeHit {
    world::ElementId host = world::NO_ELEMENT;
    float t = 0.0f;          ///< параметр вдоль оси, 0..1
    float distance_m = 0.0f; ///< от прицела до оси
    glm::vec3 point{0.0f};   ///< точка НА оси, в мире
    [[nodiscard]] bool hit() const { return host != world::NO_ELEMENT; }
};

/// ОБЩЕЕ СОСТОЯНИЕ ТРЁХ ИНСТРУМЕНТОВ: одна постройка, один выбор, одна история.
///
/// ПОЧЕМУ ОНО ОБЩЕЕ, А НЕ У КАЖДОГО СВОЁ. Инструменты правят ОДИН граф:
/// поверхность натягивается на вершины, поставленные другим инструментом, а
/// прямая соединяет их же. Копия графа у каждого — это три постройки, которые
/// разъедутся на первом же протаскивании якоря.
class HouseSession {
public:
    HouseSession() = default;

    /// Куда писать шаги отмены. Пустая — история не ведётся, и это законное
    /// состояние (проверка без App).
    void set_history(EditorHistory* h) { history_ = h; }
    [[nodiscard]] EditorHistory* history() const { return history_; }

    [[nodiscard]] world::HouseGraph& graph() { return graph_; }
    [[nodiscard]] const world::HouseGraph& graph() const { return graph_; }

    // -- постройка в мире ------------------------------------------------------
    /// world = origin + rotate_y(yaw, local) — §2.6 замысла. Хранить мировые
    /// координаты в графе значило бы приколотить дом к одному месту.
    [[nodiscard]] glm::vec3 origin() const { return origin_; }
    void set_origin(glm::vec3 o) { origin_ = o; }
    [[nodiscard]] float yaw() const { return yaw_; }
    void set_yaw(float radians) { yaw_ = radians; }
    [[nodiscard]] glm::vec3 to_world(glm::vec3 local) const;
    [[nodiscard]] glm::vec3 to_local(glm::vec3 world) const;
    /// Положение вершины В МИРЕ, с уже разрешёнными осями.
    [[nodiscard]] glm::vec3 vertex_world(world::VertexId id) const;

    // -- снимки и отмена -------------------------------------------------------
    /// Состояние целиком, текстом (write_house). Никогда не пустое: файл
    /// начинается со строки «# dfh 1», и это важно — пустая строка у истории
    /// значит «отменять нечего».
    [[nodiscard]] std::string snapshot() const;
    /// Применить снимок (отмена или повтор). false — текст не читается; граф в
    /// этом случае НЕ ТРОГАЕТСЯ читателем... точнее, читатель чистит граф до
    /// разбора, поэтому неудача возвращает пустую постройку, и об этом
    /// сообщается наружу, а не проглатывается.
    bool apply_snapshot(const std::string& text);
    /// НОМЕР ЖИЗНИ ГРАФА: растёт на каждом восстановлении снимка и больше ни от
    /// чего.
    ///
    /// ЭТУ ЗАЩИТУ НЕЛЬЗЯ СНИМАТЬ ПОД ТЕМ ПРЕДЛОГОМ, ЧТО «ИМЕНА ТЕПЕРЬ
    /// СОХРАНЯЮТСЯ». Довод написан здесь, а не оставлен в переписке зон,
    /// потому что он выглядит устаревшим и не является им — а такие доводы за
    /// эти два дня терялись дважды.
    ///
    /// Как было: читатель раздавал имена заново, и «v3 v4 v5» на входе давали
    /// «v1 v2 v3» на выходе. Зона core это починила (18.08): имя в файле И ЕСТЬ
    /// имя в графе, круговой прогон сходится побайтово с первого раза.
    ///
    /// ЧЕГО ПОЧИНКА НЕ ЗАКРЫВАЕТ И НЕ МОЖЕТ ЗАКРЫТЬ: при чтении граф
    /// обнуляется, а счётчик имён поднимается до наибольшего ПРОЧИТАННОГО, то
    /// есть откатывается вместе с графом. Снимок из трёх вершин восстанавливает
    /// «следующее имя = 4», и следующая созданная вершина снова зовётся v4 —
    /// хотя v4 из прошлой жизни графа стояла в другом месте. Измерено рукавом
    /// («имя вершины после отмены достаётся другой точке»): v4 в 99 м до
    /// отмены, v4 в -77 м после.
    ///
    /// Поэтому рука НИКОГДА не держит вершину по имени через откат. Всё, что
    /// инструмент набрал (обход поверхности, якорь прямой, тащимая вершина),
    /// бросается при смене этого номера, а выбор устанавливается заново ПО
    /// МЕСТУ. Иначе поверхность натянется на чужие якоря, и — что хуже всего —
    /// сделает это молча: на экране имена не написаны.
    [[nodiscard]] std::uint32_t revision() const { return revision_; }

    /// НОМЕР ВЕРСИИ ГЕОМЕТРИИ — И ЭТО НЕ ТО ЖЕ, ЧТО НОМЕР ЖИЗНИ ГРАФА.
    ///
    /// revision() растёт только на ОТМЕНЕ: он отвечает на вопрос «можно ли ещё
    /// доверять именам, которые рука набрала до этого», и растить его на каждой
    /// правке значило бы ронять обход поверхности после каждого щелчка.
    ///
    /// version() растёт на ЛЮБОМ изменении графа, включая отмену. Он отвечает
    /// на другой вопрос — «надо ли пересчитать тело дома», — и путать эти два
    /// вопроса я уже попробовал: тело не заливалось вовсе, потому что номер
    /// жизни после обычной постановки якоря не менялся.
    /// Версия геометрии — СПРАШИВАЕТСЯ У ГРАФА, а не считается здесь.
    ///
    /// Считалась здесь ровно один вечер и успела соврать: перетаскивание якоря
    /// правит граф напрямую (шаг истории на кадр превратил бы одно движение в
    /// сотню отмен), мимо этой двери, — и тело дома не перестраивалось, пока
    /// якорь тащили. Довод целиком лежит у HouseGraph::version().
    [[nodiscard]] std::uint32_t version() const { return graph_.version(); }

    /// ФИКСАЦИЯ ОСИ, как в любом 3D-редакторе (в Blender это G затем Z).
    ///
    /// ЗАЧЕМ. Луч прицела упирается в ЗЕМЛЮ, поэтому «тяну вверх» на экране
    /// означает «точка пересечения с землёй уезжает вдаль»: пользователь 18.08
    /// показал кадром — вместо стойки вышла длинная прямая на траве. Это не
    /// оплошность инструмента, а свойство задачи: у мыши две координаты, у
    /// точки три, и без ограничения перевод неоднозначен.
    ///
    /// ТРИ ВИДА ОГРАНИЧЕНИЯ, И ТРЕТИЙ — ЗАКАЗ ТОГО ЖЕ ДНЯ: «я выбрал якорь от
    /// вертикальной прямой, а вертикально обратно поставить просто наводясь не
    /// могу. Надо продумать систему, чтобы я мог двигать якоря вдоль любой из
    /// линий, которые рисуются от якоря». Свободно — как раньше; вертикаль —
    /// стойки и этажи; ВДОЛЬ ПРЯМОЙ — движение по уже построенной оси, то есть
    /// удлинить балку, не сбив её направления.
    ///
    /// ПОЧЕМУ В СЕССИИ, А НЕ В ИНСТРУМЕНТЕ. Ось — состояние руки, а не одной
    /// прямой: её включает клавиша, которую ловит App, и App не должен знать,
    /// какой из трёх инструментов постройки сейчас в руке. Сессия у них общая,
    /// и она же единственная, кого App держит полем. Её читают И рисование
    /// прямой, И перетаскивание якоря — одно понятие, а не два похожих.
    struct AxisLock {
        enum class Kind : std::uint8_t {
            Free = 0, ///< как раньше: точка там, где луч встретил землю
            Vertical, ///< вертикаль через якорь
            Edge,     ///< вдоль оси уже построенной прямой
        };
        Kind kind = Kind::Free;
        world::ElementId edge = world::NO_ELEMENT; ///< для Kind::Edge
        [[nodiscard]] bool free() const { return kind == Kind::Free; }
    };
    [[nodiscard]] AxisLock axis() const { return axis_; }
    void set_axis(AxisLock a) { axis_ = a; }

    /// СЛЕДУЮЩЕЕ ОГРАНИЧЕНИЕ ВОКРУГ ЭТОГО ЯКОРЯ: свободно -> вертикаль -> по
    /// очереди каждая прямая, приходящая в него -> снова свободно. Одна
    /// клавиша, один круг, и список — это то, что человек ВИДИТ вокруг якоря.
    void cycle_axis(world::VertexId around);

    /// НАПРАВЛЕНИЕ ОГРАНИЧЕНИЯ в мире (единичное). false — ограничения нет или
    /// прямая выродилась: тогда рука работает по-старому, а не замирает.
    [[nodiscard]] bool axis_dir(world::VertexId at, glm::vec3& out) const;

    /// Как назвать текущее ограничение человеку.
    [[nodiscard]] std::string axis_label() const;

    /// СЕТКА МИРА: включена ли и с каким шагом.
    ///
    /// ОДНА НА ВСЁХ И В МИРОВЫХ КООРДИНАТАХ (заказ 18.08: «сетка строится по
    /// координатам мира, а не по относительным координатам чего-либо»). По ней
    /// прилипает якорь, ею же шагают стрелки, её же рисуют отсечки на земле —
    /// три разных шага были бы тремя разными сетками, из которых видна одна.
    ///
    /// Живёт в сессии по той же причине, что и ось: это состояние РУКИ, общее
    /// для всех инструментов постройки, а App держит полем только сессию.
    [[nodiscard]] bool grid_on() const { return grid_on_; }
    void set_grid_on(bool on) { grid_on_ = on; }
    [[nodiscard]] float grid_step_m() const { return grid_step_m_; }
    void set_grid_step_m(float m) {
        // Зажим здесь, а не у каждого органа управления: шаг правят и панель, и
        // клавиши, а предел обязан быть один (правило 32).
        grid_step_m_ = std::clamp(m, 0.05f, 10.0f);
    }
    /// Ближайший узел сетки. Возвращает точку как есть, когда сетка выключена —
    /// вызывающему не нужно знать, включена она или нет.
    /// РУКА СЕЙЧАС ПРАВИТ СТРЕЛКАМИ, А НЕ ПРИЦЕЛОМ.
    ///
    /// Пока это так, ПРИЗРАК ПОД ПРИЦЕЛОМ НЕ РИСУЕТСЯ ВОВСЕ, а помечается тот
    /// якорь, который двигают. Заказ 19.08 дословно: «двигать камеру за
    /// курсором не надо, но если двигают стрелками, то пусть отдельно будет
    /// метка этой точки, под курсором ничто не рисуется; но если я задвигал
    /// камерой, то пусть она пропадает и снова под курсором рисуется».
    ///
    /// Причина не в красоте: человек нажал стрелку, шарик уехал в сторону — и
    /// рядом остался призрак под прицелом, который он прочитал как «появилась
    /// новая точка не под курсором». Две зелёные метки на экране отвечают на
    /// один вопрос по-разному, и это ровно тот сорт неясности, который тут
    /// разбирали весь вечер.
    [[nodiscard]] bool nudging() const { return nudging_; }
    void set_nudging(bool on) { nudging_ = on; }

    [[nodiscard]] glm::vec3 snap_to_grid(glm::vec3 world) const {
        if (!grid_on_) {
            return world;
        }
        const auto q = [&](float v) {
            return std::round(v / grid_step_m_) * grid_step_m_;
        };
        return {q(world.x), q(world.y), q(world.z)};
    }

    /// Якорь В ЭТОЙ ТОЧКЕ, если он там ОДИН. NO_VERTEX, если якоря там нет ИЛИ
    /// их там несколько: это опознание, а не поиск ближайшего, и на
    /// неоднозначности оно обязано отказать, а не выбрать первый попавшийся.
    [[nodiscard]] world::VertexId unique_vertex_at(glm::vec3 world_point,
                                                   float tol_m) const;

    /// Записать шаг: `before` снят до правки, «после» снимается здесь. Шаг, не
    /// изменивший состояния, история отбрасывает сама.
    void record(std::string label, const std::string& before);

    /// ОДНА ДВЕРЬ КО ВСЕМ МУТАЦИЯМ. Снимок до, действие, запись в историю —
    /// ровно в одном месте на все три инструмента.
    ///
    /// ОТКАЗ В ИСТОРИЮ НЕ ПИШЕТСЯ, и это не оптимизация: отказ ничего не
    /// изменил, а шаг отмены, который ничего не откатывает, выглядит как
    /// сломанная отмена.
    template <class Fn>
    world::GraphResult mutate(std::string label, Fn&& fn) {
        std::string before = snapshot();
        world::GraphResult r = fn(graph_);
        if (r.ok) {
            record(std::move(label), before);
        }
        return r;
    }

    // -- выбор -----------------------------------------------------------------
    /// ВЫБРАЛ ВЕРШИНУ — ПОДСВЕТИЛИСЬ ЕЁ ЭЛЕМЕНТЫ (incident); ВЫБРАЛ ЭЛЕМЕНТ —
    /// ПОДСВЕТИЛИСЬ ЕГО ВЕРШИНЫ (refs). Прямое требование пользователя, и
    /// подсветка считается ЗДЕСЬ, потому что иначе её пришлось бы считать
    /// каждому инструменту заново — то есть тремя способами.
    void select_vertex(world::VertexId id);
    void select_element(world::ElementId id);
    void clear_selection();
    [[nodiscard]] world::VertexId selected_vertex() const { return sel_vertex_; }
    [[nodiscard]] world::ElementId selected_element() const { return sel_element_; }
    [[nodiscard]] const std::vector<world::ElementId>& lit_elements() const {
        return lit_elements_;
    }
    [[nodiscard]] const std::vector<world::VertexId>& lit_vertices() const {
        return lit_vertices_;
    }
    /// Пересобрать подсветку — после правки, которая могла её обесценить
    /// (удалили элемент, добавили прямую к выбранной вершине).
    void refresh_selection();

    // -- поиск под прицелом ----------------------------------------------------
    /// Ближайшая вершина в пределах хватки, или NO_VERTEX.
    [[nodiscard]] world::VertexId pick_vertex(glm::vec3 world_point, float grab_m) const;

    /// ЧТО ПОД ЛУЧОМ ПРИЦЕЛА — И ЭТО ДРУГОЙ ВОПРОС, ЧЕМ «ЧТО РЯДОМ С ТОЧКОЙ».
    ///
    /// Точка прицела — место, где луч встретил ЗЕМЛЮ. Якорь, висящий в трёх
    /// метрах над травой, рядом с ней не окажется никогда, сколько на него ни
    /// смотри: между ним и точкой всегда те самые три метра. Пользователь
    /// 18.08 назвал это тремя жалобами сразу — не выбираются якоря, не
    /// выбираются прямые, не сажается вершина на ось.
    ///
    /// Здесь вопрос задан лучу: насколько близко он проходит от якоря. Ближе
    /// хватки — цель; из нескольких целей выигрывает БЛИЖАЙШАЯ К ГЛАЗУ, а не
    /// ближайшая к лучу, иначе дальний якорь отбирал бы щелчок у переднего,
    /// стоя точно за ним.
    [[nodiscard]] world::VertexId pick_vertex_ray(glm::vec3 origin, glm::vec3 dir,
                                                  float grab_m) const;
    /// То же для ОСИ прямой: ближайшее сближение луча с отрезком.
    [[nodiscard]] HouseEdgeHit pick_edge_ray(glm::vec3 origin, glm::vec3 dir,
                                             float grab_m) const;

    /// ЛЮБОЙ ЭЛЕМЕНТ ПОД ЛУЧОМ — для ВЫБОРА, а не для посадки вершины.
    ///
    /// Отдельно от pick_edge_ray, потому что вопросы разные: на ось садится
    /// вершина, и там годится только Line; выбрать же человек хочет и стену
    /// («не понимаю как выбрать её», 18.08). Поверхность ищется по СВОЕМУ
    /// КОНТУРУ — по тем самым отрезкам, которыми она нарисована: пока дом
    /// проволочный, целиться можно только в то, что видно.
    /// `out_distance` (если не nullptr) получает расстояние до попадания вдоль
    /// луча. Оно нужно ПРИЦЕЛУ: без него прицел не знает, что упёрся в стену, и
    /// улетает в землю за ней — а вместе с ним улетает и проверка дальности,
    /// из-за которой щелчок по стене не принимался вовсе.
    [[nodiscard]] world::ElementId pick_element_ray(glm::vec3 origin, glm::vec3 dir,
                                                    float grab_m,
                                                    float* out_distance = nullptr) const;

    /// УБРАТЬ ВЫБРАННОЕ: элемент, если выбран он, иначе якорь.
    ///
    /// ОДИН МЕТОД НА ОБА СЛУЧАЯ, потому что у человека одна клавиша и одно
    /// намерение — «убери то, что я выбрал». Отказ возвращается текстом и, если
    /// якорь держат элементы, СО СПИСКОМ ДЕРЖАТЕЛЕЙ: голое «нельзя» превращает
    /// поиск виноватого в обход дома руками.
    [[nodiscard]] std::string delete_selection();
    /// Ближайшая ОСЬ прямой в пределах допуска. Только прямые с ДВУМЯ вершинами:
    /// у прямой с одной вершиной второй конец выводится из чисел, а
    /// resolved_local вершины на такой оси возвращает не точку на оси, а её
    /// собственное поле — то есть модель посадила бы вершину не туда.
    [[nodiscard]] HouseEdgeHit pick_edge(glm::vec3 world_point, float grab_m) const;
    /// Концы прямой В МИРЕ. Для прямой с одной вершиной второй конец считается
    /// из length/angle_x/angle_y — тем же выражением, что у построителя меша.
    /// false — элемент не прямая или длины у него нет.
    [[nodiscard]] bool line_ends_world(world::ElementId id, glm::vec3& a, glm::vec3& b) const;

private:
    world::HouseGraph graph_;
    EditorHistory* history_ = nullptr;
    glm::vec3 origin_{0.0f};
    float yaw_ = 0.0f;
    world::VertexId sel_vertex_ = world::NO_VERTEX;
    world::ElementId sel_element_ = world::NO_ELEMENT;
    std::vector<world::ElementId> lit_elements_;
    std::vector<world::VertexId> lit_vertices_;
    std::uint32_t revision_ = 0;
    AxisLock axis_{};
    bool grid_on_ = false;
    bool nudging_ = false;
    float grid_step_m_ = 0.5f;
};

