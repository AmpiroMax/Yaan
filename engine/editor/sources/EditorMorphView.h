#pragma once

#include "engine/editor/sources/EditorUi.h"

#include <cstddef>
#include <functional>
#include <string>
#include <vector>

namespace dfn::app {

/// Устойчивый id панели: по нему её открывают и закрывают.
inline constexpr const char* MORPH_PANEL_ID = "character.morph";

/// ОДНА РУЧКА. `name` — имя цели из файла (оно же ключ пресета и имя в дозе
/// DFN_MORPH); `value` панель правит НА МЕСТЕ, а хозяин читает через крючок.
struct MorphSliderModel {
    std::string name;
    float lo = 0.0f;
    float hi = 1.0f;
    float value = 0.0f;
    /// Сколько миллиметров двигает эта ручка на единице веса — прямо из
    /// прибора. Показывается рядом с ползунком, потому что «ход 4.7 мм» и «ход
    /// 53 мм» — это разные ручки, и по названию их не отличить.
    float travel_mm = 0.0f;
};

/// ЧТО РИСОВАТЬ. Пустой список — это НЕ пустая панель: тело без секции MORF и
/// тело, у которого ползунки не загрузились, выглядят одинаково, и панель
/// обязана сказать, какой из двух случаев.
struct MorphModel {
    std::vector<MorphSliderModel> sliders;
    /// Последняя сказанная панелью правда: куда написан пресет, куда выпечено
    /// тело, чем отказала выпечка. Пустая строка — молчание, а не «всё хорошо».
    std::string status;
    /// Тело вообще загружено? False — сказать про это, а не показать ноль ручек.
    bool body_ready = false;
};

/// ЧЕГО ПАНЕЛЬ НЕ УМЕЕТ САМА. `set` вызывается на КАЖДОЕ движение ручки (не по
/// отпусканию): бленд стоит 0.03 мс, и ползунок, показывающий результат через
/// полсекунды после отпускания, — это ползунок, которым нельзя целиться.
struct MorphHooks {
    std::function<void(std::size_t index, float value)> set;
    std::function<void()> reset;
    std::function<void()> save_preset;
    std::function<void()> bake;
};

void draw_morph_panel(MorphModel& model, const MorphHooks& hooks);

} // namespace dfn::app
