#pragma once

#include <cstddef>
#include <functional>
#include <string>
#include <vector>

namespace dfn::app {

/// Один шаг истории. `label` — то, что человек увидит в подсказке: «поставил
/// вершину», «двинул якорь». Не украшение: отмена без имени заставляет гадать,
/// что именно откатится.
struct HistoryEntry {
    std::string label;
    /// Состояние ДО действия. Строка, потому что состояние постройки уже умеет
    /// записываться текстом (HouseFile), и второго способа сериализации мы не
    /// заводим (правило 32).
    std::string before;
    /// Состояние ПОСЛЕ действия — для повтора.
    std::string after;
};

class EditorHistory {
public:
    /// Сколько шагов помним. Не бесконечность: снимки стоят памяти, и глубина
    /// должна быть названным числом, а не «сколько влезет».
    explicit EditorHistory(std::size_t depth = 100) : depth_(depth == 0 ? 1 : depth) {}

    /// Записать совершённое действие. Зовётся ПОСЛЕ того, как модель изменена:
    /// нужны оба снимка, и «после» существует только теперь.
    void record(std::string label, std::string before, std::string after);

    [[nodiscard]] bool can_undo() const { return !done_.empty(); }
    [[nodiscard]] bool can_redo() const { return !undone_.empty(); }

    /// Что именно откатится/повторится — для подсказки на экране.
    [[nodiscard]] const std::string& undo_label() const;
    [[nodiscard]] const std::string& redo_label() const;

    /// Снимок, который надо ПРИМЕНИТЬ, и перенос записи в другую стопку.
    /// Пустая строка — отменять нечего. Применяет вызывающий: история не знает
    /// про модель и не должна знать, иначе её нельзя будет проверить без мира.
    [[nodiscard]] std::string undo();
    [[nodiscard]] std::string redo();

    void clear();

    [[nodiscard]] std::size_t undo_depth() const { return done_.size(); }
    [[nodiscard]] std::size_t redo_depth() const { return undone_.size(); }

private:
    std::size_t depth_;
    std::vector<HistoryEntry> done_;
    std::vector<HistoryEntry> undone_;
};

} // namespace dfn::app
