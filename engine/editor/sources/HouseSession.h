/// Радиус хватки якоря, метры. В МЕТРАХ ПО МИРУ, а не в пикселях — та же
/// причина, что у PATH_GRAB_M: пиксельная хватка на близком якоре накрыла бы
/// пол-дома, а на дальнем не поймала бы ничего.
inline constexpr float HOUSE_GRAB_M = 0.45f;
/// Допуск до ОСИ прямой. Меньше хватки якоря нарочно: якорь на конце оси и сама
/// ось — соседние цели, и щелчок у конца обязан достаться якорю.
inline constexpr float HOUSE_EDGE_GRAB_M = 0.30f;
/// Радиус шарика, которым рисуется вершина. УДВОЕН 18.08 по заказу («сферы
/// якорей надо сделать больше в 2 раза»): на кадре с высоты человеческого
/// роста шарик в 10 см читался как крапина на траве, и попасть в него мышью
/// было делом удачи.
inline constexpr float HOUSE_BALL_R_M = 0.20f;
/// Штрих и просвет отвеса, метры.
inline constexpr float HOUSE_PLUMB_DASH_M = 0.25f;
/// Потолок числа штрихов: вершина на километровой высоте не имеет права съесть
/// весь буфер отладочных линий.
inline constexpr int HOUSE_PLUMB_MAX_DASHES = 96;
/// Длина стрелки нормали, метры.
inline constexpr float HOUSE_NORMAL_ARROW_M = 1.0f;
/// Радиус прилипания шарика к оси прямой, метры. Больше допуска на попадание
/// лучом (HOUSE_EDGE_GRAB_M) нарочно: там вопрос «во что я целюсь», здесь —
/// «куда это встанет», и магнит должен ловить раньше, чем человек попал точно.
inline constexpr float HOUSE_SNAP_M = 0.50f;
/// Цвет призрака постройки: ЗЕЛЁНЫЙ, и это не украшение. Жёлтым рисуется то,
/// что уже стоит и сейчас выбрано; зелёным — то, чего ещё нет. Один цвет на
/// оба смысла человек 18.08 прочитал как «нарисовалось два якоря».
inline constexpr std::uint32_t HOUSE_GHOST_COLOR = 0xFF60E080u;
/// Потолок подтягивания шарика к себе, метры. Не бесконечность: шарик,
/// подтянутый вплотную к глазу, стоит в лице у человека и щелчок по нему
/// ставит вершину неизвестно где.
inline constexpr float HOUSE_PULL_MAX_M = 30.0f;
/// Шаг колеса при подтягивании, метры за щелчок.
inline constexpr float HOUSE_PULL_STEP_M = 0.25f;
/// Выше этого «в воздухе» — настоящий воздух, а не дрожание ползунка.
inline constexpr float HOUSE_AIR_EPS_M = 0.01f;
/// Допуск, с которым якорь ОПОЗНАЁТСЯ ПО МЕСТУ после восстановления снимка.
/// Мал нарочно: это не поиск ближайшего, а установление того же самого. Снимок
/// пишет координаты текстом с четырьмя знаками, и после чтения они совпадают
/// побитово или не совпадают вовсе.
inline constexpr float HOUSE_REID_TOL_M = 1e-3f;
/// Допуск до оси при зажиме длины (§5.5 замысла): насколько вбок может отстоять
